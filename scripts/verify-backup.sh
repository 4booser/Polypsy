#!/usr/bin/env bash
# Проверка восстановимости бэкапа.
#
# «Бэкап, который ни разу не разворачивали, — не бэкап»: файл может быть
# обрезан, зашифрован потерянным ключом или содержать дамп, который не
# накатывается. Узнать об этом в день аварии — поздно.
#
# Скрипт берёт самый свежий бэкап, разворачивает его в одноразовую базу,
# сверяет, что данные на месте, проверяет цепочку журнала и удаляет базу за
# собой. Ненулевой код возврата — повод для оповещения.
#
#   cd /opt/quizzy && DATABASE_URL=postgres://user@host/quizzy \
#   BACKUP_DIR=/backups BACKUP_PASSPHRASE=... ./scripts/verify-backup.sh
#
# Из каталога установки (там, где docker-compose.yml и .env.docker): журнал
# пересчитывается образом api, см. пункт 3.
#
# В cron: раз в неделю, вывод — в систему оповещений.
set -euo pipefail

# Клиентские утилиты берутся той же версии, что и сервер.
#
# PG_EXEC — префикс запуска. Пусто: pg_dump с хоста. В развёртывании через
# Docker сюда ставится «docker compose exec -T postgres», и тогда дамп
# снимает тот же PostgreSQL, который хранит данные.
#
# Это не аккуратность ради аккуратности. На сервере оказался pg_dump 18 при
# базе 16 — сочетание неподдерживаемое: дамп получается, но несёт
# «SET transaction_timeout», которого шестнадцатая версия не знает, и
# восстановление идёт с ошибками. Заметно это только при восстановлении,
# то есть в тот единственный момент, когда бэкап и нужен.
PG_EXEC="${PG_EXEC:-}"


: "${DATABASE_URL:?DATABASE_URL обязателен — из него берутся хост и учётные данные}"
: "${BACKUP_DIR:?BACKUP_DIR обязателен}"
: "${BACKUP_PASSPHRASE:?BACKUP_PASSPHRASE обязателен}"

# Самый свежий файл из копий по расписанию — суточных, недельных и
# месячных вместе, по времени файла. Прежде суточные брались первыми, а
# недельные — только если суточных нет вовсе: в воскресенье backup.sh кладёт
# копию в weekly/, и проверка после воскресной выкатки брала субботнюю
# суточную, не видя свежей (первый прогон, 2026-09-27).
#
# Только копии по расписанию и только готовые. Недописанный снимок
# (backup.sh пишет в *.gpg.part и переименовывает после проверки чтением) —
# не копия. Снимки перед обновлением (upgrade/<экземпляр>/) бывают сняты с
# других баз, и сверять их с рабочей, указанной здесь, нельзя. Прежний поиск
# «любой quizzy_* по всему каталогу» к тому же брал последний по имени
# каталога, а не по времени. Файлы .age берутся наравне с .gpg: если самый
# свежий — от прежней ветки age, restore.sh откажет с объяснением, и это
# должно стать тревогой, а не пропуском.
pick() { ls -1t "$@" 2>/dev/null | head -1 || true; }
latest="$(pick "$BACKUP_DIR"/daily/quizzy_*.gpg "$BACKUP_DIR"/daily/quizzy_*.age \
  "$BACKUP_DIR"/weekly/quizzy_*.gpg "$BACKUP_DIR"/weekly/quizzy_*.age \
  "$BACKUP_DIR"/monthly/quizzy_*.gpg "$BACKUP_DIR"/monthly/quizzy_*.age)"
[ -n "$latest" ] || { echo "ПРОВАЛ: в $BACKUP_DIR нет ни одного бэкапа"; exit 1; }

# Сначала форма GNU, потом BSD. Обратный порядок не работает: на Linux
# `stat -f` — это «показать файловую систему», а не «формат», и команда не
# падает, а печатает совсем другое. Запасной вариант при этом не
# срабатывает, а арифметика ниже получает текст вместо числа и роняет
# скрипт с «unbound variable» — то есть проверка бэкапов не работала
# именно на той системе, ради которой написана.
mtime="$(stat -c %Y "$latest" 2>/dev/null || stat -f %m "$latest")"
age_hours=$(( ( $(date +%s) - mtime ) / 3600 ))
echo "проверяю: $latest (возраст ${age_hours} ч)"

# свежесть — часть проверки: разворачивающийся, но недельной давности бэкап
# означает, что расписание встало
if [ "$age_hours" -gt 48 ]; then
  echo "ПРОВАЛ: самому свежему бэкапу ${age_hours} ч — расписание бэкапов не работает"
  exit 1
fi

# одноразовая база с меткой времени: параллельные прогоны не мешают друг другу
check_db="quizzy_verify_$(date +%s)"
# restore.sh берётся рядом с этим файлом, а не из ./scripts текущего каталога:
# обслуживание (maintenance.yml) привозит свежие скрипты во временную папку и
# запускает их из каталога установки — там лежат копии со дня настройки
base_url="${DATABASE_URL%/*}"
admin_url="$base_url/postgres"

chain_err="$(mktemp)"   # поток ошибок пересчёта журнала, см. пункт 3

# WITH (FORCE): проверка цепочки ниже подключается к одноразовой базе из
# контейнера приложения, и соединение, не закрытое вовремя (прерванный
# прогон, зависший контейнер), молча оставляло бы базу-копию лежать на
# сервере — с персональными данными, вне ротации и вне чьего-либо внимания.
cleanup() {
  $PG_EXEC psql "$admin_url" -q -c "DROP DATABASE IF EXISTS \"$check_db\" WITH (FORCE)" >/dev/null 2>&1 || true
  rm -f "$chain_err"
}
trap cleanup EXIT

$PG_EXEC psql "$admin_url" -q -c "CREATE DATABASE \"$check_db\""
DATABASE_URL="$base_url/$check_db" BACKUP_PASSPHRASE="$BACKUP_PASSPHRASE" \
  PG_EXEC="$PG_EXEC" "$(dirname "$0")/restore.sh" "$latest" >/dev/null

restored_url="$base_url/$check_db"

fail=0
say_fail() { echo "ПРОВАЛ: $1"; fail=1; }

# 1. Ключевые таблицы восстановились ПОЛНОСТЬЮ — сверяем с источником, а не
#    с нулём.
#
#    Прежняя проверка требовала, чтобы таблицы были непусты, и объявляла
#    непригодным всякий бэкап только что установленного экземпляра: там
#    методик и прохождений законно ноль. Тревога, которая срабатывает на
#    исправной системе, учит не смотреть на тревоги — а этой смотреть надо.
#
#    Сравнение с источником отвечает на настоящий вопрос: воспроизводит ли
#    дамп то, с чего снят. Пустая таблица при пустом источнике — норма;
#    пустая при непустом — та самая беда, ради которой проверка написана.
#
#    Сравнение — на МОМЕНТ СНИМКА, а не на момент проверки. Рабочая база живёт
#    дальше: за час после снимка журнал дописал полторы сотни строк, и
#    сравнение «сейчас» объявило непригодной исправную копию (первый же
#    прогон по расписанию, 2026-09-26). Поэтому источник считается до
#    последней строки, которая есть в копии: для таблиц — по времени её
#    создания, для журнала — по номеру записи, и там же сверяется хэш этой
#    записи: совпавший хэш доказывает, что копия — начало того же журнала, а
#    не другой журнал той же длины.
for spec in users:created_at surveys:created_at responses:started_at; do
  table="${spec%%:*}"; col="${spec#*:}"
  n="$($PG_EXEC psql "$restored_url" -tAc "select count(*) from $table" 2>/dev/null || echo "нет")"
  if [ "$n" = "нет" ]; then
    say_fail "таблицы $table нет в восстановленной базе"
    continue
  fi
  edge="$($PG_EXEC psql "$restored_url" -tAc "select coalesce(max($col)::text, '') from $table" 2>/dev/null || echo "")"
  if [ -z "$edge" ]; then
    src="$($PG_EXEC psql "$DATABASE_URL" -tAc "select count(*) from $table where $col is null" 2>/dev/null || echo "нет")"
  else
    src="$($PG_EXEC psql "$DATABASE_URL" -tAc "select count(*) from $table where $col <= '$edge'::timestamptz" 2>/dev/null || echo "нет")"
  fi
  if [ "$n" != "$src" ]; then
    say_fail "в $table восстановлено $n строк, в рабочей базе на момент снимка $src"
  else
    echo "  $table: $n строк (совпадает с рабочей на момент снимка)"
  fi
done

n="$($PG_EXEC psql "$restored_url" -tAc "select count(*) from audit_log" 2>/dev/null || echo "нет")"
if [ "$n" = "нет" ]; then
  say_fail "таблицы audit_log нет в восстановленной базе"
else
  last="$($PG_EXEC psql "$restored_url" -tAc "select coalesce(max(seq), 0) from audit_log" 2>/dev/null || echo 0)"
  src="$($PG_EXEC psql "$DATABASE_URL" -tAc "select count(*) from audit_log where seq <= $last" 2>/dev/null || echo "нет")"
  h_copy="$($PG_EXEC psql "$restored_url" -tAc "select entry_hash from audit_log where seq = $last" 2>/dev/null || echo "")"
  h_live="$($PG_EXEC psql "$DATABASE_URL" -tAc "select entry_hash from audit_log where seq = $last" 2>/dev/null || echo "")"
  if [ "$n" != "$src" ]; then
    say_fail "в audit_log восстановлено $n строк, в рабочей базе до записи №$last — $src"
  elif [ "$last" != "0" ] && [ "$h_copy" != "$h_live" ]; then
    say_fail "запись журнала №$last в копии и в рабочей базе разная — копия не того журнала"
  else
    echo "  audit_log: $n строк до записи №$last, хэш совпадает с рабочей"
  fi
fi

# 2. Миграции копии — начало истории рабочей базы.
#
#    Копия, снятая до выкатки, законно знает меньше миграций, чем рабочая
#    база после неё: требовать равенства значило объявлять непригодной
#    каждую копию, снятую перед обновлением (первый прогон после выкатки
#    v1.13, 2026-09-27). Беда — другое: миграция в копии, которой рабочая
#    база не знает, то есть копия не с этой базы или с будущей версии кода.
restored_migs="$($PG_EXEC psql "$restored_url" -tAc 'select hash from drizzle."__drizzle_migrations" order by id' 2>/dev/null || true)"
live_migs="$($PG_EXEC psql "$DATABASE_URL" -tAc 'select hash from drizzle."__drizzle_migrations" order by id' 2>/dev/null || true)"
have="$(printf '%s\n' "$restored_migs" | grep -c . || true)"
want="$(printf '%s\n' "$live_migs" | grep -c . || true)"
unknown="$(printf '%s\n' "$restored_migs" | grep . | grep -vxF -f <(printf '%s\n' "$live_migs" | grep .) | grep -c . || true)"
if [ "$unknown" != "0" ]; then
  say_fail "в копии $unknown миграций, которых рабочая база не знает: копия не с этой базы или с другой версии кода"
elif [ "$have" -gt "$want" ]; then
  say_fail "миграций в копии $have, в рабочей базе $want"
else
  echo "  миграций: $have в копии, $want в рабочей базе (копия — начало той же истории)"
fi

# 3. Цепочка журнала цела. Хэш-цепочка — единственное, что доказывает, что
#    журнал не переписан; если она рвётся в бэкапе, восстанавливать его в
#    качестве доказательства бессмысленно.
#
#    Цепочка ПЕРЕСЧИТЫВАЕТСЯ по восстановленным строкам, а не сверяется по
#    соседним хэшам. Прежняя проверка сравнивала prev_hash каждой строки с
#    entry_hash предыдущей — это доказывает, что хэши сцеплены между собой,
#    но не что они принадлежат содержимому строк: запись с изменёнными
#    полями и прежними хэшами проходила как «цепочка цела» (ревью заказчика,
#    2026-09-27). Сверка последнего хэша с рабочей базой выше этого тоже не
#    ловит: последняя строка при подмене в середине остаётся нетронутой.
#
#    Пересчитывает код приложения — verifyChain через auditReport.ts (то же,
#    что действие audit-verify в maintenance.yml), — а не копия алгоритма
#    здесь. Канонизация строки журнала — часть приложения и меняется вместе с
#    ним (вложенные details — с сохранением проверки прежних строк); копия на
#    оболочке однажды разошлась бы с ним и начала либо браковать исправные
#    копии, либо, что хуже, пропускать подменённые. От приложения берётся
#    только код возврата: вывод его — для человека.
#
#    APP_EXEC — чем запускать приложение, APP_DB_HOST — адрес сервера базы,
#    каким его видит приложение. По умолчанию, если в текущем каталоге лежит
#    развёртывание (docker-compose.yml и .env.docker — так запускает
#    maintenance.yml), — одноразовый контейнер api того же выпуска, что
#    работает: его код и писал журнал. --no-deps не трогает остальные
#    службы. База из контейнера видна по имени службы postgres, а не по петле
#    хоста, поэтому хост в адресе подменяется; пользователь и пароль остаются
#    из DATABASE_URL (владелец: политики строк на журнале его не касаются).
#    Адрес уходит в контейнер окружением (-e DATABASE_URL без значения берёт
#    его из окружения вызова), а не строкой команды — в ps и в журнал
#    прогона он не попадает. Без развёртывания в каталоге (разработка,
#    scripts/test/backup-roundtrip.sh) — bun из рабочей копии.
if [ -z "${APP_EXEC+x}" ]; then
  if [ -f docker-compose.yml ] && [ -f .env.docker ] && command -v docker >/dev/null 2>&1; then
    APP_EXEC="docker compose --env-file .env.docker run --rm --no-deps -T -e DATABASE_URL api"
    APP_DB_HOST="${APP_DB_HOST:-postgres:5432}"
  else
    APP_EXEC=""
  fi
fi
app_url="$restored_url"
if [ -n "${APP_DB_HOST:-}" ]; then
  rest="${restored_url#*://}"
  cred=""
  case "$rest" in *@*) cred="${rest%%@*}@"; rest="${rest#*@}" ;; esac
  app_url="${restored_url%%://*}://$cred$APP_DB_HOST/${rest#*/}"
fi
# Пароль из вывода приложения вырезается на случай, если оно, падая,
# напечатает адрес базы: этот вывод уходит в журнал прогона обслуживания.
mask() { sed -E 's#(://[^:@/[:space:]]*):[^@/[:space:]]*@#\1:***@#g'; }

# Поток ошибок — отдельно: туда же docker compose пишет ход запуска
# контейнера («Container … Created»), и при удаче это шум в отчёте. При
# провале нужен и он: там причина, если контейнер не поднялся, и там же
# строка приложения о разрыве цепочки.
if [ -z "$APP_EXEC" ] && [ ! -f apps/api/src/auditReport.ts ]; then
  say_fail "цепочку журнала нечем пересчитать: в $(pwd) нет ни развёртывания (docker-compose.yml, .env.docker), ни рабочей копии с apps/api"
elif ! mig_out="$(DATABASE_URL="$app_url" $APP_EXEC bun apps/api/src/migrate.ts 2>&1)"; then
  # Одноразовую базу доводим до схемы нынешнего кода — ровно так пойдёт и
  # настоящее восстановление: снимок, затем выкатка с миграциями. Иначе код
  # новой версии пересчитывал бы журнал копии, снятой до неё, по схеме,
  # которой там ещё нет (колонка hash_version появилась в 0096). Не
  # накатились миграции — это тоже провал копии: восстановить её этим кодом
  # нельзя.
  say_fail "миграции нынешнего кода на копию не накатываются:"
  printf '%s\n' "$mig_out" | mask | { grep -v '^ *$' || true; } | tail -n 8 | sed 's/^ */    /'
elif chain_out="$(DATABASE_URL="$app_url" $APP_EXEC bun apps/api/src/auditReport.ts 2>"$chain_err")"; then
  echo "  цепочка журнала: пересчитана кодом приложения"
  printf '%s\n' "$chain_out" | mask | sed 's/^ */    /'
else
  code=$?
  say_fail "цепочка журнала не сходится при пересчёте (или пересчёт не запустился, код выхода $code):"
  { cat "$chain_err"; printf '%s\n' "$chain_out"; } | mask | { grep -v '^ *$' || true; } | tail -n 12 | sed 's/^ */    /'
fi

if [ "$fail" != "0" ]; then
  echo
  echo "ИТОГ: бэкап непригоден. Разбираться сейчас, а не в день аварии."
  exit 1
fi

echo
echo "ИТОГ: бэкап разворачивается и проверки проходит."
