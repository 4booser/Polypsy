#!/usr/bin/env bash
# Восстановление из бэкапа, созданного backup.sh, в УКАЗАННУЮ базу.
#
#   DATABASE_URL=postgres://.../quizzy_restore BACKUP_PASSPHRASE=... \
#     ./scripts/restore.sh /backups/daily/quizzy_2026-08-26_0300.dump.zst.gpg
#
# Восстанавливайте сначала в отдельную базу и проверяйте, прежде чем трогать
# рабочую: restore с --clean в живую базу — необратим.
set -euo pipefail

# Клиентские утилиты берутся той же версии, что и сервер.
#
# PG_EXEC — префикс запуска. Пусто: pg_dump с хоста. В развёртывании через
# Docker сюда ставится «docker compose exec -T postgres», и тогда дамп
# снимает тот же PostgreSQL, который хранит данные.
#
# Это не аккуратность ради аккуратности. На сервере оказался pg_dump 18 при
# базе 16 — сочетание неподдерживаемое: дамп получается, но несёт
# «SET transaction_timeout», которого шестнадцатая версия не знает, и
# восстановление идёт с ошибками. Заметно это только при восстановлении,
# то есть в тот единственный момент, когда бэкап и нужен.
PG_EXEC="${PG_EXEC:-}"


file="${1:?путь к файлу бэкапа}"
: "${DATABASE_URL:?DATABASE_URL обязателен}"
: "${BACKUP_PASSPHRASE:?BACKUP_PASSPHRASE обязателен}"

# Обозначение базы для вывода: адрес без пароля и без параметров (в них
# тоже бывает password=). Прежде последней строкой печатался весь
# DATABASE_URL — с паролем владельца базы, в журнал cron и в журнал прогона
# проверки копий, откуда его читают куда больше людей, чем знают пароль.
safe_url() {
  printf '%s' "$1" | sed -E 's#\?.*$##; s#^([A-Za-z][A-Za-z0-9+.-]*://[^:@/]*):[^@/]*@#\1@#'
}

# Та же обвязка gpg, что в backup.sh, и по тем же причинам: фраза через
# дескриптор, а не аргументом (аргумент виден в ps); без кэша ключа в агенте
# (открывать копию должна фраза, а не память агента о прошлой расшифровке).
gpg_sym() {
  gpg --batch --quiet --yes --pinentry-mode loopback --no-symkey-cache \
    --passphrase-fd 3 "$@" 3<<<"$BACKUP_PASSPHRASE"
}

# Нечитаемый файл (копии теперь 0600, см. umask в backup.sh) иначе дошёл бы
# до gpg и выглядел бы как «неверная фраза или повреждённая копия» — то
# есть как авария, а не как права.
[ -r "$file" ] || { echo "ОТКАЗ: нет права читать $file (копии доступны только владельцу)" >&2; exit 1; }

case "$file" in
  *.gpg) ;;
  # Файлы .age снимала ветка backup.sh, которая шифровала парольную фразу
  # вместо дампа (см. пояснение в backup.sh). Восстанавливать из них нечего,
  # и сказать это надо прямо, а не предлагать ввести фразу.
  *.age) echo "ОТКАЗ: $file снят прежней веткой age, которая шифровала парольную фразу вместо дампа — данных в нём нет. Берите копию .gpg." >&2; exit 1 ;;
  *) echo "неизвестный формат: $file" >&2; exit 1 ;;
esac

# Два прохода: сначала файл целиком расшифровывается и распаковывается
# впустую, и только если это прошло — второй проход идёт в pg_restore.
#
# Почему не один поток. gpg сверяет код целостности только в конце файла,
# а pg_restore с --clean начинает сносить объекты базы с первых байт: копия,
# испорченная в середине, успела бы наполовину затереть базу, прежде чем
# выяснилось бы, что восстанавливать нечем. Неверная фраза, обрезанный файл,
# подменённый шифротекст — всё это должно останавливать восстановление ДО
# первого изменения базы.
#
# Почему не временный файл, как прежде. Прежний restore.sh клал
# расшифрованный дамп в /tmp и подавал оттуда: вся база открытым текстом на
# диске на время восстановления — ровно то, от чего копии шифруются.
# Расшифровать дважды дешевле.
#
# pg_restore --list читает только оглавление и выходит раньше конца потока;
# остаток дочитывает cat, иначе gpg получил бы SIGPIPE и до сверки кода
# целостности в конце файла дело бы не дошло. Удачу pg_restore группа
# сообщает строкой «ok»: код возврата группы — это код cat.
readable() {
  gpg_sym --decrypt "$1" | zstd -q -d -c | {
    $PG_EXEC pg_restore --list > /dev/null && echo ok
    cat > /dev/null
  }
}
if ! toc="$(readable "$file")" || [ "$toc" != "ok" ]; then
  echo "ОТКАЗ: $file не расшифровывается этой фразой, повреждён или не является дампом. База не тронута." >&2
  exit 1
fi

# Дамп подаётся на вход, а не именем файла: при PG_EXEC="docker compose exec"
# pg_restore работает внутри контейнера, где хостового пути не существует.
gpg_sym --decrypt "$file" | zstd -q -d -c \
  | $PG_EXEC pg_restore --clean --if-exists --no-owner -d "$DATABASE_URL"
echo "восстановлено в $(safe_url "$DATABASE_URL")"
