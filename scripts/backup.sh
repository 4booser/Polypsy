#!/usr/bin/env bash
# Бэкап базы Quizzy: pg_dump → сжатие → шифрование → проверка чтением → ротация.
#
# Использование:
#   DATABASE_URL=postgres://... BACKUP_DIR=/backups BACKUP_PASSPHRASE=... ./scripts/backup.sh
#
# Ротация: 7 суточных, 4 недельных (воскресенье), 12 месячных (1-е число).
#
# Разовый снимок вне расписания — BACKUP_KIND=<подкаталог>. Так снимает
# scripts/upgrade-instances.sh перед миграциями (BACKUP_KIND=upgrade/<имя>):
# тот же формат, то же шифрование, та же проверка чтением, но в ротацию такой
# снимок не входит — убирает его человек, убедившись, что обновление встало.
#
# Шифрование: gpg, симметрично, парольной фразой. Без фразы скрипт падает —
# незашифрованный дамп медицинской базы на диске недопустим.
#
# Ветки age больше нет (ревью заказчика, 2026-09-27). Она была сломана с
# первого дня, и так, что снаружи этого не видно:
#   zstd … | age -e -p > out.age <<< "$BACKUP_PASSPHRASE"
# перенаправление <<< подменяет вход age, и шифровался не дамп, а сама
# парольная фраза. Вдобавок age -p читает фразу только с терминала: под cron
# терминала нет, и там ветка падала вовсе, а запасной вызов с AGE_PASSPHRASE
# не спасал — age -p эту переменную не читает. Восстановимых файлов .age
# поэтому не существует, и restore.sh говорит об этом прямо.
#
# Чинить её ключом-получателем (age -r при снятии, age -i при восстановлении)
# не стали, по трём причинам. Выбор формата по наличию программы — сам по
# себе ловушка: поставь age на сервер зависимостью чего-то другого, и копии
# молча сменят формат и способ ключа. Ключ-файл age — второй секрет рядом с
# парольной фразой, а ежемесячная проверка восстановимости идёт на том же
# сервере и должна им расшифровывать, то есть лежал бы он там же, где копии, —
# выигрыша асимметричного ключа не остаётся. И рабочий сервер снимает копии
# через gpg: одна ветка — одна дорога, которую сквозная проверка
# (scripts/test/backup-roundtrip.sh) проходит целиком.
set -euo pipefail

: "${DATABASE_URL:?DATABASE_URL обязателен}"
: "${BACKUP_DIR:?BACKUP_DIR обязателен}"
: "${BACKUP_PASSPHRASE:?BACKUP_PASSPHRASE обязателен — дампы шифруются всегда}"

# Копии и каталоги — только владельцу. Прежде файл ложился 0644 и читался
# любым пользователем хоста. Шифрование этого не отменяет: файл, который
# может унести каждый, можно и перебирать офлайн сколько угодно.
umask 077

stamp="$(date +%Y-%m-%d_%H%M%S)"
day_of_week="$(date +%u)"   # 7 = воскресенье
day_of_month="$(date +%d)"

rotate=1
if [ -n "${BACKUP_KIND:-}" ]; then
  kind="$BACKUP_KIND"
  rotate=0
else
  kind="daily"
  [ "$day_of_week" = "7" ] && kind="weekly"
  [ "$day_of_month" = "01" ] && kind="monthly"
fi

dest="$BACKUP_DIR/$kind"
mkdir -p "$dest"
final="$dest/quizzy_${stamp}.dump.zst.gpg"

# Пишется во временное имя рядом и переименовывается только после проверки
# чтением. Иначе оборванный на середине снимок (место кончилось, службу
# остановили) лежал бы под обычным именем: ротация считала бы его копией и
# вытесняла им исправную, а проверка восстановимости брала бы его как самый
# свежий.
part="$final.part"
trap 'rm -f "$part"' EXIT

# Клиентские утилиты берутся той же версии, что и сервер.
#
# PG_EXEC — префикс запуска. Пусто: pg_dump с хоста. В развёртывании через
# Docker сюда ставится «docker compose exec -T postgres», и тогда дамп
# снимает тот же PostgreSQL, который хранит данные.
#
# Это не аккуратность ради аккуратности. На сервере оказался pg_dump 18 при
# базе 16 — сочетание неподдерживаемое: дамп получается, но несёт
# «SET transaction_timeout», которого шестнадцатая версия не знает, и
# восстановление идёт с ошибками. Заметно это только при восстановлении,
# то есть в тот единственный момент, когда бэкап и нужен.
PG_EXEC="${PG_EXEC:-}"

# Фраза — через дескриптор 3, а не аргументом: аргумент командной строки
# виден любому пользователю хоста в ps всё время шифрования, то есть минуты.
# --pinentry-mode loopback: без него gpg 2.1+ спрашивает фразу у pinentry, а
# не берёт переданную. --no-symkey-cache: агент gpg умеет запоминать ключ
# симметричного шифра по соли файла, а проверка чтением ниже (и ежемесячная
# проверка восстановимости) должна доказывать, что копию открывает фраза из
# окружения, а не память агента от прошлой расшифровки того же файла.
gpg_sym() {
  gpg --batch --quiet --yes --pinentry-mode loopback --no-symkey-cache \
    --passphrase-fd 3 "$@" 3<<<"$BACKUP_PASSPHRASE"
}

# Дамп идёт потоком — pg_dump → zstd → gpg, — а не через временный файл.
# Прежде custom-дамп сначала целиком ложился открытым в /tmp и шифровался
# потом: на время снимка вся база лежала на диске открытым текстом, а при
# убийстве процесса (SIGKILL, падение машины) там и оставалась. Цена потока
# одна: в архиве нет смещений блоков, и pg_restore -j (параллельно) по нему
# не пойдёт; полное восстановление — restore.sh — идёт последовательно и
# смещений не требует. --compress=0: сжимает zstd, дважды жать незачем.
# pipefail выше делает отказ любого звена отказом всего снимка.
$PG_EXEC pg_dump --format=custom --compress=0 "$DATABASE_URL" \
  | zstd -q -c \
  | gpg_sym --symmetric --cipher-algo AES256 --compress-algo none > "$part"

# Проверка чтением: «кладёт снимок и проверяет, что он читается»
# (docs/DEPLOY.md). Прежде её не было — скрипт печатал размер и считал дело
# сделанным, а размер не отличает дамп от зашифрованной парольной фразы:
# ровно так ветка age и прожила незамеченной. Мерить размер, как делал
# upgrade-instances.sh («pg_dump на недоступной базе иногда выходит нулём с
# пустым выводом»), здесь бесполезно: пустой вывод после сжатия и шифрования —
# уже не пустой файл. Отличить его может только чтение.
#
# Файл расшифровывается фразой из окружения и распаковывается ЦЕЛИКОМ: gpg
# сверяет код целостности только в конце потока, zstd — контрольную сумму
# кадра. pg_restore --list читает оглавление архива и выходит раньше конца,
# поэтому остаток дочитывает cat — иначе gpg получил бы SIGPIPE и проверка
# конца файла не состоялась бы. Число объектов в оглавлении идёт в вывод.
readback() {
  gpg_sym --decrypt "$1" | zstd -q -d -c | {
    n="$($PG_EXEC pg_restore --list | grep -c '^[0-9]')" && echo "$n"
    cat > /dev/null
  }
}
if ! entries="$(readback "$part")" || [ -z "$entries" ]; then
  echo "ОТКАЗ: снимок не читается обратно (расшифровка, распаковка или оглавление архива). Файл удалён." >&2
  exit 1
fi

mv "$part" "$final"
echo "бэкап: $final ($(du -h "$final" | awk '{print $1}'), объектов в архиве: $entries)"

# Внешняя копия — после того, как местная на месте и проверена. Отказ
# загрузки — отказ службы (ненулевой код, его видят оповещения), но местная
# копия остаётся: лучше копия без дубля снаружи, чем ни одной.
"$(dirname "$0")/offsite.sh" put "$final"

[ "$rotate" = "1" ] || exit 0

# ротация
prune() { # dir keep
  [ -d "$1" ] || return 0
  ls -1t "$1" | tail -n "+$(( $2 + 1 ))" | while read -r f; do rm -f "$1/$f"; done
}
prune "$BACKUP_DIR/daily" 7
prune "$BACKUP_DIR/weekly" 4
prune "$BACKUP_DIR/monthly" 12
