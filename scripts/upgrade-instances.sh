#!/usr/bin/env bash
#
# Обновление нескольких экземпляров.
#
# Каждое учреждение живёт в своей базе, и обновлять их по одному руками —
# это ровно та работа, где на пятом забывают шаг. Скрипт делает один и тот
# же порядок для каждого и останавливается на первом отказе.
#
# Порядок не случаен:
#   1. снимок базы — до всего, потому что откатывать нечем, если его нет
#      (тем же scripts/backup.sh, что и копии по расписанию: шифрованный и
#      проверенный чтением, в $BACKUP_DIR/upgrade/<имя>/);
#   2. миграции;
#   3. дошифровка открытых значений;
#   4. проверка, что приложение поднимается на новой схеме;
#   5. и только потом следующий экземпляр.
#
# Останавливается на первом отказе намеренно. Продолжить и обновить
# остальные значило бы получить пять учреждений в разных состояниях, из
# которых неизвестно какое рабочее.
#
#   INSTANCES=/etc/quizzy/instances.txt BACKUP_DIR=/backups BACKUP_PASSPHRASE=… \
#     ./scripts/upgrade-instances.sh
#
# Файл instances.txt — по строке на экземпляр:
#   hospital1  postgres://quizzy_app:…@localhost/quizzy_hospital1
#   hospital2  postgres://quizzy_app:…@localhost/quizzy_hospital2

set -euo pipefail

INSTANCES="${INSTANCES:-./instances.txt}"
BACKUP_DIR="${BACKUP_DIR:-}"

if [[ ! -f "$INSTANCES" ]]; then
  echo "Не найден список экземпляров: $INSTANCES" >&2
  exit 1
fi

if [[ -z "$BACKUP_DIR" ]]; then
  # Снимок обязателен, а не «желателен»: миграция, которая не откатывается,
  # без снимка означает потерянные клинические записи.
  echo "BACKUP_DIR не задан. Обновление без снимка базы не запускается." >&2
  exit 1
fi

# Проверяется до первого экземпляра, а не на нём: отказ на середине списка
# оставил бы часть учреждений обновлёнными, часть нет.
if [[ -z "${BACKUP_PASSPHRASE:-}" ]]; then
  echo "BACKUP_PASSPHRASE не задан. Снимок шифруется всегда — той же фразой, что копии по расписанию." >&2
  exit 1
fi

here="$(cd "$(dirname "$0")" && pwd)"

total=0
done_count=0

# Список читается с дескриптора 4, а не со стандартного входа. Всё внутри
# цикла наследует вход, и программа, которая его читает, съедает оставшиеся
# строки списка: с PG_EXEC="docker compose exec -T postgres" так делает
# docker exec. Цикл тогда молча кончается после первого экземпляра, а итог
# «Обновлено: 1 из 1» выглядит удачей — остальных он просто не увидел.
while read -r name url <&4; do
  [[ -z "${name:-}" || "${name:0:1}" == "#" ]] && continue
  total=$((total + 1))

  echo
  echo "── $name ──"

  # Снимок — тем же backup.sh, что и копии по расписанию. Прежде здесь был
  # свой pg_dump | gzip в обычный .sql.gz: обязательное шифрование копий
  # (backup.sh без фразы не работает вовсе) обходилось в том самом месте,
  # где снимок почти наверняка понадобится, и клинические базы учреждений
  # ложились на диск открытым текстом. Свой путь к тому же не знал ни
  # PG_EXEC (pg_dump другой версии, чем сервер), ни проверки чтением.
  snap_dir="$BACKUP_DIR/upgrade/$name"
  echo "  снимок → $snap_dir/"
  if ! DATABASE_URL="$url" BACKUP_DIR="$BACKUP_DIR" BACKUP_KIND="upgrade/$name" \
       "$here/backup.sh" | sed 's/^/  /'; then
    echo "  ОТКАЗ: снимок не сделан. Остальные экземпляры не трогаем." >&2
    exit 1
  fi
  dump="$(ls -1t "$snap_dir"/quizzy_*.dump.zst.gpg | head -1)"

  echo "  миграции"
  if ! DATABASE_URL="$url" bun run --cwd apps/api db:migrate; then
    echo "  ОТКАЗ на миграциях. Снимок здесь: $dump (восстановление — scripts/restore.sh)" >&2
    exit 1
  fi

  # Дошифровка — шагом обновления, а не памяткой в RUNBOOK.
  #
  # Бэкфилл идемпотентен: значения с заголовком enc1: он не трогает, поэтому
  # на обновлении, которому дошифровывать нечего, это лишний проход по трём
  # таблицам и ничего больше. Взамен он закрывает случаи, которые иначе
  # держатся на том, что кто-то вспомнит: даты рождения, уходившие в базу
  # открытыми до исправления регистрации, и записи, заведённые экземпляром,
  # который какое-то время работал без ключа.
  #
  # Без ключа шаг пропускается, а не роняет обновление: экземпляр без
  # ENCRYPTION_KEY до production не доходит (сервер не стартует), а вот
  # обновить тестовый стенд без ключа — нормальная работа.
  if [[ -n "${ENCRYPTION_KEY:-}" ]]; then
    echo "  дошифровка"
    if ! DATABASE_URL="$url" bun run --cwd apps/api db:encrypt; then
      echo "  ОТКАЗ на дошифровке. Снимок здесь: $dump" >&2
      exit 1
    fi
  else
    echo "  дошифровка пропущена: ENCRYPTION_KEY не задан"
  fi

  # Проверка, что приложение поднимается на новой схеме. Без неё «миграции
  # прошли» означает только «SQL выполнился»: несовпадение схемы и кода
  # вылезет у первого пользователя, а не здесь.
  echo "  проверка запуска"
  if ! DATABASE_URL="$url" bun run --cwd apps/api install:instance > /dev/null; then
    echo "  ОТКАЗ: приложение не поднимается на новой схеме. Снимок: $dump" >&2
    exit 1
  fi

  done_count=$((done_count + 1))
  echo "  готово"
done 4< "$INSTANCES"

echo
echo "Обновлено: $done_count из $total."
if [[ "$done_count" -ne "$total" ]]; then
  echo "Не все экземпляры обработаны — смотрите вывод выше." >&2
  exit 1
fi
