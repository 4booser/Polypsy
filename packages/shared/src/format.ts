import type { Lang } from "./types";

/**
 * Форматирование, общее для консоли и мобильного приложения.
 *
 * Держалось двумя копиями — в `format.ts` консоли и `theme.ts` мобилки — и
 * копии уже разошлись бы: ошибку с отрицательной длительностью пришлось бы
 * чинить дважды, а нашли бы её один раз.
 */

/**
 * Локаль Intl для языка интерфейса: по ней пишутся даты, время и числа.
 *
 * Одна запись на все приложения: консоль, мобилка и сервер (напоминания о
 * приёме) раньше держали каждый свою пару «uk-UA / ru-RU», и третья ветка
 * добавлялась бы трижды.
 *
 * Английский — en-GB, а не en-US. Дело не во вкусе, а в том, как читают эти
 * экраны. en-US пишет «9/2/2026» — месяц первым, и у всякого, кто вырос на
 * «день.месяц», это второе сентября превращается в девятое февраля: ошибка,
 * которую человек не заметит, а в карте пациента она меняет порядок замеров.
 * en-GB пишет «02/09/2026» и «2 September 2026» — день первым, как по-
 * украински, — и время в 24 часа («14:05»), а не «2:05 PM», которого в
 * расписании отделения нет нигде. Английский интерфейс читают в украинском
 * учреждении, рядом с украинскими документами, и формат дат у них должен
 * совпадать.
 */
export const LOCALE_OF: Record<Lang, string> = {
  uk: "uk-UA",
  ru: "ru-RU",
  en: "en-GB",
};

/*
 * Единицы длительности по языкам. Украинская минута — «хв»: прежде все
 * языки получали русское «мин», и в украинской консоли оно стояло
 * единственным русским словом на экране.
 */
const DURATION_UNITS: Record<Lang, { sec: string; min: string; comma: boolean }> = {
  uk: { sec: "с", min: "хв", comma: true },
  ru: { sec: "с", min: "мин", comma: true },
  en: { sec: "s", min: "min", comma: false },
};

/**
 * Длительность прохождения по-человечески: «4,2 с», «1 мин 12 с».
 *
 * Неположительное значение — это «не измерено», а не «нисколько». Ноль бывает
 * у прохождений, загруженных с бумаги; отрицательное даёт рассинхронизация
 * часов клиента и сервера. И то и другое, показанное числом, читается как
 * «ответил мгновенно» — прямо противоположный вывод, да ещё и повод для
 * флага небрежного заполнения.
 *
 * Язык — вторым аргументом, по умолчанию русский: так функция вела себя до
 * того, как узнала о языках, и вызов без языка не меняет того, что было.
 */
export function formatDuration(ms: number, lang: Lang = "ru"): string {
  if (!Number.isFinite(ms) || ms <= 0) return "—";
  const unit = DURATION_UNITS[lang];
  const sec = ms / 1000;
  const decimal = (n: string) => (unit.comma ? n.replace(".", ",") : n);
  /*
   * Граница секунд и минут — по ОКРУГЛЁННОМУ значению, а не по сырому.
   *
   * Проверка стояла на `sec < 60`, а печатались десятые: 59,96 с проходили
   * проверку и выходили «60,0 с» — секундами то, что уже минута, и на
   * сводке рядом с «1 мин» соседней строки. Та же ошибка порядка, что и с
   * «4 мин 60 с» ниже: сначала округлить, потом решать, в чём писать.
   */
  const tenths = Math.round(sec * 10);
  if (tenths < 600) {
    /*
     * Положительное, но меньше половины десятой — «< 0,1 с», а не «0,0 с»:
     * нуль в длительности значит «не измерено» (см. выше), и измеренные
     * тридцать миллисекунд не должны читаться так же.
     */
    if (tenths === 0) return `< ${decimal("0.1")} ${unit.sec}`;
    return `${decimal((tenths / 10).toFixed(1))} ${unit.sec}`;
  }
  /*
   * Округляем всю величину, а потом делим на минуты и секунды — не наоборот.
   *
   * Прежний порядок брал остаток и округлял его отдельно, поэтому 299,6 с
   * давали «4 мин 60 с»: остаток 59,6 округлялся до 60, а минуты считались
   * от неокруглённого значения. На сводке это видно каждый раз, когда
   * среднее попадает в последнюю половину секунды перед круглой минутой.
   */
  const total = Math.round(sec);
  const min = Math.floor(total / 60);
  const rest = total % 60;
  return rest ? `${min} ${unit.min} ${rest} ${unit.sec}` : `${min} ${unit.min}`;
}

/** Календарный день: «2026-03-14» */
export function formatDay(iso: string | null | undefined): string {
  return iso ? iso.slice(0, 10) : "—";
}

/** Дата и время без секунд: «2026-03-14 09:30» */
export function formatDateTime(iso: string | null | undefined): string {
  return iso ? iso.slice(0, 16).replace("T", " ") : "—";
}

/**
 * Короткие имена методик, в названии которых кода в скобках нет, — по ключу
 * каталога (surveys.catalog_key) и языку экрана. Это методики учреждения:
 * «БОО «Адаптивність-200»» (по-русски МЛО) и «Опитувальник Міні-мульт».
 * Остальные названия каталога — «Назва (КОД)», и код берётся из скобок.
 */
const SHORT_BY_KEY: Readonly<Record<string, Readonly<Record<"uk" | "ru", string>>>> = {
  mlo: { uk: "БОО", ru: "МЛО" },
  minimult: { uk: "Міні-мульт", ru: "Мини-мульт" },
};

/** Длина короткого имени, взятого из названия без кода: дальше — по границе слова */
const SHORT_MAX = 24;

/**
 * Текст не длиннее `max` знаков, обрезанный по границе слова, с многоточием.
 * Середину слова не режет: первое слово длиннее `max` остаётся целым.
 */
export function clipAtWord(text: string, max: number): string {
  const clean = text.trim().replace(/\s+/g, " ");
  if (clean.length <= max) return clean;
  const words = clean.split(" ");
  let out = words[0]!;
  let kept = 1;
  for (const w of words.slice(1)) {
    if (out.length + 1 + w.length > max - 1) break;
    out += ` ${w}`;
    kept += 1;
  }
  /* одно длинное слово — целым и без многоточия: ничего не отброшено */
  return kept === words.length ? out : `${out.replace(/[\s,.:;«(–—-]+$/, "")}…`;
}

/**
 * Короткое имя методики для строк, подписей и графиков: «PHQ-9» из
 * «Депресія (PHQ-9)».
 *
 * По порядку:
 *  1. Ключ каталога — из таблицы коротких имён (методики учреждения).
 *  2. Последняя скобка в конце названия, если в ней код или имя, — есть
 *     заглавная буква или цифра, регистр и длина кода не важны: «PHQ-9»,
 *     «CIWA-Ar», «Brief COPE», «Flourishing Scale», «СР-45», «шкала
 *     Розенберга» (с заглавной). Из «SRQ-20, ВООЗ» — первая часть. «(демо)» —
 *     пометка, а не имя.
 *  3. Код в начале названия перед точкой или двоеточием: «СР-45.
 *     Схильність до суїцидальних реакцій».
 *  4. Сокращение перед названием в кавычках: «БОО «Адаптивність-200»».
 *  5. Само название, а длинное — по границе слова с многоточием.
 *
 * Прежняя разборка брала скобку не длиннее 16 знаков и только прописными, а
 * иначе — название до первой точки: над графиком стояло «Ознаки СДУГ у
 * дорослих (ASRS-v1», а у CIWA-Ar, Brief COPE, RSES и Flourishing кодом
 * становилось название целиком.
 */
export function instrumentCode(title: string, opts: { catalogKey?: string | null; lang?: Lang } = {}): string {
  const key = opts.catalogKey;
  const byKey = key && Object.hasOwn(SHORT_BY_KEY, key) ? SHORT_BY_KEY[key] : undefined;
  if (byKey) return byKey[opts.lang === "ru" ? "ru" : "uk"];
  const clean = title.trim().replace(/\s+/g, " ");
  const paren = /\(([^()]+)\)$/.exec(clean)?.[1]?.split(",")[0]?.trim();
  if (paren && paren.length <= SHORT_MAX && /[A-ZА-ЯІЇЄҐ0-9]/.test(paren)) {
    return paren.charAt(0).toLocaleUpperCase() + paren.slice(1);
  }
  const head = /^([A-ZА-ЯІЇЄҐ0-9][A-ZА-ЯІЇЄҐ0-9-]{1,11})[.:]\s/.exec(clean)?.[1];
  if (head) return head;
  const abbr = /^([A-ZА-ЯІЇЄҐ]{2,6})\s+[«"„]/.exec(clean)?.[1];
  if (abbr) return abbr;
  return clipAtWord(clean, SHORT_MAX);
}
