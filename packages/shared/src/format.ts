import type { Lang } from "./types";

/**
 * Форматирование, общее для консоли и мобильного приложения.
 *
 * Держалось двумя копиями — в `format.ts` консоли и `theme.ts` мобилки — и
 * копии уже разошлись бы: ошибку с отрицательной длительностью пришлось бы
 * чинить дважды, а нашли бы её один раз.
 */

/**
 * Локаль Intl для языка интерфейса: по ней пишутся даты, время и числа.
 *
 * Одна запись на все приложения: консоль, мобилка и сервер (напоминания о
 * приёме) раньше держали каждый свою пару «uk-UA / ru-RU», и третья ветка
 * добавлялась бы трижды.
 *
 * Английский — en-GB, а не en-US. Дело не во вкусе, а в том, как читают эти
 * экраны. en-US пишет «9/2/2026» — месяц первым, и у всякого, кто вырос на
 * «день.месяц», это второе сентября превращается в девятое февраля: ошибка,
 * которую человек не заметит, а в карте пациента она меняет порядок замеров.
 * en-GB пишет «02/09/2026» и «2 September 2026» — день первым, как по-
 * украински, — и время в 24 часа («14:05»), а не «2:05 PM», которого в
 * расписании отделения нет нигде. Английский интерфейс читают в украинском
 * учреждении, рядом с украинскими документами, и формат дат у них должен
 * совпадать.
 */
export const LOCALE_OF: Record<Lang, string> = {
  uk: "uk-UA",
  ru: "ru-RU",
  en: "en-GB",
};

/*
 * Единицы длительности по языкам. Украинская минута — «хв»: прежде все
 * языки получали русское «мин», и в украинской консоли оно стояло
 * единственным русским словом на экране.
 */
const DURATION_UNITS: Record<Lang, { sec: string; min: string; comma: boolean }> = {
  uk: { sec: "с", min: "хв", comma: true },
  ru: { sec: "с", min: "мин", comma: true },
  en: { sec: "s", min: "min", comma: false },
};

/**
 * Длительность прохождения по-человечески: «4,2 с», «1 мин 12 с».
 *
 * Неположительное значение — это «не измерено», а не «нисколько». Ноль бывает
 * у прохождений, загруженных с бумаги; отрицательное даёт рассинхронизация
 * часов клиента и сервера. И то и другое, показанное числом, читается как
 * «ответил мгновенно» — прямо противоположный вывод, да ещё и повод для
 * флага небрежного заполнения.
 *
 * Язык — вторым аргументом, по умолчанию русский: так функция вела себя до
 * того, как узнала о языках, и вызов без языка не меняет того, что было.
 */
export function formatDuration(ms: number, lang: Lang = "ru"): string {
  if (!Number.isFinite(ms) || ms <= 0) return "—";
  const unit = DURATION_UNITS[lang];
  const sec = ms / 1000;
  if (sec < 60) {
    const n = sec.toFixed(1);
    return `${unit.comma ? n.replace(".", ",") : n} ${unit.sec}`;
  }
  /*
   * Округляем всю величину, а потом делим на минуты и секунды — не наоборот.
   *
   * Прежний порядок брал остаток и округлял его отдельно, поэтому 299,6 с
   * давали «4 мин 60 с»: остаток 59,6 округлялся до 60, а минуты считались
   * от неокруглённого значения. На сводке это видно каждый раз, когда
   * среднее попадает в последнюю половину секунды перед круглой минутой.
   */
  const total = Math.round(sec);
  const min = Math.floor(total / 60);
  const rest = total % 60;
  return rest ? `${min} ${unit.min} ${rest} ${unit.sec}` : `${min} ${unit.min}`;
}

/** Календарный день: «2026-03-14» */
export function formatDay(iso: string | null | undefined): string {
  return iso ? iso.slice(0, 10) : "—";
}

/** Дата и время без секунд: «2026-03-14 09:30» */
export function formatDateTime(iso: string | null | undefined): string {
  return iso ? iso.slice(0, 16).replace("T", " ") : "—";
}
