/*
 * Пункты рельсы, которые человек не может убрать с глаз.
 *
 * Скрывать пункты можно и нужно: рельса на тринадцать разделов стоит
 * внимания при каждом открытии консоли, а половиной из них конкретный
 * специалист не пользуется. Но три из них носят не раздел, а СИГНАЛ: рядом с
 * ними стоит число — сколько случаев риска не разобрано, сколько задач в
 * очереди, сколько человек ждёт сегодня. Спрятав такой пункт, человек прячет
 * не меню, а знание о том, что его ждёт работа; в психологическом отделении
 * это ровно то, ради чего всё и написано.
 *
 * Поэтому список живёт в общем пакете рядом с правами, а не в настройках
 * внешнего вида: это правило безопасности, а не вкус. На экране настроек
 * такие пункты показаны с объяснением, а не просто без галочки, — иначе
 * человек решит, что это поломка, и пойдёт искать обход.
 *
 * Своим модулем, а не в permissions.ts (волна 27, perf-bundle): рельса
 * консоли стоит в начальном куске, и ей нужен только этот список, а модуль
 * прав потянул бы туда же справочник прав на трёх языках.
 */
export const ALWAYS_VISIBLE_RAIL = ["nav.dashboard", "nav.worklist", "nav.cases"] as const;

/**
 * Віджети «Зведення» (Polypsy 2.0, pages/Dashboard.tsx) — в порядке по
 * умолчанию.
 *
 * Порядок и выключенные хранятся в профиле (WorkspacePrefs.dashboard), а не
 * в браузере: сотрудник садится за разные машины отделения.
 */
export const DASH_WIDGETS = ["cases", "day", "missed", "work", "passes", "collect", "conditions"] as const;
export type DashWidget = (typeof DASH_WIDGETS)[number];

/**
 * Віджет, который не выключается: случаи риска. Правило то же, что у
 * ALWAYS_VISIBLE_RAIL, — спрятав его, человек прячет не блок, а знание о
 * неразобранном сигнале, и потому проверка стоит в схеме, а не только на
 * экране настроек.
 */
export const ALWAYS_VISIBLE_WIDGETS = ["cases"] as const;
