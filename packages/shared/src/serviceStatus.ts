/**
 * Состояние системы для людей: «працює / обслуговування / збої».
 *
 * Решение заказчика 2026-09-26 (техпанель, пункты 8 и 10): страница статуса
 * для сотрудников и режим обслуживания одной кнопкой.
 *
 * Три состояния, и различаются они не цветом, а тем, что происходит с
 * работой:
 *
 * - `ok` — работает;
 * - `maintenance` — идут работы: чтение открыто, запись закрыта (сервер
 *   отвечает 503 на всё изменяющее, кроме техпанели и входа);
 * - `degraded` — сбои: сервер работает, но с перебоями, о которых люди
 *   должны знать. Запись при этом НЕ закрывается: закрыть её — значит
 *   потерять то, что ещё могло бы сохраниться.
 */
export const SERVICE_STATUSES = ["ok", "maintenance", "degraded"] as const;
export type ServiceStatus = (typeof SERVICE_STATUSES)[number];

/* Схема объявления (serviceStatusInputSchema) — в wireSchemas.ts, по той же причине, что у пачки счётчиков */

/** Код отказа в теле ответа: клиенты узнают по нему закрытую запись */
export const MAINTENANCE_CODE = "maintenance";

/**
 * Временный отказ: повторить позже, а не разбирать руками.
 *
 * 0 — до сервера не дошли (нет сети). 502 и 504 — прокси перед приложением
 * не дождался его: так выглядит перезапуск контейнера при выкатке. 503 —
 * приложение само сказало «сейчас нельзя»: режим обслуживания или
 * недоступная база.
 *
 * Отдельной функцией в общем пакете, а не проверкой `status === 0` на
 * местах: очередь несданных ответов в мобилке и в веб-кабинете решает по ней
 * одно и то же — положить сдачу ждать или пометить отказом. До режима
 * обслуживания повторяемым был только обрыв сети, и 503 помечал сдачу
 * «отклонённой сервером»: она ждала разбора человеком, которого не будет.
 *
 * 500 сюда не входит намеренно: это ошибка в коде, и повтор той же сдачи
 * упрётся в ту же ошибку — вечный повтор хуже честной пометки. Но и
 * приговором с первого раза он не будет: см. retriesServerFailure.
 */
export function isTransientStatus(status: number): boolean {
  return status === 0 || status === 502 || status === 503 || status === 504;
}

/**
 * Сколько раз сервер может упасть на одной сдаче очереди, прежде чем она
 * станет отвергнутой (#172, #201). Один порог на мобилку и веб-кабинет:
 * мобилка помечала сдачу отклонённой с первого же 500, веб — после пяти, и
 * одна и та же сдача на двух устройствах вела себя по-разному.
 */
export const SERVER_FAILURES_MAX = 5;

/**
 * Сбой сервера на сдаче очереди (500 и прочие 5xx, кроме временных) —
 * повторить её следующим проходом? Разовый 500 при досылке — не приговор:
 * следующий проход её обычно принимает. Но битая сдача не должна ни держать
 * очередь, ни крутиться вечно: после SERVER_FAILURES_MAX падений — отказ.
 *
 * `attempts` — сколько раз сервер упал на этой сдаче, считая этот раз.
 */
export function retriesServerFailure(status: number, attempts: number): boolean {
  return status >= 500 && attempts < SERVER_FAILURES_MAX;
}
