/** Право вместе с тем, что оно открывает, — в порядке справочника */
export interface UnlockedEffect extends PermissionEffect {
  permission: Permission;
}

/**
 * Что откроется, если выдать этот набор прав.
 *
 * Порядок берётся из справочника, а не из того, в каком порядке человек
 * расставлял галочки: список, который переставляется от каждого нажатия,
 * читать нельзя — глаз каждый раз ищет заново.
 */
export function effectsOf(permissions: Iterable<Permission>): UnlockedEffect[] {
  const have = new Set(permissions);
  return ALL_PERMISSIONS.filter((p) => have.has(p)).map((permission) => ({
    permission,
    ...PERMISSION_EFFECTS[permission],
  }));
}

/**
 * Набор прав встроенной роли «Психолог».
 *
 * Ровно то, что сегодня может администратор группы, плюс работа с приёмом:
 * своё расписание и запись пациентов — это и есть повседневная работа
 * специалиста, отбирать её у него незачем.
 *
 * Отделения и профили специалистов в набор не входят: завести отделение,
 * посадить в него человека и назначить ему кабинет — это устройство
 * учреждения, а не приём. Ошибка здесь переставляет всех, а не одного. Нужен, чтобы бэкфилл не
 * изменил поведение ни одной действующей учётной записи: сегодня «админ
 * группы» означает «всё, кроме суперадминских вещей», и роль обязана
 * означать то же самое — иначе переход на права начнётся с того, что у людей
 * пропадут возможности, которыми они пользовались вчера.
 *
 * Техпанель (ops.read и ops.manage) в набор тоже не входит. Набор собран вычитанием из
 * всех прав, и новое право попадало в него само: каждый клинический
 * администратор получил бы логи, ошибки и состояние базы, которых вчера не
 * видел, — ровно обратное «ничего не меняется». Панель выдаётся
 * разработчику личным исключением (группа «Технічна служба»).
 */
/*
 * Техпанель (ops.read, ops.manage) в набор тоже не входит. Набор собран
 * вычитанием из всего справочника, и новое право попадает в него само, если
 * его не назвать здесь: так ops.read молча досталось бы каждому
 * администратору группы — а техпанель выдаётся разработчику личным
 * исключением (группа «Технічна служба»), а не всем, кто ведёт пациентов.
 */
/*
 * Техническая служба (ops.read, ops.manage) в набор не входит.
 *
 * Набор выводится вычитанием из ALL_PERMISSIONS, и новая группа прав
 * попадает в него сама, если её не вычесть. С ops.* так и вышло: заведённые
 * в волне 10, они молча легли каждому психологу — а ops.manage закрывает
 * запись всей системе режимом обслуживания и переключает флаги функций.
 * syncBuiltinRole при старте снимет их с роли у тех, кому они уже выданы.
 * Техпанель выдаётся разработчику личным исключением (см. группу «ops»).
 */
