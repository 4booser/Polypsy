/**
 * Лестница должностей: кто кого назначает.
 *
 * Снизу вверх. Технический суперадмин назначает главного врача, главный врач —
 * заведующего отделением, заведующий — специалиста. Коды совпадают с ролями,
 * заведёнными миграцией 0071_staff_roles.sql.
 *
 * Порядок здесь — единственный источник старшинства. В базе роли лежат
 * плоским списком, и старшинство из него не выводится: набор прав для этого
 * не годится. Роль с бо́льшим числом прав не обязана быть старше — «психолог»
 * шире специалиста, но никого не назначает вовсе, — а сравнивать роли по
 * включению наборов значило бы, что снятая у заведующего галочка молча
 * превращает его в специалиста и лишает права назначать.
 *
 * Роли вне лестницы (встроенный «психолог», заведённые учреждением) старшинства
 * не имеют вовсе и назначаются только суперадмином: их состав произволен, и
 * заведующий, которому позволили бы раздавать произвольную роль, раздал бы
 * вместе с ней всё, что в неё положили.
 */
export const ROLE_LADDER = ["specialist", "head", "chief"] as const;

export type LadderRole = (typeof ROLE_LADDER)[number];

/**
 * Ранг суперадмина — на ступень выше всей лестницы.
 *
 * Не «бесконечность» и не отдельная ветка в коде: суперадмин стоит в том же
 * ряду, просто выше главного врача. Иначе правило «назначаю только ниже себя»
 * пришлось бы писать дважды — один раз для лестницы, другой для суперадмина, —
 * и две записи одного правила разошлись бы.
 */
export const SUPERADMIN_RANK = ROLE_LADDER.length + 1;

/** Ступень роли; 0 — роль вне лестницы, старшинства у неё нет */
export function roleRank(code: string): number {
  const at = ROLE_LADDER.indexOf(code as LadderRole);
  return at < 0 ? 0 : at + 1;
}

/**
 * Может ли человек своей ступени назначить эту роль.
 *
 * Строго ниже, а не «не выше». Равный уровень — это назначение себе подобного:
 * главный врач, назначивший второго главного врача, получает того, кто вправе
 * назначить третьего, и лестница перестаёт быть лестницей уже на втором шаге.
 * Кому нужен второй главный врач, тот идёт к техническому администратору, и
 * это одно действие в год, а не дыра навсегда.
 *
 * Само по себе это условие ничего не защищает: настоящая проверка стоит на
 * сервере, в маршруте назначения ролей. Здесь оно живёт общим для сервера и
 * экрана, чтобы кнопка и отказ не разъезжались.
 */
export function canAssignRole(actorRank: number, roleCode: string): boolean {
  const rank = roleRank(roleCode);
  return rank > 0 && rank < actorRank;
}

/*
 * Пункты рельсы, которые человек не может убрать с глаз.
 *
 * Скрывать пункты можно и нужно: рельса на тринадцать разделов стоит
 * внимания при каждом открытии консоли, а половиной из них конкретный
 * специалист не пользуется. Но три из них носят не раздел, а СИГНАЛ: рядом с
 * ними стоит число — сколько случаев риска не разобрано, сколько задач в
 * очереди, сколько человек ждёт сегодня. Спрятав такой пункт, человек прячет
 * не меню, а знание о том, что его ждёт работа; в психологическом отделении
 * это ровно то, ради чего всё и написано.
 *
 * Поэтому список живёт здесь, рядом с правами, а не в настройках внешнего
 * вида: это правило безопасности, а не вкус. На экране настроек такие пункты
 * показаны с объяснением, а не просто без галочки, — иначе человек решит,
 * что это поломка, и пойдёт искать обход.
 */
