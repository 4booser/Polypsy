/**
 * Что право открывает на деле.
 *
 * PERMISSION_TITLES отвечает на вопрос «как это право называется», а этот
 * справочник — на вопрос, который на самом деле задают, собирая роль: «что
 * человек увидит и сможет, когда я поставлю эту галочку». Разница не
 * косметическая. «Смотреть аналитику методик» звучит безобидно ровно до того
 * момента, когда выясняется, что вместе с ней открывается качество данных по
 * каждому пункту; «Вести обращения» не говорит ничего о диспансерном учёте,
 * хотя закрывает и его.
 *
 * Вид отделён от текста, потому что собирающий роль думает тремя разными
 * вопросами: какие разделы меню появятся, какие цифры об учреждении станут
 * видны и что человек сможет сделать руками. Первое — вопрос ориентации,
 * второе — вопрос доступа к данным по всему учреждению, третье — вопрос
 * ответственности. Смешанные в один список, они читаются как ровный перечень,
 * в котором «Раздел «Методики»» и «Выгрузка прохождений с именами» весят
 * одинаково.
 *
 * Справочник живёт здесь, рядом со списком прав, а не на экране: экранов у
 * словаря два (консоль и, когда дойдут руки, мобильное приложение), а список
 * прав один. Полнота проверяется тестом — право без пояснения означало бы
 * галочку, про которую на экране написано только «console.use».
 */
export type PermissionEffectKind = "screen" | "analysis" | "action";

export interface PermissionEffect {
  kind: PermissionEffectKind;
  /** Что именно появится — теми словами, какими это названо на экране */
  opens: CatalogText;
}

