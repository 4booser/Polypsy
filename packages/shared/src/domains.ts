/**
 * Направление методики — «что она измеряет» на полке каталога.
 *
 * Зачем отдельное поле, а не папки. Папка принадлежит группе методик
 * (survey_folders.group_id NOT NULL), а методики общего каталога ставятся
 * без группы (groupId null): разложить их по папкам нельзя, и полтора-два
 * десятка новых инструментов на волну легли бы в каталог одной длинной
 * лентой. Направление — свойство самой методики: оно одно на все
 * учреждения, его задаёт каталог (apps/api/src/instruments/catalogDomains.ts),
 * а методике, заведённой в учреждении, его выбирает конструктор.
 *
 * Перечень закрытый и короткий намеренно: фильтр каталога — это чипы с
 * числами в одну-две строки, а не дерево. Подписи — в словаре оболочки
 * (`dom.<значение>`, uiStrings.ts), а не здесь: общий пакет кириллицы вне
 * словарей не держит (apps/api/test/noRawStrings.test.ts). То же перечисление
 * держит база — ограничением surveys_domain_check (миграция 0133): новое
 * направление заводится миграцией, а не опечаткой в карте каталога.
 *
 *   distress    — настроение, тревога, дистресс;
 *   trauma      — травма и её последствия;
 *   suicide     — суицидальный риск;
 *   sleep       — сон;
 *   addiction   — зависимости;
 *   wellbeing   — ресурсы и качество жизни: благополучие, поддержка, совладание;
 *   cognitive   — когнитивные функции и внимание;
 *   personality — личность;
 *   staff       — персонал: выгорание и рабочий стресс;
 *   other       — прочее, что в перечисленное не ложится.
 *
 * null у методики — направление не выбрано (ещё не разобрано), это не то же,
 * что `other`.
 *
 * Не путать с CONDITION_DOMAINS (apps/api/src/lib/conditions.ts): там
 * направления сводки состояния пациентов — по шкалам (депрессия — PHQ-9 и
 * D у DASS-42), здесь — полка каталога по методике целиком.
 */
export const SURVEY_DOMAINS = [
  "distress",
  "trauma",
  "suicide",
  "sleep",
  "addiction",
  "wellbeing",
  "cognitive",
  "personality",
  "staff",
  "other",
] as const;

export type SurveyDomain = (typeof SURVEY_DOMAINS)[number];

/** Пришедшее снаружи (параметр, тело, строка базы) — одно из направлений? */
export function isSurveyDomain(value: unknown): value is SurveyDomain {
  return typeof value === "string" && (SURVEY_DOMAINS as readonly string[]).includes(value);
}

/**
 * Значение фильтра каталога «без направления» (?domain=none): методики, у
 * которых направление не выбрано. Отдельным словом, а не пустым параметром:
 * пустой параметр значит «фильтра нет».
 */
export const NO_DOMAIN = "none";
