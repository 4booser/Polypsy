/**
 * Приведение баллов между версиями методики.
 *
 * Версия методики иммутабельна, и это правильно: прохождение всегда знает, что
 * человек видел. Но у этого есть следствие, о котором до сих пор молчали —
 * баллы разных версий формально несравнимы, а график рисует их в один ряд.
 * Правку одного пункта видно как «динамику».
 *
 * Здесь — линейное приведение по моментам (mean–sigma linking): балл старой
 * версии переводится в шкалу новой так, чтобы совпали среднее и разброс:
 *
 *   x' = (SD_к / SD_из) · (x − M_из) + M_к
 *
 * ## Чего это НЕ делает
 *
 * Приведение не превращает разные измерения в одно. Оно опирается на
 * допущение, которое здесь названо прямо, потому что от него зависит, врёт
 * результат или нет: **выборки двух версий считаются сопоставимыми**. Если
 * версию сменили одновременно со сменой контингента — скажем, перешли с
 * призыва на контракт, — вся разница между группами уедет в коэффициенты, и
 * приведённый балл будет описывать не человека, а смену набора.
 *
 * Поэтому приведение не применяется молча. Оно возвращает и коэффициенты, и
 * размеры выборок, а решение показывать приведённый балл принимает тот, кто
 * знает, менялся ли контингент.
 *
 * ## Почему не эквипроцентильное
 *
 * Эквипроцентильное приведение точнее на маленьких выборках лишь на вид: оно
 * повторяет форму распределения, включая её случайные неровности, и требует
 * сглаживания, у которого свои параметры и свои способы соврать. Линейное
 * приведение с двумя явными числами проверяемо глазами — а это здесь важнее
 * лишней доли точности.
 */

export interface VersionMoments {
  /** Номер версии методики */
  version: number;
  n: number;
  mean: number;
  sd: number;
}

export interface Equating {
  /** Коэффициент масштаба SD_к / SD_из */
  slope: number;
  /** Сдвиг после масштабирования */
  intercept: number;
  from: VersionMoments;
  to: VersionMoments;
}

/**
 * Минимальный размер выборки версии.
 *
 * Тридцать — не ритуальное число: ниже этого стандартная ошибка SD такова, что
 * коэффициент масштаба гуляет на десятки процентов, и приведение начинает
 * добавлять больше шума, чем убирает несравнимости.
 */
export const MIN_EQUATING_SAMPLE = 30;

/**
 * Коэффициенты приведения, либо null — если считать не из чего.
 *
 * Null возвращается честно и часто: малая выборка, нулевой разброс (все
 * ответили одинаково), одна и та же версия. Во всех этих случаях правильный
 * ответ — «приводить нельзя», а не «приведено с коэффициентом 1».
 */
export function equate(from: VersionMoments, to: VersionMoments): Equating | null {
  if (from.version === to.version) return null;
  if (from.n < MIN_EQUATING_SAMPLE || to.n < MIN_EQUATING_SAMPLE) return null;
  if (!Number.isFinite(from.sd) || !Number.isFinite(to.sd)) return null;
  // нулевой разброс: делить не на что, и «шкалы» в этой версии фактически нет
  if (from.sd <= 0 || to.sd <= 0) return null;

  /*
   * Коэффициенты не округляются. Округлить множитель значит внести ошибку в
   * каждый приведённый балл, причём тем большую, чем дальше балл от среднего.
   * Округление — дело показа, и оно происходит там, где число печатают.
   */
  const slope = to.sd / from.sd;
  return {
    slope,
    intercept: to.mean - slope * from.mean,
    from,
    to,
  };
}

/** Балл, приведённый к целевой версии */
export function applyEquating(value: number, eq: Equating): number {
  return round(eq.slope * value + eq.intercept);
}

/**
 * Насколько приведение сдвинуло балл.
 *
 * Нужно, чтобы показать человеку цену приведения: сдвиг в полбалла — деталь,
 * сдвиг в пять баллов означает, что версии различаются сильно и «динамика»
 * между ними была бы выдумкой.
 */
export function equatingShift(value: number, eq: Equating): number {
  return round(applyEquating(value, eq) - value);
}

function round(x: number): number {
  return Math.round(x * 1000) / 1000;
}
