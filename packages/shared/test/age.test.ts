import { afterAll, describe, expect, test } from "bun:test";
import { ageAt } from "../src/types";

/**
 * Возраст — календарным днём в заданном поясе, а не по часам процесса
 * (волна 15, доработка участка reports).
 *
 * Было: ageAt брал числа месяца локальными геттерами Date — по поясу
 * ПРОЦЕССА — и у даты рождения, и у момента. Дата рождения «2001-09-28»
 * читалась как полночь по Гринвичу, то есть западнее Гринвича — как
 * 27 сентября; момент сдачи — днём процесса, а не учреждения. По этому
 * возрасту при сдаче выбираются нормы (T-балл, полоса) и пишется
 * возрастная полоса прохождения, по нему же SPSS выгружает возраст: на
 * сервере в UTC человек, сдавший в свой день рождения в 00:30 по Киеву,
 * получал нормы прежнего возраста.
 *
 * Стало: ageAt(рождение, момент, пояс) — рождение числами календаря, без
 * перевода поясов; момент — календарным днём в поясе, который назвал
 * вызывающий (сервер — пояс учреждения). Проверяется под тремя поясами
 * процесса: ответ от них не зависит.
 */

const PROCESS_ZONES = ["UTC", "America/Los_Angeles", "Pacific/Kiritimati"];
const saved = process.env.TZ;

afterAll(() => {
  if (saved === undefined) delete process.env.TZ;
  else process.env.TZ = saved;
});

describe("ageAt: календарный день пояса, а не часы процесса", () => {
  for (const zone of PROCESS_ZONES) {
    test(`пояс процесса ${zone}`, () => {
      process.env.TZ = zone;

      /* 27.09 22:30 UTC — в Киеве уже 28.09, 01:30: двадцатипятилетие наступило; в Лос-Анджелесе ещё 27.09 */
      expect(ageAt("2001-09-28", "2026-09-27T22:30:00.000Z", "Europe/Kyiv")).toBe(25);
      expect(ageAt("2001-09-28", "2026-09-27T22:30:00.000Z", "America/Los_Angeles")).toBe(24);

      /* 28.09 12:00 UTC — и в Киеве, и в Лос-Анджелесе 28.09: день рождения 29.09 ещё впереди */
      expect(ageAt("2001-09-29", "2026-09-28T12:00:00.000Z", "Europe/Kyiv")).toBe(24);
      expect(ageAt("2001-09-29", "2026-09-28T12:00:00.000Z", "America/Los_Angeles")).toBe(24);

      /* день без времени — как есть, пояс его не двигает */
      expect(ageAt("2001-09-28", "2026-09-28", "Pacific/Kiritimati")).toBe(25);
      expect(ageAt("2001-09-28", "2026-09-27", "Pacific/Kiritimati")).toBe(24);

      /* 29 февраля: в невисокосный год день рождения наступает 1 марта */
      expect(ageAt("2000-02-29", "2026-02-28T12:00:00.000Z", "Europe/Kyiv")).toBe(25);
      expect(ageAt("2000-02-29", "2026-03-01T12:00:00.000Z", "Europe/Kyiv")).toBe(26);
    });
  }

  test("пусто, мусор и невозможный возраст — null", () => {
    expect(ageAt(null, "2026-09-28T12:00:00.000Z", "Europe/Kyiv")).toBeNull();
    expect(ageAt("2001-09-28", null, "Europe/Kyiv")).toBeNull();
    expect(ageAt("не дата", "2026-09-28T12:00:00.000Z", "Europe/Kyiv")).toBeNull();
    expect(ageAt("2001-09-28", "не момент", "Europe/Kyiv")).toBeNull();
    expect(ageAt("2030-01-01", "2026-09-28T12:00:00.000Z", "Europe/Kyiv")).toBeNull();
  });

  test("рождение с временем (старая запись мимо схемы) — днём по Гринвичу, как записано", () => {
    process.env.TZ = "America/Los_Angeles";
    expect(ageAt("2001-09-28T00:00:00.000Z", "2026-09-27T22:30:00.000Z", "Europe/Kyiv")).toBe(25);
  });
});
