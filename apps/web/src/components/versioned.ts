import { ApiError } from "../api";

/**
 * Подпись версионной записи — заключения и заметки приёма.
 *
 * Оба редактора устроены одинаково: черновик правится на месте (растёт
 * редакция), подпись фиксирует версию навсегда, а подписывается ровно та
 * версия и редакция, которую человек видел. Логика «что уйдёт на сервер по
 * кнопке» жила в обработчике нажатия каждого редактора — и проверить её
 * можно было только в браузере, руками, с двумя учётными записями. Здесь
 * она чистая: переходы формы проверяются тестом (test/signFlow.test.ts).
 */

/** Что общего у версии заключения и версии заметки */
export interface VersionLike {
  version: number;
  revision: number;
  status: "draft" | "signed";
  text: string;
}

export interface VersionedState<V extends VersionLike = VersionLike> {
  current: V | null;
  versions: V[];
}

/** Черновик, если последняя версия — черновик; подписанная правится только новой версией поверх */
export function draftOf<V extends VersionLike>(state: VersionedState<V>): V | null {
  return state.current?.status === "draft" ? state.current : null;
}

export interface SignPlan {
  /** Кнопку «підписати» можно нажать */
  canSign: boolean;
  /** Перед подписью набранное нужно сохранить: на сервере лежит не то, что на экране */
  save: boolean;
}

/**
 * Что сделает «підписати» с тем, что сейчас на экране.
 *
 * Подписывается текст в поле — и только он. Поле пустое (или одни пробелы)
 * — подписывать нечего, даже если на сервере лежит черновик: прежде кнопка
 * в этом случае оставалась живой и подписывала сохранённый черновик, которого
 * на экране уже не было. Специалист стирал текст, чтобы написать заново, —
 * и под его подписью уходил стёртый. Подпись удостоверяет то, что прочитано,
 * а не то, что лежит где-то ещё.
 *
 * Сохранить перед подписью нужно, когда текст отличается от черновика — или
 * отличается что-то ещё, что сохраняется вместе с ним (`sameRest: false`):
 * у заметки это вид записи. Сменили «сесія» на «консультація», текст не
 * трогали — без сохранения подписалась бы прежняя «сесія».
 */
export function signPlan(text: string, draft: Pick<VersionLike, "text"> | null, sameRest = true): SignPlan {
  const filled = text.trim().length > 0;
  return {
    canSign: filled,
    save: filled && (draft === null || text !== draft.text || !sameRest),
  };
}

/**
 * Есть ли что сохранять черновиком. Пустой текст сервер не примет (400 с
 * технической строкой разбора тела), а текст из одних пробелов примет — и
 * ляжет пустой черновик поверх настоящего. Поэтому кнопка просто гаснет.
 */
export function draftSavable(text: string): boolean {
  return text.trim().length > 0;
}

export interface SignIo<S extends VersionedState> {
  /** Сохранить набранное — ответ: новое состояние записи с новой редакцией */
  save: () => Promise<S>;
  /** Подписать ровно ту версию и редакцию, что передана */
  sign: (seen: Pick<VersionLike, "version" | "revision">) => Promise<S>;
  /** Положить состояние на экран */
  apply: (next: S) => void;
}

/**
 * Сохранить (если нужно) и подписать.
 *
 * Сохранение, которое прошло, ложится на экран сразу — до подписи, а не
 * вместе с ней. Прежде оно ложилось только с подписью, и если подпись не
 * удавалась (у стажёра нет права conclusions.sign, оборвалась связь, сервер
 * перезапускали), экран оставался с редакцией ДО сохранения. Следующая
 * попытка — и сохранение, и «Зберегти чернетку» — уходила с устаревшей
 * редакцией и получала 409 «заключение изменили, пока оно было открыто»:
 * человек упирался в конфликт с самим собой, а кнопка «перечитати» стирала
 * набранное.
 */
export async function saveThenSign<S extends VersionedState>(state: S, plan: SignPlan, io: SignIo<S>): Promise<S> {
  let latest = state;
  if (plan.save) {
    latest = await io.save();
    io.apply(latest);
  }
  const signed = await io.sign(latest.current!);
  io.apply(signed);
  return signed;
}

/**
 * Отказ 409 — запись переписали, пока она была открыта: текст сервера для
 * строки «перечитати». Прочие отказы сюда не относятся (null) — их показывает
 * всплывающее сообщение действия, как любую ошибку.
 */
export function staleMessage(error: unknown): string | null {
  return error instanceof ApiError && error.status === 409 ? error.message : null;
}
