import { dayKey } from "../format";

/**
 * Срок из поля даты — у назначения набора, у выдачи методики человеку,
 * выборке и группе.
 *
 * Сервер читает дату как «до конца этого дня по поясу учреждения»
 * (apps/api/src/lib/day.ts, deadlineOf) и прошедшую дату не отвергает. А
 * прошедший срок — не срок: назначение рождается просроченным (в очереди
 * наборов — красной строкой «прострочено»), а доступ к методикам,
 * выданный до вчерашнего вечера, истёк раньше, чем человек о нём узнал, —
 * методика в его кабинете просто не появится. Опечатка в годе («2025»
 * вместо «2026») делала ровно это, и ни один экран об этом не говорил.
 * Поэтому такая дата не отправляется, а поле говорит, что с ней не так.
 */

/** Сегодня по часам консоли, «YYYY-MM-DD» — в том же виде, что значение поля даты */
export function today(now: number = Date.now()): string {
  return dayKey(new Date(now).toISOString());
}

/** Срок в прошлом: вчера и раньше. Сегодня — можно: это «до конца сегодняшнего дня». Пусто — «без срока» */
export function pastDeadline(value: string, todayKey: string): boolean {
  return value !== "" && value < todayKey;
}
