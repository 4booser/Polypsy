/**
 * Границы вертикальной оси.
 *
 * Ось строилась по теоретическому диапазону величины: у динамики шкалы это
 * было `0..maxScore`, то есть 0–27 у PHQ-9 и 0–80 у PCL-5. Настоящие баллы в
 * такой диапазон не попадают: на демонстрационной базе из 159 рядов динамики
 * данные занимали в среднем пятую часть высоты поля, а две трети рядов —
 * меньше пятой. Все линии прижимались к низу и становились похожи одна на
 * другую. «Аналитика выглядит одинаково» — это ровно оно: одинаково выглядит
 * не аналитика, а пустое поле над ней.
 *
 * Чинится это подгонкой оси под данные, но подгонка сама по себе — способ
 * соврать: срезав низ, любой шум можно превратить в обвал. Поэтому здесь три
 * правила, и все три обязательны вместе.
 *
 * 1. Верх оси идёт по данным, а не по теории. Это безопасно: ноль остаётся на
 *    месте, пропорции сохраняются, исчезает только пустота сверху. Одной этой
 *    меры хватает в большинстве случаев — на той же базе занятая высота
 *    выросла с 19% до 56%.
 * 2. Низ срезается только там, где под данными действительно пусто и разброс
 *    узок. Если ряд начинается почти от нуля, срезать нечего, и трогать ноль
 *    без нужды нельзя.
 * 3. У среза есть предел: окно не уже, чем `atom` — наименьшая разница,
 *    которую вообще стоит считать разницей. Для замеров это ошибка измерения:
 *    растягивать на весь экран колебание меньше SEM значит рисовать шум как
 *    событие.
 *
 * И отдельно от расчёта — обязанность рисующего: срезанную ось нужно назвать
 * срезанной. За это отвечает поле `zoomed` и подпись реального диапазона под
 * графиком.
 */

/**
 * Разброс уже этой доли верха считается узкой полосой.
 *
 * Треть, а не половина: при разбросе в половину поля график и так читается,
 * а срез ради него означал бы, что ноль убирают почти всегда.
 */
const NARROW = 0.35;

/**
 * Низ считается пустым, если данные начинаются выше этой доли верха.
 *
 * Одна седьмая: срезать меньше — значит двигать ноль ради нескольких
 * пикселей, а цена у этого движения одна и та же независимо от выигрыша.
 */
const EMPTY_BOTTOM = 0.15;

/** Запас по краям окна, чтобы линия не шла вплотную к рамке */
const MARGIN = 1.25;

export interface AxisRequest {
  /** Нижний край нарисованного: значение или низ полосы разброса */
  lo: number;
  /** Верхний край нарисованного */
  hi: number;
  /**
   * Наименьшая разница, которую стоит показывать как разницу.
   *
   * Ошибка измерения, шаг шкалы, ширина межквартильного размаха — смотря что
   * рисуется. Ноль означает «не знаем»: тогда единственной защитой от
   * растянутого шума остаётся подпись реального диапазона.
   */
  atom?: number;
}

export interface Axis {
  min: number;
  max: number;
  ticks: number[];
  /** Ось начинается не с нуля — это обязано быть видно на графике */
  zoomed: boolean;
}

/** Не больше стольких промежутков между линиями сетки */
const MAX_STEPS = 5;

/**
 * Шаг сетки из ряда 1–2–2.5–5–10.
 *
 * Берётся самый мелкий шаг, при котором сетка ещё не гуще пяти промежутков.
 * Мелкий шаг важен не ради подписей, а ради верха оси: он округляется вверх
 * до шага, и при грубом шаге верх уезжает далеко за данные — то самое пустое
 * поле, ради избавления от которого весь модуль и написан.
 */
function niceStep(span: number): number {
  if (!(span > 0)) return 1;
  /*
   * Порядок берётся от нужного шага, а не от размаха: `span / MAX_STEPS` —
   * это наименьший годный шаг, и десятикратный ему всегда годится тоже.
   * Поэтому лесенки из пяти множителей хватает, искать дальше нечего.
   */
  const mag = 10 ** Math.floor(Math.log10(span / MAX_STEPS));
  return [1, 2, 2.5, 5, 10].map((m) => m * mag).find((s) => span / s <= MAX_STEPS) ?? mag * 10;
}

/*
 * Двоичная дробь округляется до шести знаков.
 *
 * 0.1 + 0.2 в подписи оси выглядит как 0.30000000000000004, а граница окна,
 * посчитанная делением и умножением на 2.5, — как 24.999999999999996.
 * Округление здесь не косметика: по этим же числам считается положение
 * линии, и без него верхняя линия сетки уезжает на полпикселя за рамку.
 */
const round = (v: number) => Math.round(v * 1e6) / 1e6;

function series(min: number, max: number, step: number): number[] {
  const out: number[] = [];
  // шаг умножается на номер, а не накапливается сложением: за десять
  // сложений шага 2.5 набегает ошибка в последнем знаке
  for (let i = 0; min + step * i <= max + step / 2; i++) out.push(round(min + step * i));
  return out;
}

export function axisFor({ lo, hi, atom = 0 }: AxisRequest): Axis {
  const top = Math.max(hi, 0);
  const span = Math.max(0, hi - lo);

  // вырожденный случай: рисовать нечего, но сетка всё равно нужна
  if (!(top > 0) && !(span > 0)) return { min: 0, max: 1, ticks: [0, 1], zoomed: false };

  const narrow = span < top * NARROW;
  const emptyBottom = lo > top * EMPTY_BOTTOM;

  if (!narrow || !emptyBottom) {
    const step = niceStep(top);
    const max = Math.max(step, round(Math.ceil(top / step) * step));
    return { min: 0, max, ticks: series(0, max, step), zoomed: false };
  }

  /*
   * Окно шире разброса: сам разброс занимает четыре пятых поля, остальное —
   * поля сверху и снизу. Нижняя граница окна — `atom`, наименьшая осмысленная
   * разница; из-за неё ряд, колеблющийся в пределах ошибки измерения, так и
   * останется плоским, а не растянется во весь экран.
   */
  const window = Math.max(span * MARGIN, atom * 3);
  const step = niceStep(window);
  const centre = (lo + hi) / 2;
  const min = round(Math.max(0, Math.floor((centre - window / 2) / step) * step));
  const max = round(Math.ceil(Math.max(hi, min + window) / step) * step);

  return { min, max, ticks: series(min, max, step), zoomed: min > 0 };
}
