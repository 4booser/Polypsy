/*
 * Значки карточки пациента и разбора, которых нет в наборе (ui/icons.tsx):
 * те же контуры lucide, штрих 2, currentColor, aria-hidden. Свои, а не правка
 * набора: набор правят только ради поломки, а здесь недостающие рисунки
 * одного раздела. Когда набор их заведёт, этот файл уходит в него целиком —
 * имена те же, что у lucide в макете (style_drawer_vivid.py).
 */

function make(paths: ReactNode) {
  return function Icon({ size = 16, className }: IconProps) {
    return (
      <svg
        width={size}
        height={size}
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth={2}
        strokeLinecap="round"
        strokeLinejoin="round"
        aria-hidden
        focusable="false"
        className={cx("shrink-0", className)}
      >
        {paths}
      </svg>
    );
  };
}

