import { useLang } from "../../lang";
import { Tabs } from "../../ui/primitives";

/** Адрес вкладки «Тести» — одна строка на все двери к ней */
export const TESTS_PATH = "/analytics/tests";

/**
 * Вкладки раздела «Аналітика»: «Моделі» (перечень, кадр f10) и «Тести».
 *
 * Решение заказчика 2026-09-26: «тут также нужно добавить вкладку с полной
 * аналитикой по тестам». Кадра со вкладками у раздела нет, поэтому место
 * выбрано так, чтобы не трогать уже сверенное:
 *
 *  - над строкой заголовка, в слоте `crumbs` рамки Page, а не под ней. Под
 *    строкой вкладки легли бы между полем поиска и сеткой перечня — туда,
 *    где у f10 замерен просвет 6 до первой строки, — и разорвали бы саму
 *    сетку. Над строкой они опускают строку f10 целиком на свою высоту, а
 *    всё, что внутри неё и под ней (поле 651, «+», блок страниц, колонки
 *    600/630), остаётся в тех же отношениях;
 *  - в одном и том же месте на обоих экранах: у «Тестів» своя строка
 *    заголовка другой высоты (две строки фильтров), и вкладки под ней
 *    прыгали бы при каждом переключении;
 *  - в прибитой шапке: переход между разделами не должен требовать
 *    прокрутки наверх.
 *
 * Ссылки, а не кнопки состояния: раздел — это адрес, его пересылают. «Моделі»
 * с `end`, иначе NavLink счёл бы её активной и на /analytics/tests.
 *
 * Нижний просвет 16 (плюс 6 самого слота) отделяет полосу вкладок с её
 * дорожкой прокрутки от строки заголовка: без него дорожка ложилась бы
 * вплотную к полю поиска и читалась бы его рамкой.
 */
export function AnalyticsTabs() {
  const { ut } = useLang();
  return (
    <div className="min-w-0 flex-1 pb-[16px]">
      <Tabs
        label={ut("ant.sections")}
        items={[
          { to: "/analytics", end: true, label: ut("ant.tabModels") },
          { to: TESTS_PATH, label: ut("ant.tabTests") },
        ]}
      />
    </div>
  );
}
