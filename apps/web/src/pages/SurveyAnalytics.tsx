import { Navigate, useParams } from "react-router-dom";
import { testsHref } from "./analytics/tests/model";

/**
 * Прежний адрес аналитики методики — /surveys/:id.
 *
 * Сам экран переехал во вкладку «Тести» раздела «Аналітика»
 * (pages/analytics/tests, решение заказчика 2026-09-26): оформление
 * «Пульта» с плитками и кольцами заменено формами Polypsy, а все двери
 * прежней страницы — выгрузки, нормы, назначения, конструктор, бланк, ключ,
 * «заповнити за пацієнта» — стоят в шестерёнке нового экрана.
 *
 * Адрес не удалён, а перенаправляет: на него ссылаются каталог тестов,
 * карточка группы, батареи, лист ключей, бланк, нормы, конструктор — и
 * закладки людей, которых в коде не видно вовсе. `replace`: «назад» с
 * нового экрана не должен возвращать на перенаправление и тут же снова
 * вперёд.
 */
export default function SurveyAnalyticsRedirect() {
  const { id } = useParams<{ id: string }>();
  return <Navigate to={id ? testsHref(id) : "/analytics/tests"} replace />;
}
