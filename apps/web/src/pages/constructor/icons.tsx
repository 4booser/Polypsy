/*
 * Значки конструктора, которых нет в наборе (ui/icons.tsx) и в рамке
 * (shell/icons.tsx): ручка перетаскивания, копия, корзина, сирена
 * критического пункта, калькулятор ключа и прочие с макета
 * methods-constructor / methods-new. Контуры lucide, штрих 2, currentColor —
 * та же сетка, что у набора, поэтому рядом с его значками они не выбиваются.
 * Живут здесь, а не в наборе: набор правит его участок.
 */

function make(paths: ReactNode) {
  return function Icon({ size = 16, className }: { size?: number; className?: string }) {
    return (
      <svg
        width={size}
        height={size}
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth={2}
        strokeLinecap="round"
        strokeLinejoin="round"
        aria-hidden
        focusable="false"
        className={cx("shrink-0", className)}
      >
        {paths}
      </svg>
    );
  };
}

