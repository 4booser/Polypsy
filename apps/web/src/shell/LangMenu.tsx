import { LANG_NAMES, LANG_SELF_LABEL, type Lang } from "@quizzy/shared";
import { useLang } from "../lang";
import { cx } from "../ui/cx";
import { MenuButton, menuItemClass } from "../ui/menu";

/**
 * Языки, из которых выбирают, — ключи LANG_NAMES, а не набранный список.
 *
 * Решение заказчика 2026-09-26: выбор не из двух, а из трёх, с английским.
 * Сам английский заводит другой участок (тип Lang и его подписи), и полоса
 * обязана показать его в тот же день, без правки здесь. LANG_NAMES — запись
 * `Record<Lang, …>`: язык, добавленный в Lang без полного и короткого имени,
 * не соберётся, — то есть этот перечень не может отстать от типа молча.
 * LANG_SELF_LABEL, на который указывало задание, для этого не годится: это
 * одна строка — имя самого органа выбора, — а не запись по языкам, и ключей
 * у неё нет.
 *
 * Прежний переключатель ходил «по кругу из двух» (`lang === "uk" ? "ru" :
 * "uk"`), и третий язык в нём просто негде было бы поставить.
 */
export const LANG_CHOICES = Object.keys(LANG_NAMES) as Lang[];

/**
 * Язык одной подписью, по нажатию — плашка с языками. Одна на всю оболочку:
 * верхняя полоса консоли, лендинг и вход (кадры f00/f01, PublicFrame).
 *
 * НА ПОЛОСЕ ВСЁ КАК БЫЛО. Слово называет текущий язык («Укр», «Рус», у
 * английского — его короткое имя), 20/700 цветом полосы, без рамки и
 * каретки — как на макете, где справа стоит одно слово. Изменилось только
 * то, что нажатие больше не переключает «на второй», а раскрывает выбор:
 * языков стало три, и «по кругу» из трёх человек попадал бы на нужный со
 * второго-третьего нажатия, не видя, что его ждёт дальше.
 *
 * ПЛАШКА — ТА ЖЕ, ЧТО У МЕНЮ ЯЗЫКА ТЕКСТА В КОНСТРУКТОРЕ (кадры f23_1/
 * f24_1): короткое слово на кнопке, полные имена в списке, прижатые к правому
 * краю, белая плашка с рамкой #999999 (align="right" в ui/menu.tsx). Полное
 * имя, а не «Укр/Рус/Eng», потому что выбирает здесь в том числе тот, кто
 * попал на незнакомый язык: «Українська», «Русский», «English» написаны
 * каждое на своём языке и узнаются, даже если остальной экран не читается —
 * та же причина, по которой LANG_SELF_LABEL двуязычна.
 *
 * ТЕКУЩИЙ ЯЗЫК ОТМЕЧЕН НЕ ЦВЕТОМ: роль menuitemradio с aria-checked для
 * диктора и галочка для глаза. Цвет пункта один у всех — у правой ветки меню
 * он задан тоном (menuItemClass), и второй `text-*` поверх спорил бы с ним.
 * У каждого пункта свой `lang`: диктор читает «Русский» русским голосом, а
 * не украинским.
 *
 * Ловушка фокуса, стрелки, Esc и подложка — общие (MenuButton): кнопка
 * рисуется своя, остальное нет, см. `trigger` в ui/menu.tsx.
 *
 * `tone` — ради цвета, и только его. Полоса консоли прибита к цвету макета
 * числами и НЕ следует за темой (см. пояснение о цветах в Topbar.tsx):
 * токен в тёмной теме светлеет, а полоса остаётся светло-сиреневой, и
 * подпись на ней выцвела бы. Публичный лист темы не меняет вовсе и обязан
 * быть на токенах — правило раздела. На листе `hover:text-primary-dim` даёт
 * РОВНО тот же #7a4ea6, что литерал в полосе: --primary-dim — это
 * --polsy-violet-dim (tokens.css), а тема там прибита к светлой (App.tsx).
 *
 * `side` — куда свисает плашка. В полосе слово стоит у правого края колонки,
 * и плашка свисает влево, под ним (как меню карточек). На публичном листе
 * слово стоит у ЛЕВОГО края, на телефоне — в шестнадцати пикселях от края
 * стекла, и плашка, свисающая влево, ушла бы за край; там она раскрывается
 * вправо от левого края слова (ветка "right-out" — та же плашка с рамкой).
 */
export function LangMenu({
  tone = "band",
  side = "end",
}: {
  tone?: "band" | "token";
  side?: "end" | "start";
}) {
  const { lang, setLang, ut } = useLang();
  /*
   * Короткое имя — из словаря, запасом — из LANG_NAMES: если у нового языка
   * в словаре ещё нет своей записи «top.lang», на полосе встанет «ENG», а не
   * имя ключа.
   */
  const word = ut("top.lang", LANG_NAMES[lang].short);
  return (
    <MenuButton
      label={LANG_SELF_LABEL}
      align={side === "end" ? "right" : "right-out"}
      /*
       * Коробка меню растянута по высоте места, а не по слову: в полосе
       * плашка тогда начинается под полосой, как список бургера, а не в её
       * нижней трети. Слово остаётся по центру (items-center).
       */
      className="items-center self-stretch"
      trigger={(p) => (
        <button
          type="button"
          {...p}
          /*
           * Видимое слово входит в имя для диктора, и первым (WCAG 2.5.3
           * Label in Name): тот, кто управляет голосом, говорит то, что
           * видит («Укр»). Хвост называет сам орган выбора и потому не
           * переводится — общая запись LANG_SELF_LABEL, а не второй литерал.
           */
          aria-label={`${word} — ${LANG_SELF_LABEL}`}
          className={cx(
            // глобальное правило для button рисует рамку и поля — гасим их явно:
            // это подпись, а не кнопка панели.
            // min-h-0 обязателен: :where(button) в legacy.css ставит min-height 34,
            // а min-height сильнее height — без него коробка «Укр» выросла бы до 34
            "min-h-0 rounded-sm border-0 bg-transparent p-0",
            /*
             * Чернила 33 × 18, а нажиматься должно 44 × 44 (WCAG 2.5.5).
             * Площадка дорисована НАКЛАДКОЙ поверх слова, а не раздутой
             * коробкой кнопки: тот же приём, что у размера `glyph` в
             * primitives.tsx.
             *
             * Коробкой нельзя, и это уже проверено на живом: `min-w-[44px]`
             * увёл «Укр» на 9–11 px влево на ВСЕХ экранах консоли. Правая
             * группа полосы прибита правым краем к колонке (nav перед ней
             * держит flex-1), поэтому коробка растёт ВЛЕВО, и слово вместе с
             * ней. Замер четырёх кадров консоли (f04, f30, f41, f47) и трёх
             * кадров списков (f11, f20, f26): чернила «Укр» стоят на
             * 1321…1353, бургер на 1373…1401 — правая кромка слова ровно
             * 1400 − 29 − 18. Накладка места не занимает вовсе: коробка
             * остаётся по слову, и обе шапки стоят там, где замерены, — в
             * консоли правым краем к 1353, на f00/f01 левым к 317.
             */
            "relative inline-flex items-center",
            "after:absolute after:left-1/2 after:top-1/2 after:size-[44px] after:content-['']",
            "after:-translate-x-1/2 after:-translate-y-1/2",
            "text-[20px] font-bold leading-none",
            "transition-colors duration-[var(--dur-fast)] outline-none focus-visible:ring-2",
            tone === "token"
              ? "text-primary hover:text-primary-dim focus-visible:ring-[var(--focus)]"
              : "text-[#663399] hover:text-[#7a4ea6] focus-visible:ring-[#663399]",
          )}
        >
          {word}
        </button>
      )}
    >
      {(close) =>
        LANG_CHOICES.map((code) => {
          const current = code === lang;
          return (
            <button
              key={code}
              type="button"
              role="menuitemradio"
              aria-checked={current}
              lang={code}
              className={cx(menuItemClass("right"), "gap-3")}
              onClick={() => {
                close();
                if (!current) setLang(code);
              }}
            >
              {/*
                Галочка у левого края, имя у правого — как пункты правой
                плашки. У невыбранных она невидима, но место держит: ширина
                плашки не прыгает от того, какой язык выбран.
              */}
              <span aria-hidden className={cx("mr-auto shrink-0 text-primary", !current && "invisible")}>
                <IconCheck />
              </span>
              {LANG_NAMES[code].full}
            </button>
          );
        })
      }
    </MenuButton>
  );
}

/* галочка в штрихе набора значков консоли: 24×24, линия 1.8 */
function IconCheck() {
  return (
    <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="1.8" strokeLinecap="round" strokeLinejoin="round">
      <path d="m5 12.5 4.5 4.5L19 7.5" />
    </svg>
  );
}
