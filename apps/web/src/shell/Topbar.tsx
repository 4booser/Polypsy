/**
 * Двери текущего экрана: то, что кадр на самом экране не рисует.
 *
 * Два адреса заведены сознательно и оба остались бы недостижимыми, будь
 * ссылка на них делом самого экрана: кадр f14 рисует строку заголовка группы
 * чистой (карандашу там места нет), а на f36 в раскрытом меню шестерёнки
 * ровно два пункта (четырём инструментам черновика там места нет). Ссылка
 * обязана быть, иначе «сохранить, не подписывая» и правка опечатки в
 * названии группы живут только в адресной строке — что и случилось.
 *
 * Бургер, а не палитра команд: палитра собирается из разделов навигации и
 * людей, и обе эти двери — не раздел и не человек. Бургер же и есть то
 * место, куда макет складывает всё, что в полосу не поместилось, — там уже
 * лежат входы клинической карты, по тому же признаку «открыт такой-то
 * экран».
 *
 * Адрес читается из пути, а не приходит свойством: полоса одна на консоль и
 * стоит выше любого экрана. На самом адресе двери её в списке нет — ссылка
 * «туда, где мы уже стоим» только мешает.
 */
function screenTools(pathname: string): { to: string; key: UiKey }[] | null {
  const group = /^\/patient-groups\/([^/]+)$/.exec(pathname);
  if (group) return [{ to: `/patient-groups/${group[1]}/edit`, key: "pg.edit" }];

  const conclusion = /^\/responses\/([^/]+)\/conclusion$/.exec(pathname);
  if (conclusion) return [{ to: `/responses/${conclusion[1]}/conclusion/draft`, key: "tools.conclusionDraft" }];

  return null;
}
