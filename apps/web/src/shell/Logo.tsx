/**
 * Знак учреждения — круг и буквы POLSY.
 *
 * Нарисован разметкой, а не подключён картинкой или шрифтом: политика
 * содержимого в консоли закрыта наглухо, внешние ресурсы не грузятся вовсе.
 * Буквы расставлены поштучно — так они и стоят на знаке, вразброс по кругу.
 *
 * Размер — свойство места: в плашке полосы приложения 26 (плашка 36), в
 * шапке кабинета и гостевых страниц 28 (плашка 40). Один рисунок с `size`,
 * а не копии: копии разошлись бы на первой же правке букв.
 *
 * Замер знака — по кадру f00 (жил в Topbar.tsx до Polypsy 2.0): два кегля
 * (крупные P и Y — 30, мелкие O, L, S — 17,9 по отношению стоек 0,596),
 * парные базовые линии, без наклона, кольцо 1,7 единицы.
 *
 * Цвет — `currentColor`: цвет назначает место. В белой плашке набора
 * («.logo») это фиолетовый бренда в обеих темах.
 */
export function Logo({ size = 70 }: { size?: number }) {
  return (
    <svg width={size} height={size} viewBox="0 0 70 70" aria-hidden focusable="false" className="block shrink-0">
      <circle cx="35" cy="35" r="34" fill="none" stroke="currentColor" strokeWidth="1.7" />
      <g fill="currentColor" fontWeight="700" textAnchor="middle">
        {/* крупные: P и Y на общей базовой линии 46 */}
        <g fontSize="30">
          <text x="15.2" y="46">
            P
          </text>
          <text x="54" y="46">
            Y
          </text>
        </g>
        {/* мелкие: O и L на общей базовой линии 34, S ниже на 16 */}
        <g fontSize="17.9">
          <text x="29.6" y="34">
            O
          </text>
          <text x="41.7" y="34">
            L
          </text>
          <text x="34.5" y="50">
            S
          </text>
        </g>
      </g>
    </svg>
  );
}

/**
 * Плашка знака по набору (.logo): белый квадрат со скруглением 11/36, знак
 * фиолетовым бренда. Белый — в обеих темах: знак учреждения не меняет цвет
 * от темы, а на тёмной полосе плашка и делает его знаком, а не пятном.
 *
 * `ring` — тонкая обводка, когда плашка стоит на светлом (полоса кабинета,
 * гостевая шапка): без неё белое на белом теряет край.
 */
export function LogoTile({ size = 36, ring }: { size?: 36 | 40; ring?: boolean }) {
  return (
    <span
      aria-hidden
      className={
        "grid shrink-0 place-items-center bg-onfill text-brand " +
        (size === 40 ? "size-10 rounded-[12px] " : "size-9 rounded-[11px] ") +
        (ring ? "shadow-[inset_0_0_0_1px_var(--bcardline)]" : "")
      }
    >
      <Logo size={size === 40 ? 28 : 26} />
    </span>
  );
}
