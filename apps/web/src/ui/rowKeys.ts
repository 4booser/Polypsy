/**
 * Ключи строк списков — чистая логика, отдельно от разметки.
 *
 * Ключ React говорит, какая строка «та же самая» между двумя отрисовками.
 * Номер строки годится только списку, который не сортируется, не
 * фильтруется и не теряет строк из середины: у такого номер и есть
 * личность. Во всех остальных случаях номер — ложь. Отсортировали таблицу —
 * React переиспользует узлы по позиции, и раскрытая строка, отметка, фокус
 * внутри ячейки остаются на месте, а данные под ними уезжают. Удалили пункт
 * из середины — поле ввода этого пункта достаётся соседу вместе с курсором.
 *
 * Здесь три способа получить честный ключ: из идентификатора строки, из её
 * значения (когда идентификатора нет, а значение в списке повторяется
 * редко) и выданный на время правки (когда нет ни того ни другого).
 * Проверяется это без браузера: apps/web/test/rowKeys.test.ts.
 */

/**
 * Ключ строки таблицы: `rowKey`, если он задан, иначе поле `id`.
 *
 * Идентификатор числом — такой же идентификатор: раньше принималась только
 * строка, и таблица по строкам с числовым id (сводные ряды с номером,
 * ответы сервера со счётчиком) молча уходила на порядковый номер — ровно на
 * тот ключ, от которого таблица и лечилась. Номер остаётся только там, где
 * опознать строку нечем вовсе.
 */
export function rowKeyOf<T>(row: T, index: number, rowKey?: (row: T) => string): string {
  if (rowKey) return rowKey(row);
  const id = (row as { id?: unknown } | null)?.id;
  if (typeof id === "string" && id) return id;
  if (typeof id === "number" && Number.isFinite(id)) return `#${id}`;
  return `@${index}`;
}

/**
 * Ключи по значению для строк без идентификатора: «09:00–13:00», «s2».
 *
 * Одинаковые значения различаются номером вхождения — второе «09:00–13:00»
 * получает «09:00–13:00#2». Такой ключ переживает удаление соседа с другим
 * значением и сортировку, чего номер строки не переживает; повторяющиеся
 * значения неотличимы и по смыслу, и перестановка их между собой ничего не
 * переносит.
 */
export function occurrenceKeys<T>(items: readonly T[], valueOf: (item: T) => string): string[] {
  const seen = new Map<string, number>();
  return items.map((item) => {
    const value = valueOf(item);
    const n = (seen.get(value) ?? 0) + 1;
    seen.set(value, n);
    return n === 1 ? value : `${value}#${n}`;
  });
}

/** Строка редактируемого списка, у которой нет своего идентификатора */
export interface Keyed<T> {
  key: string;
  value: T;
}

let counter = 0;

/**
 * Выдать ключ на время правки.
 *
 * Не crypto.randomUUID: ключ живёт только в памяти вкладки и никуда не
 * уходит, а счётчик не зависит от защищённого контекста (randomUUID в
 * браузере есть только на https и localhost, а консоль открывают и с
 * адреса внутренней сети).
 */
export function freshKey(): string {
  counter += 1;
  return `k${counter}`;
}

/** Список значений — в строки с ключами (при загрузке в редактор) */
export function withKeys<T>(values: readonly T[]): Keyed<T>[] {
  return values.map((value) => ({ key: freshKey(), value }));
}

/** Строки с ключами — обратно в значения (при сохранении): ключи на сервер не уходят */
export function withoutKeys<T>(rows: readonly Keyed<T>[]): T[] {
  return rows.map((r) => r.value);
}
