import { createContext, useContext, useEffect, useState, type ReactNode } from "react";
import { cx } from "./cx";
import { useLang } from "../lang";

/*
 * Рамка экрана по макету Polypsy.
 *
 * Прежде каждый экран сам решал, где у него заголовок, где фильтры и сколько
 * до них отступ, — и решал по-разному. Разница в шесть пикселей между
 * страницами не бросается в глаза по одной, но при переходах создаёт
 * ощущение, что экраны собраны из разных приложений.
 *
 * Что задаёт макет:
 *
 * 1. Содержимое — колонка 1200px по центру кадра. Не «во всю ширину с
 *    полями»: при 1600 и шире строка списка перестаёт быть читаемой задолго
 *    до края экрана, и макет это решает шириной колонки, а не размером шрифта.
 * 2. Заголовок раздела стоит В строке над списком, а не отдельной шапкой над
 *    ней. Это главное отличие от прежней редакции: там были две полосы —
 *    заголовок и под ним фильтры. В макете полоса одна, всё на одной оси:
 *    заголовок → поиск (тянется) → «+» → прижатый вправо блок страниц.
 * 3. Отступы замерены: 50px от низа шапки до этой строки, 28px от неё до
 *    списка, 39px — если следом идут вкладки. Нижний просвет и зазор внутри
 *    строки тоже просятся экраном (`listGap`, `headGap`): f11
 *    «Повідомлення» даёт 22 и 16 там, где f05/f07 дают 28 и 24.
 *
 *    Число НЕ одно на всю консоль, и это замер, а не поблажка. «Низ полосы →
 *    верхняя рамка поля в строке заголовка»: f05 «Пацієнти» (полоса 16…115,
 *    рамка 166) и f06 «Групи» (11…110 и 161) дают ровно 50, а f11
 *    «Повідомлення» (16…113 и 154), f42 «Лікарі» (17…116 и 156) и f49
 *    «Адміністратори» (15…114 и 155) — ровно 40. Общим здесь стоит 50: на
 *    нём сведены f05 и f06, и когда-то поставленное сюда общее 40 увело эти
 *    два уже сверенных экрана на десять пикселей вверх. Кто требует 40,
 *    просит его сам — `topGap`.
 *
 * Что осталось от прежней редакции, потому что было правильным и макету не
 * противоречит:
 *
 * 4. Прокручивается содержимое, а не страница. Строка над списком остаётся на
 *    месте: на списке из восьми тысяч человек фильтр, уехавший вверх, означает
 *    прокрутку туда и обратно на каждое изменение.
 * 5. Справа — панель контекста. Кто этот человек, видно не уходя с экрана.
 *    В макете такой панели нет, но и экранов, на которых она стоит, в макете
 *    тоже нет; убрать её — значит снять возможность, а не исполнить макет.
 * 6. Заголовок несёт число. «Пациенты» и «Пациенты · 8189» отвечают на
 *    разные вопросы, и второй чаще.
 */

/**
 * Колонка содержимого.
 *
 * 1248 = 1200 замера + по 24 на боковые поля. Ограничение стоит на 1248, а не
 * на 1200, именно поэтому: при ширине окна от 1248 содержимое получается ровно
 * 1200, как в макете, а на окне у́же поля не схлопываются в ноль и строка не
 * упирается в край стекла. Записать `max-w-[1200px]` и поля снаружи было бы
 * тем же самым числом в двух местах — и одно из них однажды поправят.
 */
const COLUMN = "mx-auto w-full max-w-[1248px] px-6 max-[900px]:px-4";

interface PageCtx {
  contextOpen: boolean;
  setContextOpen: (v: boolean) => void;
}
const Ctx = createContext<PageCtx>({ contextOpen: true, setContextOpen: () => {} });
export const usePageContext = () => useContext(Ctx);

export function Page({
  title,
  titleAlign = "start",
  topGap = 50,
  listGap = 28,
  headGap = 24,
  pagerGap,
  sub,
  count,
  crumbs,
  actions,
  toolbar,
  context,
  contextTitle,
  bleed,
  tight,
  snug,
  titleHidden,
  children,
  className,
}: {
  title: ReactNode;
  /**
   * Где стоит заголовок в своей строке.
   *
   * Умолчание — слева, как на всех кадрах со строкой «заголовок · поиск ·
   * плюс». «center» нужен одному экрану: карточке человека на её разделах
   * (кадры f34/f35), где имя стоит по центру колонки, под ним линия во всю
   * ширину, и только потом строка раздела. Свойством, а не вторым каркасом:
   * рамка экрана одна на консоль, и вторая копия разошлась бы с первой.
   */
  titleAlign?: "start" | "center";
  /**
   * Просвет от низа верхней полосы до строки заголовка.
   *
   * Умолчание 50 — замер f05/f06. Раздел людей просит 40: f42 и f49 дают
   * его по рамке поля, а все семь кадров карточки (f04, f30, f31, f40, f43,
   * f47, f50) — по чернилам заголовка, которые стоят там в 47-48 от низа
   * полосы против 59-60 на f05/f06. Свойством, а не общим числом: одно
   * число на консоль уже уводило соседние разделы, и разъезд был виден
   * только на их кадрах.
   *
   * Числа перечислены литералами, а не подставляются в строку класса:
   * Tailwind собирает классы, читая исходник, и `pt-[${n}px]` он не увидит
   * вовсе — отступа не стало бы молча.
   */
  topGap?: 40 | 50;
  /**
   * Просвет от строки заголовка до содержимого.
   *
   * Умолчание 28 — замер f05/f07 (у f07 поле поиска ровно на 214 = 50 + 36 +
   * 28). Раздел «Повідомлення» просит 22: на f11 нижняя рамка поля поиска
   * стоит на 173 (низ коробки 174), а верх первой строки списка — на 196
   * (подложка наведения шестой строки 536…602 при шаге 68: 536 − 5·68 = 196),
   * то есть ровно 22.
   *
   * Отдельным свойством, а не новым умолчанием и не веткой `snug`: `snug`
   * тянет за собой и верхний просвет, и зазор строки заголовка, а здесь
   * плотный только нижний. Числа литералами — Tailwind читает исходник и
   * `pb-[${n}px]` не увидел бы вовсе.
   */
  listGap?: 22 | 28;
  /**
   * Зазор внутри строки заголовка: заголовок → полоса инструментов → действия.
   *
   * Умолчание 24 — общее по кадрам списков. f11 просит 16: чернила заголовка
   * «Повідомлення» кончаются на 363, левая рамка поля поиска стоит на 379.
   * (У «Аналітики» тот же зазор 13 приходит веткой `snug` вместе с её
   * остальными просветами — здесь нужен только он один.)
   */
  headGap?: 16 | 24;
  /**
   * Просвет от полосы инструментов до блока страниц.
   *
   * Без него блок страниц стоит от «+» на общем зазоре строки (24, а при
   * `headGap`=16 — 16), и поле поиска растягивается на всё, что осталось.
   * Два раздела просят больше, и каждый — своё: f10 («Аналітика») 78, f11
   * («Повідомлення») 105. Замер f11: правый край «+» на 1070, левый край
   * блока страниц ≈1175 (чернила «на сторінці» с 1186, коробка подписи
   * правым краем на 1231). Без добавки поле тянулось бы до 1116 вместо
   * 1029 — на 87 шире кадра.
   *
   * Задаётся ДОБАВКОЙ к зазору строки (105 − 16 = 89, 78 − 13 = 65): зазор
   * всё равно приходит от flex, и вычесть его дешевле, чем отменять.
   *
   * Отдельным свойством, а не веткой `snug`: до этого 78 приезжали вместе с
   * остальными просветами «Аналітики», и второму разделу с другим числом
   * взяться было неоткуда — пришлось бы либо ломать первый, либо заводить
   * рядом второй механизм о том же. Числа литералами — Tailwind читает
   * исходник и `ml-[${n}px]` не увидел бы вовсе.
   */
  pagerGap?: 78 | 105;
  sub?: ReactNode;
  /** Число в заголовке: сколько всего строк, людей, случаев. */
  count?: number | null;
  crumbs?: ReactNode;
  actions?: ReactNode;
  /** Полоса фильтров: прибита под заголовком и не уезжает при прокрутке. */
  toolbar?: ReactNode;
  /** Панель справа. Если её нет, содержимое занимает всю ширину. */
  context?: ReactNode;
  contextTitle?: ReactNode;
  /**
   * Экран сам управляет своей областью: без полей и без прокрутки снаружи.
   *
   * Нужно там, где содержимое — не поток блоков, а собственная раскладка во
   * всю высоту: три панели разбора случаев, редактор маршрута. Раньше такие
   * экраны выбирались из полей отрицательными отступами и держали высоту
   * через `calc(100vh − 46px − 74px)`. Числа в этой формуле — высота верхней
   * панели и шапки страницы; стоило измениться любому из них, и экран
   * начинал вылезать за окно или не доставать до низа, причём молча.
   */
  bleed?: boolean;
  /**
   * Строка над содержимым пустая: просвет до содержимого ровно 50px.
   *
   * Нужно форме повідомлення (кадры f20/f26): там над полями нет ни
   * заголовка, ни вкладок, ни поиска — только просвет в 50px от нижнего края
   * верхней панели до первого поля, а шестерня меню висит В ЭТОМ просвете у
   * правого края колонки. Обычная шапка даёт 50 + высота строки + 28 и
   * опускает форму на полсотни пикселей ниже кадра; невидимая распорка в
   * строке (как было) этот лишний просвет только закрепляла.
   *
   * Отвергнуто: отрицательный отступ у содержимого — область содержимого
   * прокручивается (`overflow-y-auto`) и срезала бы всё, что уехало выше её
   * верхнего края, вместе с шестернёй.
   *
   * `actions` при `tight` высоты не занимают: их ряд свёрнут в ноль и поднят
   * на 10px, чтобы глиф встал туда же, где он нарисован на f26 (чернила
   * шестерни 129…142 при нижнем крае полосы 100 и верхней рамке поля 150).
   * Кадр здесь f26, а не f20: на f20 шестерни нет вовсе — там форма нового
   * повідомлення, у которого ещё нет ни меню, ни того, что оно делает.
   */
  tight?: boolean;
  /**
   * Просветы строки заголовка по кадрам раздела «Аналітика».
   *
   * Кадры f10 и f19 дают не 50, а 40 от нижнего края верхней полосы до
   * строки заголовка (верх рамки поиска f10 — 140, чернила «Аналітика»
   * f19 — 146…165 при высоте строки 30), и не 28, а 6 от неё до первой
   * строки списка (подложка наведения f10 начинается на 181 при низе
   * поля 176). Зазор заголовок→полоса инструментов 13 вместо 24 (чернила
   * «Перелік аналітики» кончаются на 404, рамка поля начинается на 418).
   * Блок страниц отодвинут от «+» на 78 (плюс 1082…1108, подпись страниц
   * 1187) — это уже не `snug`, а `pagerGap`: вместе они дают поле поиска
   * ровно 651, как на кадре.
   *
   * Отдельным свойством, а не новым умолчанием: кадры разделов расходятся.
   * f42/f49 («Лікарі», «Адміністратори») и f11 («Повідомлення») дают те же
   * 40 (поле поиска на 139/140/138), но f07 («Тести») и f44
   * («Організації») — прежние 50, причём у f07 совпадает и 28 до
   * содержимого (поле поиска ровно на 214 = 50 + 36 + 28). Сверены пока
   * «Аналітика» и «Люди»; менять умолчание по двум разделам из семи
   * значило бы сломать третий.
   *
   * С `tight` складывается: там нижнего просвета нет вовсе, и `snug`
   * меняет только верхний — это случай формы модели (f19), где заголовок
   * печатается внутри колонки формы, а не в строке рамки.
   */
  snug?: boolean;
  /**
   * Заголовок остаётся в разметке, но уходит с экрана.
   *
   * Нужно каталогу тестов (кадр f07): там на месте заголовка стоят вкладки
   * «Опубліковані / Неопубліковані тести», а имя раздела уже напечатано в
   * верхнем меню, и второй раз на экране его нет. Убрать <h1> совсем было бы
   * проще и хуже: диктор и поиск по странице ищут экран по заголовку, а
   * порядок заголовков (h1 → h2) обязан начинаться с первого. Поэтому
   * заголовок печатается визуально скрытым, а строка над списком отдаётся
   * полосе инструментов целиком — вкладки встают к левому краю, как на макете.
   */
  titleHidden?: boolean;
  children: ReactNode;
  className?: string;
}) {
  const { ut } = useLang();
  const [contextOpen, setContextOpen] = useState(true);

  // на узком экране панель контекста не помещается рядом — она закрыта
  useEffect(() => {
    const mq = window.matchMedia("(max-width: 1180px)");
    const apply = () => setContextOpen(!mq.matches);
    apply();
    mq.addEventListener("change", apply);
    return () => mq.removeEventListener("change", apply);
  }, []);

  return (
    <Ctx.Provider value={{ contextOpen, setContextOpen }}>
      <div className="flex min-h-0 flex-1 flex-col">
        {/*
          Заголовок и полоса фильтров — одна строка, а не две.

          Прежде это были две полосы: шапка с заголовком и под ней прибитая
          полоса фильтров с рамками сверху и снизу. В макете полоса одна, без
          рамок, и заголовок стоит в ней слева наравне с поиском. Разница не
          косметическая: две полосы со своими отступами и разделительными
          линиями отодвигали список вниз на целую строку списка, и на коротком
          экране первый пациент оказывался за сгибом.

          Прибивать её отдельно (`sticky`) больше не нужно — она и так лежит
          ВНЕ прокручиваемой области, а прокручивается только содержимое. У
          прежней редакции `sticky` был двойной страховкой и заодно причиной
          размытой подложки, которой в макете нет.
        */}
        <header
          className={cx(
            "shrink-0",
            /*
             * Верхний просвет: 50 общий, 40 — где кадр просит его сам.
             *
             * Замер: f05 (полоса 16…115, рамка поля 166) и f06 (11…110 и
             * 161) дают 50; f11 (16…113 и 154), f42 (17…116 и 156) и f49
             * (15…114 и 155) — 40. Отсюда два механизма: `snug` (плотная
             * строка над списком, она же сдвигает и нижний просвет) и
             * `topGap` — явное число для экранов, где плотная только шапка.
             */
            bleed
              ? "pb-[14px] pt-[20px]"
              : tight
                ? snug || topGap === 40
                  ? "pt-[40px]"
                  : "pt-[50px]"
                : cx(
                    snug ? "pb-[6px]" : listGap === 22 ? "pb-[22px]" : "pb-[28px]",
                    snug || topGap === 40 ? "pt-[40px]" : "pt-[50px]",
                  ),
          )}
        >
          <div className={COLUMN}>
            {crumbs ? <div className="mb-1.5 flex items-center gap-1.5 text-[13px] text-muted">{crumbs}</div> : null}
            <div
              className={cx(
                "flex items-center max-[900px]:flex-wrap",
                snug ? "gap-[13px]" : headGap === 16 ? "gap-[16px]" : "gap-[24px]",
              )}
            >
              {/*
                Число стоит рядом с заголовком, а не внутри него.

                Внутри оно попадало в текст заголовка целиком: диктор читал
                «Пациенты восемь тысяч сто восемьдесят девять» как название
                экрана, а смоук-тесты сверяли заголовок с константой и
                спотыкались о меняющееся число. Заголовок — имя экрана,
                число — сведения о его содержимом; это разные вещи, и
                разметка теперь так и говорит.
              */}
              {titleHidden ? (
                /*
                 * `sr-only`, а не `hidden`: скрытое через display: none выпадает
                 * из дерева доступности, и заголовок пропал бы и для диктора,
                 * ради которого он оставлен. Число рядом не печатается вовсе —
                 * без видимого заголовка ему не к чему стоять.
                 */
                <h1 className="sr-only">{title}</h1>
              ) : (
              <>
              {/* распорка слева: с ней заголовок встаёт по центру строки, без неё — у левого края */}
              {titleAlign === "center" ? <span className="flex-1" /> : null}
              <div className="flex shrink-0 items-baseline gap-[10px]">
                {/*
                  24/700 фиолетовым — заголовок раздела из макета.

                  Без `font-display`: дисплейная гарнитура (Unbounded) — другая
                  порода шрифта, с широкими знаками и сильным характером, и в
                  макете её нет. Там всё набрано одним геометрическим гротеском,
                  и заголовок отличается от строки списка только кеглем и
                  начертанием. Наследовать основную гарнитуру — значит ничего не
                  писать.
                */}
                <h1 className="m-0 text-balance text-[24px] font-bold leading-tight text-primary">
                  {title}
                </h1>
                {count !== undefined && count !== null ? (
                  <span className="font-mono text-[13px] tabular-nums text-muted">{count}</span>
                ) : null}
              </div>
              </>
              )}
              {/*
                Полоса фильтров занимает остаток строки: в макете поле поиска
                тянется от заголовка до прижатого вправо блока страниц. Пустой
                распорки, когда её нет, достаточно, чтобы `actions` осталось у
                правого края.
              */}
              {toolbar ? (
                <div className="flex min-w-0 flex-1 items-center">{toolbar}</div>
              ) : (
                <span className="flex-1" />
              )}
              {actions ? (
                <div
                  className={cx(
                    "flex shrink-0 items-center gap-[14px]",
                    /* 13 зазора ряда + 65 = 78 (f10); 16 + 89 = 105 (f11) */
                    pagerGap === 78 && "ml-[65px] max-[900px]:ml-0",
                    pagerGap === 105 && "ml-[89px] max-[900px]:ml-0",
                    /* z-10: свёрнутый ряд свисает в область содержимого, и без него нажатие
                       ловила бы колонка содержимого, лежащая ниже по разметке */
                    tight && "relative z-10 h-0 -translate-y-[10px]",
                  )}
                >
                  {actions}
                </div>
              ) : null}
            </div>
            {/* мета-строка макета: 13/400 серым */}
            {sub ? <p className="m-0 mt-[6px] max-w-[70ch] text-[13px] leading-[19px] text-muted">{sub}</p> : null}
          </div>
        </header>

        <div className="flex min-h-0 flex-1">
          <div className="flex min-w-0 flex-1 flex-col">
            {/*
              Область содержимого прокручивается сама, а не вместе со
              страницей, — значит должна принимать фокус. Без этого её
              нельзя пролистать ни стрелками, ни PageDown: мышью можно,
              клавиатурой нет. Проверка доступности нашла это на отчёте
              отделения, но касается это любой длинной страницы, и жило
              так с самого появления колонок.

              tabIndex у неподвижной области не мешает: лишняя остановка
              табуляции появляется только там, где есть что листать.
            */}
            <div
              tabIndex={bleed ? undefined : 0}
              className={cx(
                "min-h-0 flex-1",
                /* верхнего отступа нет: 28px до списка уже отданы низом строки над ним */
                bleed ? "overflow-hidden" : "overflow-y-auto overflow-x-hidden pb-24",
                className,
              )}
            >
              {/*
                Колонка 1200 — здесь, внутри прокручиваемой области, а не на
                ней самой. Ограничь ширину у самой области — и полоса прокрутки
                уехала бы к краю колонки, то есть на середину экрана, где её
                никто не ищет.

                Вкладки получают 11px сверху и тем самым 39px от строки над
                ними — ровно замер макета. Отступ навешен правилом «первый
                ребёнок — <nav> или tablist» (Tabs рисует ссылки первым, а
                кнопки состояния — вторым, см. primitives.tsx), а не отдельным
                свойством Page, потому что
                свойство пришлось бы проставлять руками на каждом экране с
                вкладками, а забыть его было бы нечем поймать: 28 вместо 39
                глазом не отличить, но вместе они и есть тот самый «разный
                ритм на разных экранах», ради которого эта рамка написана.

                Режим `bleed` обёртки не получает вовсе: там экран сам
                раскладывает три панели во всю высоту, и лишний <div> между
                ними рвёт цепочку высот (`h-full` внутри `h-full`).
              */}
              {bleed ? children : <div className={cx(COLUMN, "[&>:is(nav,[role=tablist]):first-child]:mt-[11px]")}>{children}</div>}
            </div>
          </div>

          {context && contextOpen ? (
            <aside
              className={cx(
                "flex w-[336px] shrink-0 flex-col overflow-y-auto border-l border-hairline bg-surface",
                "max-[1180px]:fixed max-[1180px]:inset-y-0 max-[1180px]:right-0 max-[1180px]:z-40 max-[1180px]:shadow-pop",
              )}
            >
              <div className="flex shrink-0 items-center justify-between gap-2 border-b border-hairline px-4 py-3">
                {/*
                  Не SectionLabel: тот стал микроподписью 10px (замер макета),
                  а здесь — заголовок панели, и 10-м кеглем он читался бы как
                  служебная пометка. Ступень та же, что у заголовка панели
                  ниже, — 18/700 фиолетовым.
                */}
                <h2 className="m-0 text-[18px] font-bold leading-tight text-primary">{contextTitle}</h2>
                <button
                  type="button"
                  onClick={() => setContextOpen(false)}
                  aria-label={ut("ui.closePanel")}
                  className="min-h-0 rounded-sm border-0 bg-transparent p-1 text-faint hover:text-text"
                >
                  <svg viewBox="0 0 24 24" className="size-4" fill="none" stroke="currentColor" strokeWidth={1.8}>
                    <path d="m6 6 12 12M18 6 6 18" />
                  </svg>
                </button>
              </div>
              <div className="flex-1 p-4">{context}</div>
            </aside>
          ) : null}
        </div>
      </div>
    </Ctx.Provider>
  );
}

