import { describe, expect, test } from "bun:test";
import { UI } from "@quizzy/shared";

/**
 * Строка стоит на своём языке.
 *
 * Самая частая поломка словаря — не кривой перевод, а перевод, попавший не в
 * то поле: правку вносят в одну строку, а вписывают в соседнюю. Глазами это
 * не ловится — в словаре под две тысячи пар, и проверять их подряд никто не
 * будет, — но ловится буквами: у языков разные алфавиты. «і», «ї», «є», «ґ»
 * в русском не встречаются вовсе; «ы», «э», «ъ» — в украинском.
 *
 * Чего проверка НЕ ловит: гибридное написание одними общими буквами. Так в
 * словаре и жило «Не подтверджён» — русская строка с украинской серединой,
 * все буквы русские. Поймано оно другим способом (одна украинская строка на
 * два разных русских перевода), и починено; здесь это сказано, чтобы никто
 * не принял зелёную проверку за доказательство, что таких мест нет.
 *
 * Буква «ё» из русского набора исключена намеренно: она есть и в украинских
 * заимствованиях, и спор о ней к языку строки отношения не имеет.
 */

const UK_ONLY = /[іїєґ]/i;
const RU_ONLY = /[ыэъ]/i;

/*
 * Единственное исключение — и оно названо, а не молчаливо.
 *
 * Переключатель языка показывает украинское слово «Українською» в РУССКОМ
 * интерфейсе: язык в списке называется на себе самом, иначе человек,
 * который русского не знает, не найдёт свой язык. Это не утечка, а замысел.
 *
 * По той же причине здесь lang.uk и lang.ru — раскрытый список переключателя
 * языка теста (кадры f23_1/f24_1). Кадр печатает в нём «Українська» и
 * «Русский» рядом, каждое своим алфавитом, в обоих интерфейсах.
 */
const SELF_NAMED = new Set(["adm.inUkrainian", "adm.inRussian", "lang.uk", "lang.ru"]);

/*
 * Английский — буквами проще всех: кириллицы в нём не бывает вовсе.
 *
 * Проверяются только переведённые записи: словарь переводят постепенно, и
 * непереведённая запись (без поля en) показывает украинский намеренно — см.
 * makeUiT и счёт непереведённых в packages/shared/src/uiStrings.test.ts.
 * Исключения те же, что выше, и по той же причине: язык, названный на себе
 * самом, пишется своими буквами на любом интерфейсе.
 */
const CYRILLIC = /[\u0400-\u04FF]/;

describe("строки словаря стоят на своём языке", () => {
  test("в русских строках нет украинских букв", () => {
    const leaked = Object.entries(UI)
      .filter(([key]) => !SELF_NAMED.has(key))
      .filter(([, v]) => UK_ONLY.test(v.ru))
      .map(([key, v]) => `${key}: «${v.ru}»`);
    expect(leaked, "украинский текст попал в русское поле").toEqual([]);
  });

  test("в украинских строках нет русских букв", () => {
    const leaked = Object.entries(UI)
      .filter(([, v]) => RU_ONLY.test(v.uk))
      .map(([key, v]) => `${key}: «${v.uk}»`);
    expect(leaked, "русский текст попал в украинское поле").toEqual([]);
  });

  test("в английских строках нет кириллицы — там, где перевод уже есть", () => {
    const entries = Object.entries(UI) as [string, { uk: string; ru: string; en?: string }][];
    const leaked = entries
      .filter(([key, v]) => v.en !== undefined && !SELF_NAMED.has(key))
      .filter(([, v]) => CYRILLIC.test(v.en!))
      .map(([key, v]) => `${key}: «${v.en}»`);
    expect(leaked, "украинский или русский текст попал в английское поле").toEqual([]);
  });

  test("оба поля заполнены: пустой перевод показывается служебной строкой", () => {
    const empty = Object.entries(UI)
      .filter(([, v]) => !v.uk.trim() || !v.ru.trim())
      .map(([key]) => key);
    expect(empty, "у строки пустой перевод — на экране будет дыра").toEqual([]);
  });
});
