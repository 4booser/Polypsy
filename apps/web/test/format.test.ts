import { describe, expect, test } from "bun:test";
import { duration, day, dateTime, timeOfDay } from "../src/format";

/**
 * Форматирование времени.
 *
 * Видно на каждом экране: длительность прохождения, дата замера, время
 * последнего сохранения. Ошибка здесь не роняет ничего — она молча
 * показывает неверное число, и человек делает по нему вывод.
 */
describe("длительность", () => {
  test("секунды, минуты и часы читаются по-человечески", () => {
    expect(duration(4200)).toContain("4");
    expect(duration(65_000)).toContain("1 мин");
    expect(duration(3_600_000)).toMatch(/ч|мин/);
  });

  test("ноль — это прочерк, а не «0 с»", () => {
    /*
     * Ноль в длительности означает «не измерено»: у прохождений,
     * загруженных из бумаги, времени нет. «0 с» читалось бы как «ответил
     * мгновенно» — прямо противоположный вывод.
     */
    expect(duration(0)).toBe("—");
  });

  test("отрицательное время не выдаётся за настоящее", () => {
    // рассинхронизация часов клиента и сервера даёт отрицательную разницу
    expect(duration(-5000)).toBe("—");
  });
});

describe("даты", () => {
  test("месяц пишется словом, а не числом", () => {
    /*
     * Прежняя реализация резала строку ISO и отдавала «03-14». Проверка
     * стояла на `/14|03|2026/` и потому проходила и на «03-14», и на
     * «14 марта» — то есть не различала машинный вид и человеческий,
     * ради которого и написана.
     */
    expect(day("2026-03-14T09:30:00Z")).toContain("мар");
    expect(day("2026-03-14T09:30:00Z")).not.toMatch(/^\d{2}-\d{2}$/);
  });

  test("год виден, когда он не текущий, и не мешает, когда текущий", () => {
    // в карте, которую ведут годами, «14 мар.» без года — ловушка
    const past = new Date().getFullYear() - 3;
    expect(day(`${past}-03-14T09:30:00Z`)).toContain(String(past));
    expect(day(`${new Date().getFullYear()}-03-14T09:30:00Z`)).not.toContain(
      String(new Date().getFullYear()),
    );
  });

  test("календарный день не съезжает на сутки западнее Гринвича", () => {
    /*
     * «2026-09-02» — это день, а не момент: так приходят даты прикрепления
     * и дни расписания. `new Date` разбирает такую строку как полночь UTC,
     * и в отрицательном часовом поясе она приходится на первое сентября.
     *
     * Часовой пояс задаётся отдельному процессу, а не переменной внутри
     * теста: Node читает TZ один раз при старте, и присваивание в тесте
     * ничего бы не изменило — проверка прошла бы, ничего не проверив.
     */
    const probe = `console.log(require(${JSON.stringify(
      new URL("../src/format.ts", import.meta.url).pathname,
    )}).day("2026-09-02"))`;
    const out = Bun.spawnSync(["bun", "-e", probe], {
      env: { ...process.env, TZ: "America/New_York" },
    });
    expect(out.stdout.toString()).toContain("2 сент");
  });

  test("дата и время содержат и то, и другое", () => {
    const s = dateTime("2026-03-14T09:30:00Z");
    expect(s).toContain("мар");
    expect(s).toMatch(/\d{1,2}:\d{2}/);
  });

  test("время суток — только часы и минуты", () => {
    expect(timeOfDay("2026-03-14T09:30:00Z")).toMatch(/^\d{2}:\d{2}$/);
  });

  test("пустая дата не превращается в «Invalid Date»", () => {
    // прохождение может быть не завершено — даты сдачи ещё нет
    expect(dateTime(null)).not.toContain("Invalid");
  });
});
