import { describe, expect, test } from "bun:test";
import { duration, day, dateTime, timeOfDay } from "../src/format";

/**
 * Форматирование времени.
 *
 * Видно на каждом экране: длительность прохождения, дата замера, время
 * последнего сохранения. Ошибка здесь не роняет ничего — она молча
 * показывает неверное число, и человек делает по нему вывод.
 */
describe("длительность", () => {
  test("секунды, минуты и часы читаются по-человечески", () => {
    expect(duration(4200)).toContain("4");
    expect(duration(65_000)).toContain("1 мин");
    expect(duration(3_600_000)).toMatch(/ч|мин/);
  });

  test("ноль — это прочерк, а не «0 с»", () => {
    /*
     * Ноль в длительности означает «не измерено»: у прохождений,
     * загруженных из бумаги, времени нет. «0 с» читалось бы как «ответил
     * мгновенно» — прямо противоположный вывод.
     */
    expect(duration(0)).toBe("—");
  });

  test("отрицательное время не выдаётся за настоящее", () => {
    // рассинхронизация часов клиента и сервера даёт отрицательную разницу
    expect(duration(-5000)).toBe("—");
  });
});

describe("даты", () => {
  test("день — только календарная дата", () => {
    expect(day("2026-03-14T09:30:00Z")).toMatch(/14|03|2026/);
  });

  test("дата и время содержат и то, и другое", () => {
    const s = dateTime("2026-03-14T09:30:00Z");
    expect(s).toMatch(/14|03/);
    expect(s).toMatch(/\d{1,2}:\d{2}/);
  });

  test("время суток — только часы и минуты", () => {
    expect(timeOfDay("2026-03-14T09:30:00Z")).toMatch(/^\d{2}:\d{2}$/);
  });

  test("пустая дата не превращается в «Invalid Date»", () => {
    // прохождение может быть не завершено — даты сдачи ещё нет
    expect(dateTime(null)).not.toContain("Invalid");
  });
});
