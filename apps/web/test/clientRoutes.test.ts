import { describe, expect, test } from "bun:test";
import { readFileSync } from "node:fs";

/**
 * Клиент не зовёт того, чего на сервере нет.
 *
 * Долг, ради которого написана проверка: пятнадцать экранов консоли ходили
 * по адресам, которых на сервере не осталось. Экран при этом не падает — он
 * показывает «не удалось загрузить», и отличить «сервер прилёг» от «этого
 * маршрута нет вовсе» человек не может. Так и жили: раздел в меню есть,
 * открывается, и ничего не показывает.
 *
 * Проверка сверяет два списка, которые и так ведутся: адреса из клиентского
 * api.ts и реестр ROUTE_DOCS, по которому строится документация и считается
 * полнота прав. Третьего списка не заводится — он разошёлся бы с обоими.
 *
 * Чего проверка НЕ делает: не ходит по сети и не проверяет, что маршрут
 * отвечает. Это работа смоука; здесь ловится более грубая и более частая
 * ошибка — зов в пустоту, переживший удаление возможности.
 */

const API = readFileSync(new URL("../src/api.ts", import.meta.url), "utf8");
const DOCS = readFileSync(
  new URL("../../../apps/api/src/lib/openapi.ts", import.meta.url),
  "utf8",
);

/** Объявленные на сервере пути: «GET /api/что-то» → «/api/что-то» */
function declaredPaths(): string[] {
  return [...DOCS.matchAll(/"(?:GET|POST|PUT|PATCH|DELETE) (\/api\/[^"]*)"/g)].map((m) => m[1]!);
}

/**
 * Путь в сравнимом виде: значения заменяются звёздочкой, форма остаётся.
 *
 * Параметр сервера (`:id`) и подстановка клиента (`${id}`) — одно и то же
 * место пути, и сравнивать их надо как одно. Запрос после «?» отбрасывается:
 * он к маршруту не относится.
 */
function shape(path: string): string {
  return path
    .replace(/:[A-Za-z][A-Za-z0-9]*/g, "*")
    .replace(/\?.*$/, "")
    .replace(/\/+$/, "");
}

/**
 * Адреса, которые зовёт клиент.
 *
 * Подстановки гасятся ДО выделения литералов, и вот почему: внутри `${…}`
 * бывают свои кавычки — `${archived ? "?archived=1" : ""}`, — и выделение
 * «от кавычки до кавычки» обрывалось на них, выдавая огрызки вроде
 * «/api/surveys${archived ». Первая редакция проверки именно так и подняла
 * десять ложных тревог: сторож с ложными тревогами хуже отсутствующего,
 * потому что его отключают целиком.
 */
function calledPaths(): string[] {
  /*
   * Гасим по разу, пока меняется: подстановки бывают вложенными
   * (`${qs ? `?${qs}` : ""}`), и один проход оставляет от внешней огрызок.
   */
  let flattened = API;
  for (let before = ""; before !== flattened; ) {
    before = flattened;
    flattened = flattened.replace(/\$\{[^{}]*\}/g, "*");
  }
  return [...flattened.matchAll(/["`](\/api\/[^"`]*)["`]/g)].map((m) => shape(m[1]!));
}

/**
 * Совпадает ли зов с объявленным маршрутом.
 *
 * Звёздочка закрывает один кусок пути, а в хвосте — ещё и пустоту: адрес
 * `/api/surveys*` получается из `/api/surveys${qs}`, где `qs` бывает пустым,
 * и объявленный `/api/surveys` ему отвечает.
 *
 * Отдельно разрешается зов, который оказался НАЧАЛОМ объявленного пути: в
 * клиенте такие строки — не запросы, а проверки («не повторять вход для
 * /api/auth/»). Считать их дырой значило бы требовать объявить маршрут,
 * которого никто и не зовёт.
 */
function isKnown(called: string, declared: string[]): boolean {
  const rx = new RegExp(`^${called.replace(/[.+?^$()|[\]\\]/g, "\\$&").replace(/\*/g, "[^/]*")}$`);
  return declared.some((d) => rx.test(d) || d.startsWith(called));
}

describe("клиент не зовёт несуществующих маршрутов", () => {
  test("каждый адрес из api.ts объявлен в ROUTE_DOCS", () => {
    const declared = declaredPaths().map(shape);
    expect(declared.length, "реестр маршрутов не прочитался — проверка была бы пустой").toBeGreaterThan(50);

    const called = [...new Set(calledPaths())];
    expect(called.length, "в клиенте не нашлось ни одного адреса — проверка была бы пустой").toBeGreaterThan(50);

    const missing = called
      .filter((p) => p.length > "/api/".length)
      /*
       * Склейка адреса из кусков: `${base}/access` — такой путь целиком в
       * исходнике не стоит, и сверять его с реестром нечем. Это не дыра, а
       * граница метода: он читает литералы.
       */
      .filter((p) => !p.startsWith("*"))
      .filter((p) => !isKnown(p, declared));

    expect(missing, "клиент ходит по адресам, которых нет на сервере").toEqual([]);
  });
});
