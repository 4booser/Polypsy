import { describe, expect, test } from "bun:test";
import { readFileSync } from "node:fs";
import { UI } from "@quizzy/shared";

/**
 * Экран приёма: три правки, которые легко отменить обратно.
 *
 * Все три нашлись на скриншотных эталонах, и ни одна не ломает ничего
 * измеримого — экран продолжает работать. Такие правки и возвращаются: не
 * злым умыслом, а рефлексом «пустое состояние рисуют через Empty» и
 * «колонки просто кладут в грид».
 */

/**
 * Исходник без комментариев.
 *
 * Иначе сторож ловит объяснение вместо кода: в комментарии над самой
 * починкой сказано, что здесь СТОЯЛО «<Empty>» — и проверка «Empty больше
 * нет» падала на исправном экране. Тот же случай, что уже был с разбором
 * строк: сторож, который врёт в свою сторону, отключают целиком.
 */
const VISIT = readFileSync(new URL("../src/pages/Visit.tsx", import.meta.url), "utf8")
  .replace(/\/\*[\s\S]*?\*\//g, "")
  .replace(/^\s*\/\/.*$/gm, "");

describe("экран приёма", () => {
  test("отсутствие новостей не набрано заголовком", () => {
    /*
     * Empty ставит <strong> по центру — это утверждение. «С прошлого приёма
     * ничего не произошло» утверждением не является, и набранное крупнее
     * самих событий оно переставляет их местами по важности.
     */
    expect(
      VISIT.includes("<Empty"),
      "на экране приёма снова Empty: отсутствие новостей опять набрано как заголовок",
    ).toBe(false);
    expect(
      VISIT.includes('ut("visit.noChanges")'),
      "строка «ничего не произошло» пропала вовсе — панель стала пустой без объяснения",
    ).toBe(true);
  });

  test("три колонки, и каждая кончается на своей высоте", () => {
    const grid = VISIT.match(/className="grid[^"]*"/)?.[0] ?? "";
    expect(grid, "сетка трёх колонок не нашлась — проверка была бы пустой").toContain("grid-cols-");
    /*
     * В «Виразній» колонки не тянутся до общего низа (волна 25). Прежний
     * экран растягивал последнюю панель столбца (h-full, flex-1), и в
     * короткой колонке под содержимым стояла пустая панель: на 13-дюймовом
     * экране это полэкрана белого листа без единой строки. Теперь панели —
     * по содержимому, колонки прижаты к верху, и пустоты внутри панели нет.
     */
    expect(grid, "колонки снова тянутся: пустота уходит внутрь панели").toContain("items-start");
    expect(VISIT.includes('className="h-full"'), "панель снова растянута до низа колонки").toBe(false);
    /* на узком экране колонки встают одна под другой, в том же порядке */
    expect(grid).toContain("max-[1100px]:grid-cols-1");
  });

  test("два действия про карту звучат по-разному", () => {
    /*
     * Обе кнопки видны на экране приёма одновременно: одна ведёт на рабочий
     * экран карты, другая печатает её целиком. Пока они начинались с одного
     * слова, выбирать приходилось наугад.
     */
    const onScreen = UI["visit.openCard"];
    const printed = UI["ep.chart"];
    for (const lang of ["uk", "ru"] as const) {
      const first = (s: string) => s.trim().split(/\s+/)[0]!.toLowerCase();
      expect(
        first(onScreen[lang]) === first(printed[lang]),
        `«${onScreen[lang]}» и «${printed[lang]}» начинаются одним словом — на экране приёма они стоят рядом`,
      ).toBe(false);
    }
  });
});
