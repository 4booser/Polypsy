import { describe, expect, test } from "bun:test";
import { readFileSync, readdirSync, statSync } from "node:fs";
import { join, resolve } from "node:path";
import { UI } from "@quizzy/shared";

/**
 * Строки интерфейса — только через словарь.
 *
 * Смоук на языке уже есть: он открывает страницу на двух языках и ищет буквы,
 * которых в украинском алфавите нет. Признак надёжный, но с двумя слепыми
 * зонами. Во-первых, «Создать», «Отозвать», «Снять» таких букв не содержат и
 * проходят насквозь. Во-вторых, экранов там четырнадцать из тридцати трёх, а
 * забытая строка обычно сидит не на главном.
 *
 * Здесь проверяются исходники, а не страница: на каждом экране, включая те, до
 * которых смоук не доходит, и без запущенного приложения. Ошибка ловится в
 * момент написания, а не через полгода в кабинете.
 */

/*
 * Пути считаются от самого файла проверки, а не от текущего каталога.
 *
 * `bun test` в этом проекте запускают из корня репозитория, и относительный
 * "src" оттуда не существует. Обход каталога молча возвращал пустой список,
 * проверка не находила ни одного файла — и проходила. Зелёная проверка,
 * которая ничего не проверила, хуже её отсутствия: она отвечает «всё в
 * порядке» на вопрос, который не задавала.
 */
const WEB = resolve(import.meta.dir, "..");
const SRC = join(WEB, "src");
const MOBILE = resolve(WEB, "../mobile");

/*
 * Что разрешено оставить в разметке — с причиной для каждого случая.
 * Список короткий намеренно: длинный список исключений означает, что правило
 * не работает.
 */
const ALLOWED = new Map<string, string>([
  [
    "src/pages/UiKit.tsx",
    "витрина языка интерфейса: демонстрационные данные и пояснения к самой " +
      "системе оформления. Читает её разработчик, а не специалист в кабинете; " +
      "переводить «Петров Дмитрий» и «Рота обеспечения» не для кого",
  ],
]);

/** Подписи, которые называют сам язык и потому не переводятся. */
const LANGUAGE_LABELS = new Set(["українською", "по-русски", "Мова / Язык", "УКР", "РУС"]);

const CYRILLIC = /[А-Яа-яЁёІіЇїЄєҐґ]/;

/** Убирает комментарии: пояснения в коде по-русски — это норма проекта. */
function withoutComments(src: string): string {
  return src.replace(/\/\*[\s\S]*?\*\//g, " ").replace(/(^|[^:])\/\/[^\n]*/g, "$1 ");
}

function tsxFiles(dir: string): string[] {
  return codeFiles(dir).filter((f) => f.endsWith(".tsx"));
}

/** Все исходники каталога: и .ts, и .tsx. Каталог может не существовать. */
function codeFiles(dir: string): string[] {
  const out: string[] = [];
  let names: string[];
  try {
    names = readdirSync(dir);
  } catch {
    return out;
  }
  for (const name of names) {
    if (name === "node_modules") continue;
    const path = join(dir, name);
    if (statSync(path).isDirectory()) out.push(...codeFiles(path));
    else if (path.endsWith(".tsx") || path.endsWith(".ts")) out.push(path);
  }
  return out;
}

/**
 * Диагностика для разработчика — не интерфейс.
 *
 * `throw new Error("useAuth вне AuthProvider")` читает тот, кто сломал код,
 * а не человек в кабинете. Такие строки переводить незачем и вредно: они
 * должны совпадать с тем, что написано в исходнике, чтобы их можно было
 * найти поиском.
 */
function withoutDeveloperMessages(src: string): string {
  return src
    .replace(/throw new Error\([^)]*\)/g, " ")
    .replace(/console\.\w+\([^)]*\)/g, " ");
}

/**
 * Видимый пользователю текст файла.
 *
 * Ловятся не только узлы JSX: строка, присвоенная переменной или лежащая в
 * массиве меток, доезжает до экрана ровно так же. Проверка только по разметке
 * пропускала сорок три такие строки — а выглядела при этом зелёной, что хуже
 * её отсутствия.
 */
function visibleStrings(source: string): string[] {
  const src = withoutDeveloperMessages(withoutComments(source));
  const found = new Set<string>();

  for (const m of src.matchAll(/>([^<>]*)</g)) {
    const text = m[1]!
      .replace(/\{[^{}]*\}/g, " ") // выражения — не литералы
      .replace(/\s+/g, " ")
      .trim();
    if (text && CYRILLIC.test(text)) found.add(text);
  }

  for (const m of src.matchAll(/"([^"\n]{2,120})"|'([^'\n]{2,120})'/g)) {
    const text = (m[1] ?? m[2] ?? "").trim();
    if (text && CYRILLIC.test(text)) found.add(text);
  }

  /*
   * Шаблонные строки тоже.
   *
   * `Методика ${i + 1} из ${n}` — обычная подпись на экране киоска, но живёт
   * она внутри выражения, а не литералом, и первую редакцию этой проверки
   * обходила насквозь. Пациент видел её по-русски на украинском экране.
   * Подстановки вырезаются, проверяется то, что между ними.
   */
  for (const m of src.matchAll(/`([^`]{2,200})`/g)) {
    const text = m[1]!.replace(/\$\{[^{}]*\}/g, " ").replace(/\s+/g, " ").trim();
    if (text && CYRILLIC.test(text)) found.add(text);
  }

  return [...found].filter((t) => !LANGUAGE_LABELS.has(t));
}

describe("строки интерфейса", () => {
  test("в разметке не остаётся текста мимо словаря", () => {
    /*
     * Читаются и .ts, а не только разметка.
     *
     * Первая редакция смотрела на .tsx — и мимо неё прошли «Нет связи с
     * сервером» в клиенте запросов, «Не удалось загрузить» в загрузчике
     * данных и весь список видов вопросов в модели конструктора. Это не
     * закоулки: сетевой отказ виден на каждом экране, где что-то не
     * доехало.
     */
    const files = [...codeFiles(SRC), ...codeFiles(join(MOBILE, "src")), ...codeFiles(join(MOBILE, "app"))];
    /*
     * Сначала — что файлы вообще нашлись. Без этой строки проверка при
     * неверном пути обходила пустой список и объявляла победу.
     */
    expect(files.length).toBeGreaterThan(30);

    const offenders: string[] = [];
    for (const file of files) {
      if (ALLOWED.has(file.slice(WEB.length + 1))) continue;
      for (const text of visibleStrings(readFileSync(file, "utf8"))) {
        offenders.push(`${file.slice(WEB.length + 1)}: ${text.slice(0, 70)}`);
      }
    }
    expect(offenders).toEqual([]);
  });

  test("в словаре не копятся ключи, которых никто не зовёт", () => {
    /*
     * Экраны переписываются, ключи остаются. Через год словарь наполовину
     * состоит из строк, которых нет ни на одном экране, и переводчик тратит
     * время на текст, который никто не увидит.
     *
     * Часть ключей зовётся шаблоном: `ut(`dest.${destination}`)`. Такой ключ
     * поимённо в коде не встречается, поэтому засчитывается и обращение по
     * префиксу — иначе проверка требовала бы отказаться от шаблонов ради
     * самой себя.
     */
    /*
     * Читаются оба потребителя словаря, а не одна консоль.
     *
     * Словарь общий: из полутора тысяч ключей триста пятьдесят восемь
     * консоль не зовёт вовсе — их зовёт мобильное приложение. Проверка,
     * которая смотрит только сюда, объявила бы их мёртвыми и потребовала бы
     * либо удалить нужное, либо завести порог «примерно триста», который
     * ничего не значит.
     */
    const sources = [...codeFiles(SRC), ...codeFiles(join(MOBILE, "src")), ...codeFiles(join(MOBILE, "app"))]
      .map((f) => readFileSync(f, "utf8"))
      .join("\n");

    /*
     * Префикс берётся целиком, а не по первой точке.
     *
     * Первая редакция этой проверки распознавала только односоставный
     * префикс — `dest.${…}`, — а `goal.status.${g.status}` состоит из двух
     * частей. Ключи goal.status.* оказались «мёртвыми», проверка их
     * удалила, и приложение падало пустым экраном на первом же закрытии
     * цели: UI[key] был undefined. Ловится это только запуском, потому что
     * шаблонный ключ компилятор не проверяет.
     */
    const dynamicPrefixes = [
      ...new Set([...sources.matchAll(/`([a-z][A-Za-z0-9.]*)\.\$\{/g)].map((m) => m[1]!)),
    ];

    const unused = Object.keys(UI).filter((key) => {
      if (sources.includes(`"${key}"`)) return false;
      return !dynamicPrefixes.some((prefix) => key.startsWith(`${prefix}.`));
    });

    expect(unused).toEqual([]);
  });

  test("семейства шаблонных ключей не пустеют", () => {
    /*
     * `ut(`goal.status.${g.status}`)` компилятор не проверяет: ключ
     * складывается в рантайме. Если такое семейство исчезнет из словаря —
     * а это уже случалось, — экран упадёт пустым в тот момент, когда
     * человек нажмёт кнопку, и никакой тест до него не доберётся, кроме
     * того, что специально идёт по этому пути.
     *
     * Здесь проверяется дешёвое и достаточное: у каждого шаблонного
     * обращения в словаре есть хоть один ключ с таким началом.
     */
    const sources = [...codeFiles(SRC), ...codeFiles(join(MOBILE, "src")), ...codeFiles(join(MOBILE, "app"))]
      .map((f) => readFileSync(f, "utf8"))
      .join("\n");

    /*
     * Только обращения через ut(. Шаблоны вообще — это ещё и ключи
     * localStorage вроде `quizzy.constructor.${id}`, к словарю отношения не
     * имеющие; проверка на них ругалась бы вечно.
     *
     * В соседней проверке на мёртвые ключи распознавание, наоборот, нарочно
     * широкое: там лишний префикс означает «не удалять на всякий случай», и
     * ошибиться в эту сторону дешевле.
     */
    const prefixes = [
      ...new Set([...sources.matchAll(/\but\(`([a-z][A-Za-z0-9.]*)\.\$\{/g)].map((m) => m[1]!)),
    ];
    expect(prefixes.length).toBeGreaterThan(0);

    const keys = Object.keys(UI);
    const empty = prefixes.filter((p) => !keys.some((k) => k.startsWith(`${p}.`)));
    expect(empty).toEqual([]);
  });

  test("у каждого ключа есть оба перевода и они не совпадают по недосмотру", () => {
    /*
     * Совпадение допустимо: «Пароль», «Email», «Дата» одинаковы на обоих
     * языках. Проверяется другое — что перевод не пустой и не остался
     * заглушкой вида «TODO».
     */
    const bad: string[] = [];
    for (const [key, pair] of Object.entries(UI)) {
      if (!pair.uk?.trim()) bad.push(`${key}: пустой uk`);
      if (!pair.ru?.trim()) bad.push(`${key}: пустой ru`);
      if (/TODO|FIXME|xxx/i.test(pair.uk + pair.ru)) bad.push(`${key}: заглушка вместо перевода`);
    }
    expect(bad).toEqual([]);
  });
});
