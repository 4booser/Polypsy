import { readFileSync, readdirSync, statSync } from "node:fs";
import { join, resolve } from "node:path";
import { ERRORS, PUSH, UI } from "@quizzy/shared";

/**
 * Строки интерфейса — только через словарь.
 *
 * Смоук на языке уже есть: он открывает страницу на двух языках и ищет буквы,
 * которых в украинском алфавите нет. Признак надёжный, но с двумя слепыми
 * зонами. Во-первых, «Создать», «Отозвать», «Снять» таких букв не содержат и
 * проходят насквозь. Во-вторых, экранов там четырнадцать из тридцати трёх, а
 * забытая строка обычно сидит не на главном.
 *
 * Здесь проверяются исходники, а не страница: на каждом экране, включая те, до
 * которых смоук не доходит, и без запущенного приложения. Ошибка ловится в
 * момент написания, а не через полгода в кабинете.
 *
 * Сами литералы — кириллица и латиница мимо ut() — сторожатся теперь в
 * noRawStrings.test.ts (консоль) и apps/mobile/test/noRawStrings.test.ts
 * (мобилка): разбором исходника компилятором, а не регулярками. Регулярки
 * здесь держали почти всё, но промахивались на чётности кавычек — литерал
 * после пустой строки («"" : " · пропуск"») проходил насквозь, — и на
 * одиночной букве. Две проверки одного правила разъехались бы списками
 * исключений, поэтому старая убрана целиком, а не оставлена «на всякий
 * случай». Здесь осталось то, чего разбор литералов не видит: мёртвые
 * ключи, семейства шаблонных ключей, сырое значение сервера на экране,
 * index.html и подпись языка.
 */

/*
 * Пути считаются от самого файла проверки, а не от текущего каталога.
 *
 * `bun test` в этом проекте запускают из корня репозитория, и относительный
 * "src" оттуда не существует. Обход каталога молча возвращал пустой список,
 * проверка не находила ни одного файла — и проходила. Зелёная проверка,
 * которая ничего не проверила, хуже её отсутствия: она отвечает «всё в
 * порядке» на вопрос, который не задавала.
 */
const WEB = resolve(import.meta.dir, "..");
const SRC = join(WEB, "src");
const MOBILE = resolve(WEB, "../mobile");
const ROOT = resolve(WEB, "../..");

/*
 * Путь в сообщении — от корня репозитория.
 *
 * Отрезалось `WEB.length + 1`, и файл мобилки в списке нарушений выглядел как
 * «le/app/login.tsx»: первые девять букв «apps/mobi» съедало вычитание длины
 * чужого каталога. Такой адрес не открывается ни редактором, ни поиском —
 * проверка называла виновника так, что найти его было нельзя.
 */
const rel = (file: string) => file.slice(ROOT.length + 1);

/*
 * Файлы, которые проверка сырых значений сервера не читает, — с причиной.
 * Список короткий намеренно: длинный список исключений означает, что правило
 * не работает. Для литералов свой список — в noRawStrings.test.ts.
 */
const ALLOWED = new Map<string, string>([
  [
    "apps/web/src/pages/UiKit.tsx",
    "витрина языка интерфейса: демонстрационные данные и пояснения к самой " +
      "системе оформления. Читает её разработчик, а не специалист в кабинете; " +
      "переводить «Петров Дмитрий» и «Рота обеспечения» не для кого",
  ],
]);

const CYRILLIC = /[А-Яа-яЁёІіЇїЄєҐґ]/;

/** Убирает комментарии: пояснения в коде по-русски — это норма проекта. */
function withoutComments(src: string): string {
  return src.replace(/\/\*[\s\S]*?\*\//g, " ").replace(/(^|[^:])\/\/[^\n]*/g, "$1 ");
}

/** Все исходники каталога: и .ts, и .tsx. Каталог может не существовать. */
function codeFiles(dir: string): string[] {
  const out: string[] = [];
  let names: string[];
  try {
    names = readdirSync(dir);
  } catch {
    return out;
  }
  for (const name of names) {
    if (name === "node_modules") continue;
    const path = join(dir, name);
    if (statSync(path).isDirectory()) out.push(...codeFiles(path));
    else if (path.endsWith(".tsx") || path.endsWith(".ts")) out.push(path);
  }
  return out;
}

/**
 * Диагностика для разработчика — не интерфейс.
 *
 * `throw new Error("useAuth вне AuthProvider")` читает тот, кто сломал код,
 * а не человек в кабинете. Такие строки переводить незачем и вредно: они
 * должны совпадать с тем, что написано в исходнике, чтобы их можно было
 * найти поиском.
 */
/*
 * Скобки считаются, а не отыскиваются регуляркой `\([^)]*\)`.
 *
 * Та версия обрывалась на первой же закрывающей скобке внутри сообщения.
 * `throw new Error(\`<input> без подписи (placeholder\${…}) не считается…\`)`
 * она резала до «(placeholder», а хвост — русская фраза для разработчика —
 * оставался и попадал в список нарушений. Пока у литералов стоял потолок в
 * 200 символов, это пряталось: длинное сообщение просто не матчилось. Снимаю
 * потолок — и обязан чинить причину, иначе проверка начнёт ругаться на то,
 * что чинить не нужно.
 */
function withoutDeveloperMessages(src: string): string {
  const START = /throw new Error\s*\(|console\.\w+\s*\(/g;
  const out: string[] = [];
  let from = 0;
  let m: RegExpExecArray | null;
  while ((m = START.exec(src)) !== null) {
    out.push(src.slice(from, m.index), " ");
    let i = m.index + m[0].length;
    let depth = 1;
    let quote = "";
    for (; i < src.length && depth > 0; i += 1) {
      const ch = src[i]!;
      if (quote) {
        if (ch === "\\") i += 1;
        else if (ch === quote) quote = "";
        continue;
      }
      if (ch === '"' || ch === "'" || ch === "`") quote = ch;
      else if (ch === "(") depth += 1;
      else if (ch === ")") depth -= 1;
    }
    /*
     * Скобка не закрылась — значит это был не вызов, а упоминание вызова в
     * комментарии. Вырезать «до конца файла» в таком случае значило бы
     * ослепить проверку одной строкой комментария, поэтому не режем ничего.
     */
    if (depth > 0) {
      out.pop();
      out.push(src.slice(m.index));
      return out.join("");
    }
    from = i;
    START.lastIndex = i;
  }
  out.push(src.slice(from));
  return out.join("");
}

/*
 * Порядок важен: сначала сообщения разработчику, потом комментарии.
 *
 * Вырезание комментариев ломает чётность обратных кавычек — в пояснениях их
 * полно (`ut(\`goal.status.\${…}\`)`), и комментарий с нечётным числом
 * сдвигает разбивку шаблонов на единицу: «закрывающая» кавычка одного
 * литерала становится «открывающей» для следующего, и в захват попадает код
 * между ними. Сообщения разработчику поэтому режутся по живому исходнику,
 * где чётность ещё настоящая.
 */
function forScanning(source: string): string {
  return withoutComments(withoutDeveloperMessages(source));
}

/*
 * Имена полей-перечислений.
 *
 * `reason` в этот список НЕ входит намеренно: «с чем обращаетесь» пишет
 * человек своими словами, это данные, а не перечисление протокола. Печатать
 * их как есть — правильно, переводить — нельзя.
 */
const ENUM_FIELD = /\b\w+\.(?:status|kind|type|state|role|outcome|severity|mode|result|source)\b/;

/** Поле перечисления, напечатанное в текстовом узле напрямую. */
function rawServerValues(source: string): string[] {
  const src = forScanning(source);
  const found = new Set<string>();
  for (const m of src.matchAll(/>\s*\{([^{}]+)\}\s*</g)) {
    const expr = m[1]!.replace(/\s+/g, " ").trim();
    if (!ENUM_FIELD.test(expr)) continue;
    if (/\but\(|\bt\(/.test(expr)) continue; // уже через словарь
    if (/["'`]/.test(expr)) continue; // значение разбирают на месте, а не печатают
    found.add(expr);
  }
  return [...found];
}

describe("строки интерфейса", () => {
  test("в словаре не копятся ключи, которых никто не зовёт", () => {
    /*
     * Экраны переписываются, ключи остаются. Через год словарь наполовину
     * состоит из строк, которых нет ни на одном экране, и переводчик тратит
     * время на текст, который никто не увидит.
     *
     * Часть ключей зовётся шаблоном: `ut(`dest.${destination}`)`. Такой ключ
     * поимённо в коде не встречается, поэтому засчитывается и обращение по
     * префиксу — иначе проверка требовала бы отказаться от шаблонов ради
     * самой себя.
     */
    /*
     * Читаются оба потребителя словаря, а не одна консоль.
     *
     * Словарь общий: из полутора тысяч ключей триста пятьдесят восемь
     * консоль не зовёт вовсе — их зовёт мобильное приложение. Проверка,
     * которая смотрит только сюда, объявила бы их мёртвыми и потребовала бы
     * либо удалить нужное, либо завести порог «примерно триста», который
     * ничего не значит.
     */
    const sources = [...codeFiles(SRC), ...codeFiles(join(MOBILE, "src")), ...codeFiles(join(MOBILE, "app"))]
      .map((f) => readFileSync(f, "utf8"))
      .join("\n");

    /*
     * Префикс берётся целиком, а не по первой точке.
     *
     * Первая редакция этой проверки распознавала только односоставный
     * префикс — `dest.${…}`, — а `goal.status.${g.status}` состоит из двух
     * частей. Ключи goal.status.* оказались «мёртвыми», проверка их
     * удалила, и приложение падало пустым экраном на первом же закрытии
     * цели: UI[key] был undefined. Ловится это только запуском, потому что
     * шаблонный ключ компилятор не проверяет.
     */
    const dynamicPrefixes = [
      ...new Set([...sources.matchAll(/`([a-z][A-Za-z0-9.]*)\.\$\{/g)].map((m) => m[1]!)),
    ];

    const unused = Object.keys(UI).filter((key) => {
      if (sources.includes(`"${key}"`)) return false;
      return !dynamicPrefixes.some((prefix) => key.startsWith(`${prefix}.`));
    });

    expect(unused).toEqual([]);
  });

  test("семейства шаблонных ключей не пустеют", () => {
    /*
     * `ut(`goal.status.${g.status}`)` компилятор не проверяет: ключ
     * складывается в рантайме. Если такое семейство исчезнет из словаря —
     * а это уже случалось, — экран упадёт пустым в тот момент, когда
     * человек нажмёт кнопку, и никакой тест до него не доберётся, кроме
     * того, что специально идёт по этому пути.
     *
     * Здесь проверяется дешёвое и достаточное: у каждого шаблонного
     * обращения в словаре есть хоть один ключ с таким началом.
     */
    const sources = [...codeFiles(SRC), ...codeFiles(join(MOBILE, "src")), ...codeFiles(join(MOBILE, "app"))]
      .map((f) => readFileSync(f, "utf8"))
      .join("\n");

    /*
     * Только обращения через ut(. Шаблоны вообще — это ещё и ключи
     * localStorage вроде `quizzy.constructor.${id}`, к словарю отношения не
     * имеющие; проверка на них ругалась бы вечно.
     *
     * В соседней проверке на мёртвые ключи распознавание, наоборот, нарочно
     * широкое: там лишний префикс означает «не удалять на всякий случай», и
     * ошибиться в эту сторону дешевле.
     */
    const prefixes = [
      ...new Set([...sources.matchAll(/\but\(`([a-z][A-Za-z0-9.]*)\.\$\{/g)].map((m) => m[1]!)),
    ];
    expect(prefixes.length).toBeGreaterThan(0);

    const keys = Object.keys(UI);
    const empty = prefixes.filter((p) => !keys.some((k) => k.startsWith(`${p}.`)));
    expect(empty).toEqual([]);
  });

  test("сырое значение из ответа сервера не печатается на экране", () => {
    /*
     * Самая тихая из всех дыр.
     *
     * `{q.type}` и `{r.status}` — не забытая подпись, её нет в исходнике
     * вовсе: на экран попадает то, что прислал сервер. Поэтому ни одна
     * проверка литералов такое не увидит, а смоук на языке — тем более:
     * значение одинаково на обоих языках, и правило «осталось то же —
     * значит данные» записывает его в данные. Между тем «single», «matrix»,
     * «abandoned», «severe» — это не данные пациента, а перечисление из
     * протокола, у которого в словаре есть свои ключи.
     *
     * Ищется ровно один признак: поле с именем перечисления, напечатанное в
     * текстовом узле напрямую, без ut( и без литералов рядом (литерал рядом
     * означает, что значение уже разбирают тернарником, а не печатают).
     */
    const files = [...codeFiles(SRC), ...codeFiles(join(MOBILE, "src")), ...codeFiles(join(MOBILE, "app"))];
    const offenders: string[] = [];
    for (const file of files) {
      if (ALLOWED.has(rel(file))) continue;
      for (const expr of rawServerValues(readFileSync(file, "utf8"))) {
        offenders.push(`${rel(file)}: {${expr}}`);
      }
    }
    expect(offenders).toEqual([]);
  });

  test("оболочка страницы читается вместе с исходниками", () => {
    /*
     * index.html обход каталога не видел вовсе: он собирает .ts и .tsx.
     * А это первое, что показывает браузер, — и единственный текст, который
     * человек видит, пока приложение грузится. Забытая там строка живёт
     * вечно: ни один экранный тест до неё не доходит, потому что к моменту
     * проверки её уже перерисовал React.
     */
    const html = readFileSync(join(WEB, "index.html"), "utf8");
    expect(html).toContain("<title>");

    // комментарии разметки — такое же пояснение для разработчика, как // в коде
    const visible = html.replace(/<!--[\s\S]*?-->/g, " ");
    const offenders: string[] = [];
    for (const m of visible.matchAll(/>([^<>]*)</g)) {
      const text = m[1]!.replace(/\s+/g, " ").trim();
      if (text && CYRILLIC.test(text)) offenders.push(`index.html: ${text}`);
    }
    expect(offenders).toEqual([]);
  });

  test("у каждого ключа есть оба перевода и они не совпадают по недосмотру", () => {
    /*
     * Совпадение допустимо: «Пароль», «Email», «Дата» одинаковы на обоих
     * языках. Проверяется другое — что перевод не пустой и не остался
     * заглушкой вида «TODO».
     */
    const bad: string[] = [];
    for (const [key, pair] of Object.entries(UI)) {
      if (!pair.uk?.trim()) bad.push(`${key}: пустой uk`);
      if (!pair.ru?.trim()) bad.push(`${key}: пустой ru`);
      if (/TODO|FIXME|xxx/i.test(pair.uk + pair.ru)) bad.push(`${key}: заглушка вместо перевода`);
    }
    expect(bad).toEqual([]);
  });
});

/*
 * Все три словаря, а не один.
 *
 * UI зовёт клиент, ERRORS отдаёт сервер отказом, PUSH уходит уведомлением на
 * экран блокировки. Для человека это один и тот же текст в одном и том же
 * приложении — он не знает, какой из трёх файлов его породил. Пока проверка
 * смотрела только в UI, в ERRORS спокойно жили семь «уже» при одиннадцати
 * «вже» в UI: словарь-то держался одной формы, приложение — нет.
 */
const DICTIONARIES: [string, Record<string, { uk: string; ru: string }>][] = [
  ["UI", UI as Record<string, { uk: string; ru: string }>],
  ["ERRORS", ERRORS as Record<string, { uk: string; ru: string }>],
  ["PUSH", PUSH as Record<string, { uk: string; ru: string }>],
];

const everyUkString = (): [string, string][] =>
  DICTIONARIES.flatMap(([name, dict]) =>
    Object.entries(dict).map(([key, v]) => [`${name}/${key}`, v.uk] as [string, string]),
  );

describe("украинский не сползает в русский", () => {
  /*
   * Проверка на буквы, которых в украинском алфавите нет.
   *
   * Механическая и потому надёжная: «ы», «ъ», «э», «ё» в украинском поле
   * означают, что туда попал русский текст — не стилистическая шероховатость,
   * а другой язык. Именно так выглядит самая частая ошибка при заполнении
   * двуязычного словаря: скопировали русскую строку в обе колонки.
   */
  test("в украинских строках нет русских букв", () => {
    const wrong: string[] = [];
    for (const [key, uk] of everyUkString()) {
      const hit = [...uk].filter((ch) => "ыъэё".includes(ch));
      if (hit.length) wrong.push(`${key}: ${[...new Set(hit)].join("")} — «${uk}»`);
    }
    expect(wrong).toEqual([]);
  });

  /*
   * Одно понятие — одним словом на весь интерфейс.
   *
   * Правило сформулировано как «форма одна», а не «правильна вот эта».
   * Разница не стилистическая, а практическая: спор о том, «вираженість» или
   * «виразність» точнее, может идти годами и упирается во вкус, а вопрос
   * «называется ли эта величина на сводке и в карте пациента одним словом»
   * имеет единственный ответ и проверяется машиной. Поэтому проверка не знает
   * канона: она падает, когда в словарях встретились ДВЕ формы, и называет
   * обе вместе с ключами — выбирает человек.
   *
   * Что сюда попадает. Только то, где одно и то же понятие названо разными
   * словами: человек читает «Виразність» на сводке и «Вираженість» в карте и
   * вынужден гадать, одна это величина или две. Разница в регистре, длине
   * фразы под место на экране или роде («знято»/«знята») сюда не относится —
   * от неё никто не спотыкается, и правило, которое ловит и её, через месяц
   * выключают целиком.
   *
   * Каждая группа заведена по факту разъезда, а не на всякий случай: список
   * «всего, что теоретически может разойтись» — это способ поссориться с
   * переводчиком, а не проверка.
   */
  /*
   * Границы слова заданы через \p{L}, а не через \b.
   *
   * `\b` в JavaScript считает словом только латиницу и цифры: перед «У»
   * границы для него не существует, и /\b[Уу]же\b/ не находит «Уже маю
   * акаунт» вовсе. Первая редакция этой проверки была именно такой —
   * зелёной на строке, которую она обязана была поймать. Обнаружилось
   * снятием защиты: вернул «Уже», проверка промолчала.
   */
  const ONE_FORM: { термин: string; формы: [string, RegExp][] }[] = [
    {
      термин: "«уже»",
      формы: [
        ["вже", /(?<!\p{L})[Вв]же(?!\p{L})/u],
        ["уже", /(?<!\p{L})[Уу]же(?!\p{L})/u],
      ],
    },
    {
      // клиническая величина: график на сводке и строка в карте пациента
      термин: "выраженность (severity)",
      формы: [
        ["вираженість", /вираж[еі]н/iu],
        ["виразність", /виразн/iu],
      ],
    },
    {
      термин: "войти",
      формы: [
        ["увійти", /(?<!\p{L})[Уу]вій/u],
        ["ввійти", /(?<!\p{L})[Вв]вій/u],
      ],
    },
    {
      термин: "учётная запись",
      формы: [
        ["обліковий запис", /обліков\p{L}*\s+запис/iu],
        ["акаунт", /акаунт/iu],
      ],
    },
    {
      /*
       * «Термін» отдан срочности целиком, «строк» — сроку.
       *
       * Здесь дело не только в том, что форм было две. У них общий корень с
       * «терміновість»: «Термін минув» на экране пациента и «Терміново» в
       * очереди специалиста — разные понятия, набранные одним словом.
       */
      термин: "срок (deadline)",
      формы: [
        ["строк", /(?<!\p{L})[Сс]трок/u],
        ["термін", /(?<!\p{L})[Тт]ермін(?!о)/u],
      ],
    },
    {
      термин: "вопрос",
      формы: [
        ["питання", /(?<!\p{L})[Пп]итанн|(?<!\p{L})[Пп]итань/u],
        ["запитання", /(?<!\p{L})[Зз]апитанн|(?<!\p{L})[Зз]апитань/u],
      ],
    },
    {
      термин: "брошено (прохождение)",
      формы: [
        ["покинуто", /покинут/iu],
        ["кинуто", /(?<!\p{L})[Кк]инут/u],
      ],
    },
    {
      термин: "отправить",
      формы: [
        ["надіслати", /надісл|надсил|надсиланн/iu],
        ["відправити", /відправ/iu],
      ],
    },
    {
      термин: "удалить",
      формы: [
        ["видалити", /видал|видаленн/iu],
        ["вилучити", /вилуч/iu],
      ],
    },
    {
      термин: "только",
      формы: [
        ["лише", /(?<!\p{L})[Лл]ише(?!\p{L})/u],
        ["тільки", /(?<!\p{L})[Тт]ільки(?!\p{L})/u],
      ],
    },
    {
      термин: "специалист",
      формы: [
        ["фахівець", /фахів|фахівц/iu],
        ["спеціаліст", /спеціаліст/iu],
      ],
    },
    {
      /*
       * Апостроф — тоже форма слова.
       *
       * «зв'язок» и «зв’язок» — одно слово, набранное двумя разными знаками:
       * прямым U+0027 и типографским U+2019. На экране разница видна, а
       * поиском по словарю одно не находит другое — и перевод правят в
       * половине мест.
       */
      термин: "апостроф",
      формы: [
        ["’ (U+2019)", /[а-яіїєґ]’[а-яіїєґ]/iu],
        ["' (U+0027)", /[а-яіїєґ]'[а-яіїєґ]/iu],
      ],
    },
  ];

  test("украинский держится одной формы слова", () => {
    const wrong: string[] = [];
    const strings = everyUkString();
    for (const { термин, формы } of ONE_FORM) {
      const встречено = формы
        .map(([имя, pattern]) => ({
          имя,
          ключи: strings.filter(([, uk]) => pattern.test(uk)).map(([key]) => key),
        }))
        .filter((f) => f.ключи.length > 0);
      if (встречено.length < 2) continue;
      const где = встречено
        .map((f) => `«${f.имя}» — ${f.ключи.length} (${f.ключи.slice(0, 3).join(", ")})`)
        .join("; ");
      wrong.push(`${термин}: в словарях сразу ${встречено.length} формы: ${где}. Нужна одна`);
    }
    expect(wrong).toEqual([]);
  });
});

/**
 * Подпись «Мова / Язык / Language» живёт одной записью.
 *
 * Она особенная: словарь по определению отдаёт одну строку на выбранном
 * языке, а здесь нужны сразу оба названия — иначе тот, кто уже переключился
 * на непонятный ему язык, не найдёт дороги назад. Место для такой строки
 * одно: LANG_SELF_LABEL в packages/shared/src/types.ts. Дважды набранная
 * руками, она разъедется молча — в полосе консоли одно, в публичной шапке
 * другое, и смоук, который ищет переключатель по имени, промахнётся.
 *
 * Сторож сырых строк (noRawStrings.test.ts) сюда не дотянется: packages/shared
 * он не читает, а внутри консоли литерал «Мова / Язык» для него — обычная
 * кириллица, без знания о том, что у неё есть законное место.
 */
describe("подпись языка", () => {
  const TYPES = join(ROOT, "packages/shared/src/types.ts");

  test("объявлена один раз и в общей записи", () => {
    // с английским подпись выросла хвостом «/ Language»; начало прежнее — по нему ищут e2e
    const declarations = [...readFileSync(TYPES, "utf8").matchAll(/"Мова \/ Язык \/ Language"/g)];
    expect(declarations, "LANG_SELF_LABEL пропал или набран дважды").toHaveLength(1);
  });

  test("в разметке консоли её литералом не набирают", () => {
    const offenders = codeFiles(SRC)
      .filter((f) => withoutComments(readFileSync(f, "utf8")).includes("Мова / Язык"))
      .map(rel);
    expect(offenders, "подпись языка набрана строкой вместо LANG_SELF_LABEL").toEqual([]);
  });
});
