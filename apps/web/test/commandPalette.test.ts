import { describe, expect, test } from "bun:test";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";

/**
 * Каждый постоянный пункт навигации обязан вести на существующий экран.
 *
 * Проверяются два списка, и оба здесь не случайно: палитра команд и
 * навигация оболочки (рельса и подразделы, shell/nav.ts). Список
 * объявленных маршрутов читается из App.tsx один раз, и заводить ему вторую
 * копию в соседнем файле было бы ровно тем способом, которым две копии
 * расходятся.
 *
 * Шесть из девятнадцати вели в никуда: «Расписание повторов», «Сеансы
 * киоска», «Сравнение», «Надзор», «Состояние подразделения» и «Создать сеанс
 * киоска» указывали на маршруты, которых в приложении нет. Их ловил общий
 * перехват и молча уводил на сводку — человек набирал «расписание», выбирал
 * и оказывался не там, где просил.
 *
 * Это хвост сквозных удалений: экраны убрали, рельсу почистили, палитру
 * забыли. Проверка читает исходники, а не открывает браузер: маршрут в
 * никуда — это несовпадение двух списков, и видеть его надо в тот момент,
 * когда списки разошлись.
 */

const ROOT = resolve(import.meta.dir, "../src");
const APP = readFileSync(resolve(ROOT, "App.tsx"), "utf8");
const PALETTE = readFileSync(resolve(ROOT, "shell/CommandPalette.tsx"), "utf8");
const NAV = readFileSync(resolve(ROOT, "shell/nav.ts"), "utf8");
const APPBAR = readFileSync(resolve(ROOT, "shell/AppBar.tsx"), "utf8");

/** Пути, объявленные в приложении; параметрические приведены к образцу */
const declared = new Set(
  [...APP.matchAll(/path="([^"]+)"/g)].map((m) => m[1]!).filter((p) => p.startsWith("/")),
);

/**
 * Куда ведёт постоянная ссылка: и `to: "/x"` в списке, и `to="/x"` в разметке.
 *
 * Две записи одного и того же — не небрежность: палитра и навигация держат
 * пункты массивом, а полоса приложения ставит знак учреждения ссылкой прямо
 * в разметке. Ловить только первую форму значило бы не проверять как раз
 * тот переход, который человек делает чаще всего, — нажатие на знак.
 */
const linksIn = (src: string) => [...src.matchAll(/\bto[:=]\s*"([^"]+)"/g)].map((m) => m[1]!);

describe("палитра команд", () => {
  test("команд достаточно, чтобы проверка не была пустой", () => {
    expect(linksIn(PALETTE).length).toBeGreaterThan(8);
    expect(declared.size).toBeGreaterThan(20);
  });

  test("каждая команда ведёт на объявленный маршрут", () => {
    const missing = linksIn(PALETTE).filter((to) => !declared.has(to));
    expect(missing).toEqual([]);
  });
});

describe("рельса и подразделы", () => {
  /*
   * Polypsy 2.0: верхней полосы с шестью пунктами больше нет — разделы
   * стоят на рельсе, а их экраны — в колонке подразделов (shell/nav.ts).
   * Знак на полосе приложения ведёт на корень (AppBar.tsx). Ссылки,
   * собранные из адреса открытого человека или экрана (`/patients/${id}/…`),
   * проверяет routeDoors.test.ts по форме маршрута.
   */
  const targets = [...linksIn(NAV), ...linksIn(APPBAR)];

  test("постоянных дверей достаточно, чтобы проверка не была пустой", () => {
    /* рельса (9) и подразделы пациентов, методик, аналитики, администрирования — за три десятка */
    expect(new Set(targets).size).toBeGreaterThan(25);
  });

  test("каждая дверь ведёт на объявленный маршрут", () => {
    const missing = targets.filter((to) => !declared.has(to));
    expect(missing, "пункт навигации ведёт в никуда: общий перехват молча уведёт на сводку").toEqual([]);
  });
});
