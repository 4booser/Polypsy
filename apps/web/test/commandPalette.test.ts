import { describe, expect, test } from "bun:test";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";

/**
 * Каждый постоянный пункт навигации обязан вести на существующий экран.
 *
 * Проверяются два списка, и оба здесь не случайно: палитра команд и шесть
 * пунктов верхнего меню. Список объявленных маршрутов читается из App.tsx
 * один раз, и заводить ему вторую копию в соседнем файле было бы ровно тем
 * способом, которым две копии расходятся. Верхнее меню попало сюда в тот
 * день, когда рельсу заменили полосой: два его пункта — «Аналитика» и
 * «Статистика» — своего экрана не имеют и отправлены на ближайшие
 * существующие, и такая подстановка обязана падать вслух, если завтра
 * подставленный экран уберут.
 *
 * Шесть из девятнадцати вели в никуда: «Расписание повторов», «Сеансы
 * киоска», «Сравнение», «Надзор», «Состояние подразделения» и «Создать сеанс
 * киоска» указывали на маршруты, которых в приложении нет. Их ловил общий
 * перехват и молча уводил на сводку — человек набирал «расписание», выбирал
 * и оказывался не там, где просил.
 *
 * Это хвост сквозных удалений: экраны убрали, рельсу почистили, палитру
 * забыли. Проверка читает исходники, а не открывает браузер: маршрут в
 * никуда — это несовпадение двух списков, и видеть его надо в тот момент,
 * когда списки разошлись.
 */

const ROOT = resolve(import.meta.dir, "../src");
const APP = readFileSync(resolve(ROOT, "App.tsx"), "utf8");
const PALETTE = readFileSync(resolve(ROOT, "shell/CommandPalette.tsx"), "utf8");
const TOPBAR = readFileSync(resolve(ROOT, "shell/Topbar.tsx"), "utf8");

/** Пути, объявленные в приложении; параметрические приведены к образцу */
const declared = new Set(
  [...APP.matchAll(/path="([^"]+)"/g)].map((m) => m[1]!).filter((p) => p.startsWith("/")),
);

/**
 * Куда ведёт постоянная ссылка: и `to: "/x"` в списке, и `to="/x"` в разметке.
 *
 * Две записи одного и того же — не небрежность: палитра держит команды
 * массивом, а полоса ставит знак учреждения ссылкой прямо в разметке. Ловить
 * только первую форму значило бы не проверять как раз тот переход, который
 * человек делает чаще всего, — нажатие на знак.
 */
const linksIn = (src: string) => [...src.matchAll(/\bto[:=]\s*"([^"]+)"/g)].map((m) => m[1]!);

describe("палитра команд", () => {
  test("команд достаточно, чтобы проверка не была пустой", () => {
    expect(linksIn(PALETTE).length).toBeGreaterThan(8);
    expect(declared.size).toBeGreaterThan(20);
  });

  test("каждая команда ведёт на объявленный маршрут", () => {
    const missing = linksIn(PALETTE).filter((to) => !declared.has(to));
    expect(missing).toEqual([]);
  });
});

describe("верхнее меню", () => {
  const targets = linksIn(TOPBAR);

  test("пунктов столько, сколько на макете, и знак в придачу", () => {
    /*
     * Восемь адресов: шесть разделов полосы, седьмой «Лікарі» — он есть только
     * у тех, кому есть кого назначать (кадры f33/f35/f36 против f04), — и знак
     * учреждения. Число проверяется не ради числа — без него проверка ниже
     * проходила бы и на пустом списке, то есть молчала бы ровно в тот день,
     * когда меню разобрали по ошибке.
     */
    expect(targets.length).toBe(8);
  });

  test("каждый пункт ведёт на объявленный маршрут", () => {
    const missing = targets.filter((to) => !declared.has(to));
    expect(missing, "пункт верхнего меню ведёт в никуда: общий перехват молча уведёт на сводку").toEqual([]);
  });
});
