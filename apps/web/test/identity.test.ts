import { describe, expect, test } from "bun:test";
import { readFileSync } from "node:fs";

/**
 * Профиль в консоли берётся из /me, а не из ответа на вход.
 *
 * Долг, ради которого написана проверка, нашли не мы: человек вошёл в
 * консоль и не увидел вкладку «Приглашения», хотя право у него было. Код
 * вкладки был правильным, сервер отвечал «можно» — не хватало одного: после
 * входа профиль брался из ответа на вход, а подсказки меню (ступень
 * должностей и «можно ли выписывать приглашения») считаются на сервере и
 * приезжают только в /me. То есть возможность работала со второй загрузки
 * страницы, и это молчаливое «через раз» хуже честной поломки: жалобу на
 * него написать трудно, а воспроизвести — ещё труднее.
 *
 * Проверка держит разделение обязанностей: вход выдаёт ключи, /me отвечает
 * «кто я и что мне можно». Соблазн вместо этого дослать подсказки в ответ на
 * вход существует и выглядит короче — поэтому здесь и сторож, а не только
 * починка.
 */

const AUTH = readFileSync(new URL("../src/auth.tsx", import.meta.url), "utf8");

/**
 * Тело функции по её началу.
 *
 * Сначала закрывается СПИСОК ПАРАМЕТРОВ, и только потом ищется «{» тела.
 * Первая редакция искала фигурную скобку сразу после имени — и находила её в
 * типе параметра (`res: { token: string; … }`), то есть считала телом
 * функции её же аргумент. Все три проверки падали на исправном коде: сторож,
 * который врёт в свою сторону, отменяют целиком, и вместе с ним уходит то,
 * ради чего он написан.
 */
function bodyOf(source: string, signature: string): string {
  const at = source.indexOf(signature);
  if (at < 0) throw new Error(`в auth.tsx не нашлось «${signature}»`);

  let depth = 0;
  let i = source.indexOf("(", at);
  for (; i < source.length; i += 1) {
    if (source[i] === "(") depth += 1;
    if (source[i] === ")") {
      depth -= 1;
      if (depth === 0) break;
    }
  }

  const from = source.indexOf("{", i);
  depth = 0;
  for (let j = from; j < source.length; j += 1) {
    if (source[j] === "{") depth += 1;
    if (source[j] === "}") {
      depth -= 1;
      if (depth === 0) return source.slice(from, j + 1);
    }
  }
  throw new Error(`тело «${signature}» не закрылось`);
}

describe("кто я — спрашивается у сервера", () => {
  test("приняв токены, консоль спрашивает /me", () => {
    const body = bodyOf(AUTH, "function adopt(");
    expect(
      body.includes("api.me()"),
      "после входа профиль берётся из ответа на вход: подсказки меню приедут только со второй загрузки страницы",
    ).toBe(true);
  });

  test("отказ /me не запирает вошедшего снаружи", () => {
    const body = bodyOf(AUTH, "function adopt(");
    expect(
      /api\.me\(\)\s*\.?\s*\n?\s*\.catch\(/.test(body) || body.includes("api.me().catch("),
      "неудачный запрос профиля оставит человека без входа, хотя ключи он уже получил",
    ).toBe(true);
  });

  test("токены сохраняются до запроса профиля, а не после", () => {
    /*
     * Порядок здесь не косметика: /me идёт с заголовком авторизации, который
     * берётся из хранилища. Спросить профиль раньше, чем положены ключи, —
     * это 401 на каждом входе и падение в запасной путь всегда.
     */
    const body = bodyOf(AUTH, "function adopt(");
    expect(
      body.indexOf("tokenStore.set(") < body.indexOf("api.me()"),
      "профиль запрашивается раньше, чем сохранены ключи — /me ответит отказом",
    ).toBe(true);
  });
});
