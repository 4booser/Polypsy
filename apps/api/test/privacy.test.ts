import { describe, expect, test } from "bun:test";
import { cell } from "../src/lib/privacy";

/**
 * Подавление малых чисел.
 *
 * Отчёты уходят наружу, и по строке «в подразделении двое в тяжёлой полосе»
 * вместе с составом подразделения человек опознаётся. Проверяется здесь не
 * само подавление (оно тривиально), а то, что его нельзя обойти
 * арифметикой: именно так оно и обходилось дважды.
 */

describe("ячейка отчёта", () => {
  test("скрытое число не восстанавливается из доли и знаменателя", () => {
    /*
     * Это правило нарушалось дважды и одинаково: число подавляли, а долю,
     * посчитанную из НЕподавленного числа, отдавали рядом со знаменателем.
     * n = percent × total / 100 — и подразделение с двадцатью замерами и
     * одним тяжёлым по шкале суицидального риска называло этого одного
     * точно.
     */
    const { count, percent } = cell(1, 20);
    expect(count).toBeNull();
    expect(percent, "доля осталась при скрытом числе — оно восстанавливается умножением").toBeNull();
  });

  test("показанное число идёт с долей", () => {
    // подавление не должно превращаться в «ничего не показываем»
    const shown = cell(9, 20);
    expect(shown.count).toBe(9);
    expect(shown.percent).toBe(45);
  });

  test("ноль показывается вместе с долей", () => {
    // «никого нет» не выдаёт никого, а спрятанный ноль заставляет думать,
    // что там кто-то есть
    expect(cell(0, 20)).toEqual({ count: 0, percent: 0 });
  });

  test("пустой знаменатель не даёт ни доли, ни деления на ноль", () => {
    expect(cell(0, 0).percent).toBeNull();
  });
});
