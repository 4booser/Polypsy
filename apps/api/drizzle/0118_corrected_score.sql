-- Сохранённый результат прохождения: балл после поправок (волна 18,
-- участок submit; внешний разбор, CR-105).
--
-- response_scores хранила сырой балл, итоговое значение, максимум и
-- процент, но не балл после поправок от других шкал (K-коррекция). Всё, что
-- собирается из сохранённого результата — повтор сдачи по clientRequestId,
-- разбор прохождения, — выдавало за correctedScore сырой балл, и у шкал с
-- поправкой повтор отличался от первой сдачи числом. Теперь балл после
-- поправок хранится, как и остальные слагаемые ScoreResult: результат
-- восстанавливается по сохранённой версии без пересчёта.
--
-- У существующих строк колонка пуста (NULL): задним числом поправку не
-- восстановить честно, и сборка результата (lib/storedScores.ts) берёт для
-- них сырой балл, когда нормировка не «raw», и итоговое значение, когда
-- «raw» — у неё итог и есть балл после поправок. Права роли приложения на
-- таблицу не меняются: колонка — часть той же таблицы.

ALTER TABLE response_scores ADD COLUMN IF NOT EXISTS corrected_score double precision;

-- Снимок настроек методики каталога (CR-017, тот же участок).
--
-- Локальность методики каталога определялась одной заметкой последней
-- версии содержимого, а правка visibility, инструкции, лимита времени и
-- прочих настроек строки версии не создаёт. Каталог считал такую методику
-- своей неизменённой редакцией и при очередной правке каталога
-- перезаписывал настройки строки целиком — ограниченная методика
-- становилась общедоступной, лимит пропадал, инструкция возвращалась
-- каталоговая.
--
-- Здесь — настройки редакции каталога, с которой строку в последний раз
-- сверял установщик (surveyFields в lib/catalogInstall.ts). Поле строки,
-- равное снимку, не трогали в учреждении — его обновляет редакция каталога;
-- поле, отличное от снимка, — правка учреждения, и обычное обновление её
-- сохраняет; --force возвращает настройки каталога явным решением. У
-- методик, установленных до этой миграции, снимка нет (NULL): первое
-- обновление считает правкой учреждения всё, что отличается от каталога, не
-- трогает его и записывает снимок; дальше разница читается по нему.

ALTER TABLE surveys ADD COLUMN IF NOT EXISTS catalog_fields jsonb;
