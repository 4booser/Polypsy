-- Число попыток у назначения методики.
--
-- Колонка без значения по умолчанию на уровне базы, и это не упущение.
-- Пустое значение означает «попыток не ограничивали» — ровно то, чем были
-- все выданные до сих пор назначения. Поставь здесь `default 1` — и каждое
-- действующее назначение задним числом стало бы одноразовым: человек,
-- проходящий вторую волну замеров, упёрся бы в отказ на ровном месте.
--
-- Единицу подставляет приложение при выдаче нового назначения: там это
-- осознанный выбор, а не следствие миграции. Повторное прохождение той же
-- методики через день портит измерение — человек помнит вопросы и свои
-- ответы, — и если специалисту нужны две попытки, он говорит об этом сам.
alter table survey_access add column if not exists attempts_allowed integer
  check (attempts_allowed is null or attempts_allowed >= 1);
