-- Живые сессии — индексом, а не перебором refresh-токенов (волна 22, #202).
--
-- Живая сессия — семья, в которой есть неотозванный, непогашенный и
-- неистёкший токен (liveTokenCondition, lib/accounts.ts). Почти все строки
-- таблицы — токены, погашенные ротацией: каждое обновление пары гасит
-- прежний и выдаёт новый, и на цели их ~1,3 млн при нескольких тысячах
-- живых. Индекса под условие не было, и сводка сессий техпанели и список
-- «Сесій» перебирали таблицу целиком. Частичный индекс держит только
-- неотозванные и непогашенные токены — открытые сессии и брошенные (срок
-- вышел без выхода), на порядки меньше строк таблицы, — по человеку и
-- сроку: и сводка, и сессии одного человека (sessionCountsOf, ?userId=)
-- отсекают истёкшие по индексу.
--
-- Начало сессии — самый ранний токен семьи (min(created_at) по семье):
-- по индексу одной семьи это было чтение всех её строк, по строке на
-- каждую ротацию. Индекс семьи со временем выдачи отвечает одной строкой и
-- заменяет прежний индекс семьи (отзыв семьи целиком идёт по его началу).
CREATE INDEX IF NOT EXISTS refresh_tokens_live_idx ON refresh_tokens (user_id, expires_at)
  WHERE revoked_at IS NULL AND rotated_at IS NULL;
