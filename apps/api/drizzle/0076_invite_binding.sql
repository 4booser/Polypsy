-- Приглашение с привязкой к методике и к врачу.
--
-- До сих пор приглашение умело привязку только к набору методик. На деле
-- врач выписывает ссылку под конкретный случай: «пройдите вот это и придёте
-- ко мне». Набор для этого слишком крупная единица — в нём несколько
-- методик, — а врача приглашение не называло вовсе, и человек, пришедший по
-- ссылке, оказывался ничьим: его надо было потом искать и закреплять руками.
--
-- Обе колонки необязательны и независимы: приглашение может звать пройти
-- методику без закрепления, закрепить без методики, или и то и другое.
ALTER TABLE invites ADD COLUMN IF NOT EXISTS survey_id text REFERENCES surveys(id) ON DELETE SET NULL;
