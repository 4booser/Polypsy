-- Приём перестал делиться на первичный и повторный, а слот — вмещать больше
-- одного.
--
-- Деление на виды приёма несло одну обязанность: повторные слоты видели
-- только прикреплённые к отделению, а прикрепление создавалось записью на
-- первичный. Это половина сложности всей записи — и она оплачивала правило,
-- которого в поликлинике нет: человек записывается к специалисту, а не
-- доказывает право на второй визит. Прикрепление теперь создаётся первой же
-- записью, какой бы она ни была.
--
-- Вместимость слота больше одного закладывалась под групповую работу,
-- отложенную на неопределённый срок. Колонка стоила одну строку в схеме, но
-- каждая проверка занятости считала «сколько мест осталось» вместо «занято
-- или нет», и в трёх местах это считалось по-разному.
--
-- Колонки не удаляются: в них лежат уже состоявшиеся приёмы, и вид визита —
-- исторический факт, по которому потом отличают первое обращение. Значения
-- перестают влиять на поведение, а новые записи заводятся с умолчанием.
ALTER TABLE slots ALTER COLUMN kind SET DEFAULT 'any';
ALTER TABLE slots ALTER COLUMN capacity SET DEFAULT 1;
ALTER TABLE schedule_templates ALTER COLUMN kind SET DEFAULT 'any';

-- Открытые слоты приводятся к общему виду: разделение больше не действует, и
-- слот, помеченный «повторный», иначе остался бы невидимым для новых людей.
UPDATE slots SET kind = 'any', capacity = 1 WHERE kind <> 'any' OR capacity <> 1;
UPDATE schedule_templates SET kind = 'any' WHERE kind <> 'any';

-- У приёма вид визита остаётся, но заполняется сам: он теперь описание
-- прошлого, а не условие записи.
ALTER TABLE appointments ALTER COLUMN kind SET DEFAULT 'primary';
