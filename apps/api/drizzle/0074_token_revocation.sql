-- А вот НОВЫЕ учётные записи заводятся с меткой «никогда не отзывалось».
--
-- Умолчание now() здесь означало бы, что граница ставится часами СЕРВЕРА
-- БАЗЫ, а отметка в токене — часами процесса приложения. Пока это одна
-- машина, разницы нет; как только база отдельно и её часы уходят вперёд
-- хотя бы на секунду, первый же выданный токен оказывается «выданным до
-- отзыва» — и человек не может войти вовсе, а причину искать негде.
-- Значение по умолчанию не должно зависеть от расхождения часов; все
-- настоящие сдвиги метки делает приложение своим временем.
ALTER TABLE users
  ALTER COLUMN tokens_valid_from SET DEFAULT to_timestamp(0);
