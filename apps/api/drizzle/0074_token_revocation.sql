-- Отзыв access-токена: граница действительности вместо списка отозванных.
--
-- Access-токен — подписанный JWT на тридцать минут; он нигде не хранится, и
-- «отозвать» его можно только сверкой с состоянием на сервере. До сих пор
-- сверки не было вовсе: middleware проверял подпись и существование учётной
-- записи, а POST /logout гасил лишь семью refresh-токенов. После «выйти» и
-- после смены пароля старый токен из localStorage ещё до получаса открывал
-- карты — на общем компьютере в кабинете это означало, что следующий за
-- клавиатурой работает от имени ушедшего.
--
-- Одна колонка вместо таблицы отозванных токенов: строка пользователя и так
-- читается на каждом запросе в requireAuth, и метка рядом с ней достаётся
-- даром, тогда как список означал бы отдельный поход в базу на каждый запрос
-- и чистку просроченных записей. Метка отвечает сразу на все случаи отзыва:
-- выход, смена пароля, смена роли, блокировка — везде верно одно и то же
-- «всё, что выдано раньше, недействительно».
--
-- Значение по умолчанию now() для существующих строк означает, что в момент
-- обновления все выданные ранее access-токены становятся недействительными.
-- Это намеренно и неизбежно: в токене, выданном до этого изменения, нет
-- отметки о времени выдачи, и сверять его не с чем. Сессии консоли
-- переживут обновление незаметно — на 401 она меняет refresh на новую пару.
ALTER TABLE users
  ADD COLUMN IF NOT EXISTS tokens_valid_from timestamptz NOT NULL DEFAULT now();
