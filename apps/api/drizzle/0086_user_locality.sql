-- Населённый пункт пациента: users.locality.
--
-- ═══ Зачем ═══
--
-- Макет фильтрует выборки по населённому пункту («Населений пункт» — в
-- фильтрах статистики на кадрах f07/f25/f28 и в карточке пациента на f19),
-- а в паспортной части учётной записи его не было: sex, birth_date, unit,
-- position, specialty, rank — модель войсковая, а не территориальная. Без
-- поля фильтр нечем наполнить, и экран рисовал бы строку, которая ничего
-- не отбирает.
--
-- ═══ Почему открытым текстом, а не шифрованным, как ФИО и дата рождения ═══
--
-- Шифрованное поле нельзя ни сравнить в SQL, ни сгруппировать — ровно по
-- этой причине дата рождения дублируется снимком возрастной полосы в
-- прохождении (responses.respondent_age_band). Для населённого пункта
-- завести такой же снимок значило бы хранить его дважды и всё равно не
-- уметь фильтровать по нынешнему значению.
--
-- Населённый пункт — квази-идентификатор: сам по себе человека не называет,
-- а в сочетании с полом и возрастом сужает круг. Именно от этого сочетания
-- и защищает порог малых ячеек (lib/privacy.ts): любая выборка, где по
-- населённому пункту остаётся меньше пяти человек, наружу не выходит, а
-- единственная скрытая ячейка прячется вместе с соседней, чтобы не
-- восстанавливаться вычитанием. Шифрование здесь защищало бы от чтения
-- базы напрямую — от этого защищает доступ к базе, — а фильтрацию отняло
-- бы вовсе.
--
-- Поле необязательное: у заведённых людей его нет, и заставлять заполнять
-- задним числом некому. Правит его сам пациент (PATCH /api/auth/me) и
-- регистрационный бланк; посев раздаёт демонстрационным пациентам
-- несколько городов, чтобы фильтр было на чём показать.
ALTER TABLE users ADD COLUMN IF NOT EXISTS locality text;
