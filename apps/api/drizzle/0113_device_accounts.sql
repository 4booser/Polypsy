-- Установка и привязки учётных записей (волна 15, участок devices; внешний
-- разбор, п. 12).
--
-- Строка devices была одна на установку приложения (id — идентификатор,
-- который приложение хранит у себя, offline/device.ts), а user_id — «кто
-- вошёл первым». Второй человек на том же планшете отмечался в ЧУЖУЮ строку
-- и своей не получал: в его списке устройств было пусто, стереть «его»
-- устройство было нельзя, а его офлайн-данные на этой установке управлением
-- устройствами не покрывались вовсе. Смешаны были две разные вещи: установка
-- (платформа, версия сборки, очередь — общие для всех, кто на ней работал) и
-- привязка человека к ней (когда он с неё отмечался, была ли команда
-- стирания ЕМУ и исполнена ли она).
--
-- Теперь строка — пара «установка + учётная запись»: ключ (id, user_id).
-- Каждый, кто вошёл на планшет, получает свою строку при первой же отметке,
-- со своим списком устройств, своей командой стирания и её подтверждением.
-- Отдельной таблицы установок не заводится: всё, что о самой установке
-- (платформа, версия, очередь), приходит с каждой отметкой, и свежее берётся
-- по последней отметке установки (lib/opsData.ts, mobileReport считает
-- установки, а не привязки).
--
-- Существующие строки становятся привязкой первого вошедшего — ровно тем,
-- чем они и были; остальные люди получат свои строки при следующей отметке.
-- Политика строк прежняя (devices_access: своя строка, система и
-- суперадмин) и теперь точна: отметка пишет только строку самого
-- отмечающегося, и системной роли для неё больше не нужно.
