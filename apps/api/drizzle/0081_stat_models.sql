/* ── stat_models ──
   columns — колонки-выборки: у каждой либо presetId, либо собственные
   filters, плюс surveyId и versionId методики и показатели — полосы шкал
   (scaleId, bandId, highRisk) и вопросы с вариантами (questionId,
   optionId, highRisk). highRisk — пометка «ВШР» с кадров f07/f14/f21/f28:
   «високий ступінь ризику», аналитик отмечает ею показатель, попадание в
   который считается признаком риска; по ним расчёт отдаёт долю
   респондентов с хотя бы одним таким попаданием.

   Версия хранится всегда: идентификаторы полос и вариантов принадлежат
   версии, и модель, «плавающая» за действующей версией, после первой же
   правки методики ссылалась бы на несуществующие строки. Кто хочет считать
   по новой версии, перепривязывает показатели руками — ровно как аналитика
   методики просит ?versionId. */
CREATE TABLE IF NOT EXISTS stat_models (
  id text PRIMARY KEY,
  owner_id text NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  title text NOT NULL,
  -- «Короткий опис статистичної моделі» с кадра f26: показывается в списке
  -- рядом с названием, поэтому отдельное поле, а не часть названия
  description text,
  columns jsonb NOT NULL DEFAULT '[]'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
