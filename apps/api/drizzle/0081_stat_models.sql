/* ═══════════ Политики строк ═══════════

   Таблица без политики — дыра, которую видно только проверкой покрытия,
   поэтому политики едут той же миграцией, что и таблицы. Проверка покрытия
   в access.test.ts эти таблицы не нашла бы сама — у них нет колонки со
   ссылкой на пациента, — поэтому statModels.test.ts называет их поимённо.

   Обе таблицы — личные, как patient_groups и cohorts: видит и правит
   владелец, система и суперадмин — всё. Не отделение и не группа методик,
   и это решение, а не пропуск. Модель выражает вопрос одного аналитика —
   «чоловіки 25–45 проти жінок від 35 по шкалі тривоги», — и коллега,
   увидевший чужую модель в общем списке, прочитал бы её как принятый в
   отделении срез. Если общий список понадобится, его заводят явным
   признаком «общая», как у saved_views, а не тем, что политику однажды
   написали шире, чем думали.

   Пациенту не видно ничего: и пресет («жінки від 35 з Києва»), и модель —
   рабочие инструменты персонала, о самом пациенте они ничего не говорят и
   ему не адресованы.

   В самих строках нет ни имён, ни ответов: только правило отбора и
   перечень показателей. Персональные данные появляются при РАСЧЁТЕ — и
   там их держат зона ответственности (lib/scope.ts) и порог малых ячеек
   (lib/privacy.ts), а не политика этих таблиц.

   WITH CHECK с тем же условием — про подмену владельца: без него сотрудник
   мог бы завести пресет или модель на имя коллеги и подложить ему в работу
   срез, которого тот не собирал. */
