-- Раздел «Статистика»: пресеты фильтров выборки и статистические модели.
--
-- ═══ Что это такое ═══
--
-- На макете (кадры f06, f07, f14, f21, f25, f26, f28) раздел «Статистика»
-- отделён от «Аналітики». Аналитика в системе — это методика целиком: её
-- распределения, психометрика, качество данных. Статистика — сравнение
-- ВЫБОРОК: специалист собирает именованную модель из одной или нескольких
-- колонок, у каждой колонки свой набор фильтров по людям (дата, возраст,
-- пол, населённый пункт, группа пациентов, конкретный человек) и своя
-- методика, а ниже — показатели: полосы результата и варианты ответа на
-- выбранные вопросы, каждый с долей респондентов. Кнопка «Оновити»
-- пересчитывает, «Порівняти» ставит колонки рядом.
--
-- Фильтры выборки сохраняются отдельно от моделей — «Пресети фільтрів»
-- (кадр f25): один и тот же срез («чоловіки 25–45») нужен многим моделям,
-- и переписывать его в каждой значило бы, что правка среза не доходит до
-- половины моделей.
--
-- ═══ Почему две таблицы, а не расширение cohorts ═══
--
-- В схеме уже есть cohorts — сохранённое правило отбора людей с условиями
-- по шкалам, повторным замерам и тревогам. Казалось бы, пресет фильтров —
-- это когорта без условий по шкалам. Но у когорты другое назначение и
-- другой контур: она отдаёт СОСТАВ поимённо (POST /api/cohorts/members —
-- отдельное действие с отдельной записью в журнале), а статистика имён не
-- отдаёт никогда, только доли с подавлением малых ячеек. Положить пресеты
-- в cohorts значило бы, что каждый пресет статистики автоматически
-- становится способом получить список людей — контур, который здесь
-- открывать не собирались. Своя таблица держит эту границу устройством, а
-- не договорённостью.
--
-- Модель тоже не сводится к когорте: у неё несколько колонок, и у каждой
-- свои фильтры и своя методика, а в cohorts одна spec на строку.
--
-- ═══ Почему JSONB, а не таблицы колонок и показателей ═══
--
-- Колонки модели лежат одним jsonb, а не тремя таблицами (колонки → полосы
-- → вопросы с вариантами). Модель читается и пишется только целиком —
-- экран конструктора сохраняет всю форму одной кнопкой «Створити», по
-- частям её никто не правит, а отчёт нужен весь и сразу. Три таблицы
-- дали бы три набора политик строк, три каскада и семь запросов на одно
-- открытие экрана — ради выборки, которую ни один запрос не делает
-- отдельно. Форма jsonb проверяется схемой zod на входе (statModelInputSchema)
-- и повторно при расчёте: показатель, которого нет в версии методики,
-- отказ, а не пропуск.
--
-- Ссылки на методику и её версию лежат внутри jsonb и внешним ключом не
-- держатся. Это осознанно: методику нельзя удалить, пока по ней есть
-- прохождения, а модель без прохождений считать нечего; проверка «методика
-- в зоне ответственности и версия её» делается при каждом расчёте, потому
-- что зона меняется, а ключ этого не выразил бы.

/* ── filter_presets ──
   owner_id — restrict, как у cohorts.created_by и patient_groups.owner_id:
   уволенный специалист не уносит с собой то, на что ссылаются модели
   коллег... а точнее — свои же модели: пресет и модель личные, см. политики
   ниже. Сначала явная передача, потом закрытие учётной записи.

   criteria — строки-критерии с кадра f25: дата от/до, возраст от–до, пол,
   населённый пункт, группа пациентов, конкретный человек. Отсутствующий
   ключ — отсутствующая строка формы: «—» на макете убирает критерий, а не
   обнуляет его. */
CREATE TABLE IF NOT EXISTS filter_presets (
  id text PRIMARY KEY,
  owner_id text NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  title text NOT NULL,
  criteria jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
