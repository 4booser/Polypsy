-- Устойчивое имя методики из каталога.
--
-- Установщик каталога запускается на каждом выкате, и опознавать уже
-- установленную методику ему надо чем-то, что не меняется. Название не
-- годится: специалист вправе переименовать методику у себя, и следующий
-- выкат завёл бы её второй раз — а два одинаковых опросника в списке хуже,
-- чем ни одного, потому что прохождения разойдутся между ними и динамика
-- развалится ровно там, где она нужна.
ALTER TABLE surveys ADD COLUMN IF NOT EXISTS catalog_key text;
CREATE UNIQUE INDEX IF NOT EXISTS surveys_catalog_key_uniq
  ON surveys (catalog_key) WHERE catalog_key IS NOT NULL;
