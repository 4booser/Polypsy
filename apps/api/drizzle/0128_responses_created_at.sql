-- Момент вставки прохождения — временем базы, а не человека (волна 22, #203).
--
-- started_at и submitted_at — время того, кто отвечал: офлайн-очередь
-- присылает начало и длительность с устройства через часы и дни, demo-fill и
-- посев пишут прошлые даты. Проверке восстановимости
-- (scripts/verify-backup.sh) нужно другое — была ли строка в базе на момент
-- снимка. По started_at прохождение, вставленное после снимка задним
-- числом, выглядело потерянным копией: ложный ПРОВАЛ.
--
-- У пользователей и методик created_at и так ставит база (now() по
-- умолчанию, приложение его не задаёт); у прохождений такой колонки не было.
--
-- Существующим строкам достаётся время этой миграции: «не позже чем» —
-- правда, а настоящего момента их вставки уже не узнать. now() внутри
-- транзакции неизменен, и Postgres не переписывает таблицу: значение для
-- прежних строк хранится в каталоге.
ALTER TABLE responses ADD COLUMN IF NOT EXISTS created_at timestamptz NOT NULL DEFAULT now();
