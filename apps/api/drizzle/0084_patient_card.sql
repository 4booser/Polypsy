-- «Обрана» группа пациентов: закладка читателя над своими вкладками.
--
-- ═══ Почему таблица, а не флаг в patient_groups ═══
--
-- Столбец favourite в patient_groups напрашивается: группа и так личная, у
-- неё один владелец, — кто ещё будет её «обирать»? Суперадмин. Он видит все
-- группы сотрудников (ему разбирать чужие экраны), и флаг в самой группе
-- означал бы, что закладка суперадмина переставляет вкладку у владельца, а
-- закладка владельца — у суперадмина. Закладка — свойство пары «читатель —
-- группа», и в схеме она лежит ровно так. Заодно это оставляет дверь для
-- общих групп (см. комментарий к patient_groups в 0078: «общая» заводится
-- явным признаком, как у saved_views): у общей группы закладки у каждого
-- свои, и переносить их тогда не придётся.
--
-- ═══ Что это такое ═══
--
-- «Обрана» на кадре f10 — вкладка, которую специалист держит первой, потому
-- что открывает её чаще других. Ни прав, ни назначений, ни состава закладка
-- не меняет; убрать её — не удалить группу.

/* ── patient_group_favourites ──
   Пара ключом: закладка либо есть, либо нет; повторное «обрати» — не
   ошибка и не вторая строка, ровно как повторное «додати пацієнта».

   Каскад по обеим ссылкам: закладка не переживает ни группу, ни учётную
   запись. В строке нет ничего, кроме факта, и хранить её без того, на что
   она указывает, незачем. */
CREATE TABLE IF NOT EXISTS patient_group_favourites (
  user_id text NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  group_id text NOT NULL REFERENCES patient_groups(id) ON DELETE CASCADE,
  added_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, group_id)
);
