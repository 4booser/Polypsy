-- Двенадцать таблиц от снятых возможностей.
--
-- Киоск, консилиумы, цели лечения, маршруты помощи, дежурные смены, запрос
-- информанта, кризисный режим — всё это убрано прямыми решениями, и в коде на
-- эти таблицы не осталось ни одной ссылки. Схему они при этом продолжали
-- описывать: читающий её видел возможности, которых нет, и всякий раз шёл
-- искать, где же они используются.
--
-- Почему удаление, а не комментарий «это остатки». Мёртвая таблица стоит
-- дёшево в работе и дорого в понимании: она же попадает в проверку покрытия
-- политиками RLS, в снимки схемы, в разговор о модели данных. Оставленная
-- «на всякий случай», она остаётся навсегда — случая не наступает.
--
-- Почему это безопасно — и почему проверяется ещё раз. Перед удалением сделана
-- перепись в бою (bun apps/api/src/leftovers.ts): все двенадцать пусты. Но
-- между переписью и выкаткой проходит время, а миграция выполняется на живой
-- базе — и если за это время в таблице что-то появилось, значит возможность
-- вернули, и удаление стало бы потерей клинических записей. Поэтому миграция
-- не доверяет переписи: она проверяет сама и ОСТАНАВЛИВАЕТСЯ с внятным
-- сообщением. Упавшая выкатка чинится за час; удалённая история приёма — нет.
DO $$
DECLARE
  t text;
  n bigint;
BEGIN
  /*
   * Осиротевшая ссылка в живой таблице.
   *
   * patient_notes несла необязательную привязку к маршруту помощи — «заметка
   * как шаг пути». Маршрутов больше нет, и колонка может содержать только
   * NULL: внешний ключ на пустую таблицу другого значения не допускает. То
   * есть удаление колонки ничего не теряет не по нашему обещанию, а по
   * устройству базы. Проверяем всё равно — по той же причине, что и выше.
   *
   * Снимается ДО удаления таблиц, а не после: внешний ключ держит
   * pathway_instances, и обратный порядок упирается в «cannot drop table,
   * other objects depend on it». Подсказка Postgres в этом месте советует
   * CASCADE — ровно то, чего здесь делать нельзя: он унёс бы зависимые
   * объекты молча, вместе с теми, о которых мы не думали.
   */
  IF to_regclass('public.patient_notes') IS NOT NULL
     AND EXISTS (
       SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'patient_notes'
          AND column_name = 'pathway_instance_id'
     ) THEN
    SELECT count(*) INTO n FROM patient_notes WHERE pathway_instance_id IS NOT NULL;
    IF n > 0 THEN
      RAISE EXCEPTION 'patient_notes.pathway_instance_id заполнена у % записей — разберитесь, прежде чем удалять', n;
    END IF;
    ALTER TABLE patient_notes DROP COLUMN pathway_instance_id;
  END IF;

  FOREACH t IN ARRAY ARRAY[
    'kiosk_participants', 'kiosk_sessions',
    'conference_opinions', 'case_conferences',
    'treatment_goals',
    'pathway_progress', 'pathway_instances', 'pathway_steps', 'pathways',
    'duty_shifts', 'informant_requests', 'crisis_periods'
  ] LOOP
    IF to_regclass(format('public.%I', t)) IS NULL THEN
      CONTINUE; -- таблицы уже нет: миграция шла повторно
    END IF;

    EXECUTE format('SELECT count(*) FROM public.%I', t) INTO n;
    IF n > 0 THEN
      RAISE EXCEPTION
        'таблица % не пуста (строк: %) — возможность вернули, удалять нельзя. Разберитесь и уберите её из миграции 0077', t, n;
    END IF;

    -- без CASCADE намеренно: он молча уносит зависимые объекты, а порядок
    -- здесь выстроен от детей к родителям, и обычного DROP достаточно
    EXECUTE format('DROP TABLE public.%I', t);
  END LOOP;

END $$;
