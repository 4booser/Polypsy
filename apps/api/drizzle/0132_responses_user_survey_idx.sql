-- Прохождения человека по методике — индексом по паре (волна 27, perf-day2).
--
-- Очередь работы (routes/worklist.ts) на каждом чтении — а с волны 27 и на
-- каждом такте бейджа «Черга» (GET /api/worklist/count, раз в минуту с
-- каждой открытой консоли) — ищет просроченные повторы: выдачи доступа с
-- пометкой протокола наблюдения, после которых человек методику так и не
-- прошёл (not exists по responses: user_id = … and survey_id = …). Индекса по
-- паре не было, и база склеивала битовые карты двух индексов — по человеку и
-- по методике, а у методики тысячи прохождений. На стенде со ста тысячами
-- прохождений и сотней истёкших повторов один этот запрос шёл 47 мс из 53 у
-- очереди суперадмина; с индексом — 2,7 мс. Тот же поиск — у окон повторов
-- в той же очереди (survey_followups).
--
-- Индекс небольшой: пар «человек — методика» на порядки меньше, чем строк, и
-- B-tree хранит повторы ключа сжато — около мегабайта на сто тысяч
-- прохождений.
CREATE INDEX IF NOT EXISTS responses_user_survey_idx ON responses (user_id, survey_id);
