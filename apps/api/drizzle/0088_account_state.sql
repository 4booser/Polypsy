-- Состояние учётной записи для техпанели: выключение, последний вход,
-- временный пароль.
--
-- ═══ Зачем ═══
--
-- Решение заказчика 2026-09-26: «отдельный дашборд для супер тех админа …
-- посмотреть всех пользователей, выдать кому-то доступ, удалить или создать
-- акк». Удалить учётку с историей нельзя (docs/ARCHITECTURE.md, «Клинические
-- данные не удаляются»; журнал держит actor_id под RESTRICT), а убрать
-- человека из системы надо уметь в тот же день, когда он уволился. Отсюда
-- выключение — обратимое, с причиной и автором, и действующее сразу.
--
-- ═══ disabled_at / disabled_reason / disabled_by ═══
--
-- Метка времени, а не булев флаг: «когда выключили» спрашивают так же часто,
-- как «выключен ли», и ответ на второй вопрос следует из первого. Причина —
-- текстом, как у личного исключения прав: через год разбирают словами, а не
-- кодом. Автор — ссылкой с SET NULL: удаление автора (его и так держит
-- журнал) не должно ни падать на этой колонке, ни уносить строку.
--
-- Выключение проверяется в трёх местах — вход, обновление пары токенов и
-- middleware на каждом запросе (строка пользователя там читается всё равно,
-- колонка рядом достаётся даром). Отзыв сессий при выключении сдвигает
-- tokens_valid_from, но и без этого живой токен выключенной учётки дальше
-- middleware не пройдёт.
--
-- ═══ last_seen_at ═══
--
-- Последний вход или обновление токена. Пишется на входе и на обмене
-- refresh — не на каждом запросе: строка users под нагрузкой всей консоли
-- превратилась бы в точку записи на каждый клик. Обмен случается раз в
-- полчаса работы (срок access-токена), и точности «был сегодня около
-- полудня» техпанели хватает с избытком. Сверх того запись прореживается
-- условием (не чаще раза в пять минут, lib/accounts.ts) — на случай
-- клиента, который меняет пару чаще, чем нужно.
--
-- NULL — «ни разу с появления отметки», а не «никогда»: заполнять задним
-- числом нечем, и выдумывать дату по журналу значило бы выдавать догадку за
-- факт.
--
-- ═══ must_change_password ═══
--
-- Пароль выдан техпанелью — при заведении или сбросе — и его видел тот, кто
-- выдавал. Консоль с этим флагом открывает смену пароля вместо рабочего
-- места; снимается успешной сменой (POST /api/auth/password).
--
-- ═══ Политики строк ═══
--
-- Новых не нужно: users под политиками с 0075, и они строчные — колонки
-- наследуют их целиком. Писать новые колонки может тот же круг, что правит
-- строку сейчас: персонал и система (маршруты закрыты правом users.manage),
-- сам человек — свою строку. Последнее значит, что пациент теоретически
-- может снять себе must_change_password прямым UPDATE в обход маршрутов —
-- и это не дыра: флаг защищает его же пароль от того, кто его выдал, а не
-- систему от него. Снять с себя выключение тем же путём он не может: у
-- выключенной учётки ни вход, ни обмен токена, ни живой токен дальше
-- проверки не проходят, и запроса, в котором его строка была бы «своей»,
-- у него просто нет.
ALTER TABLE users ADD COLUMN IF NOT EXISTS disabled_at timestamptz;--> statement-breakpoint
ALTER TABLE users ADD COLUMN IF NOT EXISTS disabled_reason text;--> statement-breakpoint
ALTER TABLE users ADD COLUMN IF NOT EXISTS disabled_by text;--> statement-breakpoint
-- имя ограничения — то, которое дал бы drizzle-kit: иначе следующий generate
-- выписал бы DROP и ADD того же самого ключа под другим именем
ALTER TABLE users DROP CONSTRAINT IF EXISTS users_disabled_by_users_id_fk;--> statement-breakpoint
ALTER TABLE users ADD CONSTRAINT users_disabled_by_users_id_fk
  FOREIGN KEY (disabled_by) REFERENCES users(id) ON DELETE SET NULL;--> statement-breakpoint
ALTER TABLE users ADD COLUMN IF NOT EXISTS last_seen_at timestamptz;--> statement-breakpoint
ALTER TABLE users ADD COLUMN IF NOT EXISTS must_change_password boolean NOT NULL DEFAULT false;--> statement-breakpoint
-- «последний активный суперадмин» и фильтр «вимкнені» считаются по этой колонке
CREATE INDEX IF NOT EXISTS users_disabled_idx ON users (disabled_at);
