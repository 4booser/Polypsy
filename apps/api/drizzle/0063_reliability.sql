-- Достоверность протокола и успешность нормировки — сохраняются, а не
-- вычисляются при чтении.
--
-- Раньше вывод «протокол недостоверен» жил только в ответе на отправку:
-- динамика, отчёты, когорты и заключения читают сохранённые баллы и узнать
-- об этом не могли. Заключение по проваленной шкале лжи выглядело так же,
-- как по честному протоколу.
ALTER TABLE responses ADD COLUMN IF NOT EXISTS reliable boolean NOT NULL DEFAULT true;

-- Ложь означает, что value — сырой балл: нормы для этого пола нет, балл вне
-- таблицы стенов, знаменатель нулевой. Полосы заданы в единицах нормировки
-- и к такому значению не применяются.
ALTER TABLE response_scores ADD COLUMN IF NOT EXISTS normalized boolean NOT NULL DEFAULT true;
