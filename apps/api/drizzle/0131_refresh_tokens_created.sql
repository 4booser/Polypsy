-- Токены за период — индексом по времени выдачи (волна 23, #205).
--
-- Отчёт «Використання» техпанели (lib/opsData.ts, usageReport) считает
-- «активних людей» в том числе по обменам refresh-токенов: каждая строка —
-- след «был в сети», и берутся строки, выданные за окно отчёта (30 или 90
-- дней). Индекса по created_at не было, и отбор перебирал таблицу целиком:
-- на 1,3 млн строк за два года — 0,2–0,26 с полным просмотром против
-- 15–26 мс по индексу. Ретенция (lib/retention.ts) держит таблицу короче,
-- но окно в 30 дней остаётся долей того, что хранится.
CREATE INDEX IF NOT EXISTS refresh_tokens_created_idx ON refresh_tokens (created_at);
