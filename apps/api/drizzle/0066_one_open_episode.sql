-- Одно открытое обращение на человека — правилом базы, а не проверкой чтением.
--
-- Проверка «нет ли уже открытого» с последующей вставкой гоночная: два
-- специалиста, открывающих обращение одному человеку одновременно — обычное
-- дело при передаче пациента, — создавали два. Дальше код брал произвольное
-- из двух, и часть приёмов подшивалась к одному, часть к другому: ровно та
-- потерянная связь между событиями, ради которой обращение и заведено.

-- Уже существующие дубликаты закрываются: оставляем самое раннее открытое,
-- остальные помечаем закрытыми — иначе индекс не создастся, а разбирать их
-- вручную некому. Исход помечается «переведён»: это ближайшее по смыслу
-- из существующих значений — обращение не завершено, а слито с другим.
UPDATE episodes e
   SET closed_at = now(),
       outcome_kind = COALESCE(outcome_kind, 'transferred')
 WHERE closed_at IS NULL
   AND EXISTS (
     SELECT 1 FROM episodes o
      WHERE o.patient_id = e.patient_id
        AND o.closed_at IS NULL
        AND (o.opened_at < e.opened_at OR (o.opened_at = e.opened_at AND o.id < e.id))
   );

CREATE UNIQUE INDEX IF NOT EXISTS episodes_one_open_idx
  ON episodes (patient_id) WHERE closed_at IS NULL;
