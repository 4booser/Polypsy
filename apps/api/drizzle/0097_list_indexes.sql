-- Индексы под списки (волна 12, участок lists): внешний разбор кода нашёл,
-- что «не хватало индекса risk_alerts.case_id, а индекс открытых случаев не
-- соответствовал запросу». Проверено планом на тестовой базе (40 тысяч
-- случаев, из них 4 тысячи открытых), а не на слово.

-- ═══ risk_alerts.case_id ═══
--
-- Этот индекс уже есть: его завела 0028, и план подтверждает — счётчик
-- сигналов случая и выборка сигналов страницы идут Index Only Scan по нему.
-- Строка здесь — страховка установки, где 0028 по какой-то причине не
-- доехала: без индекса очередь снова делает по последовательному
-- сканированию таблицы сигналов на каждый случай страницы. IF NOT EXISTS
-- делает её пустой там, где всё в порядке.
CREATE INDEX IF NOT EXISTS "alerts_case_idx" ON "risk_alerts" ("case_id");

-- ═══ Очередь открытых случаев ═══
--
-- 0028 завела (last_alert_at DESC, id DESC) WHERE acknowledged_at IS NULL —
-- ровно под тогдашний ORDER BY. Потом очередь стала упорядочиваться сначала
-- по тяжести (тяжёлый случай с третьей страницы иначе там и оставался), и
-- ORDER BY получил ведущее выражение, которого в индексе нет. Индекс
-- превратился в фильтр «открытые»: план брал его битовой картой, поднимал ВСЕ
-- открытые случаи и сортировал их ради первых тридцати одного —
-- 4000 строк и top-N сортировка на каждое открытие очереди (19 мс против
-- 0,3 мс с новым индексом на тех же данных).
--
-- Новый повторяет запрос колонка в колонку, включая выражение тяжести: оно
-- должно совпадать с severityRank в routes/alertCases.ts буквально, иначе
-- планировщик не узнает в нём ключ индекса. Условие курсора — сравнение
-- тройкой — ложится на тот же индекс как Index Cond, так что и вторая
-- страница читает ровно свою порцию.
--
-- Новое имя, а не пересоздание под старым: CREATE INDEX IF NOT EXISTS под
-- прежним именем молча оставил бы старое определение там, где оно уже есть.
-- ПОПРАВКА ПРИ СВЕДЕНИИ ВОЛНЫ 12. Индекс под порядок очереди (тяжесть,
-- время, идентификатор) пережил только до слияния с участком alerts: тот
-- сложил открытую очередь по человеку (distinct on user_id с оконными
-- счётами) и сравнивает время с точностью до миллисекунды — ни один режим
-- очереди этот порядок больше не читает. Индекс, который ничего не отдаёт,
-- только утяжеляет каждую запись случая.
--
-- Горячий путь теперь другой: при каждой сдаче с тревогой открытый случай
-- человека ищется под советующей блокировкой (lib/alertCases.ts,
-- attachCaseRow: user_id = … and acknowledged_at is null), и тот же отбор
-- делает очередь по пациенту. Под него и индекс — частичный, по открытым.
DROP INDEX IF EXISTS "alert_cases_open_idx";
CREATE INDEX IF NOT EXISTS "alert_cases_open_user_idx"
  ON "alert_cases" ("user_id")
  WHERE "acknowledged_at" IS NULL;
