-- Сигнал риска по полосе шкалы, а не только по отмеченному варианту ответа.
--
-- До сих пор тревогу поднимал ТОЛЬКО вариант ответа с riskFlag. У МЛО
-- «Адаптивність-200» — основной методики учреждения — таких вариантов нет
-- ни одного: её шкала суицидального риска выражена полосой стенов, и полоса
-- «вкрай низький рівень» с severity=severe не поднимала ни тревоги, ни
-- случая. Человек с крайним значением по СР просто не появлялся в очереди
-- разбора. То же у PHQ-9: 27 баллов из 27 при ответе «жодного разу» на
-- девятый пункт не давали ничего.
--
-- Сигнал по полосе не привязан к пункту — он привязан к шкале.
ALTER TABLE risk_alerts ALTER COLUMN question_id DROP NOT NULL;
ALTER TABLE risk_alerts ADD COLUMN IF NOT EXISTS scale_id text REFERENCES scales(id) ON DELETE CASCADE;

-- Ровно один сигнал на пару «прохождение + шкала»: пересдача даёт новое
-- прохождение и новый сигнал, а повторная обработка того же — нет.
CREATE UNIQUE INDEX IF NOT EXISTS risk_alerts_scale_uniq
  ON risk_alerts (response_id, scale_id) WHERE scale_id IS NOT NULL;

-- Существующий ключ по пункту остаётся, но теперь только для сигналов
-- пунктов: у сигнала по шкале question_id пуст, и NULL в уникальном
-- индексе не сравниваются между собой — без условия индекс не мешал бы
-- ничему, но и не сторожил бы ничего.
