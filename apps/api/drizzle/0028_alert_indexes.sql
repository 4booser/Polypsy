-- Индексы под горячие пути разбора случаев.
--
-- Оба нашлись нагрузочным профилем на 14 тысячах прохождений: план
-- показывал последовательное сканирование там, где читается пачка строк.

-- Сигналы всегда берутся пачкой по случаю — и списком, и счётчиком. Без
-- индекса это было сканирование всей таблицы на каждый случай на странице,
-- то есть тридцать сканирований на один экран.
CREATE INDEX IF NOT EXISTS "alerts_case_idx" ON "risk_alerts" ("case_id");

-- Прежний индекс (acknowledged_at, last_alert_at) не использовался ни разу:
-- ведущая колонка в сортировке не участвует, и планировщик всё равно шёл
-- сканированием. Новый повторяет запрос списка колонка в колонку.
DROP INDEX IF EXISTS "alert_cases_open_idx";
CREATE INDEX "alert_cases_open_idx"
  ON "alert_cases" ("last_alert_at" DESC, "id" DESC)
  WHERE "acknowledged_at" IS NULL;
