-- Минимальная доля отвеченных пунктов шкалы: scales.min_answered_share.
--
-- ═══ Зачем ═══
--
-- Шкала без единого ответа давала балл 0 — и полосу: три необязательных
-- пункта, пропущенные все, читались как «Норма» (клиническое ревью, волна
-- 12). Ноль здесь выглядит как результат и им не является — невычислимое
-- обязано быть null (docs/ARCHITECTURE.md). Движок теперь не считает шкалу,
-- если отвечено меньше заданной доли пунктов, которые человеку задавали.
--
-- ═══ Почему колонка, а не только константа ═══
--
-- Правило пропусков — свойство методики, а не движка: у одного пособия
-- «не больше двух пропусков», у другого «не меньше половины». Общее
-- умолчание живёт в коде (packages/shared/src/scoring.ts,
-- DEFAULT_MIN_ANSWERED_SHARE), а методика, у которой правило своё,
-- записывает его сюда.
--
-- ═══ Почему допускается null ═══
--
-- null — «как у всех»: умолчание движка. Заполнять существующие строки не
-- нужно и нельзя — у них правила не было, и выдумывать его задним числом
-- для чужих методик незачем. Содержимое версий не переписывается: колонка
-- добавляется, собранные прохождения не пересчитываются.
--
-- Политик строк новая колонка не требует: таблица scales уже под ними.

ALTER TABLE "scales" ADD COLUMN IF NOT EXISTS "min_answered_share" double precision;
