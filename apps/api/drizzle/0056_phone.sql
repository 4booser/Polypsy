-- Телефон обязателен для всех, включая учётные записи под кодом.
--
-- Это меняет смысл слова «анонимный», и в приложении так и написано: запись
-- анонимна ДЛЯ СПЕЦИАЛИСТА — он видит код, а не имя, — но не для учреждения.
-- Обещать полную анонимность и при этом хранить телефон было бы обманом.
--
-- Взамен закрывается самое опасное место: при сработавшей тревоге теперь есть
-- кому позвонить. Раньше у анонима не было ни имени, ни номера — тревога
-- попадала в разбор, и на этом всё заканчивалось.

-- Шифруется тем же механизмом, что ФИО и клинические записи.
alter table users add column if not exists phone_enc text;

-- Слепой индекс от нормализованного номера: сравнить можно, расшифровывать
-- для этого не нужно. Ради него один человек не заводит два аккаунта, чтобы
-- «начать с чистого листа».
alter table users add column if not exists phone_index text;
create unique index if not exists users_phone_index_uniq on users(phone_index)
  where phone_index is not null;

-- Подтверждения нет и не будет: внешнего шлюза нет, кодом из SMS проверять
-- нечем. Колонка заведена, чтобы специалист видел «номер не подтверждён» —
-- показывать непроверенное как проверенное опаснее, чем не показывать вовсе.
alter table users add column if not exists phone_verified boolean not null default false;
