CREATE POLICY survey_folders_access ON survey_folders FOR ALL USING (
  app_role() IN ('system', 'superadmin')
  OR (app_role() = 'admin' AND rls_admin_manages_group(group_id))
) WITH CHECK (
  app_role() IN ('system', 'superadmin')
  OR (app_role() = 'admin' AND rls_admin_manages_group(group_id))
);
