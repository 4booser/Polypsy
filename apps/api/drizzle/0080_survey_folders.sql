/* ═══════════ Политики строк ═══════════

   Таблица без политики — дыра, которую видно только проверкой покрытия,
   поэтому политика едет той же миграцией, что и таблица.

   Вспомогательная функция: «эту группу методик я веду». Тот же подзапрос,
   что внутри rls_admin_sees_survey (0016), но по идентификатору группы, а
   не методики: у папки методик может не быть вовсе, а группа есть всегда —
   и именно по группе решается, кому она видна. Вынесена в функцию, а не
   вписана в политику: WITH CHECK на INSERT проверяет ещё не существующую
   строку, и функция от значения колонки — единственный способ применить одно
   условие и к чтению, и к записи, не переписав его дважды (две копии
   разъехались бы при первой же правке).

   SECURITY DEFINER, потому что читает group_admins, на которой висит своя
   политика: без этого ответ зависел бы от того, видна ли сотруднику его же
   строка назначения, и правка политики group_admins молча меняла бы смысл
   этой. search_path прибит: функция с SECURITY DEFINER без него — это
   приглашение подменить ей таблицу через временную схему. */
CREATE OR REPLACE FUNCTION rls_admin_manages_group(gid text) RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT EXISTS (
    SELECT 1 FROM group_admins ga WHERE ga.group_id = gid AND ga.user_id = app_uid()
  )
$$;
