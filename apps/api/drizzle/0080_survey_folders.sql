/* ── surveys.folder_id ──
   В какой папке лежит методика. NULL — в корне каталога своей группы.

   Ключ СОСТАВНОЙ: (folder_id, group_id) → survey_folders (id, group_id), а
   не простой folder_id → survey_folders (id). Так база сама держит правило
   «методика лежит в папке СВОЕЙ группы». Иначе методику группы А можно было
   бы положить в папку группы Б: те, кто видит методику, не видели бы папку,
   и крошки над ней вели бы в никуда, — а папка показывала бы читателям
   методику, которой им видеть не положено. Правило можно было бы проверять
   в маршрутах — в трёх местах: заведение, перенос, смена группы, — и
   четвёртое место, импорт или установщик каталога, однажды забыли бы.
   Ограничение в базе не забывается и не обходится служебным скриптом.

   MATCH SIMPLE (умолчание): методика без группы с заполненным folder_id
   проверку прошла бы — NULL в любой колонке пары её отключает. Это
   закрывает маршрут: у папки группа обязательна, и методике без группы он
   отказывает явно. MATCH FULL не годится: он запретил бы методику в группе,
   но вне папки, то есть ровно корень каталога.

   ON DELETE SET NULL (folder_id) — только folder_id, не вся пара. Обычный
   SET NULL обнулил бы заодно group_id и выводил бы методику из отделения
   удалением полки; форма с перечнем колонок есть с PostgreSQL 15. Маршрут
   удаления папки досюда не доходит — непустой он отказывает, — обнуление
   на случай каскада от удаления группы и служебных сценариев: методика при
   этом не теряет ничего, кроме полки. */
