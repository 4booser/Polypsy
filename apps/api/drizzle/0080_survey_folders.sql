-- Папки методик: «Мої тести › Тести за 2023 › Тести за лютий 2023».
--
-- ═══ Почему survey_folders, а не folders и не что-либо со словом group ═══
--
-- В схеме уже есть survey_groups, и в коде их зовут просто «группами»:
-- группа МЕТОДИК — единица разграничения доступа. На неё назначают
-- администраторов (group_admins), от неё считается зона ответственности
-- сотрудника (lib/scope.ts), ею закрыты прохождения, тревоги и аналитика.
-- Папка — не это. Папка ничего не открывает и не закрывает: это полка
-- ВНУТРИ группы, по которой уже видимые методики раскладывают для глаз —
-- по годам, по месяцам, по программам обследования.
--
-- Отсюда два требования к имени. Первое: в нём не должно быть слова
-- «группа» ни в каком виде — никаких survey_group_folders или
-- catalog_groups. Две таблицы про «группы методик» с противоположным
-- смыслом сделали бы слово пустым, и запрос «по группе» молча возвращал бы
-- не те методики; ровно от этого уже уберегались, называя patient_groups.
-- Второе: имя обязано говорить, ЧЬИ это папки. Голое folders через год
-- окажется рядом с папками документов или записей приёма, и придётся либо
-- переименовывать, либо жить с таблицей, имя которой ничего не значит.
-- survey_folders стоит в одном ряду с survey_versions и survey_access:
-- всё, что принадлежит методике, называется с этим префиксом.
--
-- ═══ Что это такое ═══
--
-- На макете заказчика (кадр f11): хлебные крошки «Мої тести › Тести за
-- 2023 › Тести за лютий 2023», у каждой папки своя дата («Лютий 2023
-- початок 05.02.2023»), вложенность произвольная, рядом вкладки
-- «Опубліковані / Неопубліковані», поиск и страницы.
--
-- Папка живёт в группе методик и видна тем же, кому видны методики группы;
-- пишет её тот, у кого право surveys.edit, — тот, кто и сами методики этой
-- группы заводит и правит.
--
-- Папка принадлежит ГРУППЕ, а не человеку, и это главное решение здесь.
-- Личные папки — как patient_groups с владельцем — были бы хуже: методика
-- одна на отделение, и раскладка по годам тоже одна. Две личные раскладки
-- одной методики означали бы, что коллеги видят разные каталоги и ищут одно
-- и то же в разных местах, а «положил в папку» одного не видно другому.
-- Личный черновик без группы (surveys.group_id IS NULL) в папку не кладётся
-- по той же причине: у него нет отделения, а значит, нет и каталога. Он
-- получит полку, когда получит группу.

/* ── survey_folders ──
   group_id — каскад. Группа удаляется только пустой — без методик и
   батарей, см. routes/groups.ts, — а папки без методик это пустые полки:
   тащить их за собой удалению незачем. RESTRICT заставил бы сначала
   вычищать полки руками ради группы, в которой уже ничего нет.

   parent_id — RESTRICT, а не CASCADE. Удалить «Тести за 2023» с вложенным
   «лютий 2023» одним нажатием значило бы стереть годовую раскладку и
   вывалить все её методики в корень (см. surveys.folder_id ниже). На экране
   это выглядело бы как «папка исчезла, методики на месте», и никто бы не
   понял, что случилось. Маршрут отказывает раньше базы и называет, что
   именно внутри; ограничение здесь — на случай, если до базы дошли мимо
   маршрута.

   created_by — SET NULL, в отличие от survey_groups.created_by с RESTRICT.
   Там за автором тянется клинический архив, здесь — полка. Держать учётную
   запись уволенного из-за того, что он однажды завёл папку, нельзя. Прав
   папка автору не даёт: кто её видит и правит, решает группа.

   starts_on — дата папки с макета: «Лютий 2023 початок 05.02.2023». Это
   видимое и правимое поле, а не created_at: папку за февраль заводят в
   марте, и дата создания говорила бы неправду. По умолчанию — сегодня:
   папки без даты на макете нет, а заставлять выбирать её при каждом «+»
   незачем, чаще всего это и есть сегодня. */
CREATE TABLE IF NOT EXISTS survey_folders (
  id text PRIMARY KEY,
  group_id text NOT NULL REFERENCES survey_groups(id) ON DELETE CASCADE,
  parent_id text REFERENCES survey_folders(id) ON DELETE RESTRICT,
  title text NOT NULL,
  starts_on date NOT NULL DEFAULT current_date,
  position integer NOT NULL DEFAULT 0,
  created_by text REFERENCES users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  -- папка не бывает собственным родителем. Более длинные циклы («2023» в
  -- «лютий 2023», который в «2023») здесь поймал бы только триггер с
  -- обходом предков; их проверяет маршрут — единственный, кто в таблицу
  -- пишет, — а ограничение закрывает самый короткий и самый вероятный
  CONSTRAINT survey_folders_not_own_parent CHECK (parent_id IS DISTINCT FROM id),
  -- составному ключу у surveys.folder_id (ниже) нужна пара (id, group_id);
  -- уникальность здесь формальная, id и так первичный ключ
  CONSTRAINT survey_folders_id_group_key UNIQUE (id, group_id)
);
