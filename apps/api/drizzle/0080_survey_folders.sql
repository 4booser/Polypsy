/* ── survey_folders ──
   Читает и пишет администратор группы; система и суперадмин — всё.

   Право surveys.edit, которым закрыта запись в маршрутах, политике
   недоступно: права живут в staff_roles и личных исключениях, и спросить их
   из SQL нельзя без второй копии всей раздачи прав. Сетка ловит то, что
   ловится надёжно: контекст без роли (забытый requireAuth) и сотрудника,
   дотянувшегося до полок чужого отделения. Разница между «видит» и «правит»
   внутри отделения остаётся за маршрутом — ровно как у surveys_write, где
   WITH CHECK тоже права не различает.

   Пациенту не видно ничего, и это решение, а не пропуск. Свой список
   методик пациент получает плоским — опубликованные и назначенные ему, — а
   названия папок («Скринінг перед відрядженням», «Група ризику — лютий»)
   говорят о том, зачем отделение собрало методики вместе. Это внутренняя
   раскладка, и пациенту она не адресована.

   WITH CHECK с тем же условием — про подмену группы: без него сотрудник мог
   бы завести (или переставить правкой) папку в группу, которую не ведёт, и
   у методик чужого отделения появилась бы полка, о которой его сотрудники
   не знают и убрать которую не могут. */
ALTER TABLE survey_folders ENABLE ROW LEVEL SECURITY;
