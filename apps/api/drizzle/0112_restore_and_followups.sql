-- ═══ 1. Восстановление 0096_integrity ═══
--
-- Внешний разбор 2026-09-28 (P1). 0096 влилась в main после 0097 и 0098 с
-- меньшим `when`, а drizzle применяет только миграции новее последней
-- применённой. База, мигрированная в промежутке (8ff2014), после обновления
-- 0096 не получила и не узнала об этом: мигратор вышел с кодом 0. Без
-- patient_notes.revision запись заметки отвечала 500, без
-- audit_log.hash_version каждая запись журнала действий падала
-- (audit.write_failed). Прод не задет — 0096–0098 ушли одним выпуском
-- v1.13.0, — но проверки на такой случай не было никакой. Теперь она есть
-- (src/db/migrations.ts, runMigrations): пропущенная миграция роняет
-- выкатку. Эта миграция чинит единственный известный случай, чтобы на
-- базах, которые его пережили, выкатка не встала.
--
-- Разбор 0096 целиком. Она делает ровно три вещи — добавляет колонки с
-- постоянным умолчанием, — и других действий (заполнения, триггеров,
-- политик) в ней нет. Заполнение — само умолчание: ADD COLUMN ... DEFAULT 1
-- даёт 1 всем существующим строкам, не переписывая их (правка каталога,
-- PostgreSQL 11+), поэтому триггеры неизменяемости подписанных документов
-- и журнала не срабатывают. 1 верна и для базы, прожившей без 0096 под
-- новым кодом: этот код не мог записать ни одной строки в эти таблицы — его
-- вставки называют отсутствующие колонки и падали, — значит, все строки там
-- написаны прежним кодом. Для них 1 и есть правда: ревизия 1 — «текст с
-- рождения версии», версия канонизации 1 — ровно то, как прежний код считал
-- хэш. Потерянные записи журнала (audit.write_failed) отсюда не
-- восстанавливаются — их нет ни в какой форме, и выдумывать их нельзя.
--
-- Повтор — теми же операторами, что в 0096, с IF NOT EXISTS: на базе, где
-- 0096 применена (прод, любая чистая установка), это пустые операции.
--
-- Отметка в журнале drizzle. После этих операторов схема ровно такая, как
-- если бы 0096 применилась, — и журнал должен это говорить, иначе сверка
-- runMigrations объявит 0096 пропущенной на базе, которую эта миграция уже
-- восстановила. Хэш и `when` — те же, что drizzle записал бы для 0096 сам
-- (sha256 текста файла; сверяет test/migrationJournal.test.ts). Отметка
-- ставится, только если записи 0096 нет ни по хэшу, ни по времени; на
-- максимальное created_at, по которому drizzle решает, что применять, она
-- не влияет — её время меньше времени этой миграции.

