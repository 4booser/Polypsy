-- Настройки рабочего места.
--
-- Отдельной колонкой JSON, а не таблицей «ключ-значение»: набор настроек
-- читается и пишется целиком, запросов по отдельным ключам не бывает, а
-- таблица на каждую галочку стоила бы соединения на каждый вход.
alter table users add column if not exists workspace jsonb;
