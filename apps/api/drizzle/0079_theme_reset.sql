-- Сброс темы, которую никто не выбирал.
--
-- Консоль при каждом монтировании писала тему в профиль (users.workspace)
-- и в браузер — включая самый первый раз, когда тема была умолчанием, а не
-- выбором. Умолчанием стояла тёмная. Итог: у каждого, кто хоть раз открывал
-- консоль, в профиле лежит "dark", и отличить его от осознанного выбора
-- нельзя — запись одна и та же.
--
-- Умолчание становится светлым: макет заказчика нарисован на белом листе, и
-- консоль обязана открываться так, как нарисована. Сохранённое умолчание
-- перебило бы новое у всех, кроме новых учёток. Поэтому тема из профилей
-- убирается целиком — в том числе у тех немногих, кто тёмную действительно
-- выбрал: выбор возвращается одним нажатием в «Учётной записи», а
-- оставленное «dark» у сотен человек означало бы, что макет не откроется
-- ни у кого. Клиент с этой выкатки сохраняет тему только по нажатию
-- переключателя (см. chooseTheme в App.tsx), так что повторно это не
-- случится.
--
-- Остальные настройки рабочего места (плотность, движение, стартовый экран,
-- скрытые разделы, закрытые подсказки) не трогаются: они умолчания не меняли.
UPDATE users
   SET workspace = workspace - 'theme'
 WHERE workspace ? 'theme';
