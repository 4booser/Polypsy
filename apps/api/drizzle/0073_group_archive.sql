-- Группу нельзя было убрать из обращения, не удалив.
--
-- Удаление разрешено только пустой группе — и это правильно: за группой
-- тянутся батареи, назначения, расписания, а методики без группы становятся
-- личными черновиками создателя. Но отделение, которое расформировали,
-- пустым не бывает никогда: в нём остаются годы прохождений, и удалить их
-- ради порядка в списке — потерять клиническую историю.
--
-- Поэтому у группы появляется снятие с использования, как у методики:
-- запись остаётся целиком, права администраторов не меняются, аналитика
-- продолжает считаться. Меняется одно — снятую группу больше не предлагают
-- при выборе группы для новой методики или батареи.
ALTER TABLE survey_groups ADD COLUMN IF NOT EXISTS archived_at timestamptz;

-- Список групп всегда читается порядком «сначала действующие»: без индекса
-- это сортировка всей таблицы на каждое открытие экрана.
CREATE INDEX IF NOT EXISTS groups_archived_idx ON survey_groups (archived_at);
