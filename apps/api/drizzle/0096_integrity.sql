-- Юридическая и доказательная целостность (волна 12, участок integrity):
-- ревизия содержимого у заключений и заметок приёма и версия канонизации
-- у строк журнала.
--
-- ═══ 1. Ревизия содержимого: зачем ═══
--
-- Решение заказчика 2026-09-26, по внешнему разбору кода. Сохранение и
-- подпись сверялись с номером версии, а номер версии растёт только поверх
-- ПОДПИСАННОГО: черновик правится на месте, и версия у него та же. Значит,
-- A открыл черновик версии 2, B переписал его (всё ещё версия 2), A нажал
-- «підписати» с версией 2 — и подпись легла под текст B, которого A не
-- видел. Той же дырой молча затиралась и чужая правка черновика.
--
-- revision — счётчик правок текста ВНУТРИ версии: 1 при рождении версии,
-- +1 на каждое сохранение черновика на месте. Подпись и сохранение приносят
-- пару «версия + ревизия», которую видел человек, и получают 409, если пара
-- с тех пор сменилась (routes/conclusions.ts, routes/notes.ts).
--
-- Отвергнуто: хэш текста. Он тоже отвечает на вопрос «тот ли это текст», но
-- считать его пришлось бы по расшифрованному тексту на каждое чтение, а
-- клиенту — возвращать строку, смысл которой ему не виден. Счётчик дешевле,
-- читается человеком в журнале («подписана редакция 3») и не повторяется:
-- два одинаковых текста подряд — это две правки, и вторая могла быть чужой.
--
-- ═══ 2. Версия канонизации журнала: зачем ═══
--
-- Полное ревью заказчика (P2): хэш строки журнала не защищал вложенное
-- содержимое details. Канонизация звала JSON.stringify(details, ключи
-- верхнего уровня) — а список ключей у JSON.stringify фильтрует ВСЕ уровни,
-- и { columns: [{ scale: "A" }] } и { columns: [{ scale: "B" }] } давали
-- одну и ту же строку { "columns": [{}] }. Правка вложенного не меняла хэш.
--
-- Новые строки считаются канонизацией версии 2 (ключи упорядочены на всех
-- уровнях, lib/audit.ts). Уже записанные посчитаны версией 1, и пересчитать
-- их нельзя: пересчёт хэшей журнала — это и есть переписывание журнала,
-- ровно то, от чего цепочка защищает. Поэтому версия лежит в самой строке.
--
-- Отвергнуто: граница по номеру или дате («с seq N — версия 2»). Её
-- пришлось бы вычислить в момент миграции, а при выкатке старый процесс
-- ещё пишет в журнал после миграции — его строки, посчитанные по-старому,
-- оказались бы за границей и порвали цепочку. Колонка же с умолчанием 1
-- верна для любого писателя: старый код её не знает и получает 1 — ровно
-- то, как он считал; новый пишет 2 явно.
--
-- Подменить версию у строки, чтобы спрятать вложенную правку, нельзя:
-- канонизация версии 2 начинается с метки "v2", и хэш версии 1 от той же
-- строки не совпадает с записанным. Колонка сама под хэш не идёт — её
-- защищает эта метка и триггер неизменяемости.
--
-- ═══ Почему ADD COLUMN ... DEFAULT, а не UPDATE ═══
--
-- Подписанные документы и журнал защищены триггерами неизменяемости
-- (conclusions_signed_immutable, patient_notes_immutable,
-- audit_log_immutable). ADD COLUMN с постоянным умолчанием — правка
-- каталога (PostgreSQL 11+), строки не переписываются и триггер не
-- срабатывает; существующим строкам достаётся 1 — ровно то, что о них
-- известно.

