-- Язык устройства для уведомлений: push_tokens.lang.
--
-- ═══ Зачем ═══
--
-- Заказчик попросил третий язык интерфейса — английский (2026-09-26).
-- Пуш-уведомление пишется сервером без запроса, и заголовка
-- Accept-Language, по которому сервер выбирает язык всего остального, в
-- этот момент нет. До сих пор язык угадывался по последнему прохождению
-- (responses.lang), и для двух языков это работало: язык интерфейса и язык
-- текста методики совпадали.
--
-- С английским они расходятся. Английского текста у методик нет (нормы
-- сняты с украинского и русского текста — docs/INSTRUMENTS.md), и
-- прохождение честно записывает язык ТЕКСТА: украинский. Угадывание по нему
-- слало бы человеку, выбравшему английский, украинские уведомления — ровно
-- тому, кто по-украински читает хуже всех.
--
-- ═══ Почему на устройстве, а не в профиле ═══
--
-- Уведомление приходит на устройство, и прочесть его должен тот, кто
-- держит это устройство, на языке, на котором у него открыто приложение.
-- Язык устройство и так сообщает с каждым запросом, в том числе с
-- регистрацией для уведомлений, — сохраняется то, что уже приходит, без
-- нового действия от человека. Профиль (users.workspace.lang) знал бы
-- только язык, выбранный вручную, а у большинства он определён по
-- настройкам телефона и нигде не записан.
--
-- ═══ Почему допускается null ═══
--
-- Устройства, зарегистрированные до миграции, языка не прислали. Для них
-- остаётся прежнее угадывание по последнему прохождению, а приложение
-- перерегистрирует устройство при следующем запуске — и пустых значений
-- станет исчезающе мало без всякого переноса данных.
--
-- Ограничение на значения — на случай записи в обход приложения: язык
-- вне списка на уведомлении превратился бы в ключ словаря вместо текста.
ALTER TABLE push_tokens ADD COLUMN IF NOT EXISTS lang text;--> statement-breakpoint
ALTER TABLE push_tokens DROP CONSTRAINT IF EXISTS push_tokens_lang_check;--> statement-breakpoint
ALTER TABLE push_tokens ADD CONSTRAINT push_tokens_lang_check CHECK (lang IN ('uk', 'ru', 'en'));
