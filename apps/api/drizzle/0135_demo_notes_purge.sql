-- Уборка вымышленных людей и их подписанные записи приёма (участок dp-demo).
--
-- Наполнение демонстрационными данными (lib/demoFill.ts) теперь пишет то, без
-- чего карточка не читается: записи приёма, подписанные специалистом. Триггер
-- неизменяемости (0034, 0092) подписанную заметку не отдаёт ни правке, ни
-- удалению — и правильно: это клинический документ. Но demo-purge обязан
-- убирать вымышленное целиком, а удаление вымышленного человека каскадом
-- упиралось бы в первую же его подписанную заметку: «убрать всех
-- вымышленных» перестало бы работать ровно тогда, когда наполнение стало
-- похоже на отделение.
--
-- Обход — уже некуда:
--   · только удаление (правка подписанного по-прежнему — прежний отказ);
--   · только в режиме уборки: app.demo_purge = 1 ставит purgeDemoData через
--     set_config(..., true) в своей транзакции; служебный режим перешифровки
--     (app.maintenance) удаления не открывает, как и раньше;
--   · только заметки о вымышленном человеке: почта пациента на домене
--     demo.local — тот же признак, по которому уборка выбирает людей. Домен
--     зарезервирован и существовать не может; подписанная заметка о
--     настоящем человеке не удаляется ни в каком режиме.
--
-- Проверка домена идёт по строке пациента, пока она есть: уборка удаляет
-- заметки ДО людей (каскад от users проверить уже нечего — строка пациента к
-- тому моменту удалена, и обход не сработал бы).
CREATE OR REPLACE FUNCTION patient_notes_immutable() RETURNS trigger AS $$
BEGIN
  IF old.status = 'signed' THEN
    IF tg_op = 'UPDATE'
       AND current_setting('app.maintenance', true) = '1'
       AND (to_jsonb(new) - 'text') = (to_jsonb(old) - 'text') THEN
      RETURN new;
    END IF;
    IF tg_op = 'DELETE'
       AND current_setting('app.demo_purge', true) = '1'
       AND EXISTS (SELECT 1 FROM users u WHERE u.id = old.user_id AND u.email LIKE '%@demo.local') THEN
      RETURN old;
    END IF;
    RAISE EXCEPTION 'Подписанная заметка неизменяема';
  END IF;
  RETURN CASE WHEN tg_op = 'DELETE' THEN old ELSE new END;
END;
$$ LANGUAGE plpgsql;
