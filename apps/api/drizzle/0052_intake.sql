-- Скрининг при записи на первичный приём.
--
-- Первичный приём наполовину уходит на заполнение бланков: час разговора
-- превращается в полчаса разговора и полчаса анкет. Если короткий скрининг
-- пройден до приёма, специалист начинает с разговора.

-- Какую методику отделение даёт при записи. NULL — не даёт вовсе, и это
-- нормальное состояние: скрининг заводится осознанно, а не появляется сам.
alter table departments add column if not exists screening_survey_id text
  references surveys(id) on delete set null;

-- Откуда взялось прохождение.
--
-- Раньше все прохождения были неразличимы, и «пришёл сам» ничем не
-- отличалось от «назначили». Для клинической записи это разные вещи:
-- самообращение — само по себе сведение о человеке, а скрининг при записи
-- нельзя показывать пациенту баллами.
alter table responses add column if not exists source text
  check (source is null or source in ('assigned', 'self', 'kiosk', 'clinician', 'informant', 'intake'));
