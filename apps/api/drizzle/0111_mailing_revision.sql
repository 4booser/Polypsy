-- Редакция черновика рассылки (волна 15, участок transitions).
--
-- Внешний разбор 2026-09-28, п. 1: правка черновика и его отправка,
-- пришедшие одновременно, доставляли НОВЫЙ текст ПРЕЖНИМ адресатам.
-- Отправка читала черновик и разворачивала адресатов до того, как брала
-- строку, а правка тем временем успевала записать другой текст и другого
-- адресата; условие status = 'draft' у обеих это пропускало — черновик
-- оставался черновиком. Пациент A читал письмо, написанное для B.
--
-- Согласованность теперь держит блокировка строки в маршруте (routes/
-- mailings.ts): и правка, и отправка берут строку FOR UPDATE и решают по
-- тому, что прочитали под замком. Этот столбец отвечает на второй вопрос —
-- «уходит ли то, что человек видел»: каждая правка поднимает номер, экран
-- называет номер, который показывал, и отправка (или правка) поверх чужой
-- правки получает 409, а не рассылает чужой текст от имени отправителя.
--
-- Номер, а не updated_at: время правки — метка для людей, и две правки в
-- одну миллисекунду (или часы разных процессов) сделали бы разные редакции
-- неразличимыми. Существующие черновики начинают с 1, как новые.
--
-- Политики строк не меняются: столбец живёт в строке, доступ к которой уже
-- решает mailings_read / mailings_write (0083).

