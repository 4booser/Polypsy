/**
 * Пройти по черновику методики и сделать двуязычными читаемые строки.
 *
 * Обход, а не правка на месте: строки лежат на пяти уровнях — заголовок,
 * разделы, шкалы, полосы, вопросы, варианты, — и переписывать их по одной
 * значит однажды пропустить уровень.
 *
 * Строка без перевода роняет посев, а не остаётся молча: молча оставленный
 * русский и есть то, из-за чего приложение в украинском режиме выглядит
 * русским.
 */
export function bilingual<T>(value: T, missing: Set<string>): T {
  if (Array.isArray(value)) return value.map((v) => bilingual(v, missing)) as unknown as T;
  if (value && typeof value === "object") {
    const out: Record<string, unknown> = {};
    for (const [k, v] of Object.entries(value as Record<string, unknown>)) {
      if (TEXT_FIELDS.has(k) && typeof v === "string") {
        const uk = UK[v];
        if (!uk) {
          missing.add(v);
          out[k] = v;
        } else {
          out[k] = { uk, ru: v };
        }
      } else {
        out[k] = bilingual(v, missing);
      }
    }
    return out as T;
  }
  return value;
}
