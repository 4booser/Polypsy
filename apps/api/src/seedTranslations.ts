/**
 * Поля, в которых лежит человеческий текст.
 *
 * Список того, ЧТО переводить, а не того, что не переводить. Первая редакция
 * была наоборот — и обход честно перевёл `aggregation: "sum"`, `severity:
 * "none"` и пару идентификаторов: у них нет украинской пары, и посев упал,
 * назвав одиннадцать «непереведённых строк», которые переводить нельзя было
 * вовсе.
 *
 * Список запретов приходится дополнять каждый раз, когда в схеме появляется
 * новое служебное поле, и о нём забывают. Список разрешений дополняют, когда
 * появляется новое читаемое поле, — и о нём не забывают, потому что оно
 * сразу видно непереведённым на экране.
 */
