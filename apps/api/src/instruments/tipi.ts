/**
 * TIPI — десятипунктовый опросник «большой пятёрки»
 * (Gosling S.D., Rentfrow P.J., Swann W.B., 2003). Досье:
 * docs/instruments/dossiers/personality.json, карточка tipi.
 *
 * Основание — слова автора на его странице: «ANYONE CAN USE IT FOR ANY
 * PURPOSE. NO NEED TO ASK ME FOR PERMISSION».
 *
 * ЕДИНСТВЕННАЯ МЕТОДИКА ГРУППЫ БЕЗ РАБОЧЕГО ПЕРЕВОДА. Оба текста —
 * валидизированные адаптации, сделанные с согласия автора и перечисленные им
 * самим: украинский — TIPI-UKR (Кліманська, Галецька, 2019, статья под
 * CC BY-NC-SA 4.0), русский — TIPI-RU (Сергеева, Кириллов, Джумагулова,
 * 2016, PDF лежит на странице автора). Поэтому describe() здесь не стоит:
 * оговорка «Робочий переклад» была бы неправдой. Тексты перенесены дословно,
 * и это решает три вопроса, которые иначе пришлось бы решать самим:
 *
 * • украинские пункты — не подстрочник. Адаптаторы заменили дескрипторы
 *   большинства пунктов по итогам психометрики («Conventional, uncreative» →
 *   «Не любить змін і пошуку нових рішень»). Вернуть буквальный перевод
 *   значило бы взять ту версию, которую сами адаптаторы отвергли по альфе;
 * • русские пункты — в мужском роде («Я воспринимаю себя как открытого…»).
 *   Это свойство опубликованной версии; правка рода изменила бы
 *   валидизированный текст. Украинская версия от пола не зависит —
 *   прилагательные согласованы с «людину, яка є»;
 * • в русской версии шкала подписана только в точках 1, 4 и 7. Так и здесь:
 *   варианты 2, 3, 5, 6 — просто цифры. Отвергнуто дописать подписи по
 *   английскому бланку: русский текст стал бы наполовину нашим.
 *
 * Общая основа пунктов («Бачу себе як людину, яка є» / «Я воспринимаю себя
 * как») — заголовок раздела. Экран прохождения печатает его над каждым
 * пунктом, как на бланке одна строка стоит над списком пар. Отвергнуто
 * склеивать основу с парой в одну фразу: «яка є товариська, активна» — не
 * украинское предложение, а дописанное «товариською» — уже не текст
 * адаптации.
 *
 * ПЯТЬ ШКАЛ ПО ДВА ПУНКТА, СРЕДНЕЕ 1–7, ПОЛОС НЕТ. У автора есть только
 * нормы американской онлайн-выборки (Gosling, Rentfrow, Potter, 2014,
 * «Unpublished Data») — без порогов и без категорий; украинские адаптаторы
 * норм не публиковали. Поэтому шкалы отдают сырое среднее, как «велика
 * п’ятірка» отдаёт сырую сумму без стенов, и у каждой шкалы в описании
 * написано, почему полос нет. Общего балла у TIPI нет.
 *
 * Пятая шкала — эмоциональная СТАБИЛЬНОСТЬ, как у автора: высокий балл —
 * устойчивее. В «великій п’ятірці» каталога та же ось названа нейротизмом и
 * направлена наоборот; код здесь ES, а не N, чтобы при сравнении двух
 * методик знак не перепутали молча.
 *
 * Результат человеку показывается — по тому же основанию, что у «великої
 * п’ятірки»: это описание черт, а не находка, ни одной тяжести и ни одной
 * тревоги здесь нет, а сам автор отдаёт TIPI с обратной связью любому
 * желающему (outofservice.com). Обратный ключ — флагом у пункта, инвертирует
 * движок (min + max − балл = 8 − балл).
 */

