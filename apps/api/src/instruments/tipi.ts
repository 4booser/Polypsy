const ordinal = (n: number) => (ITEMS[n - 1]![3] ? { uk: `${n} (обернений)`, ru: `${n} (обратный)` } : { uk: `${n}`, ru: `${n}` });

const traitScale = ({ code, title, what }: (typeof TRAITS)[number]): ScaleDraft => {
  const [a, b] = itemsOf(code).map(ordinal);
  return {
    code,
    title,
    description: L(
      `${what.uk} Пункти ${a!.uk} і ${b!.uk}. ${NO_BANDS.uk}`,
      `${what.ru} Пункты ${a!.ru} и ${b!.ru}. ${NO_BANDS.ru}`,
    ),
    kind: "clinical",
    aggregation: "average",
    normalization: "raw",
    key: sumKey(itemsOf(code)),
    bands: [],
  };
};

