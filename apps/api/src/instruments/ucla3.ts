/**
 * Трёхпунктовая шкала одиночества — короткая форма пересмотренной шкалы
 * одиночества UCLA (Hughes M.E., Waite L.J., Hawkley L.C., Cacioppo J.T.,
 * 2004; исходная шкала — Russell D., Peplau L.A., Cutrona C.E., 1980).
 *
 * Разрешение опубликовано на официальной странице соавтора шкалы Anne
 * Peplau в UCLA. Оговорка, которую нельзя проглатывать: оно сформулировано
 * для НЕКОММЕРЧЕСКИХ ИССЛЕДОВАТЕЛЬСКИХ целей, и клиническое применение
 * этой фразой прямо не покрыто — подтверждение на клиническое
 * использование запрашивается у D. W. Russell, которому принадлежит
 * копирайт полной версии.
 *
 * ПОЛОС НЕТ, и это решение против ходового обычая. В первоисточнике
 * Hughes et al. (2004) порогов не вводится вовсе; деление «3–5 не одинок /
 * 6–9 одинок» ходит по методичкам и справочникам, но публикацию, где оно
 * установлено и провалидировано автором, найти не удалось — разные работы
 * режут шкалу по-разному. Здесь отделение скринит риск, и придуманная
 * граница означала бы человека, официально признанного «не одиноким» из-за
 * одного балла. Отдаётся сумма 3–9 и её динамика.
 *
 * Пунктов тревоги в шкале нет: вопросов о суициде, самоповреждении или
 * веществах здесь не задаётся. Сам конструкт при этом — фактор риска, и
 * высокий балл имеет смысл читать вместе с PHQ-9 (пункт 9) и СР-45; но
 * правило тревоги живёт в тех методиках, а не в этой, где поднимать её
 * попросту не по чему.
 */

