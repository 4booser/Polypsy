/**
 * PCL-5 — контрольный перечень ПТСР по DSM-5
 * (Weathers F.W. и соавт., Национальный центр ПТСР США, 2013).
 *
 * Разработан за государственный счёт США и находится в общественном
 * достоянии — воспроизводится свободно («This measure was developed by staff
 * at VA's National Center for PTSD and is in the public domain and not
 * copyrighted»). Карточка — docs/instruments/dossiers/trauma.json (pcl5).
 *
 * Методика прицельно важна именно для этого учреждения, и именно поэтому с
 * ней надо аккуратнее прочих: двадцать пунктов подряд просят человека
 * вспоминать травмирующее событие. Отсюда два решения.
 *
 * Результат не показывается человеку: «ймовірний ПТСР», выданное
 * приложением сразу после двадцати таких пунктов, — худшее, что можно
 * сделать с тем, кто их только что прошёл.
 *
 * План безопасности прикладывается к методике. Это единственная методика
 * каталога, где он заполнен: остальные семь не заставляют возвращаться в
 * событие.
 *
 * Текст — рабочий перевод стандартного бланка версии 2023 г. (официально
 * правообладатель выпускает только испанский). Прежняя редакция держала
 * сокращённые формулировки, и сокращение меняло смысл: «strong negative
 * beliefs / feelings» (пп. 9, 11) стало «стійкі» — стойкие, а не сильные;
 * у п. 5 пропало «strong», у пп. 3, 9, 14 — примеры в скобках, по которым
 * человек и понимает, о чём пункт. Рецензия каталога 2.1 вернула полный текст.
 * Инструкция тоже по бланку 2023 г.: «Keeping your worst event in mind» —
 * человек отвечает про одно, самое тяжёлое событие, а не про все сразу.
 */

