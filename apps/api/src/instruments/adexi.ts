/**
 * ADEXI — самоотчёт об исполнительных функциях взрослого: рабочая память и
 * тормозной контроль в повседневной жизни (Holst Y., Thorell L.B., Karolinska
 * Institutet; Int J Methods Psychiatr Res 2018). Досье:
 * docs/instruments/dossiers/cognitive.json, карточка «adexi».
 *
 * Основание — слова правообладателя на www.chexi.se: «All three instruments are
 * freely available for both researchers and clinicians», и для языковых версий
 * с сайта «You do not need the permission of the authors». Украинской версии
 * там нет: для нового языка разработчик просит написать ей и приглашает
 * переводить по шаблонам сайта, — до этого украинский текст рабочий
 * (WORKING_TRANSLATION в украинском описании), а учреждению стоит отправить
 * перевод Lisa Thorell. Русский — перевод с сайта правообладателя (Zarina,
 * Stanevich, Korman; Ariel University): пункты и варианты ответа дословно,
 * включая мужской род глаголов и «первое и последнее» в пункте 5 при «first or
 * last» в оригинале. Изменена только инструкция: на русском бланке «выберите
 * утверждение, наилучшим образом описывающее вас», а в электронной форме ответ
 * выбирается у каждого утверждения — об этом сказано в примечании для персонала.
 *
 * ПОЛОС НЕТ — позиция разработчика: «normative data are unfortunately not yet
 * available … it is not possible to determine exact cut-offs». Порог, взятый из
 * чужого исследования, был бы выдуманной нормой; средние групп из статьи 2018 г.
 * (СДВГ, клинический контроль, неклиническая выборка) стоят в описаниях шкал
 * как ориентир для специалиста — там, где их читает он, а не движок, который
 * красит и поднимает тревогу по полосе, а не по сноске (тот же довод, что у
 * pss10.ts).
 *
 * Подсчёт — средние, а не суммы: документ правообладателя «Subscales for ADEXI»
 * пишет «Mean score for items» для обеих подшкал, а статья 2018 г. приводит все
 * три показателя на шкале 1–5 (полная шкала СДВГ-группы — 3.41). Подшкалы — по
 * тому же документу: рабочая память 1, 2, 5, 7, 8, 9, 11, 12, 13; торможение
 * 3, 4, 6, 10, 14. Обратных пунктов нет: все утверждения — о трудностях.
 * Отвергнуто: сумма 14–70 — её нет ни в документах разработчика, ни в статье, и
 * опубликованные средние стали бы несопоставимы с баллом системы.
 *
 * Результат человеку не показывается: без норм это число без смысла, а
 * «3,4 из 5» рядом с чужим средним по СДВГ легко прочитать как диагноз.
 * Разработчик сам пишет, что пока методика полезнее всего для исследований.
 * Пунктов о суициде, самоповреждении и вреде другим нет — флагов риска нет.
 */

