import type { CreateSurveyDraft } from "@quizzy/shared";
import { L, PUBLIC_DEFAULTS, allItems, bands, describe, item, sumKey } from "./common";
import { K10_ITEMS, KESSLER_ANCHORS, KESSLER_COPYRIGHT, kesslerInstructions } from "./k10";

/**
 * K6 — короткая шкала дистресса Кесслера (Kessler R.C. и соавт., 2003).
 *
 * Основание — то же заявление разработчика, что у K10 (см. k10.ts): свободно,
 * с копирайтом и ссылкой. Карточка — docs/instruments/dossiers/distress.json, k6.
 *
 * Своего текста у K6 нет. Разработчик: «Note that the K6 is merely a truncated
 * form of the K10 in which four questions are deleted»; какие именно — ABS
 * 4817.0.55.001, Table B: K6 1-6 = пункты 2, 4, 5, 8, 9, 10 K10. Пункты берутся
 * из K10_ITEMS по этим номерам — своя копия разошлась бы с K10 в одном слове,
 * и замеры одного человека по K6 и K10 стали бы несравнимыми. Перевод поэтому
 * тот же рабочий, что у K10.
 *
 * Чем опасна ошибка ИМЕННО здесь — в пороге. Шкала ответов 1-5, как у K10
 * (сумма 6-30), и порог «19+» — дословно у разработчика: «The optimal cut
 * point on the K6 for this system is 6-18 versus 19+». В американской шкале
 * 0-4 это знакомое «13+»; перенеси 13 в шкалу 6-30 — и порог провалится ниже
 * середины, а положительным станет почти каждый. Разработчик же предупреждает,
 * что 13+ оптимален «only in a population that has the same prevalence as the
 * total US population»: это сказано в описании, а не только здесь.
 *
 * Положительный K6 — «вероятное серьёзное психическое расстройство» (SMI),
 * то есть вероятность, а не тяжесть: полоса — умеренная тревога, как у
 * положительных фильтров PHQ-4 и SRQ-20. Вопросов о суициде нет, пунктов
 * риска нет. Результат человеку не показывается — как у K10.
 */

