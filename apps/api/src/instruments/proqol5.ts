/** Номера пунктов шкалы — из позиции в массиве, а не руками */
const itemsOf = (code: ScaleCode) => ITEMS.flatMap(([, , scale], i) => (scale === code ? [i + 1] : []));

/** Пункты с обратным ключом — экспорт для золотого теста: 1, 4, 15, 17, 29 по бланку */
export const PROQOL_REVERSED = ITEMS.flatMap(([, , , reverse], i) => (reverse ? [i + 1] : []));

/** Границы формы самооценки — одни на все три шкалы: 22 и меньше, 23–41, 42 и больше */
const LOW = { min: 10, max: 22 };
const MID = { min: 23, max: 41 };
const HIGH = { min: 42, max: 50 };

interface Levels {
  low: Omit<BandSpec, "min" | "max" | "grade">;
  mid: Omit<BandSpec, "min" | "max" | "grade">;
  high: Omit<BandSpec, "min" | "max" | "grade">;
}

const levels = (l: Levels) =>
  bands([
    { ...LOW, ...l.low, grade: 1 },
    { ...MID, ...l.mid, grade: 2 },
    { ...HIGH, ...l.high, grade: 3 },
  ]);

const scale = (code: ScaleCode, title: Loc, description: Loc, l: Levels): ScaleDraft => ({
  code,
  title,
  description,
  kind: "clinical",
  normalization: "raw",
  key: sumKey(itemsOf(code)),
  bands: levels(l),
});

