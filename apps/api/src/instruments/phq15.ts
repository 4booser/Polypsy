/**
 * PHQ-15 — шкала соматических симптомов семейства PHQ
 * (Kroenke K., Spitzer R.L., Williams J.B.W., 2002).
 *
 * Основание: общественное достояние по заявлению издателя (PHQ-15 — в Table 1
 * руководства; подвал бланка: «No permission required to reproduce,
 * translate, display or distribute»). Карточка —
 * docs/instruments/dossiers/distress.json, ключ phq15.
 *
 * Перевод смешанный, и примечание собрано руками, а не через WORKING_TRANSLATION.
 * Русский текст — ОФИЦИАЛЬНЫЙ перевод издателя (MAPI, «Russian for Russia» на
 * phqscreeners.com): шапка, пункты и варианты перенесены дословно, включая то,
 * что хочется «поправить» («бедрах» без «ё», «Запор, склонность к поносу или
 * диарея»). Украинского PHQ-15 у издателя нет — украинский текст рабочий, и
 * примечание для персонала называет рабочим только украинский текст (как у
 * PHQ-4, где статус тоже смешанный).
 *
 * Бланк — отдельный PHQ-15: все 15 пунктов с вариантами «not bothered at all
 * / bothered a little / bothered a lot» (0/1/2). Руководство допускает и
 * вывод PHQ-15 из полного PHQ, где сон и усталость оцениваются частотой;
 * система берёт отдельный бланк — у него одна шкала ответов на все пункты.
 *
 * Пункт 4 (менструальные боли) на бланке помечен «WOMEN ONLY». Руководство не
 * описывает пересчёт для мужчин, поэтому пункт сделан необязательным: мужчина
 * его пропускает, и движок берёт сумму данных ответов без пересчёта (14 из 15
 * — выше минимальной доли 0,8). Альтернатива — пересчёт на 15/14 — отвергнута:
 * такого правила у издателя нет, и это был бы выдуманный коэффициент.
 *
 * Пороги 5/10/15 — дословно из руководства («PHQ-15 scores of 5, 10, and 15
 * represent cutpoints for low, medium, and high somatic symptom severity»).
 * Подписи полос — словами общей лестницы тяжести каталога (мінімальні,
 * легкі, помірні, тяжкі): то же руководство на с. 2 называет эти границы
 * «mild, moderate, and severe levels of … somatic symptoms» наравне с PHQ-9 и
 * GAD-7. Прежние «низька / середня / висока вираженість» были верны, но это
 * другая лестница: «середня» здесь — та же ступень, что «помірна» у PHQ-9 и
 * GAD-7, и рядом в карточке пациента по словам этого не видно.
 * Тяжесть сигнала — по «флажкам» того же руководства: от 10 — «yellow flag»
 * (умеренная тревога), от 15 — «red flag», «active treatment is probably
 * warranted» (тяжёлая).
 *
 * Чем опасна ошибка ИМЕННО здесь — в чтении балла, а не в арифметике. В
 * госпитале с ранеными высокий PHQ-15 часто означает раны и болезни, а не
 * соматизацию: методика не различает причину симптома. Это написано в
 * примечании для персонала, где специалист выбирает методику.
 *
 * Результат человеку не показывается: «тяжкі соматичні симптоми» без
 * специалиста рядом легко прочитать как «со мной что-то не так телесно». Сомнение — в пользу «не показывать».
 */

