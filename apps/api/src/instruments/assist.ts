/**
 * ASSIST v3.1 — скрининг ВОЗ по алкоголю, табаку и другим веществам
 * (Humeniuk R., Henry-Edwards S., Ali R., Poznyak V., Monteiro M.G.; WHO 2010,
 * Appendix A; валидация — Humeniuk и соавт., Addiction 2008). Досье: behaviour.json;
 * порядок вопросов и переходы сверены с текстом Appendix A руководства ВОЗ.
 *
 * Инструмент матричный: вопросы 2–7 задаются по КАЖДОМУ из десяти классов веществ
 * отдельно, и итог — не один балл, а десять отдельных баллов вовлечённости (SSIS),
 * у каждого свои полосы. Сумма по всем веществам в методике не существует.
 *
 * Как матрица выражена моделью. Матричный тип вопроса движка не подходит: у него
 * одна шкала ответов на все строки и один вклад в одну шкалу, а здесь у каждого
 * вопроса свои баллы (Q2: 0/2/3/4/6, Q5: 0/5/6/7/8 …) и вклад идёт в шкалу своего
 * вещества. Поэтому матрица развёрнута: вопрос × вещество — отдельный пункт,
 * у каждого вещества своя шкала-сумма. Переходы бланка — условиями показа:
 *   • Q1 («употребляли ли когда-либо») — фильтр: при «нет» остальные вопросы
 *     об этом веществе не задаются;
 *   • Q2 («как часто за 3 месяца») — тоже фильтр: Q3–Q5 задаются только по
 *     веществам, употреблявшимся за последние 3 месяца («continue with Questions
 *     3, 4 & 5 for each substance used»);
 *   • Q6–Q7 — по всем веществам, употреблявшимся когда-либо («Ask questions 6 & 7
 *     for all substances ever used»).
 * У Q3–Q5 два условия, а не одно («Q2 > 0»): если Q1 переключили на «нет» уже
 * после ответа на Q2, прежний ответ Q2 остаётся в памяти формы, и одно условие
 * снова показало бы Q3–Q5 по веществу, которого человек не употреблял.
 *
 * Условие показа сравнивает балл ответа, поэтому у «Так» в Q1 балл 1. Это не
 * балл методики: Q1 ни в одну шкалу не входит («Do not include the results from
 * either Q1 or Q8»). Отвергнуто: включить Q1 в ключ с весом 0 — чтобы пройти
 * проверку «каждый пункт в какой-то шкале». Это обман проверки; вместо него
 * непосчитанные пункты перечислены явно (ASSIST_NOT_SCORED) с причиной, и
 * проверка каталога требует, чтобы ни один из них не оказался в ключе.
 *
 * Чего модель не выражает и что из этого следует:
 *   • «если "нет" на всё в Q1 — интервью окончено»: условия показа движка
 *     соединяются только через И, «хотя бы одно "да"» не записать. Поэтому Q8
 *     (инъекции) показывается всегда. На балл это не влияет — Q8 не считается,
 *     — а в инструкции сказано отметить «нет, никогда», если на всё было «нет»;
 *   • уточнение «Other – specify» — свободный текст, показывается при «так» в Q1j.
 *
 * Q5 по табаку на бланке не кодируется — пункта нет. Q5 по «другим веществам»
 * напечатан на бланке ВОЗ с баллами 0/4/5/6/7 (как Q4), а не 0/5/6/7/8 — это
 * расхождение самого бланка, и оно воспроизведено, а не «выровнено по смыслу».
 *
 * Q8 — пункт риска по досье: инъекции за последние 3 месяца требуют отдельного
 * действия (выяснить частоту; больше 4 дней в месяц — дальнейшая оценка и более
 * интенсивное лечение). Вариант «да, за последние 3 месяца» поднимает тревогу
 * "moderate". «Да, но не за 3 месяца» — нет: правило ВОЗ говорит о последних
 * трёх месяцах, другое было бы выдуманным порогом.
 *
 * Кто заполняет — специалист (administration: "clinician"). ВОЗ прямо пишет:
 * «as yet the ASSIST has not been validated for self completion by clients».
 * Отвергнуто: общедоступное самозаполнение, как у остальных методик каталога, —
 * пороги установлены для интервью, и самоотчёт мерил бы не то, для чего они.
 *
 * severity полос: «вмешательство не нужно» — none, «краткое вмешательство» —
 * mild, «более интенсивное лечение» — moderate. Краткое вмешательство делает тот
 * же специалист, что ведёт интервью, прямо на приёме (ВОЗ: «Now use ASSIST
 * feedback report card to give client brief intervention»), и случай в очереди
 * риска для него не нужен. Верхняя полоса открывает случай — нужно направление.
 * "severe" отвергнут: в этой системе он означает немедленную опасность, а
 * верхняя полоса ASSIST говорит об интенсивности лечения; острый сигнал
 * методики — Q8, и он размечен отдельно.
 *
 * Перевод рабочий на оба языка — describe(). Официального украинского ASSIST по
 * первоисточнику нет (настанова МЗ отсылает к сайту ВОЗ), русский не подтверждён;
 * ВОЗ требует регистрировать переводы — учреждение заявило, что разрешения у него
 * есть. Пороги чужие — страны валидации названы в описании.
 */

