/** Наибольший возможный балл шкалы — верх последней полосы */
function maxOf(code: string): number {
  return scored.get(code)!.reduce((sum, n) => {
    const scores = questions[n - 1]!.options!.map((o) => o.score ?? 0);
    return sum + Math.max(...scores);
  }, 0);
}

