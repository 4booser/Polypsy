type Rule = NonNullable<QuestionDraft["logic"]>[number];

const choice = (
  title: Loc,
  scaleCode: string | null,
  labels: Loc[],
  scores: number[],
  extra: Partial<QuestionDraft> = {},
): QuestionDraft => ({
  type: "single",
  title,
  required: true,
  ...(scaleCode ? { scaleCode } : {}),
  reverseScored: false,
  options: labels.map((text, i) => ({ text, score: scores[i]! })),
  ...extra,
});

const questions: QuestionDraft[] = [];
/** Номер пункта (с единицы) каждого посчитанного вопроса — по веществу */
const scored = new Map<string, number[]>(SUBSTANCES.map((s) => [s.code, []]));
/** Пункты вне шкал: фильтры Q1, уточнение, Q8 */
const notScored: number[] = [];

/** Кладёт вопрос и возвращает его индекс с нуля — на него ссылаются условия */
function push(q: QuestionDraft, scaleCode: string | null): number {
  const index = questions.push(q) - 1;
  if (scaleCode) scored.get(scaleCode)!.push(index + 1);
  else notScored.push(index + 1);
  return index;
}

