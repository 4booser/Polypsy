/**
 * GAD-7 — скрининг генерализованного тревожного расстройства
 * (Spitzer R.L., Kroenke K., Williams J.B.W., Löwe B., 2006).
 *
 * Опросник распространяется свободно, разрешения на воспроизведение и
 * перевод не требуется — это и делает его пригодным для каталога по
 * умолчанию: методика, за которую надо платить за каждое прохождение, в
 * общедоступный список попасть не может.
 *
 * Результат человеку показывается. Это осознанное отличие от PHQ-9 и PCL-5:
 * «умеренная тревога» — сообщение, с которым человек что-то может сделать
 * сам, и семь пунктов не дают повода думать, что ему поставили диагноз.
 */

/*
 * Шкала ответов — общая с PHQ-9 (подписи из приказа МОЗ №1003).
 *
 * Английские подписи у GAD-7 и PHQ-9 одни и те же слово в слово («Not at
 * all / Several days / More than half the days / Nearly every day»), а у
 * PHQ-9 для них есть официальный украинский текст. Своя подпись здесь
 * означала бы две разные украинские шкалы для одной английской — и PHQ-4,
 * собранный из GAD-2 и PHQ-2, показывал бы человеку четыре пункта с двумя
 * разными наборами ответов. Сами пункты GAD-7 при этом остаются рабочим
 * переводом: официального украинского GAD-7 досье не нашло ни у МОЗ, ни у
 * правообладателя, и оговорка в описании стоит по-прежнему.
 */
