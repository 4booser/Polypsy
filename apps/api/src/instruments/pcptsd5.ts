/**
 * PC-PTSD-5 — скрининг ПТСР по DSM-5 для первичного звена
 * (Prins A., Bovin M.J., Kimerling R., Kaloupek D.G., Marx B.P., Pless Kaiser A.,
 * Schnurr P.P., National Center for PTSD, U.S. Department of Veterans Affairs, 2015;
 * бланк — официальный PDF версии 2022).
 *
 * Основание: правообладатель заявил на своей странице, что методика создана штатом
 * Национального центра ПТСР, находится в общественном достоянии и не защищена
 * копирайтом. Единственное условие правообладателя — применение квалифицированными
 * специалистами; учреждение подтвердило, что разрешения у него есть.
 *
 * Чем опасна ошибка именно здесь. Пять пунктов — весь инструмент, и один лишний или
 * потерянный балл сдвигает человека через порог 4, то есть переводит «скрининг
 * отрицательный» в «вероятный ПТСР» и обратно. У длинной методики одна ошибка тонет
 * в сумме двадцати пунктов, здесь она стоит пятую часть шкалы.
 *
 * Отсеивающий вопрос (gate) не входит в сумму. Бланк требует: «If no, screen total = 0.
 * Please stop here» — человек, не переживавший травматического события, не должен
 * получать пять вопросов о «событии», которого не было. Поэтому пункты 1–5 показываются
 * условной логикой при ответе «Так» на gate, а ключ шкалы начинается со второго вопроса.
 * Отвергнутая альтернатива — задавать все шесть всегда и полагаться на то, что человек
 * без травмы ответит «ні» пять раз: она даёт ту же сумму 0, но заставляет пять раз
 * подряд вспоминать несуществующее событие и ломает смысл отсева.
 *
 * Результат человеку не показывается — по той же причине, что и у PCL-5: «ймовірний
 * ПТСР» сразу после пяти вопросов о травме хуже, чем ничего. План безопасности заполнен:
 * это вторая методика каталога после PCL-5, которая возвращает человека в событие.
 *
 * Текст пунктов — рабочий перевод с английского бланка 2022 года (describe() в описании).
 * Отвергнутая альтернатива — украинская версия ТОВ «ЮЕЙ-ТЕСТ» (Павленко Н. О., 2024): у
 * неё есть своя психометрика, но это не перевод правообладателя (Национальный центр
 * ПТСР официально выпускает только испанский), а её руководство закрыто «Всі права
 * застережено». Взять её пункты значило бы воспроизвести чужой закрытый текст; взять её
 * психометрику к нашему тексту — приписать нашему переводу валидацию, которой у него нет.
 * Поэтому и порог в описании назван как есть: 4, выборка ветеранов первичного звена США.
 */

/** Ответы бланка — только «нет»/«да»; балл равен количеству «да» */
