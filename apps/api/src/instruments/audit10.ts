/**
 * AUDIT — тест выявления расстройств, связанных с употреблением алкоголя
 * (Saunders J.B. и соавт. для ВОЗ, 1993).
 *
 * Издан ВОЗ и свободно воспроизводится.
 *
 * Единственная методика каталога, у которой шкала ответов своя почти у
 * каждого пункта: первые два спрашивают о частоте и дозе, следующие шесть —
 * о частоте признаков, последние два — о событиях, которые либо были, либо
 * нет. Поэтому набор вариантов передаётся в `item()` отдельно на каждый
 * пункт, а не берётся один на всю методику.
 *
 * Восьмой пункт — про провалы в памяти — единственный размечен тревогой:
 * это не «много пьёт», а признак, при котором человека нельзя отпускать до
 * приёма через две недели.
 *
 * ТЕКСТ. Пункты 1–3 по-украински — ОФИЦИАЛЬНЫЕ: рисунок 4.1 «AUDIT-C»
 * клинической настановы МЗ Украины КН 2025-1897 (с. 143), дословно вместе с
 * вариантами ответа (см. AUDIT_CONSUMPTION). Пункты 4–10 — рабочий перевод
 * оригинала ВОЗ (Babor et al., 2001, Box 4 и Box 10), и это не недосмотр:
 * официальные украинские тексты полного AUDIT есть, но дословно ни один не
 * годится.
 *   • Украинский перевод руководства ВОЗ (Центр общественного здоровья МЗ):
 *     интервью (Вставка 4) и самоотчёт (Вставка 10) расходятся между собой; в
 *     Вставке 10 у пунктов 3–8 вместо «Less than monthly» стоит «Раз на місяць
 *     або рідше»; в пункте 10 «стурбованість вашим ставленням до алкоголю, і чи
 *     рекомендував» — «отношение» вместо употребления и «и» вместо «или».
 *   • Стандарт медицинской помощи ГС 2025-1897, приложение 2, — адаптация, а
 *     не перевод: пункт 3 заменён объёмами по полу за 24 часа, у пунктов 3–8
 *     первый вариант «Один раз на місяць або рідше» пересекается со
 *     «Щомісяця». Копия того же текста в приложении настановы — с «180 мг»
 *     вместо мл.
 * Варианты пунктов 4–8 взяты те же, что у официального пункта 3: английская
 * шкала у них одна, и две разные украинские подписи одного «Less than monthly»
 * в одной методике были бы той самой несогласованной шкалой.
 *
 * Перевод пунктов 4–10 сверен с Box 4 руководства ВОЗ: вернулись выпавшие
 * «зазвичай» (normally expected, п. 5), «після того, як напередодні багато
 * випили» (after a heavy drinking session, п. 6; «to get yourself going» —
 * «оговтатися», а не «прийти до тями», то есть очнуться), «через вживання алкоголю»
 * (because you had been drinking, п. 8 — без этого пункт спрашивал о любых
 * провалах памяти), «друзі» и «інший медичний працівник» в п. 10. Варианты
 * пунктов 9–10 — «за останній рік», а не «цього року»: «цей рік» в январе —
 * несколько недель, а ВОЗ спрашивает о последних 12 месяцах.
 */

