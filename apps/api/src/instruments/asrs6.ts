/**
 * ASRS-v1.1, скринер из шести вопросов — признаки СДВГ у взрослых
 * (Adler L., Kessler R.C., Spencer T.; Workgroup on Adult ADHD совместно с ВОЗ;
 * психометрика — Kessler и соавт., Psychol Med 2005). Досье: behaviour.json.
 *
 * ГЛАВНАЯ ЛОВУШКА — ПОДСЧЁТ. Баллы 0–4 у вариантов на бланке — порядковые метки,
 * а не слагаемые. Правило правообладателя: «Add the number of checkmarks that
 * appear in the darkly shaded area. Four (4) or more checkmarks indicate…» —
 * итог есть ЧИСЛО ответов в затемнённой зоне, 0–6. А зона у пунктов разная:
 * у 1–3 затемнены «Иногда», «Часто», «Очень часто», у 4–6 — только «Часто» и
 * «Очень часто». Поэтому «Иногда» засчитывается в первых трёх и не
 * засчитывается в последних.
 *
 * Как это выражено: у варианта балл 1, если он в затемнённой зоне, и 0, если
 * нет; шкала — сумма. Сумма нулей и единиц и есть число отметок в зоне.
 * Отвергнуто:
 *   • сумма частот 0–4 с каким-либо порогом — это другая, не авторская
 *     методика: шесть ответов «Иногда» дают 12 — столько же, сколько «Часто» в
 *     четырёх пунктах и «Никогда» в двух, хотя по бланку первое — отрицательный
 *     скрининг (3 отметки), а второе — положительный (4);
 *   • ключ «совпал ли код варианта» (matchKey) — ключ умеет ждать у пункта ровно
 *     один код, а в затемнённую зону попадают два или три варианта; одинаковые
 *     коды у вариантов одного пункта валидатор запрещает, и правильно.
 * Золотой тест держит оба случая: высокая сумма частот при трёх отметках даёт
 * отрицательный результат.
 *
 * Перевод. Официального украинского перевода у правообладателя нет, русский
 * есть (NYU TOV), но в досье не сверен — поэтому оба языка здесь рабочий
 * перевод, и это сказано через describe(). Правообладатель запрещает любые
 * изменения, кроме электронной формы; учреждение заявило, что разрешения у него
 * есть, но формулировки, порядок пунктов и шкала ответов всё равно не тронуты.
 *
 * Атрибуция обязательна дословно — она в описании (там, где методику видят) и в
 * `source` каталога (там, где её спросят через год).
 *
 * severity положительного скрининга — "mild", а не "moderate". "moderate" в этой
 * системе открывает случай в очереди риска рядом с суицидальными пунктами; СДВГ
 * — не угроза, а находка, требующая планового обследования. Цвет и
 * рекомендацию специалист увидит и без случая. Результат человеку показывается:
 * этот скринер — форма для самого пациента, с самоподсчётом по затемнённым
 * клеткам, и правообладатель сам пишет на ней, что значат четыре отметки.
 */

