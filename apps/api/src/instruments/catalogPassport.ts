import type { CatalogRole, CutoffOp } from "@quizzy/shared";
import { L, type Loc } from "./common";

/**
 * Клинический паспорт методик каталога — по устойчивому ключу (ключ записи
 * CATALOG в ./catalog.ts): роль, что методика измеряет, ключевые пороги, связи
 * полной методики с её короткими формами и шаг ступенчатого скрининга.
 *
 * Зачем отдельно от черновика методики. Черновик — содержимое, от него
 * считается отпечаток редакции (lib/catalogInstall.ts, fingerprint): строка
 * паспорта внутри него выпускала бы новую версию методики с теми же пунктами.
 * Паспорт же — знание каталога о методике, а не её текст: сервер читает его
 * по ключу при каждой выдаче (lib/catalogPassport.ts), и поправка здесь
 * доходит до консоли без версии и без выката каталога.
 *
 * Что здесь есть и откуда:
 *
 *  - role — полная методика / скринінгова (скорочена) форма / оцінка фахівцем
 *    (shared/catalogPassport.ts). Короткой названа форма, которую её
 *    первоисточник представляет как фильтр или как сокращение более длинной
 *    методики; полная методика может быть в каталоге (fullForms) или нет
 *    (GDS-15 — сокращённая GDS-30, AQ-10 — AQ-50). Отнесение — решение,
 *    которое должен подтвердить клинический психолог, как и направления
 *    (catalogDomains.ts);
 *  - purpose — одна строка для специалиста: что измеряет и за какой срок.
 *    Это не описание методики: описание читает обследуемый на первом экране
 *    («Два запитання про настрій…»), а специалисту в каталоге нужен смысл
 *    («скринінг депресії: знижений настрій і втрата інтересу»);
 *  - cutoffs — ключевые пороги строкой каталога. Каждый обязан совпадать с
 *    границей полосы своей шкалы в черновике методики — это проверяет
 *    __tests__/catalogPassport.test.ts: порог паспорта не выдумывается, а
 *    называется словами. Полосы целиком — в паспорте методики;
 *  - steps — ступенчатый скрининг: положительный результат короткой формы
 *    ведёт к полной методике. Порог — граница полосы и цитата первоисточника
 *    (`source`); у методики без порогов у разработчика шага нет (PSS-4 —
 *    короткая форма PSS-10, но «позитивного» PSS-4 не бывает). По каждому
 *    шагу установщик каталога один раз заводит правило поддержки решений
 *    (catalogRules ниже, lib/catalogInstall.ts) — дальше им распоряжается
 *    отделение;
 *  - minutes — время заполнения, только если его называет руководство
 *    методики; иначе сервер считает его по числу пунктов (estimateMinutes).
 *
 * Язык строк — украинский и русский, как у содержимого методик; источник шага
 * — по-украински, как `source` и примечание записи каталога.
 *
 * ── Куда добавлять ── новая методика каталога — записью в блок своего
 * направления. Без записи проверка каталога упадёт с её ключом.
 */

export interface CutoffSpec {
  /** Код шкалы; без кода — порог общий для всех шкал с полосами (CBI, MSPSS) */
  scale?: string;
  op: CutoffOp;
  value: number;
  means: Loc;
}

export interface StepSpec {
  /** Код шкалы короткой формы, по которой решается шаг */
  scale: string;
  op: CutoffOp;
  value: number;
  /** Ключ полной методики каталога */
  next: string;
  /** Откуда порог: автор, год, где опубликован, — по-украински */
  source: string;
}

export interface PassportSpec {
  /** Сокращение, которым методику называют вслух: из него собираются названия правил шага */
  code?: string;
  role: CatalogRole;
  purpose: Loc;
  /** Полные методики каталога для короткой формы; первая — та, под которой стоит строка */
  fullForms?: string[];
  cutoffs?: CutoffSpec[];
  steps?: StepSpec[];
  /** Время заполнения из руководства, минут; без него — по числу пунктов */
  minutes?: number;
}

