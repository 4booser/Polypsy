/** Паспорт по ключу; null — ключа нет (своё свойство, а не унаследованное от Object) */
export function passportSpec(key: string | null | undefined): PassportSpec | null {
  return key && Object.hasOwn(CATALOG_PASSPORT, key) ? (CATALOG_PASSPORT[key] ?? null) : null;
}

/**
 * Глава семьи — полная методика, под которой строка стоит в каталоге: первая
 * из fullForms, иначе сама методика. Ключ, которого в паспорте нет, — сам себе
 * глава.
 */
export function familyHead(key: string): string {
  return passportSpec(key)?.fullForms?.[0] ?? key;
}

/** Короткие формы полной методики — ключи каталога, у которых она среди fullForms */
export function shortFormsOf(key: string): string[] {
  return Object.entries(CATALOG_PASSPORT)
    .filter(([, spec]) => spec.fullForms?.includes(key))
    .map(([k]) => k);
}

/* ─────────── правила ступенчатого скрининга ─────────── */

/**
 * Правило шага, которое установщик каталога заводит один раз
 * (lib/catalogInstall.ts, installRules): «PHQ-2 ≥ 3 → PHQ-9».
 *
 * Название и пояснение — одной украинской строкой, как у наборов-заготовок
 * (CATALOG_BATTERY_LANG): decision_rules.title и note — текст отделения, а не
 * объект языков, и правит их отделение. Ключ правила — пара «короткая форма —
 * полная методика»: у PHQ-4 два шага, к PHQ-9 и к GAD-7, и два правила.
 */
export interface CatalogRuleSpec {
  /** Устойчивое имя правила: `${короткая}-${полная}` */
  key: string;
  /** Ключ короткой формы — методика, по прохождению которой правило срабатывает */
  short: string;
  scale: string;
  op: CutoffOp;
  value: number;
  /** Ключ полной методики — что правило предлагает назначить */
  next: string;
  title: string;
  note: string;
}

const OP_SIGN: Record<CutoffOp, string> = { ">=": "≥", "<=": "≤", ">": ">", "<": "<" };

/** Порог числом по-украински: «2,54», «3» */
const ukNumber = (n: number) => String(n).replace(".", ",");

/**
 * Правила шагов всех методик каталога. `scaleTitle` — название шкалы короткой
 * формы по-украински, когда шаг идёт не по её первой шкале с полосами (PHQ-4:
 * подшкалы депрессии и тревоги), иначе null.
 */
export function catalogRules(scaleTitle: (key: string, scale: string) => string | null): CatalogRuleSpec[] {
  const out: CatalogRuleSpec[] = [];
  for (const [key, spec] of Object.entries(CATALOG_PASSPORT)) {
    for (const step of spec.steps ?? []) {
      const short = spec.code ?? key;
      const next = passportSpec(step.next)?.code ?? step.next;
      const sub = scaleTitle(key, step.scale);
      const condition = `${short}${sub ? ` · ${sub}` : ""} ${OP_SIGN[step.op]} ${ukNumber(step.value)}`;
      out.push({
        key: `${key}-${step.next}`,
        short: key,
        scale: step.scale,
        op: step.op,
        value: step.value,
        next: step.next,
        title: `${condition} → ${next}`,
        note:
          `Ступінчастий скринінг каталогу: результат ${condition} — привід пройти повну методику ${next}. ` +
          `Поріг: ${step.source}. Правило завів установник каталогу один раз; далі ним розпоряджається відділення — ` +
          "змінює поріг або вимикає, і наступні викати каталогу його не чіпають.",
      });
    }
  }
  return out;
}
