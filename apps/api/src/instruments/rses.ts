/**
 * Шкала самооценки Розенберга (RSES)
 * (Rosenberg M., 1965; Society and the Adolescent Self-Image).
 *
 * Распорядитель наследия — кафедра социологии Университета Мэриленда —
 * прямо объявил шкалу общественным достоянием: «The Rosenberg Self-Esteem
 * Scale is now in the public domain, meaning you may use it without charge
 * and without notifying the Sociology Department». Переводы и адаптации
 * разрешены там же, при обычном научном цитировании.
 *
 * ПОЛОС У МЕТОДИКИ НЕТ, И ЭТО НЕ ПРОБЕЛ В ЭТОМ ФАЙЛЕ. Правообладатель
 * отвечает на вопрос о порогах дословно: «There are no discrete cut-off
 * points to delineate high and low self-esteem». Ходовое «меньше 15 —
 * низкая самооценка» не установлено ни в первоисточнике, ни у
 * распорядителя. Завести его значило бы выдать придуманную границу за
 * норму в отделении, где по результатам принимают решения о людях;
 * поэтому методика отдаёт сырой балл 0–30 и динамику — ровно как «велика
 * п’ятірка», у которой по той же причине нет валидированных норм.
 *
 * Отсюда же showResultsToPatient: false. Балл без полосы человек прочитает
 * как оценку («20 из 30»), а объяснить её некому: интерпретация
 * самооценки — это разговор со специалистом, а не число на экране.
 *
 * Пять пунктов — обратные, и это половина методики: без них шкала мерила
 * бы готовность соглашаться. Обратный ключ стоит флагом у пункта,
 * инвертирование делает движок один раз (min+max−балл = 3−балл).
 */

