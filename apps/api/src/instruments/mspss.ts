/** Номера пунктов субшкалы выводятся из того же массива, из которого собраны вопросы */
const itemsOf = (code: (typeof ITEMS)[number][2]) =>
  ITEMS.flatMap((it, i) => (it[2] === code ? [i + 1] : []));

const subscale = (code: (typeof ITEMS)[number][2], title: Loc, description: Loc): ScaleDraft => ({
  code,
  title,
  description,
  kind: "clinical",
  aggregation: "average",
  normalization: "raw",
  key: sumKey(itemsOf(code)),
  bands: SUPPORT_BANDS,
});

