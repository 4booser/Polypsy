/**
 * MSPSS — многомерная шкала воспринимаемой социальной поддержки
 * (Zimet G.D., Dahlem N.W., Zimet S.G., Farley G.K., 1988).
 *
 * Разработчик разрешил свободное использование единственным условием —
 * ссылкой на Zimet et al., 1988; пункты, ключ и полосы взяты с его
 * официальной страницы шкалы.
 *
 * Чем опасна ошибка именно здесь. Социальная поддержка — защитный фактор:
 * по её дефициту не ставят диагноз, но именно она решает, есть ли кому
 * позвонить человеку, у которого ночью стало плохо. Заниженный балл из-за
 * перепутанного ключа означает лишнюю работу с окружением — это дёшево.
 * Завышенный означает «поддержка есть, можно не вмешиваться» у человека,
 * которому звонить некому, и стоит он дорого.
 *
 * ДВА РЕШЕНИЯ, КОТОРЫЕ ЗДЕСЬ ПРИНЯТЫ ЗА НАС И ПОТОМУ ОБЪЯСНЕНЫ.
 *
 * Первое: итог — СРЕДНИЙ балл, а не сумма. Так у автора дословно: «Total
 * Scale: Sum across all 12 items, then divide by 12», и его же полосы
 * заданы в средних баллах 1.00–7.00. Сумма 12–84 дала бы те же протоколы
 * в других единицах, и авторские границы к ней применить было бы нельзя.
 * Движок средние считает сам (aggregation: "average" в computeProfile),
 * поэтому "average" стоит у всех четырёх шкал. Отвергнут обходной путь
 * «сумма плюс полосы, умноженные на 12 и на 4»: 2.9 × 12 = 34.8 — граница,
 * которой у автора нет, и её округление в ту или иную сторону было бы
 * нашим решением, выданным за авторское.
 *
 * Второе: кодировка ответов 1..7, как у Зимета. Свободный украинский
 * посібник Мельника і Стадніка (2023), откуда можно было бы взять готовый
 * украинский текст, кодирует те же варианты как 0..6 — средний балл там
 * смещён ровно на единицу, и авторские полосы к нему неприменимы без
 * пересчёта. Смешать две кодировки значит получить «низьку підтримку» у
 * человека со средней. Здесь зафиксирована кодировка первоисточника.
 */

