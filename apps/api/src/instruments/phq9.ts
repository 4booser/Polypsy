/**
 * PHQ-9 — скрининг депрессии
 * (Kroenke K., Spitzer R.L., Williams J.B.W., 2001).
 *
 * Распространяется свободно, разрешения на воспроизведение не требуется.
 *
 * Украинский текст — ОФИЦИАЛЬНЫЙ: додаток 1 до Уніфікованого клінічного
 * протоколу «Депресія», наказ МОЗ України №1003 від 25.12.2014. Пункты,
 * шапка и варианты ответа перенесены оттуда дословно (подписи полос — нет,
 * см. PHQ_BAND_LABELS), включая то, что хочется «поправить»: во втором
 * пункте у МОЗ «відчуття безпорадності», хотя в английском оригинале
 * «hopeless». Альтернатива —
 * вернуть «безнадію» по оригиналу — отвергнута: тогда это уже не
 * официальный текст, а наш перевод, и оговорка о рабочем переводе снова
 * становится обязательной. Поэтому у PHQ-9 оговорки WORKING_TRANSLATION в
 * примечании для персонала нет, а оба источника названы в каталоге.
 *
 * Русский текст — тоже ОФИЦИАЛЬНЫЙ: перевод правообладателя «PHQ-9 Russian
 * for Ukraine» с phqscreeners.com (файл PHQ9_Russian for Ukraine.pdf, раздел
 * переводов Pfizer; «Відтворення, переклад … дозволяються без попередньої
 * згоди»). Пункты, шапка и варианты ответа перенесены дословно; версия «for
 * Ukraine», а не «for Russia» — она сделана для русскоязычных жителей Украины.
 *
 * Прежняя редакция переводила на русский украинский текст МОЗ: тогда
 * официального русского файла в досье не было, а описание обещало «сверить
 * с официальной русской версией издателя». Сверка (рецензия каталога 2.1)
 * заменила рабочий перевод официальным. Цена известна и названа в примечании для персонала:
 * во втором пункте языковые версии расходятся по смыслу — у МОЗ
 * «безпорадності» (беспомощность), у правообладателя «безысходности» (как
 * «hopeless» оригинала). Расхождение делает МОЗ, а не система; свой
 * русский текст «под МОЗ» означал бы рабочий перевод там, где официальный
 * есть, а свой украинский — отказ от текста приказа.
 *
 * Девятый пункт — про мысли о смерти и самоповреждении — размечен тревогой
 * на уровне варианта ответа. Это единственная причина, по которой методику
 * вообще можно отдавать в самостоятельное прохождение: без разметки система
 * собрала бы такой ответ и положила его лежать до ближайшего приёма.
 *
 * Результат человеку НЕ показывается, и это не перестраховка. План проекта
 * уже сформулировал правило на скрининге при записи: «пацієнт бачить „ми
 * передали відповіді фахівцю“, а не свої бали: інтерпретувати їх нема кому,
 * а тривожна людина з цифрою і без пояснення — гірший результат, ніж людина
 * без цифри». Надпись «тяжка депресія», выданная приложением в три часа
 * ночи, — ровно этот случай.
 */

