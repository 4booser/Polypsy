/**
 * COWS — клиническая шкала синдрома отмены опиоидов (Wesson D.R., Ling W.,
 * J Psychoactive Drugs 2003). Досье: docs/instruments/dossiers/addiction.json,
 * карточка `cows`.
 *
 * Основание: на бланке авторов (Appendix 1 статьи, копия NIDA) — «This version
 * may be copied and used clinically». Ровно это система и делает: оценку ведёт
 * специалист отделения. Публикацию и продажу это разрешение не покрывает.
 *
 * Украинский текст — ОФИЦИАЛЬНЫЙ: додаток 6 к Стандарту медицинской помощи
 * «Психічні та поведінкові розлади внаслідок вживання опіоїдів» (ГС 2025-1102,
 * приказ МЗ Украины от 11.07.2025 № 1102). Пять отступлений от него, каждое
 * сверено с английским бланком и записано в досье:
 *   • «помітне вологість» → «помітна вологість» (согласование);
 *   • в заголовке «Неспокійний стан» убраны слова «температури або діяльності
 *     пацієнта» — в оригинале «Restlessness Observation during assessment», а
 *     оговорка о температуре относится к потоотделению и там уже стоит;
 *   • «потирає суглобу» → «потирає суглоби»;
 *   • русская аббревиатура «ЖКТ» → «шлунково-кишкового тракту»;
 *   • «обведіть кружечком число» → «оберіть число» (электронная форма).
 * Остальное — дословно, включая «патологічний страх» там, где в оригинале
 * «anxious»: это решение переводчика МОЗ, а не опечатка. Русский — рабочий
 * перевод с английского, оговорка стоит только в русском описании (как у CAGE).
 *
 * Баллы вариантов идут с пропусками (0/1/2/4, 0/1/3/5, 0/3/5) — так на бланке,
 * и номер балла стоит в подписи варианта, чтобы специалист сверял с бумажным
 * бланком глазами. «Выровнять» шкалу значило бы считать другую методику.
 *
 * Полосы — с бланка: «5-12 = mild; 13-24 = moderate; 25-36 = moderately severe;
 * more than 36 = severe withdrawal»; МОЗ повторяет их слово в слово. Значения
 * 0–4 бланк не описывает; полоса «нижче порога» — дополнение до опубликованного
 * порога 5, а не новый порог (как 0–1 у CAGE). Без неё баллы
 * 0–4 остались бы без полосы, и проверка покрытия полос справедливо упала бы.
 *
 * severity: 0–4 — none; лёгкий — mild (случая не открывает); умеренный и
 * умеренно тяжёлый — moderate: Стандарт связывает COWS ≥ 13 с началом
 * медикаментозного лечения, это случай на разбор; тяжёлый (> 36) — severe.
 * Пометок риска по пунктам нет: пунктов о суициде, самоповреждении или вреде
 * другим в шкале нет, а правила тревоги по отдельному пункту бланк не даёт.
 *
 * Заполняет специалист, результат человеку не показывается — как у CIWA-Ar.
 */

