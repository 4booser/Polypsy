/** Пункт «близость к попытке»: его «10 — совершил попытку» — тяжёлая тревога */
const ATTEMPT_ITEM = 3;

/**
 * Пункт 0…10. Балл варианта — число с бланка; обратный ключ второго пункта считает движок
 * (reverseScored: min + max − балл), поэтому варианты остаются такими, как на бланке.
 */
function sidasItem(spec: Item, n: number): QuestionDraft {
  const denial = spec.reverse ? 10 : 0;
  return {
    type: "single",
    title: spec.title,
    required: true,
    scaleCode: "SIDAS",
    reverseScored: spec.reverse ?? false,
    options: Array.from({ length: 11 }, (_, v) => {
      const text =
        v === 0 ? L(`0 — ${spec.min.uk}`, `0 — ${spec.min.ru}`) : v === 10 ? L(`10 — ${spec.max.uk}`, `10 — ${spec.max.ru}`) : L(String(v), String(v));
      if (v === denial) return { text, score: v };
      const attempt = n === ATTEMPT_ITEM && v === 10;
      return {
        text,
        score: v,
        riskFlag: true,
        riskSeverity: attempt ? ("severe" as const) : ("moderate" as const),
        riskLabel: attempt
          ? L("SIDAS: спроба самогубства за останній місяць", "SIDAS: попытка самоубийства за последний месяц")
          : L(`SIDAS: ${spec.what.uk} — ${v} з 10`, `SIDAS: ${spec.what.ru} — ${v} из 10`),
      };
    }),
    // пункты 2–5 — только при мыслях о самоубийстве: «0 – Never» на первом — пропуск остальных
    ...(n > 1 ? { logic: [{ sourceIndex: 0, operator: "gte" as const, value: 1, action: "show" as const }] } : {}),
  };
}

