/**
 * SIDAS — шкала характеристик суицидальных мыслей (Suicidal Ideation Attributes Scale;
 * van Spijker B.A.J., Batterham P.J., Calear A.L., Farrer L., Christensen H., Reynolds J.,
 * Kerkhof A.J.F.M., Suicide and Life-Threatening Behavior, 2014). Досье:
 * docs/instruments/dossiers/suicide.json, карточка sidas.
 *
 * Основание: правообладатель (Centre for Mental Health Research, Австралийский национальный
 * университет) пишет «No permission required – please cite reference.» Ссылка стоит в
 * описании и в источнике каталога.
 *
 * Пять пунктов — частота мыслей о самоубийстве, контроль над ними, близость к попытке,
 * мучительность и помехи в повседневных делах — каждый от 0 до 10. Ключ дословно со
 * страницы правообладателя: «the sum of the five items, with controllability reverse scored
 * (10=0, 9=1, …, 0=10). Total scores range from 0 to 50.»
 *
 * Чем опасна ошибка именно здесь — во втором пункте. Контроль считается наоборот: «0 — нет
 * контроля» весит 10. Без обратного ключа человек, который не может остановить эти мысли,
 * получал бы за это меньше баллов, чем тот, кто легко их останавливает, и проходил бы под
 * порогом 21 (пример досье: 24 с обратным ключом, 20 без него).
 *
 * Правило пропуска: «Respondents who respond “0 – Never” to the first item skip all remaining
 * items and score a total of zero.» Пункты 2–5 показываются условием «первый ≥ 1»; скрытый
 * пункт движок не считает «заданным», и сумма при «0» на первом — ноль, как велит бланк.
 * Пропуск ответа при видимом пункте (бланк PMHC MDS): «If any item is missing, the Total
 * Score is set as missing» — поэтому minAnsweredShare = 1.
 *
 * Полосы — два опубликованных порога: «any ideation would be indicative of risk for suicidal
 * behaviour» (сумма от 1) и «a cut-off of 21 on the SIDAS may be used to indicate high risk of
 * suicidal behaviour». Порог установлен на онлайн-выборке взрослых Австралии из общей
 * популяции; это названо в описании.
 *
 * Тревога по пунктам. Опубликованных правил по отдельному пункту нет; разметка — как у SBQ-R:
 * тревогу поднимает каждый вариант, кроме отрицающего («0» на пунктах 1, 3, 4, 5; «10 —
 * повний контроль» на пункте 2), тяжесть moderate — по правилу авторов «any ideation». Пункты
 * 2–5 видны лишь при ненулевом первом, так что сигнал о самих мыслях поднимает первый, а
 * остальные добавляют, что именно с ними, и значение — в подписи тревоги. Severe — «10 —
 * здійснив(-ла) спробу» на пункте 3 (попытка за последний месяц; у C-SSRS поведение за
 * последние 3 месяца — «High Risk») и полоса 21+. Отвергнуто: тревога только по первому
 * пункту — тогда «наближення до спроби 9 з 10» при частоте 1 стояло бы рядом с мимолётной
 * мыслью; severe с какого-то балла на пунктах 2, 4, 5 — такого порога у авторов нет.
 *
 * Перевод рабочий на оба языка (describe()): официальных украинского и русского текстов
 * правообладатель не выпускал. Инструкция бланка «circle the number under the option that
 * best describes the amount of time you felt that way» передана как «оберіть число, яке
 * найкраще описує ваш стан»: из пяти пунктов о времени только первый, и дословное «скільки
 * часу» сбивало бы на пунктах о контроле и близости к попытке.
 *
 * Результат человеку не показывается, план безопасности заполнен — по той же причине, что у
 * SBQ-R: пять вопросов подряд о собственных мыслях о самоубийстве.
 */

interface Item {
  title: Loc;
  /** Подписи краёв шкалы 0 и 10 — с бланка */
  min: Loc;
  max: Loc;
  /** Что сообщает тревога этого пункта; значение подставляется в подпись */
  what: Loc;
  /** Обратный ключ: у второго пункта (контроль) отрицающий вариант — 10, а не 0 */
  reverse?: boolean;
}

