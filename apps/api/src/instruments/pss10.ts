/**
 * PSS-10 — шкала воспринимаемого стресса
 * (Cohen S., Kamarck T., Mermelstein R., 1983; краткая форма 1988).
 *
 * Основание: разрешение разработчика запрашивается бесплатно через ePROVIDE
 * (Mapi Research Trust) — это не общественное достояние, а бесплатная
 * лицензия по запросу. Заказчик заявил, что разрешения у учреждения есть.
 * Украинская научная адаптация (Вельдбрехт, Тавровецька, 2022) — по правилу
 * разработчика собственность переводчиков, поэтому текст здесь свой и помечен
 * как рабочий перевод.
 *
 * ПОЛОС НЕТ — и это позиция разработчика, а не недоделка: «The Perceived
 * Stress Scale is not a diagnostic instrument; there are no score cut-offs.
 * There are only comparisons within your own sample». Раньше здесь стояли
 * полосы 0-13 / 14-26 / 27-40 «низький / помірний / високий стрес». Их нет ни
 * на странице разработчика, ни в первоисточниках: разбивка гуляет по
 * калькуляторам и блогам. Хуже того, полоса 27-40 имела severity "moderate" и
 * поднимала сигнал в очереди разбора — то есть звала специалиста по порогу,
 * которого не существует. Сняты. Альтернатива — оставить полосы с оговоркой
 * «ориентировочно» — отвергнута: движок красит результат и поднимает тревогу
 * по полосе, а не по оговорке, и специалист увидит «Високий стрес», а не
 * сноску. Показывается сырая сумма 0-40; осмысленное сравнение — с
 * собственными прошлыми замерами человека, для чего методика и повторяется.
 *
 * Пункты 2 и 6 сверены с текстом разработчика и поправлены: во втором было
 * «впоратися з важливим» при «unable to CONTROL the important things», в
 * шестом — «не встигаєте» при «could not COPE with all the things». Контроль,
 * совладание и нехватка времени — разные вопросы, а шкала меряет ровно
 * воспринимаемую неподконтрольность и перегрузку.
 *
 * Четыре пункта — обратные. Это не украшение: без них опросник измерял бы
 * готовность соглашаться с утверждениями наравне со стрессом. Обратный ключ
 * стоит флагом `reverse` у пункта, а инвертирование делает движок один раз в
 * одном месте (min+max−балл) — считать инверсию руками в баллах вариантов
 * значило бы завести её в четырёх местах и однажды забыть в пятом.
 */

