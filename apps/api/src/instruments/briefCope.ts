/**
 * Brief COPE — краткий опросник совладания со стрессом
 * (Carver C.S., 1997; International Journal of Behavioral Medicine, 4(1), 92–100).
 *
 * Автор на своей странице в University of Miami разрешает использовать все
 * шкалы или часть из них и прямо разрешает менять инструкцию и временную
 * рамку под свою задачу; ссылаться положено на Carver, 1997. Пункты, якоря
 * и ключ — оттуда же (docs/instruments/dossiers/function.json, brief_cope).
 *
 * ЧЕТЫРНАДЦАТЬ ШКАЛ ПО ДВА ПУНКТА, И НИЧЕГО СВЕРХ НИХ. У методики нет
 * общего балла и нет полос — это позиция автора дословно: «There is no such
 * thing as an "overall" score on this measure», и отдельно — не писать ему
 * за правилами сводных «адаптивных / дезадаптивных» композитов, потому что
 * таких правил у него нет. Поэтому здесь:
 *
 * • нет итоговой шкалы. Сумма двадцати восьми пунктов складывала бы юмор с
 *   самообвинением и молитву с употреблением алкоголя — число, которое
 *   выглядит как «уровень совладания», а не значит ничего;
 * • нет полос. Каждая шкала отдаёт сырую сумму 2–8 и динамику, как RSES и
 *   «велика п’ятірка» без стенов;
 * • нет трёх «стилей» украинской адаптации (Яблонська, Вернік, Гайворонський,
 *   2023: проблемно-фокусований / емоційно-фокусований / уникаючий). Это
 *   группировка украинских адаптаторов, прямо противоречащая запрету автора
 *   на композиты; если отделение захочет её видеть, её надо заводить
 *   отдельной шкалой с подписью «группировка 2023 року», а не выдавать за
 *   свойство Brief COPE.
 *
 * КОДИРОВКА 1..4, КАК У КАРВЕРА. В перепечатках ходит 0..3 — она сдвигает
 * диапазон шкалы с 2–8 на 0–6, и баллы из двух кодировок перестают быть
 * сравнимыми между собой и с литературой. Зафиксирована кодировка автора;
 * менять её задним числом значит сделать несравнимыми прошлые прохождения.
 *
 * ТЕКСТ — РАБОЧИЙ ПЕРЕВОД АВТОРСКОГО АНГЛИЙСКОГО. Украинская адаптация
 * Яблонської та ін. (2023) существует и открыта под CC BY 4.0, но её
 * украинского текста нет в досье, а правило каталога — текст пунктов только
 * из досье. Поэтому пункты переведены с оригинала и помечены через
 * describe(); отвергнуто и «взять украинский текст по памяти / из
 * пересказов» — непроверенный текст под именем чужой адаптации хуже честно
 * названного рабочего перевода. Перед клиническим применением текст
 * сверяется с Додатком статьи.
 *
 * Пункты стоят в настоящем времени («я звертаюся», «я жартую»): английское
 * «I've been …» — про продолжающееся сейчас, а первое лицо настоящего
 * времени в украинском и русском не требует рода. Прошедшее «робив/робила»
 * пришлось бы писать через косую черту в каждом из двадцати восьми пунктов
 * и в каждом из четырёх якорей.
 *
 * ТРЕВОГА ПО ПУНКТАМ 4 И 11 — ПРАВИЛО ОТДЕЛЕНИЯ, А НЕ МЕТОДИКИ. Автор никаких
 * правил тревоги не устанавливал. Досье относит пункты 4 и 11 (алкоголь или
 * другие вещества, чтобы справиться) к пунктам риска: это единственное
 * место методики, где человек прямо сообщает об употреблении ради
 * совладания, и у военнослужащих это повод для отдельного разговора и
 * AUDIT-C. Поднимается любой ответ, кроме «зовсім цього не роблю»: сигнал —
 * сам факт такого способа справляться, а не его частота, и любой порог выше
 * был бы нашей выдуманной границей, которой у методики нет. Severity
 * "moderate", не "severe": это повод к скринингу, а не угроза жизни. Подпись
 * тревоги прямо называет правило правилом відділення, как требует досье.
 *
 * Пункты 6 и 16 (отказ от попыток справиться) досье упоминает как близкие к
 * безнадёжности, но в risk_items их НЕТ — и здесь они не размечены: флаг
 * без основания в досье был бы тем же выдуманным порогом.
 */

