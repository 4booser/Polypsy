/**
 * SCI — Sleep Condition Indicator, индикатор состояния сна
 * (Espie C.A., Kyle S.D., Hames P., Gardani M., Fleming L., Cape J.,
 * BMJ Open 2014;4:e004183). Досье: docs/instruments/dossiers/sleep.json,
 * карточка `sci`.
 *
 * Лицензия — слова самого правообладателя в статье: «The copyright associated
 * with the SCI is reserved by Sleepio Limited, and is licensed free for
 * non-commercial use on condition under a Creative Commons Attribution Non
 * Commercial 4.0 international license». То есть бесплатно и с правом
 * перевода, но ТОЛЬКО некоммерчески — условие записано в источнике каталога,
 * как у SRQ-20. Официального украинского и русского текста нет (обзор 2025 г.
 * насчитывает 13 языковых версий, этих двух среди них нет) — перевод рабочий.
 *
 * НАПРАВЛЕНИЕ: БОЛЬШЕ — ЛУЧШЕ, как у WHO-5 и в отличие от ISI и PSQI. Бланк
 * печатает столбцы «Score 4 3 2 1 0» слева направо: лучший вариант каждого
 * пункта даёт 4, худший — 0. Поэтому обратных пунктов нет — «обратность» уже
 * в баллах вариантов, и флаг `reverse` здесь был бы второй инверсией.
 *
 * Варианты у пунктов разные (минуты, ночи в неделю, оценка качества, мера
 * влияния, длительность) — передаются в item() отдельно на каждый пункт, как
 * в OSSS-3. Бланк строит пункты как продолжения трёх общих начал («Thinking
 * about a typical night in the last month …», «… to what extent has poor
 * sleep …», «Finally …»); в форме, где пункты идут по одному, начало вписано в
 * сам пункт или в инструкцию.
 *
 * Порог ≤16 — «probable insomnia disorder» (Espie 2014). Оговорки досье идут в
 * примечание для персонала: порог выведен из количественных критериев DSM-5, а не эмпирически;
 * в работах с эталоном DSM-5 оптимум выше (20–23); низкий балл дают и другие
 * расстройства сна. Пересчёт 0–32 в 0–10 (÷3,2) — та же величина в другой
 * записи; порог сформулирован в 0–32, его и показываем.
 *
 * severity положительной полосы — "mild", не "moderate": полоса moderate+
 * открывает случай в очереди разбора, а бессонница — повод к клинической
 * оценке сна, а не к срочному вызову специалиста. Так же решено у OSSS-3 и у
 * средней полосы CBI: очередь разбора, заполненная теми, кому ничто не
 * угрожает, прячет тех, кому угрожает. Решение системы, а не авторов шкалы, —
 * записано в листе сверки.
 *
 * Результат человеку показывается: пунктов риска нет, а «поріг безсоння
 * досягнуто — потрібна оцінка сну» — сообщение, с которым можно что-то
 * сделать (та же логика, что у GAD-7).
 */

