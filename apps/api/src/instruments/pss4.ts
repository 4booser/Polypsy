/**
 * PSS-4 — шкала воспринимаемого стресса, четыре пункта
 * (Cohen S., Kamarck T., Mermelstein R., 1983). Досье:
 * docs/instruments/dossiers/wellbeing.json.
 *
 * Тот же правообладатель и то же основание, что у PSS-10: бесплатное
 * разрешение через ePROVIDE на «Perceived Stress Scale (PSS)»; заказчик заявил,
 * что разрешения у учреждения есть.
 *
 * Собственного текста у PSS-4 нет: это пункты 2, 6, 7 и 14 PSS-14 из статьи
 * 1983 г. («a short version of the scale, consisting of the four items
 * (numbers 2, 6, 7, and 14) that correlated most highly with the 14-item
 * scale»), они же — пункты 2, 4, 5 и 10 PSS-10 на странице разработчика.
 * Поэтому вопросы берутся из определения PSS-10 каталога целиком — текст,
 * варианты, флаг обратного ключа, — а не набираются второй раз: расхождение в
 * одном слове сделало бы несравнимыми короткий и полный замер одного
 * человека, а правка формулировки PSS-10 должна доходить и сюда (так же PHQ-4
 * собран из пунктов GAD-7 и PHQ-9).
 *
 * Обратные пункты — 2 и 3 короткой формы («PSS-4 scores are obtained by
 * reverse coding items # 2 and 3»): это пункты 4 и 5 PSS-10, и флаг у них уже
 * стоит. Сумма 0–16.
 *
 * ПОЛОС НЕТ, как у PSS-10: «The Perceived Stress Scale is not a diagnostic
 * instrument; there are no score cut-offs». Результат человеку показывается,
 * как у PSS-10: тот же инструмент, и человек, прошедший обе формы, иначе видел
 * бы свой балл у одной и не видел у другой.
 */

/** Номера пунктов PSS-10, из которых состоит PSS-4 — по порядку короткой формы */
export const PSS4_FROM_PSS10 = [2, 4, 5, 10] as const;

function fromPss10(n: number): QuestionDraft {
  const q = pss10.questions?.[n - 1];
  if (!q) throw new Error(`PSS-4: в PSS-10 нет пункта ${n}`);
  return { ...q, scaleCode: "PSS4", options: q.options?.map((o) => ({ ...o })) };
}

