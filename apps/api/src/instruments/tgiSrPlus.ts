/*
 * Пункт 17 — пассивное желание смерти. У разработчиков правила тревоги нет; разметка —
 * правило отделения по образцу девятого пункта PHQ-9: «Рідко» и «Іноді» — умеренная тревога
 * (повод связаться), «Часто» и «Завжди» — тяжёлая (повод не ждать). Отвергнуто: тревога
 * только с «Часто» — тогда «іноді хотів(ла) померти, щоб бути з покійним» проходило бы
 * молча; одна тяжёлая тревога на всё — тогда редкая мысль стояла бы в очереди рядом с
 * постоянной. Флаг к баллу ничего не прибавляет, балл варианта — бланковый.
 */
const DEATH_WISH_ITEM = 17;

const deathWish = (title: Loc): QuestionDraft => ({
  type: "single",
  title,
  required: true,
  scaleCode: "TGI",
  reverseScored: false,
  options: ANCHORS.map(([text, score]) => ({
    text,
    score,
    ...(score === 1
      ? {}
      : {
          riskFlag: true,
          riskSeverity: score <= 3 ? ("moderate" as const) : ("severe" as const),
          // чьё это правило — в примечании для персонала; в тексте тревоги — что ответил человек
          riskLabel: L(
            `TGI-SR+: бажання померти, щоб бути з покійним (${text.uk.toLowerCase()})`,
            `TGI-SR+: желание умереть, чтобы быть с умершим (${text.ru.toLowerCase()})`,
          ),
        }),
  })),
});

const QUESTIONS: QuestionDraft[] = ITEMS.map((title, i) =>
  i + 1 === DEATH_WISH_ITEM ? deathWish(title) : item(title, "TGI", ANCHORS),
);

