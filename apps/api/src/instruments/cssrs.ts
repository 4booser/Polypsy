/**
 * C-SSRS Screener — скрининговая версия Колумбийской шкалы оценки тяжести суицида
 * («Screen Version - Recent», с точками сортировки риска; Posner K. и соавт., 2008;
 * валидизация — Posner и соавт., Am J Psychiatry 2011). Досье:
 * docs/instruments/dossiers/suicide.json, карточка cssrs (она же снимает прежний вердикт
 * cssrs_screener из trauma.json).
 *
 * Основание. Правообладатель (The Research Foundation for Mental Hygiene, The Columbia
 * Lighthouse Project) пишет для учреждений здравоохранения: «You do not need special
 * permission from us to take the Columbia Protocol tools and use them in your setting,
 * create your own unique triage next steps, or embed the Columbia Protocol in your
 * electronic health record keeping systems (EHR)». Лицензия нужна для клинических
 * исследований, а eC-SSRS — «a computer-automated, patient-reported C-SSRS» — лицензируется
 * через Clario. Отсюда главное решение файла.
 *
 * Кто заполняет — специалист (administration: "clinician"): клиницист задаёт вопросы и
 * записывает ответы в систему учреждения, то есть ровно то, что разрешено без отдельного
 * разрешения. Отвергнуто: самозаполнение на устройстве пациента — это уже eC-SSRS под
 * лицензией Clario, и официального украинского и русского текста самоотчётной версии нет.
 *
 * Текст — официальный: украинский и русский скринеры из папки переводов правообладателя
 * («C-SSRS Screener - Ukrainian.pdf», «... - Russian.pdf», 2026). Перенесено дословно, с
 * двумя правками, обе не формулировки: «накаласти» на украинском бланке — опечатка, здесь
 * «накласти»; «Hi» в шапке украинского бланка набрано латинскими буквами, здесь кириллическое
 * «Ні». Правообладатель требует «The core Columbia Protocol questions do not vary» — поэтому
 * вопросы не «улучшались» и на русском («запаслись таблетками» в примерах повторяется, как
 * на бланке). Пояснения бланка под вопросами 3, 4 и 6 — подсказки (help) для специалиста.
 * Инструкция специалисту — наш текст: на украинском бланке она оставлена по-английски.
 *
 * Суммы баллов нет — шкала не сумма, а алгоритм: уровень риска — по самому тяжёлому «да».
 * Поэтому шкал нет и профиль пуст; результат — сигналы риска. Любой «суммарный балл
 * C-SSRS» был бы выдумкой (досье). Пункты перечислены как не считающиеся (notScored).
 *
 * Тревога — по цветовой разметке бланка, одинаковой на всех трёх языках: вопросы 1 и 2 —
 * «Low Risk», 3 — «Moderate Risk», 4 и 5 — «High Risk», вопрос 6 за всё время — «Moderate
 * Risk», за последние 3 месяца — «High Risk». У системы тяжести две: Low и Moderate Risk —
 * moderate (нужна оценка специалиста; карточка Columbia: «If YES to 2 or 3, seek behavioral
 * healthcare for further evaluation»), High Risk — severe («get immediate help»). Уровень
 * бланка сохранён в подписи тревоги, чтобы дежурный видел, Low это или Moderate.
 *
 * Порядок вопросов — условиями показа: «If YES to 2, ask questions 3, 4, 5, and 6. If NO to
 * 2, go directly to question 6.» Вопросы 3–5 видны при «Так» на вопрос 2; вопрос 6 — всем;
 * уточнение «за последние 3 месяца» — при «Так» на вопрос 6. Ответ на скрытый вопрос риска не
 * поднимает: его по бланку не задавали.
 *
 * Результат человеку не показывается: методику проводит специалист.
 */

interface Risk {
  severity: "moderate" | "severe";
  label: Loc;
}

const LOW: Loc = L("низький ризик за шкалою", "низкий риск по шкале");
const MODERATE: Loc = L("помірний ризик за шкалою", "умеренный риск по шкале");
const HIGH: Loc = L("високий ризик за шкалою", "высокий риск по шкале");

/** Тревога с уровнем бланка в скобках: дежурному важно, Low это или Moderate Risk */
const risk = (severity: Risk["severity"], what: Loc, level: Loc): Risk => ({
  severity,
  label: L(`${what.uk} (${level.uk})`, `${what.ru} (${level.ru})`),
});

/** «Так / Ні» — порядок бланка («Так | Ні»); балл «так» — 1, им записаны условия показа */
function yesNo(title: Loc, r: Risk, opts: { help?: Loc; showIfYes?: number } = {}): QuestionDraft {
  return {
    type: "yesno",
    title,
    ...(opts.help ? { help: opts.help } : {}),
    required: true,
    options: [
      {
        text: L("Так", "Да"),
        keyCode: "yes",
        score: 1,
        riskFlag: true,
        riskSeverity: r.severity,
        riskLabel: L(`C-SSRS: ${r.label.uk}`, `C-SSRS: ${r.label.ru}`),
      },
      { text: L("Ні", "Нет"), keyCode: "no", score: 0 },
    ],
    ...(opts.showIfYes
      ? { logic: [{ sourceIndex: opts.showIfYes - 1, operator: "gte" as const, value: 1, action: "show" as const }] }
      : {}),
  };
}

