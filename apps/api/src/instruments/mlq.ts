  ITEMS.flatMap((it, i) => (it[2] === code ? [i + 1] : []));

const subscale = (code: (typeof ITEMS)[number][2], title: Loc, description: Loc): ScaleDraft => ({
  code,
  title,
  description,
  kind: "clinical",
  normalization: "raw",
  key: sumKey(itemsOf(code)),
  bands: [],
});

