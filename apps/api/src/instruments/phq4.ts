/**
 * PHQ-4 — сверхкраткий скрининг тревоги и депрессии
 * (Kroenke K., Spitzer R.L., Williams J.B.W., Löwe B., 2009).
 *
 * Основание: общественное достояние по заявлению издателя опросника, PHQ-4
 * назван в Table 1 официального руководства поимённо («PHQ-4 — PHQ-2 and
 * GAD-2»).
 *
 * Собственного текста у PHQ-4 нет вообще: первые два пункта — это GAD-2
 * (первые два пункта GAD-7), вторые два — PHQ-2 (первые два пункта PHQ-9).
 * Поэтому пункты импортируются, а не переписываются. Альтернатива — набрать
 * четыре строки заново — отвергнута ровно по той причине, по которой издатель
 * и определяет PHQ-4 через готовые части: расхождение в одном слове между
 * PHQ-4 и GAD-7 делает несравнимыми замеры одного и того же человека, а
 * заметить такое расхождение глазами в четырёх строках почти невозможно.
 *
 * Чем опасна ошибка ИМЕННО здесь. Четыре пункта — это самый грубый инструмент
 * каталога: он отвечает только на вопрос «смотреть дальше или нет». Ошибка в
 * ключе подшкал не даст ни смещения суммы, ни странного профиля — она просто
 * отправит тревожного человека в ветку депрессии или наоборот, и следующий
 * шаг окажется не тем. Поэтому подшкалы заведены явными ключами (пункты 1-2 и
 * 3-4), а не «по коду шкалы у вопроса».
 *
 * Порог подшкалы ≥3 — дословно из руководства издателя: «the recommended
 * cutpoints for each when used as screeners is a score of 3 or greater».
 * Полосы общего балла (0-2/3-5/6-8/9-12) взяты из Kroenke et al., 2009; в
 * досье они помечены как не сверенные дословно с PDF статьи (платный доступ),
 * и это сказано в описании методики, а не спрятано в комментарии.
 *
 * Статус перевода здесь смешанный, и описание собрано руками, а не через
 * `describe()`: пункты PHQ-2 — официальный украинский текст МОЗ (они
 * приходят из phq9.ts), пункты GAD-2 — рабочий перевод (официального
 * украинского GAD-7 нет). Общая оговорка «робочий переклад» соврала бы про
 * одну половину, её отсутствие — про другую.
 */

