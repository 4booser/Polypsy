/**
 * Событие — множественный выбор без баллов и без кода шкалы. Баллы 0 стоят не «для порядка»:
 * у вариантов номинальной шкалы их нет, и любое другое число однажды сложилось бы во что-то
 * в конструкторе, если кто-то добавит методике шкалу.
 */
const event = (title: Loc): QuestionDraft => ({
  type: "multiple",
  title,
  required: true,
  scaleCode: null,
  reverseScored: false,
  options: OPTIONS.map((text) => ({ text, score: 0 })),
});

