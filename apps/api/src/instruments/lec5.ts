/**
 * LEC-5 — перечень жизненных событий для DSM-5, стандартная версия самоотчёта
 * (Weathers F.W., Blake D.D., Schnurr P.P., Kaloupek D.G., Marx B.P., Keane T.M., National
 * Center for PTSD, 2013; бланк 12 April 2018). Досье — карточка `lec5` в
 * docs/instruments/dossiers/trauma.json.
 *
 * Основание: «This measure was created by staff at VA's National Center for PTSD and is in the
 * public domain and not copyrighted».
 *
 * Это не шкала, и система не делает вид, что это шкала. Правообладатель пишет прямо: «There is
 * no formal scoring protocol or interpretation per se, other than identifying whether a person
 * has experienced one or more of the events listed… The LEC-5 does not yield a total score or
 * composite score». Поэтому шкал нет, у вариантов нет баллов, а все 17 пунктов объявлены
 * непосчитанными в записи каталога (LEC5_NOT_SCORED) с этой цитатой — правило каталога «пункт
 * либо в ключе, либо в notScored с причиной» выполнено буквально. Отвергнуто: «число событий,
 * случившихся лично» — такого показателя у правообладателя нет, это была бы своя метрика под
 * чужим именем.
 *
 * Зачем тогда методика каталогу: это стандартная пара к PCL-5 — специалист видит, какие
 * события были в жизни человека и в какой роли, и по ним выбирает событие, о котором
 * спрашивать PCL-5 или ITQ.
 *
 * Множественный выбор, а не один вариант: «respondents may endorse multiple levels of exposure
 * to the same trauma type» — боевые действия можно пережить и лично, и по службе. Шесть
 * вариантов у каждого события, как в официальном заполняемом бланке (103 поля-флажка): в копии
 * ITC у пунктов 14–16 части столбцов нет, но это её отличие, а не бланка.
 *
 * Текст — рабочий перевод с английского оригинала (официально правообладатель выпускает
 * только испанский). Украинская и русская копии на сайте ITC не взяты: в них не названы ни
 * переводчик, ни условия, а столбцы расходятся с бланком.
 *
 * Результат человеку не показывается (его и нет), план безопасности заполнен: перечень
 * спрашивает о насилии, плене и смерти.
 */

