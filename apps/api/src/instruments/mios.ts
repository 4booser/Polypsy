/**
 * MIOS — Moral Injury Outcome Scale, краткая клиническая версия (Litz B.T. и
 * консорциум MIOS; Frontiers in Psychiatry, 2022). Досье: staff.json, карточка
 * mios.
 *
 * Лицензия: авторы в статье — «the MIOS is a public domain scale»; сама статья с
 * бланками — CC BY 4.0. Условие одно — ссылка на авторов и публикацию: она в
 * описании и в source записи каталога.
 *
 * Зачем она в группе «персонал». Свободной меры морального дистресса медиков
 * с явной лицензией не нашлось (MMD-HP, MISS-HP, термометр — по разрешению; см.
 * отказы в досье). Лучший кандидат — MIDS Национального центра ПТСР (валидирована
 * на медработниках, порог 27), но её правило «часть 2 — если хоть один из шести
 * пунктов части 1 больше нуля» движок выразить не может: условия показа
 * соединяются только через «И». У MIOS отсеивающий вопрос один — «так / ні», —
 * и он ложится на движок так же, как у PC-PTSD-5. MIOS валидирована и на
 * медсёстрах (2023), а консорциум собирал пункты в том числе у клиницистов.
 *
 * Устройство — как на бланке краткой версии (Brief-MIOS.pdf, Litz Lab):
 * 1) отсеивающий вопрос «Have you had at least one experience like this that
 *    troubles you currently?» — «Persons who answer no should not complete the
 *    MIOS»: при «Ні» остальное скрыто;
 * 2) тип события (А, Б, В; «If more than one, check all that apply») — «These
 *    initial questions are not scored»: в ключ не входит и объявлен в notScored;
 * 3) 14 утверждений, 0–4 («Strongly Disagree» … «Strongly Agree»).
 * Восемь пунктов функционирования (B-IPF) с бланка не заведены: это отдельная
 * методика, её формула на бланке противоречит сама себе (досье, items_note).
 *
 * Подсчёт — суммы: стыд (пункты 1, 3, 7, 8, 12, 13, 14 бланка), подорванное
 * доверие (2, 4, 5, 6, 9, 10, 11), общий балл — все 14, 0–56. Номера в ключах
 * выводятся из позиции пункта в массиве, а не выписываются руками: пункт 1
 * бланка — третий вопрос методики. При «Ні» на отсеивающий вопрос пункты не
 * задавались, и движок даёт честный ноль (скрытый пункт не идёт в знаменатель
 * доли) — так же, как у PC-PTSD-5.
 *
 * ПОЛОС НЕТ. На бланке краткой версии правообладатель пишет прямо: «There are
 * currently no proposed scoring categories or cut offs». В отдельном документе
 * той же лаборатории есть «as a guide: 14-28 = mild; 29-42 = moderate; 43-56 =
 * severe» и отсечка 37 для одной австралийской выборки ветеранов с оговоркой,
 * что в других выборках она может отличаться. Правообладатель противоречит сам
 * себе — значит, порога нет; показывается сырой балл, как у PSS-10.
 *
 * Пунктов о суициде, самоповреждении или вреде другим нет. Ближе всех — п. 7 «I
 * feel like I don’t deserve a good life»; правила тревоги по нему у
 * правообладателя нет, и флага нет: лишний флаг без правила первоисточника
 * приучает не читать тревоги (решение — клиницисту, см. досье).
 *
 * Результат человеку не показывается: полос нет, а голое «31 из 56» после
 * четырнадцати утверждений о стыде и вине ничего человеку не объясняет; читает
 * его специалист. Как у PCL-5, приложен план безопасности: методика просит
 * держать в уме самое тяжёлое морально травмирующее событие.
 *
 * Перевод рабочий (describe()): официальных украинского и русского текстов у
 * правообладателя нет. Родовые формы обойдены («Я більше не вірю», «як мені
 * здавалося»), чтобы не писать «(-а)».
 */

