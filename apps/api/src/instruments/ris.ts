/**
 * RIS — Regensburg Insomnia Scale, Регенсбургская шкала инсомнии
 * (Crönlein T., Langguth B., Popp R., Lukesch H., Pieh C., Hajak G.,
 * Geisler P., Health Qual Life Outcomes 2013;11:65). Досье:
 * docs/instruments/dossiers/sleep.json, карточка `ris`.
 *
 * Шкала напечатана самими авторами (Table 1: немецкий оригинал и английский
 * перевод с баллами вариантов) в статье под CC BY 2.0 — воспроизведение и
 * перевод разрешены при указании авторства. Официального украинского и
 * русского нет; перевод рабочий и сделан с НЕМЕЦКОГО оригинала (валидирован
 * именно он; для английской версии авторы норм не публиковали) со сверкой по
 * английскому. Отсюда п. 3: немецкое «Ich kann nicht durchschlafen» — «не могу
 * проспать ночь, не просыпаясь», а не расплывчатое английское «My sleep is
 * disturbed».
 *
 * Чем отличается от SCI: шкала создана для психофизиологической инсомнии и
 * оценки КПТ-И — кроме сна она спрашивает о мыслях о сне, страхе бессонницы,
 * дневной форме и снотворных. Поэтому в каталоге обе: SCI — скрининг
 * расстройства по DSM-5, RIS — выраженность и динамика при лечении.
 *
 * Вводный пункт 0 бланка (обычное время отхода ко сну и подъёма) НЕ заведён:
 * по авторам он «is not included in the score. It serves as a plausibility
 * check» — свободный ввод времени, который ничего не считает. Номера пунктов
 * 1–10 поэтому совпадают с бланком.
 *
 * Ключ — Table 1: каждый пункт 0–4, сумма 0–40. Пункт 9 («Ich fühle mich voll
 * leistungsfähig» / «I feel fit during the day») ключуется обратно: «Always» = 0
 * … «Never» = 4. Варианты у него те же, что у пп. 3–10, а инверсию делает
 * движок по флагу `reverse`. Пункты 1 и 2 — свои варианты (минуты, часы); у
 * п. 2 последний вариант в Table 1 «0–1 h», в Table 2 — «0–2 h»: взят бланк.
 *
 * Одна шкала. Факторный анализ дал четыре компонента, но авторы прямо пишут:
 * «the RIS has been developed and validated as a single scale and should also
 * be primarily used so».
 *
 * Полосы — дословно: «We propose to consider a score from 0–12 points as normal
 * and a higher score as indicative of PI symptoms». Выборка — немецкий третичный
 * центр сна; авторы: «the RIS has neither been designed nor validated as a tool
 * for the diagnosis of PI». severity второй полосы — "mild" (случая не
 * открывает), по той же причине, что у SCI.
 *
 * Результат человеку не показывается: шкала клиническая, её назначение —
 * оценка и динамика при лечении, а подпись «ознаки психофізіологічної
 * інсомнії» — термин, который без разговора со специалистом читается как
 * диагноз. При сомнении — не показывать.
 */

