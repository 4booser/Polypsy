import type { CreateSurveyDraft } from "@quizzy/shared";
import { L, PUBLIC_DEFAULTS, allItems, bands, describe, item, sumKey, type Anchor } from "./common";

/**
 * WHO-5 — индекс благополучия
 * (Всемирная организация здравоохранения, региональное бюро для Европы, 1998).
 *
 * Распространяется свободно.
 *
 * Единственная методика каталога, где высокий балл означает хорошее, а не
 * плохое. Полосы поэтому перевёрнуты относительно остальных: нулевой конец
 * шкалы — тяжёлый, а не благополучный. Это место, в котором легче всего
 * ошибиться при добавлении методики, и ошибка была бы тихой: система честно
 * показывала бы «немає ознак» человеку, у которого не осталось ничего, что
 * его радует.
 *
 * Пять пунктов — самый короткий опросник каталога, и это его смысл: WHO-5
 * ставится первым в очередь, когда неизвестно, с чего начинать.
 */

