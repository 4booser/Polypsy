import type { LocalizedText } from "@quizzy/shared";

/**
 * Наборы-заготовки общего каталога: связки методик, которые отделение
 * назначает одним действием (routes/batteries.ts).
 *
 * Установщик (lib/catalogInstall.ts, installBatteries) заводит каждую
 * заготовку ОДИН раз — общим набором (groupId null: его видит весь персонал)
 * — и больше не трогает: ни правкой этого файла, ни на следующих выкатах.
 * С первой установки набором распоряжается отделение: меняет состав,
 * переименовывает, отправляет в архив или удаляет. Методики — другое дело:
 * их редакции каталог доводит до базы сам, потому что от текста пункта
 * зависит смысл балла; от состава набора — только удобство назначения, и
 * решение о нём принадлежит тем, кто назначает.
 *
 * Заготовка узнаётся по `key` (batteries.catalog_key), а не по названию:
 * название вправе изменить отделение. Удалённая отделением заготовка не
 * возвращается — установщик помнит её по журналу (battery.create с
 * catalogKey).
 *
 * Состав — ключи записей CATALOG (./catalog.ts) в порядке прохождения.
 * Методику, которой в базе нет или которая снята, установщик пропускает с
 * записью в лог, а не роняет выкат. Название и описание — на обоих языках
 * содержимого, но набор хранит одну строку, которую правит отделение
 * (batteries.title — текст, не объект языков): установщик пишет украинскую,
 * язык учреждения и каталога (CATALOG_BATTERY_LANG). Русская — на случай,
 * когда названия наборов станут двуязычными, и для сверки.
 *
 * ── Куда добавлять ── заготовка — записью в конец списка; новые методики
 * в уже поставленные наборы так не попадут (см. выше), только в новые
 * заготовки и в базы, где набор ещё не заведён.
 */
export interface CatalogBattery {
  /** Устойчивое имя заготовки: batteries.catalog_key */
  key: string;
  title: LocalizedText;
  description: LocalizedText;
  /**
   * Строгий порядок: следующий самоотчёт открывается после предыдущего.
   * Шаги специалиста (ASSIST) идут параллельной дорожкой при любом значении
   * (lib/batteries.ts, batteryProgress).
   */
  strictOrder: boolean;
  /** Ключи методик каталога в порядке прохождения; required по умолчанию — да */
  items: { key: string; required?: boolean }[];
}

