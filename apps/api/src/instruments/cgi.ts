/**
 * CGI — шкала общего клинического впечатления (Guy W., ECDEU Assessment Manual
 * for Psychopharmacology, 1976, форма 028-CGI). Досье:
 * docs/instruments/dossiers/clinician.json, карточки `cgi_s` и `cgi_i`.
 *
 * Основание: издание Минздрава США; NINDS CDE называет шкалу общественным
 * достоянием.
 *
 * Две записи каталога, а не одна методика с двумя пунктами. Тяжесть (CGI-S)
 * оценивают на каждом приёме, в том числе на первом; изменение (CGI-I) — только
 * после начала лечения и всегда от исходного состояния. В одной методике
 * пункт изменения на первом приёме пришлось бы заполнять «не оценивалось», а
 * код 0 бланка вошёл бы в балл как значение. Третий пункт формы — индекс
 * эффективности (терапевтический эффект против побочных действий препарата) —
 * инструмент испытаний препаратов, не заведён.
 *
 * Код 0 «не оценивалось» в обеих не заведён: методику заполняют, когда оценка
 * проведена. Шкала 1–7, полоса — каждая ступень со своей подписью: порогов у
 * CGI нет, и значение говорит само за себя.
 *
 * Перевод — собственный рабочий на оба языка (WORKING_TRANSLATION в примечании
 * для персонала). Подписи ступеней — о расстройстве, а не о человеке: «Легкий
 * розлад», а не «легко хворий» — род пациента подпись не угадывает.
 *
 * Тяжесть полос — решение системы, как у HAM-D (hamd17.ts): это общая оценка
 * самого специалиста, и случая риска полосы не открывают; 1 — none, остальное —
 * mild. Пунктов риска нет.
 */

const q = (title: Loc, help: Loc, scaleCode: string, anchors: [Loc, number][]) => item(title, scaleCode, anchors, { help });

