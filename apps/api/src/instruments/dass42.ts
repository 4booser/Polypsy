/** Код подшкалы пункта — из ключа шаблона, а не отдельной разметкой */
const scaleOf = (n: number): DassCode =>
  (Object.keys(DASS_KEY) as DassCode[]).find((code) => (DASS_KEY[code] as readonly number[]).includes(n))!;

