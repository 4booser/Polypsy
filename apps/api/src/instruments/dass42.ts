/**
 * DASS-42 — шкалы депрессии, тревоги и стресса, полная форма
 * (Lovibond S.H., Lovibond P.F., 1995; University of New South Wales).
 *
 * Основание: общественное достояние по заявлению разработчиков («The DASS
 * questionnaire is public domain, and so permission is not needed to use
 * it»). Украинского перевода ПОЛНОЙ формы на сайте разработчиков нет (есть
 * только DASS-21), поэтому текст здесь — рабочий перевод, и это сказано в
 * описании через `describe()`.
 *
 * ПОЛОС НЕТ, и это главная ловушка DASS. Разработчики дословно: «we have
 * developed a set of cut-off scores for defining mild/moderate/severe/
 * extremely severe scores for each DASS scale. To avoid misinterpretation
 * and reification of these (arbitrary) labels, they are only provided in the
 * DASS manual». Таблица порогов есть только в платном руководстве, а числа,
 * которые гуляют по статьям и калькуляторам, — пересказ, который досье
 * проверить не может. Альтернатива — взять «общеизвестные» пороги из
 * вторичных источников — отвергнута: полоса с severity поднимает сигнал в
 * очереди разбора, и система звала бы специалиста по числу, которое никто не
 * сверил с первоисточником. Когда руководство будет куплено, полосы
 * добавляются сюда из него — и только из него.
 *
 * Три подшкалы по 14 пунктов, сумма каждой 0-42; общий балл разработчики
 * основным не считают, и его здесь нет. Умножение на 2 — правило DASS-21, к
 * полной форме оно НЕ применяется: удвоенная сумма DASS-42 дала бы 0-84 и
 * ничего не значила бы.
 *
 * Номера пунктов подшкал выписаны списками — ровно как на официальном
 * шаблоне подсчёта (Dass_template.pdf), — а код шкалы у вопроса выводится из
 * них. Обратная схема (буква шкалы у каждого пункта, как в IPIP-50)
 * отвергнута: сверять с шаблоном пришлось бы 42 разбросанные буквы вместо
 * трёх строк, а шаблон — единственный первоисточник ключа. Что три списка
 * вместе дают каждый из 42 пунктов ровно один раз, проверяет золотой тест.
 *
 * Риск. Прямого вопроса о суицидальном намерении в DASS нет. Пункт 21
 * («життя не варте того, щоб жити») и близкий к нему пункт 38 («життя не має
 * сенсу») размечены тревогой moderate с любого ненулевого ответа: досье
 * называет их поводом для отдельной оценки риска клиницистом — это правило
 * клинической практики, а не разработчиков, и так оно и подписано в тексте
 * тревоги. Пропустить здесь безнадёжность дороже, чем лишний раз позвать
 * специалиста, поэтому severity не понижается до «без тревоги» и на слабом
 * ответе.
 */

