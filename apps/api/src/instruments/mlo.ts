const keyOf = (code: string) => [
  ...(KEY[code]!.yes ?? []).map((item) => ({ item, matchKey: "yes" })),
  ...(KEY[code]!.no ?? []).map((item) => ({ item, matchKey: "no" })),
];

const stenTableOf = (code: string) =>
  (STENS[code] ?? []).map(([sten, rawMin, rawMax]) => ({ rawMin, rawMax, sten }));

const scaleOf = (code: string): ScaleDraft => ({
  code,
  title: { uk: TITLES[code]![0], ru: TITLES[code]![1] },
  kind: "clinical",
  normalization: "sten",
  key: keyOf(code),
  stenTable: stenTableOf(code),
  bands: stenBands(code === "SR"),
});

