/**
 * ASQ — Ask Suicide-Screening Questions, скрининг суицидального риска в медицинском
 * учреждении (Horowitz L.M., Bridge J.A., Teach S.J. и соавт., NIMH, 2012; у взрослых —
 * Horowitz и соавт., Psychosomatics 2020). Бланк — «NIMH Toolkit: Screening Tool for Youth
 * and Adults», редакция 9/29/25. Досье: docs/instruments/dossiers/suicide.json, карточка asq.
 *
 * Основание: «Public domain tool, free of charge» (ASQ Information Sheet NIMH) и политика
 * NIMH: материалы — общественное достояние, копировать можно без разрешения, со ссылкой
 * на NIMH и не меняя текст так, чтобы он вводил в заблуждение.
 *
 * Кто заполняет — специалист (administration: "clinician"). Бланк начинается словами «Ask
 * the patient», валидация шла опросом персоналом, а не самозаполнением. Отвергнуто:
 * общедоступное самозаполнение, как у остальных скринингов каталога, — сведений о его
 * валидности у взрослых досье не нашло, а порог «любое да» установлен для опроса.
 *
 * Суммы баллов у ASQ нет — результат категориальный: отрицательный, неострый
 * положительный, острый положительный скрининг. Шкала ниже — правило бланка «Yes to any of
 * Questions #1–#4», записанное числом: «да» на вопросы 1–4, полоса «≥ 1». Это не балл
 * тяжести, и полоса не делит «да» на градации, потому что первоисточник их не делит.
 *
 * Острота — пятый вопрос, а не шкала: «Yes to Question #5 = acute positive screen
 * (imminent/acute risk identified)». Его «Так» поднимает тяжёлую тревогу сам.
 *
 * Пятый вопрос показывается всегда. По бланку его задают, если хотя бы на один из вопросов
 * 1–4 ответ «да», а после четырёх «нет» его задавать «not necessary». Условия показа в
 * движке складываются через «и», и «да хотя бы на один из четырёх» ими не выразить.
 * Отвергнуто: показывать пятый вопрос по одному «да» на третьем вопросе — тогда человек с
 * «да» только на первом, втором или четвёртом остался бы без вопроса об остроте, то есть
 * без отличия острого скрининга от неострого. Задать вопрос лишний раз безопасно; не
 * задать его тому, кому положено, — нет. По той же причине он обязательный.
 *
 * Тревога по вопросам, а не только по полосе. «Так» на 1–4 — moderate: «non-acute positive
 * screen (potential risk identified)», нужна краткая оценка безопасности, наблюдение один на
 * один не требуется. «Так» на 5 — severe: STAT-оценка, человек не уходит до оценки, его не
 * оставляют без присмотра. Уточнение о давности попытки тревоги не поднимает: бланк
 * использует его только для исключения у взрослых (положительный скрининг лишь по вопросу 4
 * и попытка больше года назад — краткая оценка «may not be necessary»), и решает это
 * клиницист, глядя на сигнал вопроса 4.
 *
 * Отказ отвечать бланк 2025 г. для взрослых положительным скринингом не считает («refusal is
 * NOT considered a positive screen […] Document the refusal») — варианта «відмова» здесь
 * нет; отказ записывают отдельно, как велит бланк, а не ответом.
 *
 * Перевод. Русский текст вопросов 1–5 и уточнения к пятому — официальный перевод NIMH
 * (asq-russian.pdf, бланк 2017 г.), дословно, включая «если бы Вас не было бы в живых» и
 * «На прошлой неделе» вместо «за последнюю неделю». Вопросы 1–5 в редакциях 2017 и 2025 гг.
 * совпадают; уточнение о давности попытки появилось в 2025 г. и переведено нами. Украинский
 * — рабочий перевод с английского, сверенный с официальным русским, чтобы оба языка задавали
 * один вопрос (так же PHQ-9 переводит русский от официального украинского). Отвергнуто:
 * украинский «слово в слово» с английского без оглядки на русский — у одной методики стало
 * бы два инструмента под двумя языками интерфейса.
 *
 * Результат человеку не показывается: это скрининг суицидального риска, и интерпретирует
 * его клиницист, который и задаёт вопросы.
 */

interface Risk {
  severity: "moderate" | "severe";
  label: Loc;
}

/**
 * «Так / Ні» — порядок бланка («Yes  No»); балл «так» — 1, чтобы правило «≥ 1» и условия
 * показа читались числом. Код шкалы — только у вопросов 1–4: он запасной ключ шкалы
 * (createVersion собирает ключ из вопросов с кодом, если ключ очистили), и у вопроса 5 он
 * тихо добавил бы остроту к правилу «да на 1–4», которого она по бланку не касается.
 */
function yesNo(title: Loc, scaleCode: string | null, risk?: Risk, help?: Loc): QuestionDraft {
  return {
    type: "yesno",
    title,
    ...(help ? { help } : {}),
    required: true,
    scaleCode,
    options: [
      {
        text: L("Так", "Да"),
        keyCode: "yes",
        score: 1,
        ...(risk
          ? {
              riskFlag: true,
              riskSeverity: risk.severity,
              riskLabel: L(`ASQ: ${risk.label.uk}`, `ASQ: ${risk.label.ru}`),
            }
          : {}),
      },
      { text: L("Ні", "Нет"), keyCode: "no", score: 0 },
    ],
  };
}

