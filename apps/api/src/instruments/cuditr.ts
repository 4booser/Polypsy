/**
 * CUDIT-R — тест выявления расстройств, связанных с употреблением каннабиса,
 * пересмотренный (Adamson S.J., Kay-Lambkin F.J., Baker A.L., Lewin T.J.,
 * Thornton L., Kelly B.J., Sellman J.D., Drug Alcohol Depend 2010).
 * Досье: docs/instruments/dossiers/addiction.json, карточка `cuditr`.
 *
 * Основание: на авторском бланке напечатано «This scale is in the public domain
 * and is free to use with appropriate citation»; NIH PhenX — «freely available;
 * permission not required for use». Единственное условие — ссылка на статью 2010
 * года, она стоит в примечании для персонала и в журнале установки.
 *
 * Отсеивающий вопрос — как у PC-PTSD-5. Бланк начинается с «Have you used any
 * cannabis over the past six months? YES / NO … If YES, please answer the following
 * questions», поэтому восемь пунктов показываются только при «Так», а ключ шкалы
 * начинается со второго вопроса. Человек, который каннабис не употреблял, не
 * отвечает восемь раз «ніколи», а получает балл 0 и полосу ниже порога. Код
 * шкалы у отсеивающего вопроса снят по той же причине, что у PC-PTSD-5: код
 * шкалы у вопроса — запасной ключ, и «так» тихо добавило бы единицу.
 *
 * Пороги — с авторского бланка: 8 и больше — опасное употребление, 12 и больше —
 * возможное расстройство употребления каннабиса. В самой статье 2010 года
 * оптимальная точка для расстройства по DSM-IV — 13 (91,3 % / 90,0 %), а для
 * DSM-5 соавторы позже нашли 9–10. Отвергнуто: полоса по 13 — правообладатель
 * печатает со шкалой именно 8 и 12, и лист сверки должен совпадать с бланком;
 * 13 и 9–10 названы в описании шкалы, чтобы специалист видел, откуда разброс.
 *
 * Пометка риска — пункт 7 бланка (8-й в системе): употребление в физически
 * опасных ситуациях — за рулём, с механизмами, при уходе за детьми. Это пункт о
 * вреде другим, и без пометки он был бы клиническим дефектом. Правила тревоги
 * по отдельному пункту первоисточник не даёт: порог «любая частота, кроме
 * «ніколи»» — решение системы по аналогии с девятым пунктом PHQ-9, тяжесть
 * "moderate" — случай на разбор. "severe" отвергнута: неотложности пункт не
 * устанавливает.
 *
 * severity полос: ниже порога — none; опасное употребление — mild, как
 * положительный AUDIT-C: случай в очереди не открывается, разговор ведёт тот,
 * кто читает результат; возможное расстройство — moderate, как положительный
 * CAGE: это просьба к специалисту посмотреть.
 *
 * Результат человеку показывается: бланк задуман для самозаполнения и
 * самоподсчёта, интерпретация баллов напечатана на нём же. Полоса называет
 * «возможное» расстройство и «может знадобитися» вмешательство — не диагноз.
 *
 * Перевод рабочий на оба языка (describe): официального украинского и русского
 * текста нет ни у авторов, ни у МОЗ.
 */

