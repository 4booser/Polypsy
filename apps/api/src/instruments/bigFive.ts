/**
 * «Большая пятёрка» на пунктах IPIP Big-Five Factor Markers, 50 утверждений
 * (Goldberg L.R., 1992; International Personality Item Pool).
 *
 * Единственная методика каталога, у которой пункты — общественное достояние.
 * Остальные приходится сопровождать оговоркой о правообладателе; здесь
 * воспроизведение, перевод и изменение разрешены безусловно, и это стоит
 * сказать в примечании для персонала: специалист, выбирающий, что можно раздать людям, а что
 * нет, принимает решение именно там.
 *
 * Это не скрининг. «Большая пятёрка» описывает устойчивые черты, а не
 * состояние за последние две недели, и высокий балл по любой из пяти шкал —
 * не находка, а описание человека. Из этого следуют два решения ниже.
 *
 * Первое: `showResultsToPatient: true`. Клинические методики каталога прячут
 * результат от человека там, где он без специалиста прочитается как диагноз.
 * Здесь прятать нечего и не от чего: профиль личности — это то, ради чего
 * человек и проходит методику. По той же причине здесь нет ни одного
 * riskFlag: ни один вариант ответа не является поводом поднять тревогу.
 *
 * Второе: `normalization: "raw"`, никаких `norms` и НИКАКИХ ПОЛОС. Перевод в
 * стены или T-баллы требует выборки, на которой посчитаны среднее и
 * отклонение, а валидированных украиноязычных норм для IPIP-50 нет. Показать
 * стен, посчитанный по американской выборке, значит сказать человеку «вы выше
 * среднего» про среднее, которое к нему не относится. Поэтому показывается
 * сырая сумма 10–50, как сырой балл PSS-10.
 *
 * Полос «очень низкий … очень высокий» здесь раньше было пять (10–19 / 20–29 /
 * 30–34 / 35–42 / 43–50), и источника у них не было: комментарий называл их
 * равномерной разметкой, хотя ширина у них 10, 10, 5, 8 и 8 баллов, и середина шкалы
 * (30 — все ответы «як коли») стояла на нижнем краю «среднего», так что 29
 * было уже «низким». Сняты по правилу каталога «полосы без опубликованного
 * источника не существует» (как у PSS-10) и по прямой позиции IPIP: «No norms
 * are available on the IPIP website… Most "norms" are misleading, and therefore
 * they should not be used. Far more defensible are local norms» (ipip.ori.org,
 * Norms) и «we caution against interpreting IPIP scale scores in terms of
 * categories» (Interpreting Individual IPIP Scale Scores). Подпись «высокий»
 * без выборки — та же категория, только без среднего, от которого она
 * отсчитана.
 */

