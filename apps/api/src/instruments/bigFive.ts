/**
 * Полосы одинаковы для всех пяти шкал: черта не бывает «лёгкой» или
 * «тяжёлой», бывает выражена сильнее или слабее, и шкала у всех пяти одна и
 * та же — десять пунктов по 1..5, то есть 10..50.
 *
 * severity везде "none". Это не недосмотр и не заглушка: движок красит
 * результат и поднимает тревогу по severity, и любое другое значение здесь
 * превратило бы описание характера в клиническую находку. grade 1..5 при этом
 * задан честно — он упорядочивает полосы для графика профиля, где важно
 * видеть, какая черта выше, а какая ниже.
 */
const TRAIT_BANDS = bands([
  { min: 10, max: 19, label: L("Дуже низький", "Очень низкий"), severity: "none", grade: 1 },
  { min: 20, max: 29, label: L("Низький", "Низкий"), severity: "none", grade: 2 },
  { min: 30, max: 34, label: L("Середній", "Средний"), severity: "none", grade: 3 },
  { min: 35, max: 42, label: L("Високий", "Высокий"), severity: "none", grade: 4 },
  { min: 43, max: 50, label: L("Дуже високий", "Очень высокий"), severity: "none", grade: 5 },
]);

/**
 * Номера пунктов шкалы берутся из того же массива, из которого собираются
 * вопросы. Ключ IPIP-50 — это пять арифметических прогрессий (E: 1, 6, 11 …),
 * и выписать их руками несложно ровно один раз; ошибиться в одной цифре из
 * пятидесяти — тоже несложно, а результат такой ошибки виден только смещением
 * суммы у всех, кто методику прошёл. Пока номер выводится из позиции в
 * массиве, разойтись им негде.
 */
const itemsOf = (code: TraitCode) =>
  IPIP50_ITEMS.flatMap((it, i) => (it.scale === code ? [i + 1] : []));

const traitScale = ({ code, title, description }: (typeof TRAITS)[number]): ScaleDraft => ({
  code,
  title,
  description,
  kind: "clinical",
  normalization: "raw",
  key: sumKey(itemsOf(code)),
  bands: TRAIT_BANDS,
});

