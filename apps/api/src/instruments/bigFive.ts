/**
 * «Большая пятёрка» на пунктах IPIP Big-Five Factor Markers, 50 утверждений
 * (Goldberg L.R., 1992; International Personality Item Pool).
 *
 * Единственная методика каталога, у которой пункты — общественное достояние.
 * Остальные приходится сопровождать оговоркой о правообладателе; здесь
 * воспроизведение, перевод и изменение разрешены безусловно, и это стоит
 * сказать в описании: специалист, выбирающий, что можно раздать людям, а что
 * нет, принимает решение именно там.
 *
 * Это не скрининг. «Большая пятёрка» описывает устойчивые черты, а не
 * состояние за последние две недели, и высокий балл по любой из пяти шкал —
 * не находка, а описание человека. Из этого следуют два решения ниже.
 *
 * Первое: `showResultsToPatient: true` и severity "none" во всех полосах.
 * Клинические методики каталога прячут результат от человека там, где он без
 * специалиста прочитается как диагноз. Здесь прятать нечего и не от чего:
 * профиль личности — это то, ради чего человек и проходит методику, а
 * severity выше "none" на любой полосе означала бы, что интроверсия или
 * открытость опыту — степень тяжести чего-то. Она не степень тяжести ничего.
 * По той же причине здесь нет ни одного riskFlag: ни один вариант ответа не
 * является поводом поднять тревогу.
 *
 * Второе: `normalization: "raw"` и никаких `norms`. Перевод в стены или
 * T-баллы требует выборки, на которой посчитаны среднее и отклонение, а
 * валидированных украиноязычных норм для IPIP-50 нет. Показать стен,
 * посчитанный по американской студенческой выборке 1990-х, значит сказать
 * человеку «вы выше среднего» про среднее, которое к нему не относится.
 * Поэтому показывается сырая сумма, а полосы ниже — равномерная разметка
 * диапазона 10..50, помогающая прочитать свой балл, а не норматив.
 */

