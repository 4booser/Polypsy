import { describe, expect, test } from "bun:test";
import { CATALOG } from "../catalog";

/**
 * Описание методики каталога — для обследуемого, примечание — для персонала.
 *
 * Описание показывается человеку на первом экране методики (patient/Runner.tsx,
 * мобилка) и строкой каталога. В нём жили заметки сопровождающих каталога:
 * правообладатель, чей перевод, номер приказа, выборка ветеранов США, на
 * которой взят порог, почему варианты ответа взяты из другой методики. Человек
 * перед опросником о суицидальных мыслях читал про «онлайн-вибірку дорослих в
 * Австралії». Теперь описание — что и за какой срок спрашивают, а всё это —
 * в примечании (`note`, «Джерело» в паспорте методики).
 *
 * Мутация: вернуть в описание фразу «Робочий переклад…» или ссылку на выборку —
 * вторая проверка называет методику и слово.
 */

/** Слова сопровождающих: переводы, права, приказы, выборки, ссылки на статьи */
const PROVENANCE = [
  /переклад|перевод/iu,
  /правовласник|правообладател/iu,
  /наказ|приказ|настанов|руководств/iu,
  /вибірк|выборк|валідов|валидир/iu,
  /пор[іо]г/iu,
  /США|ВООЗ|ВОЗ|NIMH|Pfizer/u,
  /та ін\.|и соавт\.|et al/iu,
  /©|copyright|CC BY|www\.|https?:/iu,
  /УВАГА|ВНИМАНИЕ/u,
];

describe("каталог: описание для обследуемого, примечание для персонала", () => {
  test("у каждой методики есть примечание для персонала", () => {
    const empty = CATALOG.filter((e) => !e.note || e.note.trim().length < 40).map((e) => e.key);
    expect(empty).toEqual([]);
  });

  test("описание — короткое и без происхождения текста, порогов и прав", () => {
    const bad: string[] = [];
    for (const e of CATALOG) {
      const d = e.draft.description as { uk: string; ru: string };
      for (const lang of ["uk", "ru"] as const) {
        const text = d[lang] ?? "";
        if (!text.trim()) bad.push(`${e.key}/${lang}: пусто`);
        // две строки на экране обследуемого, а не абзац
        if (text.length > 160) bad.push(`${e.key}/${lang}: ${text.length} знаков`);
        for (const re of PROVENANCE) if (re.test(text)) bad.push(`${e.key}/${lang}: «${re.source}» — ${text}`);
      }
    }
    expect(bad).toEqual([]);
  });

  test("примечание украинское, без русских букв", () => {
    const bad = CATALOG.filter((e) => /[ыэъёЫЭЪЁ]/.test(e.note)).map((e) => e.key);
    expect(bad).toEqual([]);
  });
});
