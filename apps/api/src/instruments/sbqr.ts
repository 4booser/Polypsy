/**
 * SBQ-R — опросник суицидального поведения, пересмотренный
 * (Osman A., Bagge C.L., Gutierrez P.M., Konick L.C., Kopper B.A., Barrios F.X., 2001).
 *
 * Основание: разрешение правообладателя напечатано на самом бланке — «© Osman et al
 * (1999) Revised. Permission for use granted by A. Osman, MD»; условия — сохранять
 * строку копирайта, не менять формулировки и баллы. Строка копирайта поэтому стоит и в
 * описании методики, а не только в каталоге: описание — то, что видит специалист.
 * Учреждение подтвердило, что разрешения у него есть.
 *
 * Чем опасна ошибка именно здесь. Это единственная методика каталога, где неверный
 * балл — это пропущенная попытка самоубийства. Две ловушки первоисточника, на которых
 * реализация ломается молча:
 *
 *   • У четвёртого пункта «Ніколи» стоит 0, а «Жодного шансу» — 1. Это единственный
 *     пункт каталога, где минимум варианта равен нулю. Реализация «как везде», с
 *     1..7 или 1..6, сдвигает минимум суммы с 3 на 4 и уводит весь диапазон вверх —
 *     то есть выдаёт положительный скрининг там, где его нет.
 *   • У пунктов 1 и 3 разные по тексту варианты дают одинаковый балл (3a и 3b — по 3,
 *     4a и 4b — по 4; 2a и 2b — по 2, 3a и 3b — по 3). Различаются они не баллом, а
 *     тем, что видит специалист: «хотів померти» и «не хотів померти» при одной сумме
 *     означают разное. Сводить их в один вариант нельзя.
 *
 * Текст — рабочий перевод (официального украинского и русского нет ни у
 * правообладателя, ни в рецензируемых публикациях). Глаголы от первого лица даны в
 * обоих родах — «намагався(-лася)»: вопрос о собственной попытке, заданный женщине в
 * мужском роде, — лишний повод не ответить. Отвергнутая альтернатива — мужской род,
 * как в МЛО: там это текст валидированного бланка, здесь такого текста нет.
 *
 * Результат человеку не показывается, и план безопасности заполнен: четыре вопроса
 * подряд о собственной смерти — та ситуация, ради которой план безопасности вообще
 * существует.
 */

interface Risk {
  severity: "moderate" | "severe";
  uk: string;
  ru: string;
}

/**
 * Пункт SBQ-R: у каждого варианта свой балл бланка и, возможно, своя тревога.
 *
 * Общий item() из ./common не подходит: он ставит одну тревогу «с такого-то балла», а
 * у первого и четвёртого пунктов тяжесть тревоги меняется внутри пункта (см. ниже).
 */
function sbqItem(title: Loc, options: [Loc, number, Risk?][]): QuestionDraft {
  return {
    type: "single",
    title,
    required: true,
    scaleCode: "SBQR",
    reverseScored: false,
    options: options.map(([text, score, risk]) => ({
      text,
      score,
      ...(risk
        ? {
            riskFlag: true,
            riskSeverity: risk.severity,
            riskLabel: L(`SBQ-R: ${risk.uk}`, `SBQ-R: ${risk.ru}`),
          }
        : {}),
    })),
  };
}

/*
 * Тревога по пункту, а не по сумме.
 *
 * Досье относит к пунктам риска все четыре: «весь опросник — про суицид». Опубликованное
 * правило есть ровно одно — «Item 1: a cutoff score of >= 2» (чувствительность 0.80,
 * специфичность 0.97 у стационарных пациентов). Остальные три размечены по тексту
 * самих вариантов, без придуманного порога: тревогу поднимает каждый вариант, кроме
 * отрицающих, — думал об этом в прошлом году, говорил кому-то, не исключает попытки.
 *
 * Тяжесть. Где первоисточник различает ответы, различаем и мы: у первого пункта бланк
 * сам делит варианты на подгруппы «Suicide Risk Ideation», «Suicide Plan» и «Suicide
 * Attempt». Мимолётная мысль когда-то в жизни — умеренная тревога (как «кілька днів»
 * у девятого пункта PHQ-9), план и попытка — тяжёлая. У четвёртого пункта граница
 * проходит по знаку самого ответа: «малоймовірно» — человек не исключает попытки,
 * «імовірно» и выше — считает её вероятной. Где первоисточник ответов не различает
 * (пункты 2 и 3), тяжесть одна — "severe", та же, что движок ставит отмеченному
 * варианту без указанной тяжести.
 *
 * Отвергнутые альтернативы. Разметить тревогой только первый пункт, раз правило есть
 * только у него, — тогда «дуже часто» о мыслях за последний год не поднимало бы ничего
 * при сумме 6. Размечать четвёртый пункт только с «імовірно» — тогда «малоймовірно»
 * (человек прямо допускает попытку) проходило бы молча. Всё сделать тяжёлым — тогда
 * мимолётная мысль двадцатилетней давности стояла бы в очереди разбора рядом с
 * попыткой и размывала бы её. Флаг к баллу ничего не прибавляет: он только приводит
 * специалиста к протоколу, и лишний флаг здесь дешевле пропущенного.
 */
