/**
 * CBI — Копенгагенский опросник выгорания (Kristensen T.S., Borritz M.,
 * Villadsen E., Christensen K.B., Work & Stress 2005; правообладатель — NFA,
 * Дания). Досье: behaviour.json.
 *
 * Три отдельные шкалы — личное выгорание, выгорание, связанное с работой, и
 * выгорание, связанное с работой с клиентами. Общего балла CBI не существует, и
 * его здесь нет.
 *
 * Подсчёт — исследовательская версия правообладателя, дословно: «Always: 100.
 * Often: 75. Sometimes: 50. Seldom: 25. Never/almost never: 0. Total score on the
 * scale is the average of the scores on the items.» То есть балл шкалы — СРЕДНЕЕ
 * 0–100, не сумма. Пункт 7 шкалы работы («хватает ли сил на семью и друзей»)
 * обратный: флаг `reverse`, инверсию 100−балл делает движок.
 *
 * Полосы. В статье 2005 года порогов нет — только средние. Полосы есть в
 * датской форме самопроверки самого NFA, и заданы они в СЫРОЙ СУММЕ при баллах
 * 0–4 за пункт: 0–5 / 6–11 / 12–17 / 18–24 из 24 (шесть пунктов) и 0–6 / 7–13 /
 * 14–20 / 21–28 из 28 (семь пунктов). Перевод точный: сумма × 100 / (4 × число
 * пунктов) — это среднее 0–100, и границы 6/12/18 из 24 и 7/14/21 из 28 — ровно
 * 25/50/75. Поэтому полосы ниже стоят на 25/50/75 и воспроизводят датские
 * границы без округлений: наибольшее среднее ниже 25 — 20,8 (5 из 24) и 21,4
 * (6 из 28). Отвергнуто: считать сырую сумму 0–4, как в датской форме, — тогда
 * балл нельзя сравнить с нормативами NFA (32,7 ± 15,7 по личному выгоранию),
 * которые даны в 0–100. Отвергнут и тиражируемый порог «≥50 = выгорание»: в
 * первоисточниках его нет.
 *
 * severity по полосам — none/mild/moderate/severe по нарастанию слов самого
 * правообладателя: от «признаков нет» до «немедленно ищите помощь» («du straks
 * bør søge hjælp»). Верхняя полоса — единственное, что досье называет триггером;
 * отдельного тревожного пункта в CBI нет, и riskFlag здесь нет.
 *
 * Правило неответов («меньше трёх/четырёх ответов — не респондент») в движок не
 * переносится и не нужно: все пункты обязательны, среднее всегда по полной шкале.
 *
 * Порядок пунктов. Правообладатель: «The questions of the CBI should not be
 * printed in the questionnaire in the same order as shown here… This is
 * recommended in order to avoid stereotyped response patterns.» Пункты
 * перемешаны по кругу (личное, работа, клиенты, …) и в одном и том же порядке для
 * всех. Отвергнута случайная перестановка на каждое прохождение: у одного и того
 * же человека повторные замеры шли бы в разном порядке, и изменение балла
 * смешивалось бы с эффектом порядка. Номера пунктов в ключах выводятся из
 * позиции в массиве, а не выписываются руками.
 *
 * «Клиенты». Правообладатель велит подставлять уместное слово («patients» у
 * медсестёр и т. п.). Каталог общий, поэтому оставлено «клієнти», а в инструкции
 * объяснено, кто это. Шкала работы с клиентами осмысленна только для тех, кто
 * работает с людьми, — это сказано в описании шкалы.
 *
 * Перевод рабочий (у NFA только английская и датская версии) — describe().
 * Норма чужая (Дания) — сказано в описании.
 */

