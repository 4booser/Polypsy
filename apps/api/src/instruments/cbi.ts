/**
 * Порядок показа: по кругу — личное, работа, клиенты, — пока пункты не кончатся.
 * Последним остаётся седьмой пункт работы, обратный. Экспорт — для золотого
 * теста: он отвечает по шкале и номеру пункта у правообладателя, а не по
 * позиции на экране, и перестановка здесь не должна его ломать.
 */
export const CBI_ORDER: { scale: ScaleCode; n: number }[] = (() => {
  const lists: [ScaleCode, CbiItem[]][] = [
    ["PB", PERSONAL],
    ["WB", WORK],
    ["CB", CLIENT],
  ];
  const longest = Math.max(...lists.map(([, l]) => l.length));
  const order: { scale: ScaleCode; n: number }[] = [];
  for (let i = 0; i < longest; i++) {
    for (const [scale, list] of lists) if (i < list.length) order.push({ scale, n: i + 1 });
  }
  return order;
})();

const byScale: Record<ScaleCode, CbiItem[]> = { PB: PERSONAL, WB: WORK, CB: CLIENT };
const ITEMS: CbiItem[] = CBI_ORDER.map(({ scale, n }) => byScale[scale][n - 1]!);

/** Номера пунктов шкалы — из позиции в показанном порядке, а не руками */
const itemsOf = (code: ScaleCode) => ITEMS.flatMap((it, i) => (it.scale === code ? [i + 1] : []));

interface BandTexts {
  none: Loc;
  attention: Loc;
  symptoms: Loc;
  seekHelp: Loc;
}

/**
 * Полосы на 25/50/75 — см. докблок: точный перевод датских границ из сырой суммы.
 * Верхняя граница нижних полос — 24,999 и т. д., а не 24: среднее может быть
 * дробным, а движок округляет его до тысячных.
 */
const cbiBands = (t: BandTexts) =>
  bands([
    { min: 0, max: 24.999, label: t.none, severity: "none", grade: 1 },
    { min: 25, max: 49.999, label: t.attention, severity: "mild", grade: 2 },
    {
      min: 50,
      max: 74.999,
      label: t.symptoms,
      severity: "moderate",
      grade: 3,
      recommendation: L("Обговорити з фахівцем, що можна змінити", "Обсудить со специалистом, что можно изменить"),
    },
    {
      min: 75,
      max: 100,
      label: t.seekHelp,
      severity: "severe",
      grade: 4,
      recommendation: L(
        "Потрібна допомога фахівця найближчим часом",
        "Нужна помощь специалиста в ближайшее время",
      ),
    },
  ]);

