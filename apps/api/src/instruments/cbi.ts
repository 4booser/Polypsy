const scale = (code: ScaleCode, title: Loc, description: Loc, texts: BandTexts): ScaleDraft => ({
  code,
  title,
  description,
  aggregation: "average",
  kind: "clinical",
  normalization: "raw",
  key: sumKey(itemsOf(code)),
  bands: cbiBands(texts),
});

