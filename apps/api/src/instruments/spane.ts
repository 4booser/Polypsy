/**
 * SPANE — шкала позитивных и негативных переживаний
 * (Diener E., Wirtz D., Tov W., Kim-Prieto C., Choi D., Oishi S.,
 * Biswas-Diener R., 2009/2010). Досье: docs/instruments/dossiers/wellbeing.json.
 *
 * Правообладатель разрешает использование практикам без запроса.
 *
 * Двенадцать чувств за последние ЧЕТЫРЕ НЕДЕЛИ, частота 1–5. Ключ автора:
 * SPANE-P — пункты 1, 3, 5, 7, 10, 12 (positive, good, pleasant, happy,
 * joyful, contented), SPANE-N — 2, 4, 6, 8, 9, 11 (negative, bad, unpleasant,
 * sad, afraid, angry), каждая 6–30. Обратных пунктов нет: негативные чувства —
 * своя шкала, а не перевёрнутые позитивные.
 *
 * БАЛАНС SPANE-B = P − N (−24…24) ОТДЕЛЬНОЙ ШКАЛОЙ НЕ ЗАВЕДЁН, хотя движок
 * умеет композит поправками (как ЛАП у МЛО). Причина — в отображении, а не в
 * подсчёте: график динамики консоли строит ось шкалы без полос от нуля
 * (apps/web/src/charts/courseModel.ts, `axisFor({ lo: 0, … })`), а профиль
 * обрезает долю снизу нулём (pointShare). Отрицательный баланс ушёл бы за
 * нижний край графика, а на профиле выглядел бы как ноль — специалист увидел
 * бы «баланс 0» у человека, у которого негативных переживаний больше, чем
 * позитивных. Автор прямо допускает работу с двумя шкалами («The measure can
 * be used to derive an overall affect balance score, but can also be divided
 * into positive and negative feelings scales»), и разность двух чисел
 * специалист видит сам; формула названа в описании. Когда графики научатся
 * отрицательным значениям, баланс заводится одной записью в `scales`.
 *
 * ПОЛОС НЕТ: порогов у автора нет. Результат человеку не показывается — два
 * числа без подписи читаются как оценка себя.
 *
 * ТЕКСТ. Украинский — валидизированная адаптация Олефіра, Боснюка і
 * Малофейкіної (Вісник ХНУ ім. В. Н. Каразіна, «Психологія», 2021, № 71;
 * журнал под CC BY 4.0) дословно, с заглавной буквой в начале пункта.
 * Адаптация передаёт «Angry» как «роздратованим», «Sad» — как «засмученим».
 * Русский — рабочий перевод каталога с этой адаптации пункт в пункт
 * («раздражённым», «расстроенным»): валидизированную русскую версию
 * (Рассказова, Лебедева, 2020) проверить не удалось — сервер журнала был
 * недоступен. Поэтому оговорка о рабочем переводе стоит только в русском
 * описании, как у CAGE.
 */

