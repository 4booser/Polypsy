/**
 * CESD-R — пересмотренная шкала депрессии Центра эпидемиологических исследований
 * (Eaton W.W., Smith C., Ybarra M., Muntaner C., Tien A., 2004;
 * оригинал CES-D — Radloff L.S., 1977).
 *
 * Основание: общественное достояние по заявлению авторов пересмотра на
 * официальном сайте шкалы («The CESD-R is in the public domain»).
 *
 * Чем опасна ошибка ИМЕННО здесь — в верхнем варианте ответа. У CESD-R пять
 * категорий, и последняя («майже щодня протягом 2 тижнів») по замыслу авторов
 * весит столько же, сколько предпоследняя: «In order to make the revised CESD-R
 * have the same range as the original version … the values for the top two
 * responses are given the same value». Диапазон при этом 0-60, и порог 16
 * унаследован от CES-D именно для такого счёта. Дать верхней категории вес 4 —
 * значит получить сумму до 80 и сравнивать её с порогом, посчитанным для 60:
 * человек с умеренной симптоматикой перешагнёт отсечку, ничего не изменив в
 * ответах. Поэтому оба верхних варианта ниже стоят с баллом 3.
 *
 * Чего здесь НЕТ и почему. Авторы дают не только порог, но и алгоритм
 * категорий (possible / probable / meets criteria for major depressive episode)
 * — он строится не на сумме, а на комбинации симптомных групп DSM и частоты
 * ответа по каждой. Полосы шкалы устроены по сумме и такой алгоритм выразить не
 * могут, поэтому здесь есть ровно то, что по сумме и определяется: граница 16.
 * Альтернатива — назвать полосу «ймовірний депресивний епізод» по одной лишь
 * сумме — отвергнута: это другое утверждение, чем сделали авторы, и оно
 * называет эпизодом то, что эпизодом не устанавливалось.
 *
 * Официального украинского и русского текста у CESD-R нет: на странице
 * переводов авторов пятнадцать языков, и ни одного из этих двух.
 */

