/**
 * GDS-15 — гериатрическая шкала депрессии, короткая форма
 * (Sheikh J.I., Yesavage J.A., 1986; полная форма — Yesavage, Brink и соавт., 1982).
 *
 * Основание: общественное достояние по заявлению разработчика на его
 * официальной странице («The original scale is in the public domain due to it
 * being partly the result of Federal support»).
 *
 * Чем опасна ошибка ИМЕННО здесь. У GDS-15 ответы «да/нет», и пять пунктов
 * (1, 5, 7, 11, 13) зачитываются в балл при ответе «НЕТ»: это вопросы о
 * хорошем — доволен ли жизнью, бодр ли, полон ли сил. Перепутать их
 * направление — значит не сместить балл на единицу, а превратить шкалу в её
 * противоположность на трети пунктов: довольный жизнью пожилой человек
 * наберёт баллы за благополучие, а подавленный — не наберёт. Поэтому
 * обратное направление стоит флагом `reverseScored` у пункта, а инвертирование
 * делает движок (min+max−балл). Альтернатива — записать «да» нулём прямо в
 * варианте ответа — отвергнута: тогда на экране у человека и в выгрузке
 * оказались бы «да» с весом 0 и «да» с весом 1, и никакая проверка не
 * отличила бы это от опечатки.
 *
 * Отдельно про полосы. У разработчика их ровно три, и они заданы словами:
 * «a score > 5 points is suggestive of depression and should warrent a
 * follow-up interview. Scores > 10 are almost always depression». Ходовая
 * четырёхполосная схема (0-4 / 5-8 / 9-11 / 12-15), которая гуляет по
 * калькуляторам, на официальной странице ОТСУТСТВУЕТ — и здесь её нет.
 * Дорисовать четвёртую полосу значило бы выдать за норму разработчика чужую
 * разметку и назвать «умеренной» депрессию, про степень которой автор шкалы
 * ничего не утверждал.
 *
 * Методика рассчитана на пожилых: формулировки про память и про «сидеть
 * дома» у молодого человека означают не то же самое, что у восьмидесятилетнего.
 */

