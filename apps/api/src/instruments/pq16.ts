/**
 * PQ-16 — краткий продромальный опросник
 * (Ising H.K., Veling W., Loewy R.L. и соавт., 2012).
 *
 * Это и есть «тест на шизофрению», о котором спрашивают, — и название у
 * него другое не из вежливости. PQ-16 не выявляет шизофрению и не может:
 * он ищет признаки, при которых человека стоит показать специалисту, и
 * даже полный балл означает «поговорить», а не «болен». Опросник, названный
 * тестом на шизофрению, читался бы как приговор и на входе, и на выходе —
 * а среди тех, кто отвечает «так» на шесть пунктов, расстройство разовьётся
 * у меньшинства.
 *
 * Отсюда три решения, каждое из которых снимает часть вреда:
 *
 * • Результат человеку не показывается. Число «9 із 16» без того, кто
 *   объяснит, что оно значит, — худшее, что можно выдать человеку,
 *   отметившему, что он слышит голоса.
 * • Сигнал поднимает не отдельный пункт, а полоса: один «так» про дежавю
 *   не значит ничего, а шесть — значат. Именно поэтому размеченных
 *   вариантов здесь нет ни одного, и работает сигнал по полосе шкалы.
 * • Полосы названы порогом, а не диагнозом: «поріг подальшого обстеження
 *   досягнуто».
 *
 * Источник — Ising et al., Schizophr Bull 2012;38(6):1288–1296, Appendix
 * (карточка — docs/instruments/dossiers/psychosis.json). Рецензия каталога
 * 2.1 сверила с ним текст: в п. 4 пропали «clapping» — «плескання», в п. 15 —
 * «or force» — «чи сила», в п. 11 — «ideas», в п. 2 — «(déjà vu)»; вернула.
 * Инструкция больше не говорит «за последний месяц»: у бланка срока нет, а
 * в исследовании, давшем порог 6, опросник «assessed over participants'
 * lifetimes». Порог, полученный на ответах «за всю жизнь», с ответами «за
 * месяц» считал бы меньше людей, чем должен.
 */

