/**
 * Сводка пакета сверки (README) и лист «Как система считает».
 *
 * README — вход для психолога: таблица всех методик, риск одной таблицей,
 * пороги, изменённые в волне 12, чек-лист и все замечания. Пороги волны 12
 * берутся из установленных методик и из движка, а не пишутся числами: если
 * их поправят, сводка поменяется вместе с ними, и тест расхождения это
 * заметит.
 */

/** Отметка сверки из блока «Перевірка психологом»: первая заполненная строка таблицы */
export function reviewStatus(block: string | null): { who: string; date: string; verdict: string } | null {
  if (!block || !block.startsWith(REVIEW_BEGIN)) return null;
  const rows = block
    .split("\n")
    .filter((l) => l.startsWith("|") && !/^\|\s*-/.test(l))
    .slice(1);
  for (const row of rows) {
    const cells = row
      .split("|")
      .slice(1, -1)
      .map((c) => c.trim());
    if (cells[0]) return { who: cells[0], date: cells[1] ?? "", verdict: cells[2] ?? "" };
  }
  return null;
}

const firstSentence = (text: string | null): string => {
  if (!text) return "";
  const m = text.match(/^(.+?[.!?])(\s|$)/);
  return (m ? m[1]! : text).trim();
};

/**
 * Пороги тревоги методики одной строкой: «PHQ: 10–14 — помірна, 15–27 —
 * тяжка; критичні пп. 9». Диапазонами, а не «от»: у стенов БОО шкала
 * обратная, и «від 1 — тяжка» читалось бы наоборот. Соседние полосы одной
 * тяжести сливаются — важна граница, с которой меняется реакция.
 */
function alarmSummary(lang: SheetLang, survey: SurveyFull): string {
  const s = pick(lang);
  const parts: string[] = [];
  for (const scale of survey.scales) {
    const runs: { from: number; to: number; sev: "moderate" | "severe" }[] = [];
    let prev: "moderate" | "severe" | null = null;
    for (const b of [...scale.bands].sort((a, x) => a.minScore - x.minScore)) {
      const sev = bandAlarm(scale, b);
      const last = runs[runs.length - 1];
      if (sev && last && prev === sev) last.to = b.maxScore;
      else if (sev) runs.push({ from: b.minScore, to: b.maxScore, sev });
      prev = sev;
    }
    if (runs.length) {
      parts.push(`${scale.code}: ${runs.map((r) => `${r.from === r.to ? num(r.from) : `${num(r.from)}–${num(r.to)}`} — ${severityWord(lang, r.sev)}`).join(", ")}`);
    }
  }
  const items = survey.questions.flatMap((q, i) => (q.options.some((o) => o.riskFlag) ? [i + 1] : []));
  if (items.length) parts.push(s(`критичні пп. ${ranges(items)}`, `критические пп. ${ranges(items)}`));
  return parts.join("; ") || s("немає", "нет");
}

function riskRows(lang: SheetLang, b: BuiltInstrument): string[][] {
  const s = pick(lang);
  const survey = lang === "uk" ? b.inst.uk : b.inst.ru;
  const title = t(b.inst.input.title as never, lang);
  const link = `[${cell(title)}](${lang}/${b.inst.entry.key}.md)`;
  const rows: string[][] = [];
  survey.questions.forEach((q, i) => {
    const bySeverity = new Map<string, string[]>();
    for (const o of q.options.filter((x) => x.riskFlag)) {
      const sev = o.riskSeverity ?? "severe";
      bySeverity.set(sev, [...(bySeverity.get(sev) ?? []), `«${o.text}»`]);
    }
    for (const [sev, opts] of bySeverity) {
      rows.push([
        link,
        s(`п. ${i + 1}: ${cell(q.title.length > 70 ? `${q.title.slice(0, 68)}…` : q.title)}`, `п. ${i + 1}: ${cell(q.title.length > 70 ? `${q.title.slice(0, 68)}…` : q.title)}`),
        s(`відповідь ${opts.join(" або ")}`, `ответ ${opts.join(" или ")}`),
        severityWord(lang, sev as "moderate" | "severe"),
      ]);
    }
  });
  for (const scale of survey.scales) {
    for (const band of [...scale.bands].sort((x, y) => x.minScore - y.minScore)) {
      const alarm = bandAlarm(scale, band);
      if (!alarm) continue;
      rows.push([
        link,
        s(`шкала ${scale.code}, смуга «${cell(band.label)}»`, `шкала ${scale.code}, полоса «${cell(band.label)}»`),
        readingOf(lang, scale.bands, band),
        severityWord(lang, alarm),
      ]);
    }
  }
  return rows;
}

function byKey(built: BuiltInstrument[], key: string): BuiltInstrument | undefined {
  return built.find((b) => b.inst.entry.key === key);
}

/** Раздел о порогах волны 12 — числа берутся из установленных методик и движка */
function wave12(lang: SheetLang, built: BuiltInstrument[]): string {
  const s = pick(lang);
  const out: string[] = [];
  const who5 = byKey(built, "who5");
  if (who5) {
    const scale = (lang === "uk" ? who5.inst.uk : who5.inst.ru).scales[0]!;
    const bands = [...scale.bands]
      .sort((a, b) => a.minScore - b.minScore)
      .map((b) => `${num(b.minScore)}–${num(b.maxScore)} «${b.label}» (${severityWord(lang, b.severity)})`);
    out.push(
      s(
        `**WHO-5** ([лист](uk/who5.md)): ${bands.join("; ")}. Джерело — WHO, 1998; Topp et al., 2015: нижче 13 — погане благополуччя, 7 і нижче — ймовірна депресія. Раніше 13 із 25 потрапляло в помірну смугу з тривогою.`,
        `**WHO-5** ([лист](ru/who5.md)): ${bands.join("; ")}. Источник — WHO, 1998; Topp et al., 2015: ниже 13 — плохое благополучие, 7 и ниже — вероятная депрессия. Раньше 13 из 25 попадало в умеренную полосу с тревогой.`,
      ),
    );
  }
  const sr45 = byKey(built, "sr45");
  const L = sr45?.inst.uk.scales.find((x) => x.code === "L");
  if (L && L.validityThreshold !== null) {
    out.push(
      s(
        `**СР-45, шкала брехні** ([лист](uk/sr45.md)): протокол ненадійний при L ${L.validityDirection === "below" ? "<" : ">"} ${num(L.validityThreshold)}, тобто L ≥ 0,6 (частка з десяти пунктів іде кроком 0,1). Раніше поріг «> 0,6» пропускав рівно L = 0,6.`,
        `**СР-45, шкала лжи** ([лист](ru/sr45.md)): протокол ненадёжен при L ${L.validityDirection === "below" ? "<" : ">"} ${num(L.validityThreshold)}, то есть L ≥ 0,6 (доля из десяти пунктов идёт шагом 0,1). Раньше порог «> 0,6» пропускал ровно L = 0,6.`,
      ),
    );
  }
  const mm = byKey(built, "minimult");
  const hs = mm?.inst.uk.scales.find((x) => x.code === "Hs");
  if (hs?.bands.length) {
    const low = [...hs.bands].sort((a, b) => a.minScore - b.minScore)[0]!;
    out.push(
      s(
        `**Міні-мульт, нижня T-смуга** ([лист](uk/minimult.md)): починається з ${num(low.minScore)} — найнижчого T, досяжного за нормами посібника (у жінок Pt: M = 14,48, SD = 2,27, тож T при нульовому балі ≈ −13,8). Раніше смуга починалася з 0, і такий профіль лишався без інтерпретації.`,
        `**Мини-мульт, нижняя T-полоса** ([лист](ru/minimult.md)): начинается с ${num(low.minScore)} — самого низкого T, достижимого по нормам пособия (у женщин Pt: M = 14,48, SD = 2,27, так что T при нулевом балле ≈ −13,8). Раньше полоса начиналась с 0, и такой профиль оставался без интерпретации.`,
      ),
    );
  }
  out.push(
    s(
      `**Мінімальна частка відповідей** (усі шкали без власного правила): ${num(DEFAULT_MIN_ANSWERED_SHARE)}. Якщо відповідей на пункти шкали менше, шкала не обчислюється (а не дає 0 і смугу «норма»). Для шкали з 2–4 пунктів це означає «усі пункти». Пункти каталогу обов’язкові, тож при звичайній здачі правило спрацьовує лише на частковій відповіді.`,
      `**Минимальная доля ответов** (все шкалы без своего правила): ${num(DEFAULT_MIN_ANSWERED_SHARE)}. Если ответов на пункты шкалы меньше, шкала не вычисляется (а не даёт 0 и полосу «норма»). Для шкалы из 2–4 пунктов это означает «все пункты». Пункты каталога обязательные, поэтому при обычной сдаче правило срабатывает только на частичном ответе.`,
    ),
  );
  const demo: ScaleBand[] = [
    { minScore: 0.6, maxScore: 0.74 },
    { minScore: 0.75, maxScore: 1 },
  ] as ScaleBand[];
  const hit = bandFor(demo, 0.743);
  out.push(
    s(
      `**Напівінтервал сусідніх смуг**: межі, записані з точністю посібника («0,60–0,74 · 0,75–1», «0–4 · 5–9»), читаються як «до початку наступної смуги, не включно». Перевірка рушієм зараз: 26/35 = 0,743 → ${hit === demo[0] ? "смуга 0,60–0,74" : hit === demo[1] ? "смуга 0,75–1" : "без смуги"}. Раніше таке значення провалювалося між смугами — без смуги й без тривоги. Щілина, ширша за точність меж, лишається без смуги: її система не вигадує.`,
      `**Полуинтервал соседних полос**: границы, записанные с точностью пособия («0,60–0,74 · 0,75–1», «0–4 · 5–9»), читаются как «до начала следующей полосы, не включительно». Проверка движком сейчас: 26/35 = 0,743 → ${hit === demo[0] ? "полоса 0,60–0,74" : hit === demo[1] ? "полоса 0,75–1" : "без полосы"}. Раньше такое значение проваливалось между полосами — без полосы и без тревоги. Щель шире точности границ остаётся без полосы: её система не выдумывает.`,
    ),
  );
  return out.map((x) => `- ${x}`).join("\n");
}

