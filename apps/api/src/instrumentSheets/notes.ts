/**
 * Что о методике знает человек, а не определение: откуда она, чем
 * отличается от первоисточника, что сверить отдельно.
 *
 * Всё остальное в листе выводится из определения и движка; здесь — только
 * то, что вывести нельзя. Каждая запись сводится к комментарию в файле
 * методики (apps/api/src/instruments/*.ts), к паспорту docs/INSTRUMENTS.md
 * или к досье docs/instruments/dossiers/*.json — своих утверждений о
 * первоисточниках здесь нет: лист сверки, который сам выдумывает, что
 * написано в пособии, хуже листа без этого раздела.
 *
 * Проверочные примеры досье переписаны из поля `example` карточки досье в
 * ответы по номерам пунктов; ожидаемое значение — число из досье, а не из
 * движка. Если движок разойдётся с досье, лист покажет это строкой «✗», а
 * README — замечанием.
 */

export interface InstrumentNotes {
  /** Имя в describe("золотой протокол: …") эталонного теста */
  golden?: string;
  /** Источник, записанный только в комментарии определения и паспорте (встроенные методики) */
  passportSource?: Loc;
  /** Известные отличия от первоисточника — из комментариев кода и досье */
  differences: Loc[];
  /** Что сверить сверх общего списка */
  verify: Loc[];
  /** Замечания для проверки — идут и в лист, и в сводку README */
  remarks: Loc[];
  /** Проверочные примеры досье */
  dossier?: DossierExampleSpec[];
}

