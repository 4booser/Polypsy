import { sql } from "drizzle-orm";
import { baseDb } from "../db";

/**
 * Один проход задачи на все реплики — транзакционным замком Postgres.
 *
 * Реестр тактов (opsJobs.ts) знает только свой процесс: «уже идёт» там
 * значит «идёт у меня». Ручной запуск из техпанели может прийти в любую
 * реплику API, и две переиндексации или две проверки оповещений на двух
 * репликах разом — это двойная работа, а у оповещений ещё и двойное
 * «збій» в Telegram. Замок в базе видят все.
 *
 * Приём тот же, что у планировщика (scheduler.ts, runDueSchedules), и по
 * той же причине: сессионный замок в пуле соединений ломается — захват и
 * освобождение уходят в разные соединения. Транзакция-обёртка держит одно
 * соединение и ничего не пишет; работа внутри идёт обычным пулом, а замок
 * отпускается сам при выходе — в том числе при ошибке. Обёртка берётся от
 * baseDb напрямую и не открывает системного контекста: иначе вся работа
 * пошла бы одной транзакцией, со всеми бедами, описанными у планировщика.
 *
 * Пространство ключей — двухчисловое (класс, хэш имени): так замки задач не
 * пересекаются с одночисловыми замками планировщика и журнала.
 */
const JOB_LOCK_CLASS = 7_154_400;

export class JobLocked extends Error {
  constructor(name: string) {
    super(`задача ${name} уже выполняется на другом экземпляре`);
    this.name = "JobLocked";
  }
}

export function withJobLock<T>(name: string, fn: () => Promise<T>): Promise<T> {
  return baseDb.transaction(async (tx) => {
    const [row] = (await tx.execute(
      sql`select pg_try_advisory_xact_lock(${JOB_LOCK_CLASS}, hashtext(${name})) as ok`,
    )) as unknown as { ok: boolean }[];
    if (!row?.ok) throw new JobLocked(name);
    return fn();
  });
}
