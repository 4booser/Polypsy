import { inArray } from "drizzle-orm";
import { db } from "../db";
import { asSystem } from "../db/context";
import { users } from "../db/schema";
import { fullNameOf } from "./auth";

/**
 * Имена людей, с которыми пациента уже связала отобранная строка: автор
 * рассылки из его ящика, ведущий специалист его переписки, автор его плана
 * безопасности, специалист его приёма.
 *
 * Под политикой users (0075) пациент видит только свою строку. Соединение с
 * users в его запросе всегда пусто, и вместо имени стояло «—», а выборка
 * строки специалиста «ради имени» отдавала undefined — справка о посещении
 * падала пятисоткой. Тесты этого не показывали: они ходят в базу владельцем,
 * для которого политик нет. Нашлось сначала у рассылок (волна 12), потом —
 * обходом всех GET под ролью приложения (волна 13, appRoleFlows.test.ts):
 * переписка, план безопасности, справка о посещении.
 *
 * Отвергнуто: расширить политику users — «пациент видит строки
 * сотрудников». Это отдало бы пациенту на уровне базы почту, телефон и хеш
 * пароля любого сотрудника, а нужно ему одно имя одного человека.
 * SECURITY DEFINER-функция в базе тоже не подходит: ФИО шифрованы,
 * расшифровка живёт в приложении, и функция отдавала бы шифртекст — второй
 * путь к колонкам имени ради того же decryptField. Копия имени в самой строке
 * (письме, плане) — ещё одна шифрованная колонка с персональным полем, которая
 * расходится с users при смене фамилии.
 *
 * Системная роль здесь — на одну выборку ровно тех колонок, из которых
 * складывается имя, и только по идентификаторам, которые вызывающий уже
 * получил своей выборкой под политикой: больше, чем имя собственного
 * собеседника, пациент не узнаёт.
 *
 * asSystem — в той же транзакции запроса, а не systemContext. Отдельная
 * системная транзакция брала второе соединение пула, пока транзакция запроса
 * держала первое, — на каждый просмотр. Это тот же узор, от которого пул
 * вставал при двойной авторизации (внешний разбор 2026-09-26, сторож —
 * test/authOnce.test.ts).
 */
export async function namesOf(ids: (string | null | undefined)[]): Promise<Map<string, string>> {
  const wanted = [...new Set(ids.filter((id): id is string => Boolean(id)))];
  if (!wanted.length) return new Map();
  const rows = await asSystem(() =>
    db
      .select({
        id: users.id,
        firstName: users.firstName,
        lastName: users.lastName,
        middleName: users.middleName,
        anonymous: users.anonymous,
        pseudonym: users.pseudonym,
      })
      .from(users)
      .where(inArray(users.id, wanted)),
  );
  return new Map(rows.map((r) => [r.id, fullNameOf(r)]));
}
