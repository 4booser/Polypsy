/**
 * Подавление малых ячеек.
 *
 * Не формальность: в роте на двенадцать человек строка «выраженная степень: 1»
 * указывает на конкретного, и по ней его узнают сослуживцы. То же верно для
 * когорты из трёх человек — то, что её собрали визуальным конструктором, а не
 * отчётом, никак не меняет, кого в ней узнают.
 *
 * Порог живёт здесь, а не в каждом маршруте: два числа в разных файлах — это
 * два числа, которые однажды разойдутся, и разойдутся молча.
 */
export const SMALL_CELL_FLOOR = 5;

/** Число, если ячейка достаточно велика; иначе null — «нельзя показать» */
export function suppress(count: number): number | null {
  /*
   * Ноль показывается. «Никого нет» не выдаёт никого, а спрятанный ноль
   * заставляет думать, что там кто-то есть.
   */
  if (count === 0) return 0;
  return count >= SMALL_CELL_FLOOR ? count : null;
}

/** Можно ли вообще разбивать выборку на части: слишком малую — нельзя */
export function canBreakDown(total: number): boolean {
  return total >= SMALL_CELL_FLOOR;
}

/**
 * Ячейка отчёта: число и его доля подавляются вместе.
 *
 * Отдельная функция, потому что порознь это правило уже нарушалось дважды —
 * и оба раза одинаково: число подавляли, а долю, посчитанную из
 * НЕподавленного числа, отдавали рядом со знаменателем. Восстановить
 * скрытое умножением может кто угодно: n = percent × total / 100.
 * Подразделение с двадцатью замерами и одним тяжёлым по шкале
 * суицидального риска отдавало «count: null, percent: 5, total: 20» —
 * единственный человек вычислялся точно.
 *
 * Пока доля считалась отдельным выражением рядом, ничто не мешало забыть
 * про неё в третий раз. Здесь забыть нельзя: она возвращается вместе с
 * числом или не возвращается вовсе.
 */
export function cell(count: number, total: number): { count: number | null; percent: number | null } {
  const shown = suppress(count);
  return {
    count: shown,
    percent: shown === null || total <= 0 ? null : Math.round((count / total) * 100),
  };
}

/**
 * Дополняющее подавление: одна скрытая ячейка восстанавливается вычитанием.
 *
 * Порог сам по себе не защищает, если рядом опубликовано целое. Строка
 * «показано 40 и 57, скрыта одна страта» вместе с общим числом 100 называет
 * скрытую точно: 3. Скрывать её после этого бессмысленно — она уже названа,
 * просто не своими руками, а руками того, кто вычел.
 *
 * Целое в системе публикуется: число прохождений методики отдаёт
 * `/api/analytics/surveys/:id` без всякого подавления — и правильно, это
 * объём работы отделения, а не сведение о человеке. Значит закрывать надо не
 * целое, а единственность скрытого: пока скрытых ДВЕ, остаток делится между
 * ними, и ни одна не называется.
 *
 * Отсюда правило: скрыта ровно одна — прячем ещё одну, самую маленькую из
 * показанных НЕнулевых. Самую маленькую, а не любую, потому что теряется
 * меньше всего: у маленькой страты и доверительный интервал шире, и выводов
 * по ней меньше. Обратный выбор — прятать самую большую — дал бы лучшую
 * защиту (остаток размазывается сильнее), но выбил бы из отчёта ровно ту
 * группу, ради которой его открывали.
 *
 * Чего функция НЕ делает: не трогает случай, когда скрытых нет вовсе, и не
 * трогает случай, когда их уже две и больше. Первое — нечего защищать,
 * второе — уже защищено.
 *
 * ═══ Где пара доказуема, а где нет ═══
 *
 * Правило выбора пары опубликовано вместе с отчётом, и читатель считает по
 * нему не хуже нас. Пусть h — скрытая малая ячейка, d — дополняющая, а
 * S = h + d — их сумма (целое минус оставшиеся показанные). Читателю
 * известно: 1 ≤ h ≤ порог − 1 (её спрятал порог), d ≥ порог (её показывали)
 * и d ≤ m — наименьшей из оставшихся ненулевых показанных (мы прячем самую
 * маленькую). Отсюда
 * h = S − d лежит в [max(1, S − m), min(порог − 1, S − порог)]; если в этом
 * отрезке меньше двух целых, h названа точно, и пара — видимость защиты.
 * Так «5, 5, 4» при пороге 5 даёт S = 9, m = 5, отрезок [4, 4] — скрытая
 * четвёрка восстановлена. В таких случаях и когда все показанные нули (ноль
 * ничего не размазывает, скрытая равна остатку) прячется ВСЁ разбиение:
 * тогда неизвестных столько же, сколько ячеек, и ни одна не определена.
 *
 * Поэтому статистические модели (lib/statModels.ts) пары не заводят вовсе и
 * прячут группу целиком: там поверх разбиения стоят ещё остаток и «ВШР»,
 * уравнений больше, чем ячеек, и отрезок выше считался бы по неполному
 * знанию читателя — то есть не считался бы.
 *
 * @param cells пары «ключ — размер», ВСЕ, и показанные и скрытые
 * @returns ключи, которые нельзя показывать, включая добавленный дополняющий
 */
export function suppressedKeys<K>(cells: { key: K; n: number }[]): Set<K> {
  const hidden = new Set<K>();
  for (const c of cells) if (suppress(c.n) === null) hidden.add(c.key);
  if (hidden.size !== 1) return hidden;

  const shown = cells.filter((c) => !hidden.has(c.key));
  /*
   * Прятать нечего: скрытая страта — единственная, и целое совпадает с ней.
   * Добавочное подавление здесь ничего не изменило бы, а отчёт опустел бы
   * ради защиты, которой и так нет: целое названо, слагаемое одно.
   */
  if (!shown.length) return hidden;

  const all = new Set(cells.map((c) => c.key));
  /*
   * Ноль в пару не годится: спрятанный ноль не уносит с собой ничего, и
   * скрытая ячейка по-прежнему равна остатку. Нули к тому же восстановимы
   * из строения отчёта — «никто не выбрал» видно и по соседним срезам.
   */
  const nonZero = shown.filter((c) => c.n > 0).sort((a, b) => a.n - b.n);
  if (!nonZero.length) return all;

  /* отрезок допустимых значений скрытой ячейки: меньше двух целых — она названа */
  const [pair, ...others] = nonZero;
  const small = cells.find((c) => hidden.has(c.key))!;
  const pairSum = small.n + pair!.n;
  const low = Math.max(1, pairSum - (others[0]?.n ?? Number.POSITIVE_INFINITY));
  const high = Math.min(SMALL_CELL_FLOOR - 1, pairSum - SMALL_CELL_FLOOR);
  if (high - low < 1) return all;

  hidden.add(pair!.key);
  return hidden;
}
