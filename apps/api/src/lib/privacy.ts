/**
 * Подавление малых ячеек.
 *
 * Не формальность: в роте на двенадцать человек строка «выраженная степень: 1»
 * указывает на конкретного, и по ней его узнают сослуживцы. То же верно для
 * когорты из трёх человек — то, что её собрали визуальным конструктором, а не
 * отчётом, никак не меняет, кого в ней узнают.
 *
 * Порог живёт здесь, а не в каждом маршруте: два числа в разных файлах — это
 * два числа, которые однажды разойдутся, и разойдутся молча.
 */
export const SMALL_CELL_FLOOR = 5;

/**
 * Год рождения из даты — для списков.
 *
 * Год, а не возраст: возраст меняется каждый год, а различают тёзок по
 * неизменному. И год, а не полная дата: списка это не касается, а полная
 * дата рождения — та самая мелочь, из которой складывается опознание.
 * Живёт здесь, рядом с порогом малых ячеек: это тоже правило о том, сколько
 * можно показать, — и раньше оно лежало копией в маршруте динамики, откуда
 * второй список его бы не увидел.
 */
export function birthYearOf(birthDate: string | null): number | null {
  if (!birthDate) return null;
  const year = Number(birthDate.slice(0, 4));
  return Number.isFinite(year) && year > 1900 ? year : null;
}

/** Число, если ячейка достаточно велика; иначе null — «нельзя показать» */
export function suppress(count: number): number | null {
  /*
   * Ноль показывается. «Никого нет» не выдаёт никого, а спрятанный ноль
   * заставляет думать, что там кто-то есть.
   */
  if (count === 0) return 0;
  return count >= SMALL_CELL_FLOOR ? count : null;
}

/** Можно ли вообще разбивать выборку на части: слишком малую — нельзя */
export function canBreakDown(total: number): boolean {
  return total >= SMALL_CELL_FLOOR;
}

/**
 * Ячейка отчёта: число и его доля подавляются вместе.
 *
 * Отдельная функция, потому что порознь это правило уже нарушалось дважды —
 * и оба раза одинаково: число подавляли, а долю, посчитанную из
 * НЕподавленного числа, отдавали рядом со знаменателем. Восстановить
 * скрытое умножением может кто угодно: n = percent × total / 100.
 * Подразделение с двадцатью замерами и одним тяжёлым по шкале
 * суицидального риска отдавало «count: null, percent: 5, total: 20» —
 * единственный человек вычислялся точно.
 *
 * Пока доля считалась отдельным выражением рядом, ничто не мешало забыть
 * про неё в третий раз. Здесь забыть нельзя: она возвращается вместе с
 * числом или не возвращается вовсе.
 */
export function cell(count: number, total: number): { count: number | null; percent: number | null } {
  const shown = suppress(count);
  return {
    count: shown,
    percent: shown === null || total <= 0 ? null : Math.round((count / total) * 100),
  };
}

/**
 * Дополняющее подавление: одна скрытая ячейка восстанавливается вычитанием.
 *
 * Порог сам по себе не защищает, если рядом опубликовано целое. Строка
 * «показано 40 и 57, скрыта одна страта» вместе с общим числом 100 называет
 * скрытую точно: 3. Скрывать её после этого бессмысленно — она уже названа,
 * просто не своими руками, а руками того, кто вычел.
 *
 * Целое в системе публикуется: число прохождений методики отдаёт
 * `/api/analytics/surveys/:id` без всякого подавления — и правильно, это
 * объём работы отделения, а не сведение о человеке. Значит закрывать надо не
 * целое, а единственность скрытого: пока скрытых ДВЕ, остаток делится между
 * ними, и ни одна не называется.
 *
 * Отсюда правило: скрыта ровно одна — прячем ещё одну, самую маленькую из
 * показанных НЕнулевых. Самую маленькую, а не любую, потому что теряется
 * меньше всего: у маленькой страты и доверительный интервал шире, и выводов
 * по ней меньше. Обратный выбор — прятать самую большую — дал бы лучшую
 * защиту (остаток размазывается сильнее), но выбил бы из отчёта ровно ту
 * группу, ради которой его открывали.
 *
 * Чего функция НЕ делает: не трогает случай, когда скрытых нет вовсе, и не
 * трогает случай, когда их уже две и больше. Первое — нечего защищать,
 * второе — уже защищено.
 *
 * ═══ Где пара доказуема, а где нет ═══
 *
 * Правило выбора пары опубликовано вместе с отчётом, и читатель считает по
 * нему не хуже нас. Пусть h — скрытая малая ячейка, d — дополняющая, а
 * S = h + d — их сумма (целое минус оставшиеся показанные). Читателю
 * известно: 1 ≤ h ≤ порог − 1 (её спрятал порог), d ≥ порог (её показывали)
 * и d ≤ m — наименьшей из оставшихся ненулевых показанных (мы прячем самую
 * маленькую). Отсюда
 * h = S − d лежит в [max(1, S − m), min(порог − 1, S − порог)]; если в этом
 * отрезке меньше двух целых, h названа точно, и пара — видимость защиты.
 * Так «5, 5, 4» при пороге 5 даёт S = 9, m = 5, отрезок [4, 4] — скрытая
 * четвёрка восстановлена. В таких случаях и когда все показанные нули (ноль
 * ничего не размазывает, скрытая равна остатку) прячется ВСЁ разбиение:
 * тогда неизвестных столько же, сколько ячеек, и ни одна не определена.
 *
 * Поэтому статистические модели (lib/statModels.ts) пары не заводят вовсе:
 * там поверх разбиения стоят ещё остаток, «ВШР» и соседние колонки,
 * уравнений больше, чем ячеек, и отрезок выше считался бы по неполному
 * знанию читателя — то есть не считался бы. Вместо пары там стоит
 * pinnedAreas ниже: не правило, а проверка всей системы разом.
 *
 * @param cells пары «ключ — размер», ВСЕ, и показанные и скрытые
 * @returns ключи, которые нельзя показывать, включая добавленный дополняющий
 */
export function suppressedKeys<K>(cells: { key: K; n: number }[]): Set<K> {
  const hidden = new Set<K>();
  for (const c of cells) if (suppress(c.n) === null) hidden.add(c.key);
  if (hidden.size !== 1) return hidden;

  const shown = cells.filter((c) => !hidden.has(c.key));
  /*
   * Прятать нечего: скрытая страта — единственная, и целое совпадает с ней.
   * Добавочное подавление здесь ничего не изменило бы, а отчёт опустел бы
   * ради защиты, которой и так нет: целое названо, слагаемое одно.
   */
  if (!shown.length) return hidden;

  const all = new Set(cells.map((c) => c.key));
  /*
   * Ноль в пару не годится: спрятанный ноль не уносит с собой ничего, и
   * скрытая ячейка по-прежнему равна остатку. Нули к тому же восстановимы
   * из строения отчёта — «никто не выбрал» видно и по соседним срезам.
   */
  const nonZero = shown.filter((c) => c.n > 0).sort((a, b) => a.n - b.n);
  if (!nonZero.length) return all;

  /* отрезок допустимых значений скрытой ячейки: меньше двух целых — она названа */
  const [pair, ...others] = nonZero;
  const small = cells.find((c) => hidden.has(c.key))!;
  const pairSum = small.n + pair!.n;
  const low = Math.max(1, pairSum - (others[0]?.n ?? Number.POSITIVE_INFINITY));
  const high = Math.min(SMALL_CELL_FLOOR - 1, pairSum - SMALL_CELL_FLOOR);
  if (high - low < 1) return all;

  hidden.add(pair!.key);
  return hidden;
}


/* ─────────── Восстановимость: отчёт как система уравнений ─────────── */

/**
 * Проверка вместо правил.
 *
 * Набор правил «спрячь ещё вот это» проигрывает тому, кто решает систему:
 * каждое новое правило закрывает свой случай и открывает следующий. Так и
 * выходило раз за разом. Правило «прячь группу целиком» закрывало колонку
 * изнутри — а «Усі» = «Велике» ⊎ «Мале» вычитанием двух показанных соседок
 * назвало скрытую ячейку третьей. Правило «закрывай колонку при малой
 * разности составов» мерило РАЗМЕР разности — а утекала колонка, ей равная.
 * Правило «покажи группу, если каждая ячейка над порогом» пропустило
 * |Біль ∖ Шум| = 1: разности двух показанных множеств не проверял никто.
 *
 * Поэтому здесь не правило, а проверка. Отчёт — система над ОБЛАСТЯМИ:
 * область — самая мелкая группа людей, которую числа отчёта ещё различают.
 * Набор чисел безопасен, если ни одна область-горстка не определена
 * системой однозначно: пока у скрытого есть хотя бы два совместимых
 * значения, назвать по нему человека нельзя.
 *
 * ═══ Что именно знает читатель ═══
 *
 * Не только напечатанные числа. Прочерк — тоже сведение: ноль отчёт
 * печатает всегда (см. suppress), значит за каждым прочерком стоит хотя бы
 * один человек. Отсюда скрытые числа входят в систему НЕРАВЕНСТВАМИ «≥ 1»,
 * и без них проверка слепнет буквально: восемь вариантов, «А» 15 из 20,
 * два варианта с честными нулями и пять прочерков — сумма прочерков 5,
 * слагаемых пять, каждое не меньше единицы, значит каждое равно единице, и
 * пятеро названы поимённо. По одним показанным числам эта пятёрка — один
 * класс из пяти человек, то есть «не горстка»; вся утечка живёт в том, что
 * класс поделён прочерками.
 *
 * Отвергнуто: считать, что читатель ничего не знает о прочерке. Это ровно
 * то допущение, на котором защиту и пробили: правило публикации известно
 * вместе с отчётом, и «показываем ноль, прячем единицу» читается как
 * «прочерк ≥ 1» без всякого доступа к коду.
 *
 * Верхний край у прочерка тоже есть, но не у всякого: порог прячет число
 * меньше пяти, цикл подавления — любое. Край ставится только там, где он
 * ВЕРЕН по живым данным; иначе настоящий расклад выпал бы из системы, и
 * проверка считала бы по миру, которого нет. Без края разбиение 5/5/4/4 на
 * восемнадцати печаталось как «18 | 5 | 5 | × | ×»: сумма прочерков 8, а
 * при крае в четыре она разбивается единственным способом — 4 и 4.
 *
 * ═══ Ярусы: сперва дешёвые, дорогой — последним ═══
 *
 * (1) Линейная оболочка показанных чисел: если вектор области выражается
 *     через напечатанные суммы, область названа вычитанием. Матрица
 *     приводится один раз на систему, и потом каждая область стоит
 *     столько, сколько в системе свободных столбцов.
 * (2) Сужение границ по неравенствам: «≥ 1» за прочерками плюс точные
 *     суммы. Ловит вынужденные значения, до которых оболочке дела нет:
 *     над рациональными числами пятёрка из пяти единиц ничем не
 *     закреплена, а над целыми неотрицательными — закреплена насмерть.
 * (3) Перенос одного человека внутри связки и готовые «другие миры» из
 *     базиса ядра: и то и другое ПРЕДЪЯВЛЯЕТ расклад, отличный от
 *     настоящего, то есть доказывает, что область свободна, не решая
 *     ничего.
 * (4) Целочисленный поиск второго значения — только для областей, которые
 *     не закрыл ни один ярус выше, и только когда выше вообще ничего не
 *     найдено. Во время цикла подавления ярусы 1–2 находят по нескольку
 *     областей на шаг, и до четвёртого дело доходит один-два раза за
 *     расчёт.
 *
 * ═══ Где у проверки границы — и они записаны, а не подразумеваются ═══
 *
 * 1. ОДИНОЧНЫЕ области проверяются ВСЕ до единой, и каждая малая строка
 *    отчёта — тоже целиком. Это не украшение: в прежней редакции и то и
 *    другое бралось из усечённого списка «шестнадцать самых мелких», и
 *    отчёт с двумя десятками клеток Венна по одному человеку вытеснял
 *    оттуда искомую четвёрку. Защита вела себя наоборот здравому смыслу:
 *    чем подробнее отчёт, тем слабее проверка.
 * 2. Усечён только перебор ОБЪЕДИНЕНИЙ: не больше UNION_LIMIT малых
 *    связок. Сумма двух связок за этой границей не проверяется. Связка,
 *    а не область, — единица не для красоты: части связки переносом
 *    человека размываются, значит объединение, называющее людей, состоит
 *    из целых связок, и границу теперь приходится подпирать куда реже.
 * 3. Целочисленный поиск (ярус 4) ограничен числом узлов. Исчерпал узлы —
 *    считается, что второго значения нет, то есть область названа. Ошибка
 *    в сторону лишнего подавления, а не пропуска.
 * 4. Систему шире AREA_LIMIT областей проверка не решает, а объявляет
 *    восстановимой — и вызывающий прячет ещё одно число. Тоже в сторону
 *    подавления.
 * 5. Области считаются по живым данным, а не перебором мыслимых: у нас
 *    есть точные размеры. Мыслимых областей больше, чем настоящих, и от
 *    этого проверка строже настоящей опасности.
 */

/** Число отчёта вместе с людьми, из которых оно сложено */
export interface Reported {
  key: string;
  /**
   * Кто попал в число. Множество, а не готовое значение: области проверка
   * строит сама, по тому, какие числа накрывают одного и того же человека.
   * Пары «ключ — значение» не хватило бы: две ячейки с числом 5 бывают над
   * одними и теми же пятью людьми и над разными, и системы получаются
   * разные.
   */
  members: ReadonlySet<string>;
  /**
   * Напечатано ли значение. Скрытое число из системы НЕ выбрасывается: оно
   * делит области (пять прочерков делят класс из пяти человек на пятерых)
   * и добавляет неравенство «≥ 1» (ноль печатается, значит за прочерком
   * кто-то есть).
   */
  shown: boolean;
}

/** Область, которую числа отчёта называют точно */
export interface PinnedArea {
  /** Показанные числа, накрывающие область: из них её и вычитают */
  inside: string[];
  /** Сколько в ней человек; 0 — систему проверить не удалось, считаем восстановимой */
  n: number;
}

/**
 * Потолок областей в одной системе. Приведение матрицы стоит как
 * «строк × строк × столбцов», и при потолке расчёт остаётся
 * миллисекундным. Система шире потолка не объявляется безопасной: она
 * объявляется НЕПРОВЕРЕННОЙ, и вызывающий прячет ещё одно число — от
 * этого области сливаются, и система сходится.
 */
const AREA_LIMIT = 800;

/**
 * Сколько мелких областей берётся в перебор ОБЪЕДИНЕНИЙ.
 *
 * Горстка — это меньше SMALL_CELL_FLOOR человек, а в каждой области хотя
 * бы один: значит, объединение-горстка складывается не больше чем из
 * порог−1 областей, и перебирать глубже незачем. Ограничение только на
 * ЧИСЛО мелких областей, и только здесь: одиночные области проверяются
 * все, сколько бы их ни было (см. границу 1 выше).
 */
const UNION_LIMIT = 64;

/**
 * Предел целых в строках. Приведение без дробей растит числа, и за этой
 * границей double считает неточно. Отвергнуто: BigInt — он верен, но на
 * живом расчёте медленнее в разы, а неточность здесь и так решается в
 * сторону подавления: непроверенная система считается восстановимой.
 */
const INT_LIMIT = 2 ** 45;

/**
 * Потолок узлов целочисленного поиска на один расчёт.
 *
 * Поиск ищет ВТОРОЕ значение области; кончились узлы — второго значения
 * считается не найденным, то есть область названа и вызывающий прячет ещё
 * число. Отвергнуто: считать «не нашлось за потолок» безопасным — это
 * ровно та ошибка, ради которой всю проверку и переписывали.
 */
const SEARCH_NODES = 20_000;

/**
 * Модуль отпечатков для поиска объединений. Простое и мелкое: произведение
 * двух вычетов умещается в double без потери точности, а случайное
 * совпадение отпечатков ничем не грозит — кандидата всё равно проверяет
 * точная арифметика. Отвергнуто простое около 2³¹: умножение пришлось бы
 * вести в BigInt, а это разы времени на каждом расчёте.
 */
const FINGERPRINT_MOD = 1_000_003;

/** Сколько узлов достаётся одной области: тяжёлая не должна съедать потолок у остальных */
const SEARCH_NODES_PER_AREA = 400;

/**
 * Сколько «других миров» строится из базиса ядра. Каждый освобождает разом
 * все области, размер которых в нём другой, и дальше они не стоят ничего;
 * больше шестидесяти четырёх запас не улучшает, а память и время ест.
 */
const WORLD_LIMIT = 64;

/** Кругов сужения границ: дальше границы почти не двигаются, а цена линейна */
const TIGHTEN_ROUNDS = 24;

/** Обратное по модулю отпечатков; 0 — обратного нет */
function inverseMod(a: number): number {
  let [prev, cur] = [((a % FINGERPRINT_MOD) + FINGERPRINT_MOD) % FINGERPRINT_MOD, FINGERPRINT_MOD];
  let [prevK, curK] = [1, 0];
  while (cur !== 0) {
    const q = Math.floor(prev / cur);
    [prev, cur] = [cur, prev - q * cur];
    [prevK, curK] = [curK, prevK - q * curK];
  }
  return prev === 1 ? ((prevK % FINGERPRINT_MOD) + FINGERPRINT_MOD) % FINGERPRINT_MOD : 0;
}

function gcd2(a: number, b: number): number {
  let x = Math.abs(a);
  let y = Math.abs(b);
  while (y) [x, y] = [y, x % y];
  return x;
}

/** Общий множитель строки снимается сразу: без этого числа растут после каждого шага */
function shrink(row: number[]): void {
  let g = 0;
  for (const v of row) {
    if (v !== 0) g = gcd2(g, v);
    if (g === 1) return;
  }
  if (g > 1) for (let i = 0; i < row.length; i += 1) row[i] = row[i]! / g;
}

/**
 * Приведённый вид системы: у каждой строки свой ведущий столбец, и в чужих
 * ведущих столбцах нули.
 *
 * Именно приведённый, а не просто ступенчатый: из него сразу читается, от
 * каких СВОБОДНЫХ столбцов зависит строка, и вопрос «названа ли область»
 * стоит потом столько же, сколько свободных столбцов, — а не целого
 * прохода по матрице на каждую область. Одиночных областей в отчёте с
 * клетками Венна бывают сотни, и разница между «на область» и «на систему»
 * решает, укладывается расчёт в миллисекунды или нет.
 */
interface Reduced {
  rows: number[][];
  /** ведущий столбец каждой строки */
  pivots: number[];
  /** строка, чей ведущий стоит в этом столбце; −1 — столбец свободный */
  rowAt: number[];
  free: number[];
}

/** Приведённый вид на целых; null — числа вышли за предел точности */
function reduce(rows: number[][], width: number): Reduced | null {
  const out = rows.map((r) => r.slice());
  const pivots: number[] = [];
  let r = 0;
  for (let col = 0; col < width && r < out.length; col += 1) {
    let sel = -1;
    for (let i = r; i < out.length; i += 1) {
      if (out[i]![col] !== 0) {
        sel = i;
        break;
      }
    }
    if (sel < 0) continue;
    [out[r], out[sel]] = [out[sel]!, out[r]!];
    const head = out[r]!;
    const pivot = head[col]!;
    for (let i = 0; i < out.length; i += 1) {
      if (i === r) continue;
      const row = out[i]!;
      const factor = row[col]!;
      if (factor === 0) continue;
      /* по всем столбцам, а не с ведущего: у строки бывают числа и левее — в свободных столбцах */
      for (let k = 0; k < width; k += 1) {
        const v = row[k]! * pivot - head[k]! * factor;
        if (!Number.isSafeInteger(v) || Math.abs(v) > INT_LIMIT) return null;
        row[k] = v;
      }
      shrink(row);
    }
    pivots.push(col);
    r += 1;
  }
  out.length = pivots.length;
  const rowAt = new Array<number>(width).fill(-1);
  for (const [i, col] of pivots.entries()) rowAt[col] = i;
  const free: number[] = [];
  for (let col = 0; col < width; col += 1) if (rowAt[col] === -1) free.push(col);
  return { rows: out, pivots, rowAt, free };
}

/**
 * Лежит ли область в линейной оболочке показанных чисел — то есть
 * называют ли они её размер однозначно.
 *
 * Значения правых частей для этого не нужны: однозначность — свойство
 * одной матрицы. Решение существует всегда (настоящие данные ему
 * удовлетворяют), и вопрос только в том, есть ли у него второе.
 *
 * Считается через приведённый вид: область — это вектор из единиц по своим
 * столбцам, коэффициент при строке задан её ведущим столбцом, и остаётся
 * сверить свободные столбцы. Дроби сведены к общему знаменателю; вышли за
 * предел точности — область считается названной, то есть в сторону
 * подавления.
 */
function spanned(take: number[], red: Reduced): boolean {
  const usedRows: number[] = [];
  let den = 1;
  for (const col of take) {
    const i = red.rowAt[col]!;
    if (i < 0) continue;
    usedRows.push(i);
    const c = Math.abs(red.rows[i]![red.pivots[i]!]!);
    den = (den / gcd2(den, c)) * c;
    if (!Number.isSafeInteger(den) || den > INT_LIMIT) return true;
  }
  const inside = new Set(take);
  for (const f of red.free) {
    let s = inside.has(f) ? den : 0;
    for (const i of usedRows) {
      const c = red.rows[i]![red.pivots[i]!]!;
      s -= red.rows[i]![f]! * (den / c);
      if (!Number.isSafeInteger(s) || Math.abs(s) > INT_LIMIT) return true;
    }
    if (s !== 0) return false;
  }
  return true;
}

/**
 * Правило системы: сумма областей лежит между lo и hi.
 *
 * Показанное число даёт lo = hi = значению, прочерк — lo = 1 (ноль
 * печатается, значит за прочерком кто-то есть), hi = всей выборке. Все
 * коэффициенты — единицы: область либо входит в число целиком, либо не
 * входит вовсе, на то она и область.
 */
interface Rule {
  vars: number[];
  lo: number;
  hi: number;
}

/**
 * Сужение границ областей по правилам; false — противоречие, то есть
 * такого отчёта не бывает.
 *
 * Границы получаются ВЕРНЫЕ, но не самые узкие: сужение не видит связей
 * между правилами. Этого хватает для вынужденных значений («пять
 * слагаемых, каждое ≥ 1, сумма 5»), а чего не хватает — добирает
 * целочисленный поиск. Отвергнуто: считать минимум и максимум задачей
 * линейного программирования — она дала бы границы над ДРОБНЫМИ числами,
 * а вся суть вынужденного значения в том, что людей нельзя делить.
 */
function tighten(rules: Rule[], lo: number[], hi: number[]): boolean {
  for (let round = 0; round < TIGHTEN_ROUNDS; round += 1) {
    let moved = false;
    for (const r of rules) {
      let sumLo = 0;
      let sumHi = 0;
      for (const v of r.vars) {
        sumLo += lo[v]!;
        sumHi += hi[v]!;
      }
      if (sumLo > r.hi || sumHi < r.lo) return false;
      for (const v of r.vars) {
        const top = r.hi - (sumLo - lo[v]!);
        if (top < hi[v]!) {
          sumHi += top - hi[v]!;
          hi[v] = top;
          moved = true;
        }
        const bottom = r.lo - (sumHi - hi[v]!);
        if (bottom > lo[v]!) {
          sumLo += bottom - lo[v]!;
          lo[v] = bottom;
          moved = true;
        }
        if (lo[v]! > hi[v]!) return false;
      }
    }
    if (!moved) return true;
  }
  return true;
}

/** Счётчик узлов поиска: общий на весь расчёт, иначе потолок обходился бы числом областей */
interface Budget {
  left: number;
}

/**
 * Есть ли у системы хоть одно целое неотрицательное решение.
 *
 * Перебор по остаточным степеням свободы: сузили границы, взяли область с
 * самым узким разбросом, перебрали её значения. Узкая берётся первой не
 * из вкуса — после её закрепления сужение обычно закрывает половину
 * остальных, и дерево не растёт.
 *
 * Спорная область берётся раньше всех прочих. Без этого поиск разбредался
 * по отчёту, закреплял пятнадцать областей их настоящими размерами и
 * только на шестнадцатой упирался в требование «сумма другая» — а потолок
 * узлов к тому времени кончался, и свободная область объявлялась
 * названной. Отвергнуто: поднять потолок — та же работа за большее время.
 *
 * Возвращается сам расклад, а не «да». Один найденный расклад
 * освобождает разом все области, размер которых в нём другой, и поиск по
 * ним не запускается вовсе.
 *
 * Значения перебираются ОТ НАСТОЯЩЕГО РАЗМЕРА области наружу. Мы ищем
 * мир, отличающийся от настоящего одним числом, и ближайший такой мир
 * находится в нескольких шагах от настоящего; перебор же с нуля вверх
 * уходил в тысячи узлов на раскладах вроде «двадцать одна область, у
 * каждой разброс от нуля до двадцати пяти» — и потолок узлов кончался
 * раньше ответа. Кончился потолок — область считается названной, то есть
 * отчёт молча пустел там, где прятать было нечего.
 *
 * Кончились узлы — возвращается «решения нет». Для вызывающего это значит
 * «второго значения не нашлось», то есть лишнее подавление, а не
 * пропущенная утечка.
 */
function solvable(
  rules: Rule[],
  lo: number[],
  hi: number[],
  seed: number[],
  focus: ReadonlySet<number>,
  budget: Budget,
): number[] | null {
  if (budget.left <= 0) return null;
  budget.left -= 1;
  if (!tighten(rules, lo, hi)) return null;
  let pick = -1;
  let best = Number.POSITIVE_INFINITY;
  for (let i = 0; i < lo.length; i += 1) {
    const w = hi[i]! - lo[i]!;
    if (w <= 0) continue;
    /* спорная область идёт первой: из-за неё и затеян поиск, и её значение сразу двигает остальные */
    const rank = focus.has(i) ? w : w + lo.length * lo.length;
    if (rank < best) {
      pick = i;
      best = rank;
    }
  }
  if (pick < 0) return lo.slice();
  const width = hi[pick]! - lo[pick]!;
  const from = Math.min(Math.max(seed[pick]!, lo[pick]!), hi[pick]!);
  for (let step = 0; step <= width; step += 1) {
    for (const v of step === 0 ? [from] : [from + step, from - step]) {
      if (v < lo[pick]! || v > hi[pick]!) continue;
      const nextLo = lo.slice();
      const nextHi = hi.slice();
      nextLo[pick] = v;
      nextHi[pick] = v;
      const found = solvable(rules, nextLo, nextHi, seed, focus, budget);
      if (found) return found;
      if (budget.left <= 0) return null;
    }
  }
  return null;
}

/**
 * Области, которые числа отчёта называют точно, — то есть горстки людей,
 * восстановимые из ответа.
 *
 * Область здесь — класс людей, неразличимых числами отчёта, показанными и
 * скрытыми. Почему именно так: любое деление такого класса надвое система
 * не видит вовсе, и человека из одной половины можно переложить в другую,
 * не изменив ни одного напечатанного числа, — значит, такое деление никого
 * не называет. Отвергнуто: перебирать все мыслимые пересечения
 * показателей — их экспоненциально много, а называют людей ровно классы.
 *
 * Скрытые числа делят классы наравне с показанными. Прежняя редакция
 * строила классы по одним показанным — и пятеро, стоящие под пятью
 * прочерками, были для неё одним классом из пятерых, то есть «не
 * горсткой». Каждый из них при этом назван: прочерков пять, сумма пять,
 * под каждым хотя бы один.
 *
 * Объединения классов проверяются наравне с классами: горсткой бывает не
 * один класс, а сумма нескольких — «двоє, що не чують шуму» складывается
 * из тех, кто не выбрал ничего, и тех, кто выбрал только скрытый вариант.
 * Глубина перебора не выбрана на глаз: в горстке меньше порога человек, в
 * каждом классе хотя бы один, значит классов в ней меньше порога.
 */
export function pinnedAreas(system: Reported[]): PinnedArea[] {
  const profile = new Map<string, number[]>();
  for (const [i, q] of system.entries()) {
    for (const id of q.members) {
      const list = profile.get(id);
      if (list) list.push(i);
      else profile.set(id, [i]);
    }
  }

  const areas: { inside: number[]; n: number }[] = [];
  const byKey = new Map<string, number>();
  for (const list of profile.values()) {
    const key = list.join(",");
    const at = byKey.get(key);
    if (at === undefined) {
      byKey.set(key, areas.length);
      areas.push({ inside: list, n: 1 });
    } else areas[at]!.n += 1;
  }
  if (!areas.length) return [];

  const shownKeys = system.filter((q) => q.shown).map((q) => q.key);
  const whole = (n: number): PinnedArea[] => [{ inside: shownKeys, n }];
  /* нечего печатать — нечего и восстанавливать: цикл подавления обязан на этом остановиться */
  if (!system.some((q) => q.shown && q.members.size > 0)) return [];
  if (areas.length > AREA_LIMIT) return whole(0);

  const people = areas.reduce((n, a) => n + a.n, 0);
  /*
   * Потолок прочерка. Снизу он всегда единица: ноль отчёт печатает, значит
   * за прочерком кто-то есть. Сверху — порог, если за прочерком и правда
   * горстка: правило публикации известно вместе с отчётом, и читатель,
   * проигрывая его на всех мыслимых раскладах, отбрасывает те, при которых
   * отчёт выглядел бы иначе. Один разбор показал это в лоб: восемнадцать
   * человек, разбиение 5/5/4/4, печатается «18 | 5 | 5 | × | ×» — сумма
   * прочерков 8, и если каждый меньше пяти, то оба равны четырём.
   *
   * Потолок ставится ТОЛЬКО там, где он верен на самом деле: числу,
   * спрятанному циклом, а не порогом, он был бы ложью и выкинул бы
   * настоящий расклад из системы. Проверка от этого строже настоящей
   * опасности — читателю ещё надо догадаться, чем именно спрятано
   * число, — и это ровно та сторона, в которую ошибаться.
   */
  const capOf = (q: Reported): number => (q.members.size < SMALL_CELL_FLOOR ? SMALL_CELL_FLOOR - 1 : people);
  const varsOf: number[][] = system.map(() => []);
  for (const [j, a] of areas.entries()) for (const i of a.inside) varsOf[i]!.push(j);

  const matrix: number[][] = [];
  const rules: Rule[] = [];
  for (const [i, q] of system.entries()) {
    /* число без людей ничего не связывает: его строка — одни нули, а прочерка над пустотой не бывает */
    if (!q.members.size) continue;
    if (q.shown) {
      const row = new Array<number>(areas.length).fill(0);
      for (const j of varsOf[i]!) row[j] = 1;
      matrix.push(row);
      rules.push({ vars: varsOf[i]!, lo: q.members.size, hi: q.members.size });
    } else rules.push({ vars: varsOf[i]!, lo: 1, hi: capOf(q) });
  }
  const red = reduce(matrix, areas.length);
  if (!red) return whole(0);

  /*
   * Блок — класс людей, неразличимых ПОКАЗАННЫМИ числами. Внутри блока
   * человека можно переложить из области в область, не тронув ни одного
   * напечатанного числа, — и этим доказывается, что область свободна.
   * Мешает переносу только прочерк ровно на ОДНОГО человека: уйдёт он —
   * прочерк станет нулём, а ноль печатается, и читатель заметит подмену.
   *
   * Отсюда СВЯЗКА — то, что нельзя разделить переносом. Если в блоке есть
   * хоть одна область без прочерков-одиночек, она отдаёт человека любой
   * другой области блока, и весь блок — одна связка; если такой области
   * нет, каждая области сама себе связка (прочерк на одного человека и
   * есть эта область целиком, отдавать ей нечего).
   *
   * Связка — это и есть единица перебора объединений, и это не эвристика,
   * а теорема: если объединение забрало часть связки, найдётся пара
   * соседних областей по разные стороны разреза, перенос между ними меняет
   * размер объединения на единицу — значит объединение не названо.
   * Перебирать поэтому надо связки, а не области, и разница решает:
   * двадцать одна клетка Венна по человеку — это несколько связок, а не
   * двадцать одна строка перебора. Прежняя редакция брала «шестнадцать
   * самых мелких областей», одиночки занимали весь срез, и «Г: 4»,
   * рассыпанная по двум областям по два человека, не проверялась никогда.
   */
  const sig = areas.map(() => "");
  const hiddenAt = areas.map(() => new Set<number>());
  for (const [j, a] of areas.entries()) {
    const shownIn: number[] = [];
    for (const i of a.inside) {
      if (system[i]!.shown) shownIn.push(i);
      else if (system[i]!.members.size) hiddenAt[j]!.add(i);
    }
    sig[j] = shownIn.join(",");
  }
  const bySig = new Map<string, number[]>();
  for (const [j, key] of sig.entries()) {
    const list = bySig.get(key);
    if (list) list.push(j);
    else bySig.set(key, [j]);
  }
  /** область, которой есть чем поделиться: над ней нет прочерка ровно на одного человека */
  const canGive = (j: number): boolean => {
    for (const h of hiddenAt[j]!) if (system[h]!.members.size < 2) return false;
    return true;
  };
  /** область, которая может принять: ни один прочерк над ней не упёрся в свой потолок */
  const canTake = (j: number): boolean => {
    for (const h of hiddenAt[j]!) if (system[h]!.members.size >= capOf(system[h]!)) return false;
    return true;
  };
  const knot = areas.map(() => -1);
  const knots: number[][] = [];
  const alone = (j: number): void => {
    knot[j] = knots.length;
    knots.push([j]);
  };
  for (const block of bySig.values()) {
    /*
     * Перенос нужен с обеих сторон: одна область отдаёт, другая принимает.
     * Отдающая и принимающая связаны, значит все отдающие и все
     * принимающие блока — одна связка, а область, которая не умеет ни
     * того ни другого, стоит сама по себе. Условие достаточное, а не
     * точное (пара могла бы сойтись и на общем прочерке), и неточность
     * его дробит связки мельче настоящих — то есть в сторону подавления.
     */
    const moving = block.filter((j) => canGive(j) || canTake(j));
    if (moving.length < 2 || !block.some(canGive) || !block.some(canTake)) {
      for (const j of block) alone(j);
      continue;
    }
    for (const j of moving) knot[j] = knots.length;
    knots.push(moving);
    for (const j of block) if (knot[j] === -1) alone(j);
  }

  const sizeOf = (take: number[]): number => take.reduce((n, j) => n + areas[j]!.n, 0);
  /** взята часть связки — значит объединение свободно, переносить есть куда */
  const partial = (take: number[]): boolean => {
    const taken = new Map<number, number>();
    for (const j of take) taken.set(knot[j]!, (taken.get(knot[j]!) ?? 0) + 1);
    for (const [c, n] of taken) if (n < knots[c]!.length) return true;
    return false;
  };

  /*
   * Одиночные области — ВСЕ, без усечения: усечённый список и был той
   * дырой, через которую четвёрка «31–40 років» уходила от проверки,
   * вытесненная шестнадцатью клетками Венна по одному человеку. Стоят они
   * дёшево (одна область — один проход по свободным столбцам), а
   * рассуждать о них проще всего: это строка отчёта, а не её комбинация.
   *
   * Объединения — по связкам, с потолка UNION_LIMIT. Здесь и осталась
   * единственная граница перебора: если малых связок больше шестидесяти
   * четырёх, суммы самых крупных из них не проверяются. Отдельно от среза
   * проверяется каждая малая строка отчёта (ниже) — именно она и была той
   * горсткой, которую срез терял, — но сумма двух строк за границей среза
   * остаётся непроверенной, и это записано тут, а не подразумевается.
   */
  const targets: number[][] = [];
  const seen = new Set<string>();
  const addTarget = (take: number[]): void => {
    const key = [...take].sort((a, b) => a - b).join(",");
    if (seen.has(key)) return;
    seen.add(key);
    targets.push(take);
  };
  for (const [j, a] of areas.entries()) if (a.n > 0 && a.n < SMALL_CELL_FLOOR) addTarget([j]);
  /*
   * Каждая малая строка отчёта — кандидат сама по себе, и это не роскошь.
   * «Г: 4» у восьми вариантов рассыпана по двум областям, а обе они
   * крупнее двадцати одной клетки Венна, лежащих рядом, — в срез самых
   * мелких связок они не попадали, и вычитание 25 − 7 − 7 − 7 называло
   * четверых. Строку отчёта читатель видит целиком, поэтому целиком её и
   * проверяем, мимо всякого среза.
   */
  for (const [i, q] of system.entries()) {
    if (q.members.size > 0 && q.members.size < SMALL_CELL_FLOOR) addTarget(varsOf[i]!);
  }

  /*
   * Объединения связок ищутся ОТПЕЧАТКОМ, а не перебором.
   *
   * Связка названа в сумме с другими, только если их векторы в линейной
   * оболочке гасят друг друга. Свернём вектор в одно число по постоянным
   * весам — и гашение станет равенством «сумма отпечатков ноль». Дальше не
   * перебор четвёрок, а встреча посередине: складываем все пары и ищем
   * пару с противоположным отпечатком. Прямой перебор стоил как четвёртая
   * степень числа связок, и это не отвлечённость: три колонки по
   * двенадцать показателей на тридцати непохожих людях считались три
   * секунды, восемь колонок — двенадцать. Встреча посередине стоит как
   * квадрат, и то же самое укладывается в десятки миллисекунд.
   *
   * Отпечаток может совпасть случайно — пусть: совпадение лишь добавляет
   * кандидата, а названа область или нет, решает точная проверка оболочки
   * ниже. Пропустить настоящее гашение отпечаток не может: ноль остаётся
   * нулём при любом свёртывании.
   */
  const freeAt = new Array<number>(areas.length).fill(-1);
  for (const [k, f] of red.free.entries()) freeAt[f] = k;
  const weight = red.free.map((_, k) => 1 + ((k * 7919 + 104729) % (FINGERPRINT_MOD - 1)));
  const markOf = new Array<number>(areas.length).fill(0);
  for (let a = 0; a < areas.length; a += 1) {
    const i = red.rowAt[a]!;
    if (i < 0) {
      markOf[a] = weight[freeAt[a]!]!;
      continue;
    }
    const inv = inverseMod(red.rows[i]![red.pivots[i]!]!);
    /* ведущее число кратно модулю — отпечатки не строятся; считаем систему непроверенной */
    if (!inv) return whole(0);
    let acc = 0;
    for (const [k, f] of red.free.entries()) {
      const v = ((-red.rows[i]![f]! % FINGERPRINT_MOD) + FINGERPRINT_MOD) % FINGERPRINT_MOD;
      acc = (acc + v * weight[k]!) % FINGERPRINT_MOD;
    }
    markOf[a] = (acc * inv) % FINGERPRINT_MOD;
  }

  const pool = knots
    .map((k) => ({ k, n: sizeOf(k), mark: k.reduce((v, a) => (v + markOf[a]!) % FINGERPRINT_MOD, 0) }))
    .filter((x) => x.n > 0 && x.n < SMALL_CELL_FLOOR)
    .sort((a, b) => a.n - b.n)
    .slice(0, UNION_LIMIT);
  const opposite = (v: number): number => (FINGERPRINT_MOD - (v % FINGERPRINT_MOD)) % FINGERPRINT_MOD;
  const pairs = new Map<number, { i: number; j: number; n: number }[]>();
  for (const [i, one] of pool.entries()) {
    if (one.mark === 0) addTarget(one.k);
    for (let j = i + 1; j < pool.length; j += 1) {
      const n = one.n + pool[j]!.n;
      if (n >= SMALL_CELL_FLOOR) continue;
      const v = (one.mark + pool[j]!.mark) % FINGERPRINT_MOD;
      if (v === 0) addTarget([...one.k, ...pool[j]!.k]);
      const list = pairs.get(v);
      if (list) list.push({ i, j, n });
      else pairs.set(v, [{ i, j, n }]);
    }
  }
  /* тройка — связка и пара правее неё */
  for (const [c, one] of pool.entries()) {
    for (const pair of pairs.get(opposite(one.mark)) ?? []) {
      if (pair.i <= c || pair.n + one.n >= SMALL_CELL_FLOOR) continue;
      addTarget([...one.k, ...pool[pair.i]!.k, ...pool[pair.j]!.k]);
    }
  }
  /* четвёрка — пара и пара правее неё; счётчик держит цену, если отпечатки совпали толпой */
  let room = UNION_LIMIT * UNION_LIMIT;
  for (const [v, list] of pairs) {
    const other = pairs.get(opposite(v));
    if (!other) continue;
    for (const a of list) {
      for (const b of other) {
        if (room-- <= 0) break;
        if (b.i <= a.j || a.n + b.n >= SMALL_CELL_FLOOR) continue;
        addTarget([...pool[a.i]!.k, ...pool[a.j]!.k, ...pool[b.i]!.k, ...pool[b.j]!.k]);
      }
    }
  }

  const nameOf = (take: number[]): PinnedArea => {
    const inside = new Set<number>();
    for (const j of take) for (const i of areas[j]!.inside) if (system[i]!.shown) inside.add(i);
    return { inside: [...inside].map((i) => system[i]!.key), n: sizeOf(take) };
  };

  const lo = areas.map(() => 0);
  const hi = areas.map(() => people);
  /* настоящие данные правилам удовлетворяют; противоречие значит ошибку в сборке системы */
  if (!tighten(rules, lo, hi)) return whole(0);

  /*
   * Готовые «другие миры» из базиса ядра.
   *
   * Каждый свободный столбец приведённого вида даёт вектор, который можно
   * прибавить к настоящим размерам, не тронув ни одного показанного числа.
   * Уцелел он (все размеры неотрицательны, под каждым прочерком остался
   * человек) — вот и расклад, отличный от настоящего, и он разом
   * освобождает все области, размер которых в нём другой.
   *
   * Без этого запаса целочисленный поиск запускался на каждую область
   * отдельно: восемьдесят один непохожий человек — восемьдесят один поиск,
   * двадцать шесть секунд на расчёт. С запасом до поиска доходят единицы.
   * Отвергнуто: считать «нашёлся свободный столбец — область свободна».
   * Столбец свободен над дробями, а людей на доли не делят: вынужденные
   * значения живут ровно в этом зазоре.
   */
  const worlds: number[][] = [];
  const holds = (w: number[]): boolean => {
    for (const v of w) if (v < 0) return false;
    for (const r of rules) {
      if (r.lo <= 0) continue;
      let sum = 0;
      for (const v of r.vars) sum += w[v]!;
      if (sum < r.lo) return false;
    }
    return true;
  };
  for (const f of red.free) {
    if (worlds.length >= WORLD_LIMIT) break;
    const shift = new Array<number>(areas.length).fill(0);
    shift[f] = 1;
    let integral = true;
    for (const [i, col] of red.pivots.entries()) {
      const c = red.rows[i]![col]!;
      const v = -red.rows[i]![f]!;
      if (v % c !== 0) {
        integral = false;
        break;
      }
      shift[col] = v / c;
    }
    if (!integral) continue;
    for (const sign of [1, -1]) {
      const w = areas.map((a, k) => a.n + sign * shift[k]!);
      if (holds(w)) worlds.push(w);
    }
  }
  const elsewhere = (take: number[], n: number): boolean =>
    worlds.some((w) => take.reduce((sum, j) => sum + w[j]!, 0) !== n);

  const pinned: PinnedArea[] = [];
  const rest: number[][] = [];
  for (const take of targets) {
    if (spanned(take, red)) {
      pinned.push(nameOf(take));
      continue;
    }
    let bottom = 0;
    let top = 0;
    for (const j of take) {
      bottom += lo[j]!;
      top += hi[j]!;
    }
    if (bottom === top) pinned.push(nameOf(take));
    else if (!partial(take) && !elsewhere(take, sizeOf(take))) rest.push(take);
  }
  /*
   * Целочисленный поиск — только когда ярусы выше молчат. Во время цикла
   * подавления они находят по нескольку областей на шаг, и шаг обрывается
   * на первой же находке: искать второе значение там, где число всё равно
   * будет спрятано, — это платить за ответ, который не нужен.
   */
  if (pinned.length || !rest.length) return pinned;

  const budget: Budget = { left: SEARCH_NODES };
  const seed = areas.map((a) => a.n);
  for (const take of rest) {
    const n = sizeOf(take);
    if (elsewhere(take, n)) continue;
    const focus = new Set(take);
    /*
     * Своя доля узлов на область: без неё одна тяжёлая область съедала
     * потолок, и все следующие объявлялись названными без единой попытки.
     */
    const share: Budget = { left: Math.min(budget.left, SEARCH_NODES_PER_AREA) };
    const otherValue = (bottom: number, top: number): number[] | null => {
      if (top < bottom) return null;
      return solvable([...rules, { vars: take, lo: bottom, hi: top }], lo.slice(), hi.slice(), seed, focus, share);
    };
    const world = otherValue(n + 1, people) ?? otherValue(0, n - 1);
    budget.left -= Math.min(budget.left, SEARCH_NODES_PER_AREA) - share.left;
    if (world) worlds.push(world);
    else pinned.push(nameOf(take));
  }
  return pinned;
}
