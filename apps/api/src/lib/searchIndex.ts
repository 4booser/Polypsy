import { createHmac } from "node:crypto";
import { env } from "../env";

/**
 * Слепой индекс для поиска по зашифрованным записям.
 *
 * Заметки приёма и заключения шифруются в базе, и обычный полнотекстовый
 * индекс по ним построить нельзя: `tsvector` по шифртексту — это индекс по
 * случайным байтам. Расшифровывать всё подряд при каждом поиске тоже нельзя —
 * тогда шифрование перестаёт что-либо значить, а поиск по десяти тысячам
 * записей начинает занимать секунды.
 *
 * Поэтому в базе лежат не слова, а их отпечатки: HMAC каждого нормализованного
 * слова на секрете приложения. Поиск считает отпечатки слов запроса и ищет
 * пересечение. Сам текст из индекса не восстанавливается.
 *
 * **Что это НЕ скрывает,** и это надо знать, а не обнаружить потом: длину
 * записи (по числу отпечатков), совпадение слов между записями и частоту
 * повторов. Тот, кто получил доступ к базе и к секрету, сможет проверить
 * гипотезу «есть ли в записи слово X», перебрав словарь. Слепой индекс — это
 * защита от чтения базы, а не от целенаправленного анализа с ключом на руках.
 *
 * **Морфологии здесь нет.** Украинский стеммер в PostgreSQL не встроен, а
 * писать свой — отдельная работа с собственными ошибками. Вместо этого слово
 * обрезается до основы фиксированной длины: «тривожність», «тривожності» и
 * «тривожністю» дают один отпечаток. Это грубее морфологии и честнее её
 * имитации: правило видно целиком и предсказуемо.
 */

/** До скольких букв обрезается слово. Шесть покрывает большинство основ */
const STEM_LENGTH = 6;

/** Короче трёх букв — предлоги и союзы, они только раздувают индекс */
const MIN_WORD = 3;

/**
 * Нормализация слова: нижний регистр, «ё» к «е», «ї/і» остаются как есть.
 *
 * Замена «ё» — не косметика: одно и то же слово пишут и так, и так, и без неё
 * поиск по «еще» не найдёт «ещё».
 */
function normalize(word: string): string {
  return word.toLowerCase().replaceAll("ё", "е").replaceAll("ъ", "ь");
}

/** Слова текста, приведённые к основам */
export function stems(text: string): string[] {
  const out = new Set<string>();
  for (const raw of text.split(/[^\p{L}\p{N}]+/u)) {
    if (raw.length < MIN_WORD) continue;
    const word = normalize(raw);
    out.add(word.slice(0, STEM_LENGTH));
  }
  return [...out];
}

/**
 * Отпечаток основы.
 *
 * HMAC, а не хеш: без секрета отпечатки нельзя перебрать по словарю, имея одну
 * лишь базу. Секрет тот же, что подписывает токены, — отдельный ключ здесь
 * означал бы ещё одну вещь, которую надо не потерять при переносе.
 */
export function fingerprint(stem: string): string {
  return createHmac("sha256", env.jwtSecret).update(stem).digest("base64url").slice(0, 22);
}

/** Отпечатки всего текста — то, что кладётся в индекс */
export function indexOf(text: string): string[] {
  return stems(text).map(fingerprint);
}

/**
 * Отпечатки запроса.
 *
 * Слова короче трёх букв выброшены так же, как при индексации: иначе запрос
 * «не спит» искал бы отпечаток «не», которого в индексе нет, и не находил
 * ничего.
 */
export function queryFingerprints(query: string): string[] {
  return indexOf(query);
}
