import { and, eq, inArray, sql, type SQL } from "drizzle-orm";
import type { PgUpdateSetSource } from "drizzle-orm/pg-core";
import { db } from "../db";
import { appointments } from "../db/schema";

export type AppointmentStatus = NonNullable<typeof appointments.$inferSelect["status"]>;

/**
 * Перевод приёма в новое состояние с проверкой прежнего в самой записи.
 *
 * Маршруты отмены, переноса и движения по приёму устроены одинаково:
 * прочитать приём, убедиться, что переход допустим, записать новое
 * состояние. Между чтением и записью помещается второй запрос — и это не
 * теоретическая возможность: пациент отменяет приём с телефона, пока
 * регистратор переносит его же на другое время, обычное дело за сутки до
 * приёма. Оба проходили проверку по одному и тому же прочитанному
 * состоянию, и записывал последний:
 *
 *   — перенос после отмены воскрешал отменённый приём в новом слоте, и
 *     человек, отменивший визит, получал напоминание и неявку;
 *   — отмена после переноса оставляла приём отменённым, но новый слот —
 *     занятым: время не возвращалось никому.
 *
 * Здесь проверка прежнего состояния перенесена в WHERE самого UPDATE.
 * Проиграв гонку, второй запрос не находит строки и получает отказ, а не
 * молча затирает чужое решение. Возвращается обновлённая строка или null —
 * решение, что сказать в отказе, остаётся за маршрутом: «приём уже закрыт»
 * и «такой переход не разрешён» читаются по-разному.
 *
 * Слот — вторая половина состояния (волна 12, внешний разбор). Перенос
 * меняет не статус, а слот: приём остаётся «записан», и проверка одного
 * статуса пропускала запись, решённую о прежнем времени, — подтверждение
 * прежнего времени ложилось на новое, отмена считала «позднюю» по старому
 * слоту, второй перенос затирал первый. Маршрут передаёт слот, который
 * прочитал, и запись проходит, только если приём всё ещё на нём.
 */
export async function moveAppointment(
  id: string,
  from: readonly AppointmentStatus[],
  set: PgUpdateSetSource<typeof appointments>,
  expected: { slotId?: string } = {},
): Promise<typeof appointments.$inferSelect | null> {
  const [row] = await db
    .update(appointments)
    .set(set)
    .where(
      and(
        eq(appointments.id, id),
        inArray(appointments.status, [...from]),
        expected.slotId ? eq(appointments.slotId, expected.slotId) : undefined,
      ),
    )
    .returning();
  return row ?? null;
}

/**
 * Метка «событие календаря ждёт сведения» — если событие у приёма есть по
 * самой строке, которую меняет запись, а не по прочитанной маршрутом.
 *
 * Событие в приём пишет и шаг после фиксации записи (createBookedMeeting).
 * Отмена или перенос, прочитавшие приём за миг до записи шага, видели
 * meeting_event_id = null, проходили условный UPDATE — статус и слот те
 * же — и календарь не сводили: событие оставалось на прежнем времени или у
 * отменённого приёма, а фоновый проход без метки его не брал. Выражение
 * считается по той версии строки, которую UPDATE действительно меняет;
 * решение «сводить ли» маршрут принимает по строке, которую тот вернул.
 */
export function meetingSyncIfEvent(at: string): SQL {
  return sql`case when ${appointments.meetingEventId} is not null then ${at}::timestamptz else ${appointments.meetingSyncAt} end`;
}
