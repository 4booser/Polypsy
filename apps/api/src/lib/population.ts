import { sql, type SQL } from "drizzle-orm";
import { env } from "../env";

/**
 * Кого и за какие сутки считают агрегаты по людям — одним местом.
 *
 * Сводка, ряд выраженности, «Зведення», когорты, статистика, срезы и
 * кандидаты норм отвечали на эти два вопроса каждый по-своему, и ответы
 * расходились: один и тот же фильтр «по 30 вересня» резал сутки то по
 * Гринвичу, то по Киеву, а прохождение, которое сотрудник заполнил на себя
 * «попробовать методику», попадало в «стан пацієнтів» наравне с
 * настоящими. Правило, записанное семь раз, расходится на восьмом.
 */

/* ─────────────── сутки и недели учреждения ─────────────── */

/*
 * Пояс — учреждения, явно, а не пояс сессии базы.
 *
 * Отвергнуто: выставить `timezone` роли приложения в базе. Это тоже чинит
 * сутки, но решение живёт вне кода — в базе, которую поднимают с нуля из
 * резервной копии, на стенде разработчика и в CI, — и выпадает при первом же
 * «пересоздать роль». Ровно так и вышло с compose: пояс там не задан, база в
 * UTC, а на машине разработчика — местный, и одни и те же проверки
 * проходили у одного и падали у другого. К тому же сессия одна на всё
 * приложение, а часы в техпанели (журнал, сигналы) нарочно в UTC.
 *
 * Пояс читается при каждом вызове, а не при загрузке модуля: так его можно
 * поменять в проверке, и помощники не запомнят старый.
 */
const tz = (): string => env.institutionTz;

/** День — это «ГГГГ-ММ-ДД» без времени; всё остальное — момент */
const isDay = (value: string): boolean => /^\d{4}-\d{2}-\d{2}$/.test(value);

/** Начало календарного дня `day` (ГГГГ-ММ-ДД) в поясе учреждения — момент, timestamptz */
export function dayStart(day: string): SQL {
  return sql`(${day}::date::timestamp at time zone ${tz()})`;
}

/** Начало СЛЕДУЮЩЕГО дня: верхняя граница «по такой-то день включительно» */
export function dayEnd(day: string): SQL {
  return sql`((${day}::date + 1)::timestamp at time zone ${tz()})`;
}

/**
 * Нижняя граница периода из запроса.
 *
 * Схема запроса (queryDate) пропускает и день, и полный момент. День
 * режется по поясу учреждения; момент — какой прислан, он и так абсолютен.
 */
export function periodFrom(value: string): SQL {
  return isDay(value) ? dayStart(value) : sql`${value}::timestamptz`;
}

/**
 * Верхняя граница периода, день включительно: человек выбирает день, а не
 * момент. У момента берётся его дата — так граница считалась и прежде.
 */
export function periodTo(value: string): SQL {
  return dayEnd(value.slice(0, 10));
}

/** Понедельник недели момента в поясе учреждения — timestamp без пояса */
export function localWeek(moment: SQL): SQL {
  return sql`date_trunc('week', ${moment} at time zone ${tz()})`;
}

/** Понедельник текущей недели учреждения — timestamp без пояса */
export function currentWeek(): SQL {
  return sql`date_trunc('week', now() at time zone ${tz()})`;
}

/** Местный timestamp (начало недели, дня) обратно в момент — для сравнения с submitted_at */
export function localToMoment(local: SQL): SQL {
  return sql`(${local} at time zone ${tz()})`;
}

/* ─────────────── кого считать ─────────────── */

/**
 * Прохождение — обследуемого, а не сотрудника.
 *
 * Сотрудник, заполняющий бланк ЗА пациента, пишет прохождение на пациента
 * (lib/submission.ts: «прохождение принадлежит обследуемому, а не тому, кто
 * внёс данные»), и оно здесь остаётся. Отсекается только то, где
 * респондент — сама учётная запись сотрудника: проба методики перед
 * назначением, демонстрация, обучение. В сводке «стан пацієнтів» такой
 * бланк — это сведение о враче, выданное за сведение о пациенте.
 *
 * Анонимное прохождение (user_id пуст) остаётся: сотрудника в нём нет по
 * определению, а человек за ним — обследуемый.
 *
 * `alias` — алиас таблицы responses в запросе; константа вызывающего, не ввод.
 */
export function patientRespondent(alias: string): SQL {
  const r = sql.raw(alias);
  return sql`not exists (select 1 from users staff_u where staff_u.id = ${r}.user_id and staff_u.role <> 'user')`;
}
