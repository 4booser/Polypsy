import type { Context } from "hono";
import { PASSWORD_CHANGE_CODE, renderError } from "@quizzy/shared";
import { langOf } from "./http";
import { currentRequestId } from "./log";

/**
 * Временный пароль: сначала свой, потом работа — на сервере, а не только
 * на экране.
 *
 * Пароль, выданный техпанелью при заведении или сбросе
 * (users.must_change_password), видел тот, кто его выдавал. Консоль с
 * таким паролем открывает смену пароля вместо рабочего места, но этим
 * ограничение и заканчивалось: API отвечал на всё как обычно, и знающий
 * временный пароль читал карты запросами мимо консоли (внешний разбор
 * 2026-09-26, P1). Экран — подсказка, а не замок.
 *
 * Проверка отдельной функцией рядом с авторизацией (middleware/auth.ts), по
 * образцу сторожа второго фактора (lib/secondFactor.ts, allowedDuringSetup):
 * один перечень пропускаемого, один отказ, одинаковый для консоли, кабинета
 * и мобилки.
 */

/**
 * Куда пускать, пока пароль временный.
 *
 * Смена пароля — ради неё всё и затеяно; «кто я» — по нему клиент и
 * понимает, что открыть смену. Настройки рабочего места — тема и плотность:
 * консоль шлёт их сама, как только применит профиль, и отказ здесь писал бы
 * в журнал «доступ запрещён» на каждое открытие экрана смены, ничего не
 * защищая — это оформление собственной консоли, а не чьи-то данные (так же
 * их пропускает сторож второго фактора). Правка профиля (PATCH /me) —
 * нет: это паспортная часть. Выход сюда не попадает — он без токена
 * (routes/auth.ts, POST /logout).
 */
export function allowedWithTemporaryPassword(method: string, path: string): boolean {
  if (method === "GET" && path === "/api/auth/me") return true;
  if (method === "POST" && path === "/api/auth/password") return true;
  if (method === "PUT" && path === "/api/auth/me/workspace") return true;
  return false;
}

/**
 * Отказ — 403 с кодом, а не только текстом.
 *
 * Код нужен клиенту, который смены пароля ещё не показывает (мобильное
 * приложение): по нему он открывает смену, а не пересказывает человеку
 * отказ. Тело — того же вида, что у прочих отказов (текст на языке
 * запроса и номер запроса), плюс код, как у режима обслуживания.
 */
export function passwordChangeRequired(c: Context): Response {
  return c.json(
    {
      error: renderError("err.passwordChangeRequired", langOf(c)),
      code: PASSWORD_CHANGE_CODE,
      requestId: currentRequestId(),
    },
    403,
  );
}
