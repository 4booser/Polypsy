import { env } from "./env";

/**
 * Сколько секунд соединение может молчать, пока обработчик думает (#186).
 *
 * По умолчанию у Bun — 10 с: запрос дольше получал обрыв, а обработчик
 * работал дальше, держа соединение пула. На цели дольше 10 с шли список
 * пациентов врача, «Огляд», динамика, аналитика, SPSS, «Якість даних» — и
 * из «медленно» превращались в «не открывается». Человек повторял — второе
 * соединение пула; выгрузка писала в журнал analytics.export, хотя файл
 * никто не получил.
 *
 * Две минуты: вдвое больше предела одного оператора в транзакции запроса
 * (db/context.ts, REQUEST_STATEMENT_TIMEOUT_MS) — запрос из нескольких
 * тяжёлых чтений успевает, — и далеко от потолка Bun (255 с). Дольше
 * держать запрос открытым незачем: тяжёлое, что не укладывается, — работа
 * для фоновой задачи с сохранённым итогом (как «Якість даних»), а не для
 * ожидания у экрана. Обрыв по простою, как и уход клиента, отменяет запросы
 * обработчика к базе (db/cancelOnAbort.ts). Поток событий (routes/events.ts)
 * шлёт пульс раз в 25 с и в предел укладывается с запасом.
 */
export const IDLE_TIMEOUT_S = 120;

/** Настройки сервера Bun для приложения — те же у index.ts и у проверки в сюите */
export function serveOptions<F>(fetch: F): { port: number; fetch: F; idleTimeout: number } {
  return { port: env.port, fetch, idleTimeout: IDLE_TIMEOUT_S };
}
