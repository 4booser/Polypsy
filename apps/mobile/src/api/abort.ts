/**
 * Отмена чтения: экран ушёл, пока ответ ещё шёл (волна 27).
 *
 * Карта пациента с динамикой отвечает секунды, на холодной базе — десятки
 * секунд. Человек открыл карту, не дождался и вернулся к списку — запрос
 * продолжал идти: держал соединение (их у приложения на сервер немного, и
 * следующий экран ждал в очереди за брошенным), а пришедший ответ разбирался
 * и ложился в состояние экрана, на который уже никто не смотрит.
 *
 * Отменённый запрос не отдаёт ничего: ни данных, ни ошибки сети. Отмена —
 * не «нет связи» (иначе чтение с кэшем отдало бы копию с прошлого раза, а
 * экран показал бы «нет сети»), и не отказ сервера (иначе отказ доступа
 * стёр бы кэш карты, #126). Экран, получив её, молчит.
 *
 * Только для чтений: отменить запись — значит не знать, дошла ли она.
 *
 * Модуль без react-native — проверяется тестом.
 */
export class RequestAborted extends Error {
  constructor() {
    super("aborted");
    // то же имя, что у отмены самого fetch: проверка одна на оба случая
    this.name = "AbortError";
  }
}

/** Запрос отменил вызывающий — показывать нечего: ни данных, ни ошибки */
export function isAborted(error: unknown): boolean {
  return (error as { name?: unknown } | null)?.name === "AbortError";
}

/** Чем чтение можно отменить — сигнал AbortController экрана */
export interface Abortable {
  signal?: AbortSignal;
}
