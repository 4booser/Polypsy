/**
 * Ночная палитра для обследований в казарме после отбоя.
 *
 * Не «тёмная тема потемнее». Тёмная тема остаётся сине-зелёной и на полной
 * яркости светит на всю комнату; ночная уводит всё в тёплый край и снижает
 * контраст ровно настолько, чтобы текст ещё читался с расстояния вытянутой
 * руки, но экран не будил соседей по кубрику.
 *
 * Синий убран намеренно: он сильнее прочих подавляет мелатонин, а
 * обследование после отбоя — это и так не лучшее время для сна.
 *
 * Выраженность здесь тоже приглушена, но не выброшена: «выраженная» обязана
 * оставаться отличимой — риск не становится меньше оттого, что отбой.
 */
export const night: typeof light = {
  bg: "#12100c",
  card: "#1a1712",
  cardAlt: "#221d16",
  text: "#d8cdb8",
  muted: "#9a8f7c",
  border: "#2e2820",
  primary: "#c9a86a",
  primaryText: "#12100c",
  accent: "#d99b3f",
  danger: "#c96a5a",
};

/*
 * Палитра графиков ночью — тёплая и приглушённая, но слоты те же и в том же
 * порядке: серия «первая» обязана оставаться первой, иначе один и тот же
 * график днём и ночью показывал бы разные ряды одним цветом.
 */
export const chartNight: typeof chartLight = {
  series: ["#c9a86a", "#c98a5a", "#a9a06a", "#b08a7a", "#c9b07a", "#9a9a6a"],
  bar: night.primary,
  grid: "#2e2820",
  axis: "#9a8f7c",
};

/** Все палитры разом — для проверок контраста */
export const PALETTES = { light, dark, night } as const;
