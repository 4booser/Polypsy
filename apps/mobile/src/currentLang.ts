import type { Lang } from "@quizzy/shared";

/**
 * Текущий язык — синхронно и без React Native.
 *
 * Живёт отдельным модулем, а не в `lang.tsx`, потому что его спрашивают
 * места, работающие вне React: клиент запросов и очередь несданных
 * прохождений. Очередь при этом обязана оставаться проверяемой без
 * эмулятора — её тесты гоняются в обычном процессе, — а `lang.tsx` тянет
 * `react-native`, и одного импорта хватило, чтобы эти тесты перестали
 * запускаться вовсе.
 *
 * Значение выставляет переключатель языка; здесь только хранилище.
 */
export let currentLang: Lang = "uk";

export function setCurrentLang(lang: Lang): void {
  currentLang = lang;
}
