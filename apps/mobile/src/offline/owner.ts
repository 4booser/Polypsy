/**
 * Чьи это офлайн-данные.
 *
 * Офлайн-слой жил без хозяина: очередь несданных прохождений, черновики и кэш
 * лежали под общими ключами, а отправлялись с тем токеном, какой найдётся в
 * хранилище в момент прогона. На общем планшете это значило: пациент А сдал
 * методику в подвале, вышел, в приложение вошёл пациент Б — и ответы А ушли на
 * сервер от имени Б, а кэш показал Б список методик и план безопасности А.
 * Хуже ошибки не придумать: чужие клинические ответы в чужой карте.
 *
 * Владелец — тот, чей токен лежит в хранилище: `sub` из полезной нагрузки
 * JWT. Не пользователь из экрана и не «последний, кого видел кэш», а ровно
 * тот, от чьего имени запрос уйдёт на сервер. Поэтому проверка «можно ли
 * отправить эту запись» сводится к сравнению двух строк и не может разойтись
 * с тем, что действительно уедет в заголовке Authorization.
 *
 * Подпись здесь не проверяется и не должна: это не вопрос доверия (токен
 * проверит сервер), а вопрос сортировки своих записей на своём же устройстве.
 *
 * Модуль без react-native: его зовут и клиент запросов, и очередь, а они
 * обязаны проверяться тестами в обычном процессе.
 */

export function ownerOfToken(token: string | null | undefined): string | null {
  if (!token) return null;
  const part = token.split(".")[1];
  if (!part) return null;
  try {
    // base64url → base64 с выравниванием: atob понимает только второе
    const b64 = part.replace(/-/g, "+").replace(/_/g, "/");
    const padded = b64 + "=".repeat((4 - (b64.length % 4)) % 4);
    const claims = JSON.parse(atob(padded)) as { sub?: unknown };
    return typeof claims.sub === "string" && claims.sub ? claims.sub : null;
  } catch {
    return null;
  }
}

/*
 * Владелец «сейчас» — синхронно, для полосы очереди и счётчиков на экранах:
 * они опрашивают очередь раз в несколько секунд и не должны ради этого
 * каждый раз читать защищённое хранилище. Значение выставляет обёртка
 * хранилища токенов (src/storage.ts) при каждом чтении, записи и очистке,
 * так что оно не отстаёт от токена.
 *
 * Отправка на него не полагается: перед отправкой владелец сверяется с тем
 * самым токеном, который уйдёт в запросе (src/api/client.ts, request).
 */
let active: string | null = null;

export function setActiveOwner(owner: string | null): void {
  active = owner;
}

export function activeOwner(): string | null {
  return active;
}

/*
 * Стирание закрывает офлайн-слой на запись (#125).
 *
 * Команда стирания чистит хранилище и снимает сессию, но чтения и
 * автосохранение, начатые до неё, заканчиваются после: ответ /api/worklist,
 * запрошенный за секунду до команды, ложился в кэш уже стёртого планшета, а
 * открытое прохождение продолжало писать черновик. Следующий запуск команды
 * уже не получал, и записанное оставалось навсегда — при «стёрто» в консоли.
 *
 * Поэтому с начала стирания на устройство не пишется ничего, пока на него
 * снова не войдут, а после входа — только за вошедшего: запрос прежнего
 * владельца, ответивший уже при новом, не кладёт его данные обратно.
 * Решает момент записи, а не момент запроса — проверка стоит там, где запись
 * ложится (cache.ts). Состояние живёт до перезапуска: после него ответов,
 * начатых до стирания, не бывает.
 */
let afterWipe: { reopenedFor: string | null } | null = null;

/**
 * Стирание началось (offline/wipe.ts): с этого мига офлайн-слой не пишет ни
 * за кого. `reopenedFor` — вход, сделанный уже после команды (довод стирания
 * при запуске, resumeWipe): за него писать можно, его сессия законна.
 */
export function closeForWipe(reopenedFor: string | null = null): void {
  afterWipe = { reopenedFor };
}

/**
 * Вход — в хранилище лёг новый токен (src/storage.ts, set). Это и владелец
 * «сейчас», и, после стирания, тот, за кого снова можно писать.
 */
export function signedIn(owner: string | null): void {
  active = owner;
  if (afterWipe) afterWipe.reopenedFor = owner;
}

/** Можно ли сейчас класть на устройство данные этого владельца */
export function mayStore(owner: string | null): owner is string {
  return !!owner && (afterWipe === null || afterWipe.reopenedFor === owner);
}

/** Стирания не было — состояние нового запуска; для тестов (test/store.mock.ts, resetStore) */
export function forgetWipe(): void {
  afterWipe = null;
}

/**
 * Токен в хранилище сменился между тем, как запрос решили отправить от имени
 * владельца, и тем, как его собрались отправить.
 *
 * Это не отказ сервера и не сбой сети: запись цела и ждёт своего владельца.
 * Прогон очереди на такой ошибке останавливается, а не помечает запись
 * «отвергнутой» (queue.ts, flush).
 */
export class OwnerChanged extends Error {
  constructor(message: string) {
    super(message);
    this.name = "OwnerChanged";
  }
}

export function isOwnerChanged(error: unknown): boolean {
  return error instanceof OwnerChanged || (error as { name?: string } | null)?.name === "OwnerChanged";
}
