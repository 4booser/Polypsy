/**
 * Печатный лист прохождения в мобилке — чистая часть (волна 14).
 *
 * Было: кнопка «Відкрити висновок» (экран после сдачи, динамика пациента)
 * отдавала браузеру телефона голый адрес листа, /api/reports/responses/:id,
 * через Linking.openURL. Браузер приходил без заголовка Authorization —
 * лист не открывался вовсе (401), — и без языка приложения: открой сервер
 * лист, он был бы на языке браузера.
 *
 * Стало: приложение обычным запросом — с токеном и языком в заголовках —
 * получает у сервера одноразовую ссылку на этот лист (минута, одно открытие,
 * язык запроса; apps/api/src/lib/reportLinks.ts) и отдаёт браузеру её.
 * Токен в адрес не кладётся никогда: адрес оседает в истории браузера, в
 * логах прокси и в заголовке Referer.
 *
 * Почему браузер, а не показ внутри приложения. Показать HTML внутри — это
 * WebView или модуль печати: новая нативная зависимость и новая сборка, а
 * файл с листом на устройстве пережил бы смену человека на общем телефоне
 * обхода (offline/owner.ts). Браузер уже умеет показать, распечатать,
 * сохранить в PDF и отправить, а ссылка на минуту и один раз даёт ему ровно
 * один лист.
 *
 * Здесь — то, что проверяется без эмулятора: какой адрес уйдёт браузеру.
 * Открывается только то, что похоже на одноразовую ссылку нашего сервера:
 * ответ, переписанный по дороге (прокси, подменённый сервер), не должен
 * увести человека браузером на чужой адрес, а случайно попавший в ответ
 * токен входа (в нём точки) — уехать в адресную строку.
 */

/** Префикс ссылки — тот же, что выдаёт сервер (REPORT_LINK_PREFIX в lib/reportLinks.ts) */
export const REPORT_LINK_PREFIX = "/api/report-links/";

/** 256 бит в base64url — 43 знака без точек, слэшей и прочего; короче — не наша ссылка */
const TICKET = /^[A-Za-z0-9_-]{32,}$/;

/** Куда просить ссылку на лист прохождения */
export function reportLinkPath(responseId: string): string {
  return `/api/reports/responses/${encodeURIComponent(responseId)}/link`;
}

/**
 * Адрес для браузера — или null, если сервер прислал не одноразовую ссылку.
 *
 * Хост — всегда наш API_URL, а не из ответа: путь из ответа приклеивается к
 * известному адресу сервера, и абсолютный адрес («https://…», «//…») в
 * ответе ссылкой не считается вовсе.
 */
export function reportLinkUrl(apiUrl: string, path: unknown): string | null {
  if (typeof path !== "string" || !path.startsWith(REPORT_LINK_PREFIX)) return null;
  if (!TICKET.test(path.slice(REPORT_LINK_PREFIX.length))) return null;
  return `${apiUrl.replace(/\/+$/, "")}${path}`;
}
