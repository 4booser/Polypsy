import { expect, test } from "@playwright/test";
import { LANG_FULL, langToggle, login, openMenu, setLang, topNav } from "./helpers";

/**
 * Двуязычная оболочка.
 *
 * Госпиталь украинский, и держать консоль только на русском — не мелочь:
 * специалист читает эти экраны каждый день. Проверяется, что переключатель
 * действительно меняет оболочку, а выбор переживает перезагрузку.
 */
test("переключение языка меняет оболочку и запоминается", async ({ page }) => {
  await login(page, "psy");
  const nav = topNav(page);
  const toggle = langToggle(page);

  /*
   * Берутся пункты полосы и слово на переключателе. Полоса стоит всегда и
   * целиком — в отличие от рельсы, где пункты закрытой группы не
   * существовали в разметке, и проверять по ним значило бы проверять заодно
   * умолчание раскрытия. Слово на переключателе — не украшение: оно называет
   * текущий язык, и человек по нему понимает, где он.
   */
  // конфигурация смоука ходит с русской локалью — стартуем с неё
  await expect(nav.getByRole("link", { name: "Пациенты" })).toBeVisible();
  await expect(toggle).toHaveText("Рус");

  /*
   * Меню нажимается само, а не через setLang: проверяется именно то, что
   * слово раскрывает выбор из всех языков (решение заказчика 2026-09-26 —
   * не «по кругу из двух»), текущий в нём отмечен не цветом, а состоянием
   * пункта, и выбор уводит на выбранный язык.
   */
  await toggle.click();
  const langs = page.getByRole("menu", { name: /Мова \/ Язык/ });
  await expect(langs.getByRole("menuitemradio")).not.toHaveCount(0);
  await expect(langs.getByRole("menuitemradio", { name: LANG_FULL.ru })).toHaveAttribute("aria-checked", "true");
  await expect(langs.getByRole("menuitemradio", { name: LANG_FULL.uk })).toHaveAttribute("aria-checked", "false");
  await langs.getByRole("menuitemradio", { name: LANG_FULL.uk }).click();
  await expect(langs).toBeHidden();
  await expect(nav.getByRole("link", { name: "Пацієнти" })).toBeVisible();
  await expect(toggle).toHaveText("Укр");
  /* после выбора фокус вернулся на слово: человек с клавиатуры не потерял место */
  await expect(toggle).toBeFocused();

  /*
   * Бургер переведён тем же нажатием: разделы в нём берутся из того же
   * словаря, что и полоса, но рисуются другим кодом — и забытый ut() там
   * полоса бы не выдала. Закрывается по Esc, чтобы дальше не читать оболочку
   * сквозь список.
   */
  const menu = await openMenu(page);
  await expect(menu.getByRole("link", { name: "Випадки ризику" })).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(menu).toBeHidden();

  // язык страницы меняется тоже: от него зависят диктор и переносы слов
  await expect(page.locator("html")).toHaveAttribute("lang", "uk");

  await page.reload();
  await expect(nav.getByRole("link", { name: "Пацієнти" })).toBeVisible();

  await setLang(page, "ru");
  await expect(nav.getByRole("link", { name: "Пациенты" })).toBeVisible();
  await expect(toggle).toHaveText("Рус");
});

test("экраны ежедневного пути переведены целиком", async ({ page }) => {
  await login(page, "psy");
  await setLang(page, "uk");

  /*
   * У экрана начала смены заголовком стоит дата, а не название: сводка и
   * приём слиты, и называть экран одним из двух было бы неправдой. Его
   * перевод проверяется по вкладке — и заодно проверяется, что дата
   * склоняется по-украински, чего словарь не покрывает вовсе.
   */
  await page.goto("/");
  await expect(page.locator(".main").getByRole("link", { name: "Зведення" })).toBeVisible();
  /*
   * Дата стоит подзаголовком, а не заголовком.
   *
   * Проверка искала её в h1 — там она была, пока заголовком экрана служила
   * дата. Теперь заголовок называет экран («Зведення»), а дата ушла под
   * него; смысл проверки прежний: месяц склоняется по-украински, чего
   * словарь не покрывает вовсе.
   */
  await expect(page.locator(".main")).toContainText("вересня");

  for (const [path, marker] of [
    ["/worklist", "Черга роботи"],
    ["/alerts", "Розбір випадків"],
    ["/patients", "Пацієнти"],
    ["/referrals", "Направлення"],
  ] as const) {
    await page.goto(path);
    await expect(page.locator("h1")).toHaveText(marker);
  }
});

/**
 * Русские остатки в украинском режиме.
 *
 * Точечных проверок «этот заголовок переведён» мало: строка, забытая в
 * середине экрана, не ломает ни один тест и живёт годами. Здесь читается весь
 * видимый текст страницы и ищутся буквы, которых в украинском алфавите нет.
 *
 * ы, ъ, э, ё — надёжный признак: слово с ними по-украински не пишется.
 *
 * Отделить оболочку от данных нельзя по написанию: названия методик, ФИО и
 * подразделения в посеве русские, и это правильно — содержимое базы не
 * переводится переключателем. Поэтому страница читается дважды, на обоих
 * языках, и подозрительным считается лишь то, что не изменилось: данные
 * совпадут, а непереведённая подпись останется на месте.
 */
const RUSSIAN_ONLY = /[ыъэё]/i;

/*
 * Все экраны, которые открываются без параметра в адресе.
 *
 * Было четырнадцать из тридцати трёх — и забытая строка обычно сидела как раз
 * на пропущенном. Экраны с параметром (карта пациента, аналитика методики)
 * сюда не входят: им нужен идентификатор из посева, и они проверяются
 * отдельным сценарием в screens.e2e.ts. Статическую проверку исходников это
 * не заменяет и не дублирует: та ловит строку в момент написания, эта — то,
 * что строка действительно доехала до экрана переведённой.
 */
const SCREENS = [
  "/",
  "/worklist",
  "/alerts",
  "/patients",
  "/referrals",
  "/surveys",
  "/batteries",
  "/invites",
  "/audit",
  "/groups",
  "/patient-groups",
  "/cohorts",
  "/search",
  "/constructor",
  "/users",
  "/consent-text",
  "/permissions",
  "/today",
  "/my-schedule",
  "/messages",
  "/account",
];

test("в украинском режиме не остаётся русских слов", async ({ page }) => {
  /*
   * Бюджет считается от числа экранов, а не берётся общий.
   *
   * Проверка открывает каждый экран дважды — по разу на язык, — и растёт
   * вместе со списком. С общим тридцатисекундным бюджетом она однажды
   * упирается в него не потому, что что-то сломалось, а потому что экранов
   * стало на два больше; так и вышло. Падение по времени в проверке полноты
   * перевода — худший вид ложной тревоги: смотреть в ней надо на слова, а не
   * на секундомер.
   */
  test.setTimeout(SCREENS.length * 3_000);
  /*
   * Вход суперадмином, а не рядовым специалистом.
   *
   * Список экранов содержит и те, что открыты только сверху: учётные записи,
   * журнал, текст согласия, права. Специалисту они отвечают отказом или
   * уводят на главную — и проверка четырежды пересчитывала слова на главной,
   * считая, что смотрит на четыре разных экрана. Дыра была тихой: тест
   * зеленел, а половина списка не открывалась ни разу.
   */
  await login(page, "superadmin");

  const wordsOf = async (path: string) => {
    await page.goto(path);
    await page.locator("h1").waitFor();
    /*
     * Заголовок появляется раньше содержимого: на «Сравнении» графики
     * приезжают отдельным запросом. Ждать «тишины в сети» нельзя — консоль
     * держит открытым поток событий, и она не наступает никогда. Ждём, пока
     * исчезнут скелеты: это и есть признак, что данные приехали.
     */
    await expect.poll(async () => page.locator(".skeleton").count(), { timeout: 10_000 }).toBe(0);
    await page.waitForTimeout(150);
    const text = await page.locator("main").innerText();
    return new Set(text.split(/[\s,.:;()«»…—-]+/).filter((w) => RUSSIAN_ONLY.test(w)));
  };

  const found: string[] = [];
  for (const path of SCREENS) {
    /*
     * Язык ставится выбором пункта в меню языков шапки, а не нажатием
     * вслепую (см. setLang). Меню берётся из шапки поимённо — на «Учётной
     * записи» стоит второй переключатель.
     */
    await setLang(page, "ru");
    const inRussian = await wordsOf(path);
    await setLang(page, "uk");
    const inUkrainian = await wordsOf(path);

    // осталось в украинском ровно то же, что было в русском, — значит данные;
    // всё прочее — забытая строка оболочки
    for (const word of inUkrainian) {
      if (!inRussian.has(word)) found.push(`${path}: ${word}`);
    }
  }

  expect(found).toEqual([]);
});
